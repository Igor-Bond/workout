/**
 * Настройки приложения (§28 ТЗ).
 *
 * Хранятся в localStorage — доступ синхронный, разметка собирается без await.
 *
 * На этапе 2 сюда добавится зеркалирование в базу: настройки должны попадать
 * в резервную копию и подтягиваться на новом устройстве. Пока хранилище одно.
 */

const PREFIX = 'wt_';

/**
 * Пальцем или мышью.
 *
 * При отсутствии matchMedia считаем, что телефон: приложение прежде всего
 * для него.
 */
export const touchDevice = () =>
    (typeof matchMedia === 'function' ? matchMedia('(pointer: coarse)').matches : true);

/**
 * Как приложение выбирает следующее упражнение (§11).
 *
 * Одна ось, а не две настройки: все три значения отвечают на один вопрос —
 * куда перевести взгляд после записанного подхода.
 *
 * По кругу — то, как тренируются на самом деле: пока отдыхает грудь,
 * работает спина. Раньше такого режима не было вовсе, и круговую тренировку
 * приходилось вести вручную в свободном.
 */
export const MODES = [
    { value: 'circuit', label: 'По кругу',  hint: 'После подхода — следующее упражнение плана' },
    { value: 'linear',  label: 'По одному', hint: 'Пока не закрыт план упражнения' },
    { value: 'free',    label: 'Свободный', hint: 'Упражнение выбираешь сам' }
];

/** Как режим «по одному» назывался до появления кругового. */
const LEGACY_MODES = { plan: 'linear' };

/**
 * Значения по умолчанию. Тип значения здесь же задаёт тип при чтении:
 * булево читается как булево, число — как число.
 */
const DEFAULTS = {
    /**
     * Язык интерфейса (§53): 'auto' | 'ru' | 'en'.
     *
     * По умолчанию берётся у телефона. Так приложение, отданное за пределы
     * русскоязычных стран, оказывается английским само, без объяснений, где
     * тут переключатель, — а объяснять их пришлось бы на языке, которого
     * человек не знает.
     */
    lang: 'auto',

    /** Как приложение выбирает следующее упражнение (§11). См. MODES. */
    mode: 'circuit',

    /** Таймер отдыха (§16). */
    restEnabled: true,
    restSeconds: 90,
    restSound: true,
    restVibration: true,

    /**
     * Название следующего упражнения вслух в интервальной программе (§50).
     *
     * Подчинено общему выключателю звука: молчаливая программа не должна
     * внезапно заговорить.
     */
    voiceNames: true,

    /** Не гасить экран во время тренировки. На iOS может не работать. */
    keepAwake: true,

    // Полноэкранный режим (§31) стоит здесь только ради порядка настроек:
    // значение по умолчанию у него зависит от устройства и задано ниже
    fullscreen: true,

    /**
     * Входил ли пользователь в учётную запись хоть раз (§39).
     *
     * По этому признаку приложение решает, поднимать ли SDK Firebase при
     * запуске. Без него было бы плохо в обе стороны: поднимать всегда —
     * значит грузить почти мегабайт тем, кто облаком не пользуется; не
     * поднимать никогда — значит не синхронизировать, пока не откроешь
     * профиль, потому что до подъёма SDK приложение не знает, что вход
     * уже выполнен.
     */
    syncEnabled: false
};

/**
 * Полный экран по умолчанию включён на телефоне и выключен на компьютере.
 *
 * Смысл режима — убрать системную панель навигации: на Android она светлая
 * и портит тёмный экран снизу, а во время подхода часы и заряд не нужны. На
 * компьютере убирать нечего, зато есть что терять: окно во весь экран
 * прячет вкладки и панель задач, а приложение там обычно одно из нескольких
 * открытых. Признак — вид указателя: палец есть там, где есть и панель.
 *
 * Значение вычисляется при каждом чтении, а не один раз: так его видно
 * проверке, и подключённая мышь не требует перезапуска.
 */
Object.defineProperty(DEFAULTS, 'fullscreen', { enumerable: true, get: touchDevice });

/**
 * Настройки, которые имеет смысл переносить на другое устройство (§41).
 *
 * Всё остальное к устройству и привязано: включено ли здесь облако, когда
 * здесь был последний обмен, переносилась ли здесь версия 1. Перенести их
 * вместе с копией значило бы соврать новому устройству о его собственном
 * состоянии — например, объявить синхронизацию включённой там, где вход не
 * выполнялся.
 */
const PORTABLE = ['lang', 'mode', 'restEnabled', 'restSeconds', 'restSound', 'restVibration',
                  'voiceNames', 'keepAwake'];

export const config = {

    DEFAULTS,
    PORTABLE,
    MODES,

    /**
     * Режим выполнения с оглядкой на прошлые названия.
     *
     * У тех, кто выбирал режим до появления кругового, в настройках лежит
     * «plan» — это нынешний «по одному». Читать его как неизвестное значение
     * и молча переключать человека на другой порядок нельзя.
     */
    mode() {
        const value = config.get('mode');
        if (LEGACY_MODES[value]) return LEGACY_MODES[value];

        return MODES.some((m) => m.value === value) ? value : DEFAULTS.mode;
    },

    /** Настройки для резервной копии — только переносимые. */
    getPortable() {
        const result = {};
        for (const key of PORTABLE) result[key] = config.get(key);
        return result;
    },

    /**
     * Применение настроек из копии.
     *
     * Незнакомые ключи и значения не того типа отбрасываются: файл могли
     * сделать другой версией приложения или поправить руками, и принимать
     * из него что попало нельзя.
     */
    setPortable(values = {}) {
        let applied = 0;

        for (const key of PORTABLE) {
            if (!(key in values)) continue;

            const value = values[key];
            if (typeof value !== typeof DEFAULTS[key]) continue;

            config.set(key, value);
            applied += 1;
        }

        return applied;
    },

    get(key) {
        const raw = localStorage.getItem(PREFIX + key);
        if (raw === null) return DEFAULTS[key];

        try {
            return JSON.parse(raw);
        } catch {
            // Значение записано до появления JSON-формата либо испорчено
            return DEFAULTS[key];
        }
    },

    set(key, value) {
        localStorage.setItem(PREFIX + key, JSON.stringify(value));
    },

    /** Все настройки одним объектом. */
    getAll() {
        const result = {};
        for (const key of Object.keys(DEFAULTS)) result[key] = config.get(key);
        return result;
    },

    /** Сброс к значениям по умолчанию. */
    reset() {
        for (const key of Object.keys(DEFAULTS)) localStorage.removeItem(PREFIX + key);
    }
};
