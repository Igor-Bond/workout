/**
 * Обращение к языковой модели (§60 ТЗ).
 *
 * Напрямую из браузера, без посредника. Проверено: Google отвечает на запрос
 * с личным ключом прямо со страницы приложения, и заводить ради этого сервер
 * значило бы завести то единственное, чего в приложении нет, — сервер.
 *
 * Ключ личный и лежит только на этом устройстве. В облако он не уезжает
 * (§39.1): ключ — это доступ к оплаченной квоте, и класть его в общее
 * хранилище наравне с планом нельзя. На втором устройстве заводится свой.
 *
 * Ключ в клиентском приложении виден тому, кто откроет хранилище браузера, и
 * это надо знать. Защита от чужих рук здесь не в тайне, а в ограничении
 * ключа по адресу в консоли Google: ключ, работающий только с этого сайта,
 * бесполезен в чужих.
 *
 * Модель задаётся настройкой, а не зашита. Их состав меняется чаще, чем
 * выходят версии приложения, и человек, у которого перестала отвечать одна,
 * должен уметь вписать другую сам, а не ждать обновления.
 */

import { t } from '../core/i18n.js';

const ENDPOINT = 'https://generativelanguage.googleapis.com/v1beta/models';

/** Модель по умолчанию. Меняется в настройках, если состав моделей уехал. */
export const DEFAULT_MODEL = 'gemini-3.5-flash';

/**
 * Под какими ключами лежат ключ и модель.
 *
 * Здесь, а не в экране разговора: обращаться к модели стало нужно и с других
 * экранов — из плана, чтобы заполнить карточки упражнений (§60.1), — и
 * второе написание тех же имён рано или поздно разошлось бы с первым.
 */
export const KEY_SETTING = 'aiKey';
export const MODEL_SETTING = 'aiModel';

/**
 * Сколько ждать ответа.
 *
 * Минута: программа на восемь недель считается дольше короткого ответа, а
 * висеть без конца нельзя — человек не поймёт, идёт ли что-то вообще.
 */
const TIMEOUT = 60000;

/**
 * Понятная причина вместо кода ошибки — и слова самого Google следом (Р-195).
 *
 * Своими словами объясняется то, что человек может поправить: ключ не тот,
 * модель не та, слишком часто. Но приложение не знает всех отказов Google и
 * знать не может, а любой неузнанный превращался в «Гугл ответил ошибкой» —
 * фразу, по которой нечего делать ни человеку, ни тому, кому он о ней
 * расскажет.
 *
 * Поэтому объяснение и первоисточник стоят рядом: первое для того, кто будет
 * чинить сам, второе — для того, кто перескажет. Google пишет по-английски, и
 * переводить его мы не беремся: перевод отказа — это пересказ, а пересказ
 * теряет ровно ту подробность, ради которой строку и читают.
 */
function причина(status, body) {
    const текст = String(body?.error?.message || '').trim();

    const своими = status === 400 && /API key not valid/i.test(текст)
        ? t('Ключ не принят. Проверьте, что скопирован он целиком.')
        : status === 400 ? t('Запрос не принят.')
        : status === 403 ? t('Доступ запрещён. Возможно, ключ ограничен другим адресом, модель недоступна в вашей стране или у проекта не включён Gemini API.')
        : status === 429 ? t('Слишком часто. Google просит подождать.')
        : status >= 500 ? t('Google ответил ошибкой. Попробуйте ещё раз.')
        : t('Не удалось получить ответ.');

    return текст
        ? t('{своими} Google говорит так: «{ответ}»', { своими, ответ: текст })
        : t('{своими} Код ответа {код}.', { своими, код: String(status) });
}

export const ai = {

    DEFAULT_MODEL,

    /** Готов ли разговор: без ключа обращаться некуда. */
    ready: (key) => !!String(key || '').trim(),

    /**
     * Какие модели этот ключ вправе спрашивать (§60.2, Р-191).
     *
     * Состав моделей у Google меняется чаще, чем выходят версии приложения, —
     * это записано в заголовке модуля и потому и сделана настройка. Но
     * настройку правит тот, кто уже работает; **новый человек в неё не
     * заглянет**, потому что до разговора он ещё не дошёл. Ему зашитая
     * умолчанием модель, которой у Google больше нет, закрывает вход целиком:
     * ключ верный, а приложение отвечает ошибкой.
     *
     * Спрашивать надо не догадками, а у самого Google: он отдаёт список
     * списком. Заодно это и есть самая дешёвая проверка ключа — она не тратит
     * квоту на ответ, которого никто не прочтёт.
     *
     * Возвращаются только те, что умеют отвечать на вопросы: в списке лежат и
     * те, что умеют лишь считать близость текстов.
     */
    async models({ key } = {}) {
        if (!ai.ready(key)) throw new Error(t('Ключ не задан.'));

        const control = new AbortController();
        const срок = setTimeout(() => control.abort(), TIMEOUT);

        let response;
        let data;

        try {
            response = await fetch(`${ENDPOINT}?key=${encodeURIComponent(key)}`, { signal: control.signal });
            data = await response.json().catch(() => null);
        } catch (e) {
            if (e.name === 'AbortError') throw new Error(t('Ответа нет уже минуту. Похоже, не дождёмся.'));
            throw new Error(t('Нет связи с Google.'));
        } finally {
            clearTimeout(срок);
        }

        if (!response.ok) throw new Error(причина(response.status, data));

        const список = Array.isArray(data?.models) ? data.models : [];

        return список
            .filter((m) => (m?.supportedGenerationMethods || []).includes('generateContent'))

            // Приходят с приставкой «models/», а в запрос идут без неё
            .map((m) => String(m?.name || '').replace(/^models\//, ''))
            .filter(Boolean);
    },

    /**
     * Выбрать модель из того, что предлагает Google (Р-191).
     *
     * Правило простое и объяснимое: быстрая и новая. «Flash» — самая дешёвая
     * из отвечающих, а разговор у приложения короткий; из flash берётся
     * старшая по номеру версии.
     *
     * Черновые и облегчённые пропускаются, пока есть обычные: «preview» и
     * «exp» Google выключает без предупреждения, а «lite» хуже отвечает на
     * длинный разбор — а разбор здесь именно длинный.
     *
     * Ничего не подошло — берём первую попавшуюся: список непустой, значит
     * отвечать есть чему, и молчать об этом хуже, чем выбрать не лучшее.
     */
    pick(names = []) {
        const все = names.filter(Boolean);
        if (все.length === 0) return null;

        const версия = (имя) => {
            const m = String(имя).match(/(\d+(?:\.\d+)?)/);
            return m ? Number(m[1]) : 0;
        };

        const черновая = (имя) => /preview|exp|latest/i.test(имя);
        const лёгкая = (имя) => /lite/i.test(имя);

        const вес = (имя) => (/flash/i.test(имя) ? 2 : /pro/i.test(имя) ? 1 : 0);

        const годные = все.filter((имя) => !черновая(имя) && !лёгкая(имя));
        const откуда = годные.length ? годные : все;

        return [...откуда].sort((a, b) => вес(b) - вес(a) || версия(b) - версия(a) || a.localeCompare(b))[0];
    },

    /**
     * Спросить. messages — [{ role: 'user' | 'model', text, image }].
     *
     * image — `{ mime, data }`, где data в основании 64 без приставки
     * `data:`. Уменьшать снимок здесь не станем: это дело того, кто его
     * выбрал (js/core/photo.js), а отправка обязана отправлять.
     *
     * Возвращает текст ответа или бросает с понятным сообщением: разговор —
     * не обмен данными, его провал должен быть виден сразу и словами.
     */
    async ask({ key, model = DEFAULT_MODEL, system = '', messages = [] } = {}) {
        if (!ai.ready(key)) throw new Error(t('Ключ не задан.'));
        if (messages.length === 0) throw new Error(t('Нечего спрашивать.'));

        const url = `${ENDPOINT}/${encodeURIComponent(model)}:generateContent?key=${encodeURIComponent(key)}`;

        const body = {
            contents: messages.map((m) => ({
                role: m.role === 'model' ? 'model' : 'user',

                /*
                 * Снимок стоит перед словами, а не после.
                 *
                 * Так его и просят показывать в примерах Google, и по смыслу
                 * это верно: сначала предмет, потом вопрос о нём. Обратный
                 * порядок модель читает как «вот вопрос, а вот ещё зачем-то
                 * картинка».
                 */
                parts: [
                    ...(m.image?.data
                        ? [{ inlineData: { mimeType: m.image.mime || 'image/jpeg', data: m.image.data } }]
                        : []),
                    { text: m.text }
                ]
            }))
        };

        if (system.trim()) body.systemInstruction = { parts: [{ text: system }] };

        const control = new AbortController();
        const срок = setTimeout(() => control.abort(), TIMEOUT);

        let response;
        let data;

        try {
            response = await fetch(url, {
                method: 'POST',
                headers: { 'Content-Type': 'application/json' },
                body: JSON.stringify(body),
                signal: control.signal
            });

            data = await response.json().catch(() => null);
        } catch (e) {
            if (e.name === 'AbortError') throw new Error(t('Ответа нет уже минуту. Похоже, не дождёмся.'));
            throw new Error(t('Нет связи с Google.'));
        } finally {
            clearTimeout(срок);
        }

        if (!response.ok) {
            const сообщение = response.status === 404
                ? t('Модель «{модель}» не найдена. Нажмите «Подобрать модель» в настройках разговора — приложение спросит у Google, что он предлагает сейчас.', { модель: model })
                : причина(response.status, data);

            throw new Error(сообщение);
        }

        const текст = (data?.candidates?.[0]?.content?.parts || [])
            .map((p) => p.text || '')
            .join('')
            .trim();

        /*
         * Пустой ответ — не молчание, а отказ, и сказать об этом надо прямо.
         *
         * Модель обрывает ответ по своим соображениям — упёрлась в предел
         * длины или в свои правила, — и человек, увидевший пустое место,
         * решит, что сломалось приложение.
         */
        if (!текст) {
            const причина_отказа = data?.candidates?.[0]?.finishReason || data?.promptFeedback?.blockReason;

            throw new Error(причина_отказа
                ? t('Ответ не получен: {что}', { что: причина_отказа })
                : t('Ответ пришёл пустым.'));
        }

        return текст;
    }
};
