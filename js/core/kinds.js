/**
 * Виды упражнений — один список на всё приложение (§5).
 *
 * Их четыре, и различаются они не названием, а тем, что записывается в
 * подходе: у силового повторения и вес, у собственного веса только
 * повторения, у упражнения на время длительность, у кардио время и
 * дистанция. Всё остальное — подписи, поля ввода, столбцы в итогах, выбор
 * величины для рекорда — следствия.
 *
 * Раньше следствия жили порознь: подписи в справочнике, те же подписи в
 * карточке упражнения, подсказки в плане, поля в итогах, главная величина в
 * рекордах. Пять таблиц об одном и том же, и ничто не мешало забыть в одной
 * из них вид — на экране появилась бы пустота там, где ждали слово.
 *
 * Подписи здесь по-русски и переводятся при показе: список собирается один
 * раз при загрузке модуля, а язык меняется на ходу.
 */

import { t } from './i18n.js';

export const KINDS = [
    {
        value: 'weight',
        label: 'Силовое с весом',
        hint: 'повторения и вес',

        /** Поля подхода: их спрашивают при вводе и показывают в итогах. */
        fields: ['reps', 'weight'],

        /**
         * Поле, по которому видно, что подход этого вида.
         *
         * Всегда первое из полей. Вид у упражнения можно поменять в
         * справочнике, а записанные подходы от этого не меняются: отжимания,
         * ставшие «упражнением на время», по-прежнему хранят повторения. По
         * этому полю приложение и понимает, что перед ним на самом деле.
         */
        main: 'reps'
    },
    {
        value: 'reps',
        label: 'Собственный вес',
        hint: 'повторения',

        // Вес здесь тоже бывает: пояс на подтягиваниях, гантель между стоп
        fields: ['reps', 'weight'],
        main: 'reps'
    },
    {
        value: 'time',
        label: 'На время',
        hint: 'длительность',
        fields: ['duration'],
        main: 'duration'
    },
    {
        value: 'distance',
        label: 'Кардио',
        hint: 'время и дистанция',
        fields: ['distance', 'duration'],
        main: 'distance'
    }
];

const BY_VALUE = Object.fromEntries(KINDS.map((k) => [k.value, k]));

/**
 * Вид по значению. undefined для незнакомого — и это важно.
 *
 * Незнакомый вид приходит из чужой резервной копии и из будущей версии
 * приложения. Молча подставить вместо него силовое значило бы соврать про
 * записанное; тот, кто спрашивает, обязан решить сам, что с этим делать.
 */
export const kindOf = (value) => BY_VALUE[value];

/** Подпись вида на текущем языке. Незнакомое показывается как есть. */
export const kindLabel = (value) => t(BY_VALUE[value]?.label || value || '');

/** Подсказка «что записывается» — для списков выбора. */
export const kindHint = (value) => t(BY_VALUE[value]?.hint || '');

/** Поля подхода у вида. У незнакомого — как у силового: чаще всего он и есть. */
export const kindFields = (value) => (BY_VALUE[value] || BY_VALUE.weight).fields;
