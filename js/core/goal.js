/**
 * Цифровые цели (§67 ТЗ).
 *
 * До сих пор цель у приложения была словесная — строка «убрать живот» в
 * профиле. Из неё выводилось ровно одно: в какую сторону хорошо. Всё
 * остальное, что человек держит в голове — «до восьмидесяти восьми», «талию
 * под девяносто четыре», — приложению не сообщалось никак, хотя именно эти
 * числа и есть цель.
 *
 * Модуль чистый: числа на входе, числа на выходе. Ни базы, ни разметки — как
 * и у здоровья (js/core/health.js), потому что здесь считается то, что потом
 * будет сказано человеку про него самого.
 *
 * Главное правило здесь своё: **цель сравнивается с тем, откуда вышли, а не
 * с нулём**. «Осталось 4,6 кг» без «прошли 1,6» — это приговор без истории:
 * человек, снявший полтора килограмма, видит только оставшееся и не видит
 * сделанного.
 */

const DAY = 86400000;
const WEEK = 7 * DAY;

/**
 * Число или ничего — но пустое не считается нулём.
 *
 * `Number(null)` — это 0, и проверка «конечное ли число» его пропускает. На
 * этом уже обжигались в кондициях (Р-134): пропущенный замер читался как ноль
 * и превращался в падение веса на девяносто два килограмма. Здесь вышло бы
 * тише и хуже: цель, объявленная неизвестно от чего, показала бы пройденными
 * сто процентов пути.
 */
const число = (v) => (v === null || v === undefined || v === '' ? NaN : Number(v));

/** Сколько дней смотреть свой ход, когда считаем скорость. То же окно, что у кондиций. */
const ОКНО = 30;

export const goal = {

    ОКНО,

    /**
     * Как далеко прошли: доля, остаток и направление.
     *
     * from — величина в день, когда цель объявили. Без неё доля не считается
     * вовсе: «сколько осталось» знает и школьник, а «сколько прошли» — это
     * то, ради чего цель и заводят.
     */
    progress({ from, target, current } = {}) {
        const начало = число(from);
        const к = число(target);
        const сейчас = число(current);

        if (![начало, к, сейчас].every(Number.isFinite)) return null;

        const весь = к - начало;

        // Цель, равная началу, — это не цель, а отметка: делить на ноль нечем
        if (весь === 0) return null;

        const пройдено = сейчас - начало;

        return {
            direction: весь < 0 ? 'down' : 'up',

            // Доля может выйти за единицу — значит, перевыполнено, и это
            // честнее обрезанной сотни процентов
            share: пройдено / весь,

            left: Math.abs(к - сейчас),
            done: весь < 0 ? сейчас <= к : сейчас >= к
        };
    },

    /**
     * Свой ход за окно — сколько величина меняется в неделю.
     *
     * Берутся крайние точки окна, а не средняя по всем: человека занимает
     * путь от «было» к «стало», а не сглаженная кривая между ними. Меньше
     * двух точек — скорости нет.
     */
    pace(points = [], { now = Date.now(), days = ОКНО } = {}) {
        const с = now - days * DAY;

        const ряд = points
            .filter((p) => Number.isFinite(p?.at) && Number.isFinite(p?.value) && p.at >= с)
            .sort((a, b) => a.at - b.at);

        if (ряд.length < 2) return null;

        const первая = ряд[0];
        const последняя = ряд[ряд.length - 1];

        const срок = последняя.at - первая.at;

        // Два замера в один день скорости не дают: делить на ноль нечем, а
        // «полкило за час» — это вода, а не ход
        if (срок < DAY) return null;

        return ((последняя.value - первая.value) / срок) * WEEK;
    },

    /**
     * Когда придём, если пойдём как шли.
     *
     * Возвращает момент времени или null — и null здесь частый ответ:
     * стоящая на месте величина до цели не дойдёт никогда, а идущая от цели
     * не дойдёт тем более. Обещать срок в таких случаях значило бы
     * придумывать.
     */
    eta({ current, target, perWeek, now = Date.now() } = {}) {
        const сейчас = число(current);
        const к = число(target);
        const вНеделю = число(perWeek);

        if (![сейчас, к, вНеделю].every(Number.isFinite) || вНеделю === 0) return null;

        const осталось = к - сейчас;

        // Идём в другую сторону — срока нет
        if (Math.sign(осталось) !== Math.sign(вНеделю)) return null;

        const недель = осталось / вНеделю;

        /*
         * Дальше года не обещаем.
         *
         * При ходе в двадцать граммов в неделю срок выходит за десятилетие, и
         * такая дата — не прогноз, а насмешка: за год изменится и вес, и
         * жизнь, и сама цель.
         */
        if (недель > 52) return null;

        return now + недель * WEEK;
    },

    /**
     * Ход к цели или от неё — за окно.
     *
     * Отвечает на вопрос, которого нет ни у доли, ни у срока: человек за
     * последний месяц приближался или удалялся. Доля может быть большой, а
     * последние три недели — обратный ход, и сказать об этом надо.
     */
    heading({ target, current, perWeek } = {}) {
        const к = число(target);
        const сейчас = число(current);
        const вНеделю = число(perWeek);

        if (![к, сейчас, вНеделю].every(Number.isFinite)) return null;
        if (вНеделю === 0) return 'still';

        return Math.sign(к - сейчас) === Math.sign(вНеделю) ? 'toward' : 'away';
    }
};
