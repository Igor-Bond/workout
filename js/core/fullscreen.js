/**
 * Полноэкранный режим (§31 ТЗ).
 *
 * На Android системная панель навигации в установленном приложении светлая,
 * если светлая тема системы, и покрасить её со стороны страницы нечем:
 * `theme-color` красит строку состояния, а панель навигации следует системе.
 * Снизу остаётся белая полоса, которая к приложению не относится и портит
 * тёмный экран.
 *
 * Убрать её можно только полноэкранным режимом. В манифесте его ставить
 * нельзя: `display` читается в момент установки, и уже установленному
 * приложению значение не поменять — пришлось бы удалять значок и добавлять
 * заново. Поэтому Fullscreen API, который включается на ходу.
 *
 * Браузер требует, чтобы вход шёл от действия пользователя, а при запуске
 * его ещё не было. Поэтому режим включается на первом же касании — самом
 * раннем моменте, когда это законно, — и держится всё время работы
 * приложения, а не только на экране выполнения.
 */

import { config, touchDevice } from '../config.js';

const supported = () =>
    typeof document !== 'undefined'
    && !!document.documentElement?.requestFullscreen;

/**
 * Когда браузер отказал в последний раз.
 *
 * Отсчитывается только от отказа, не от удачного входа: режим может слететь
 * через секунду после того, как включился, и заставлять человека ждать до
 * следующей попытки было бы наказанием ни за что.
 */
let lastRefusal = 0;
const RETRY_MS = 3000;

/** Слежение уже включено. Второй слушатель просил бы полный экран дважды. */
let watching = false;

/** Чем браузер отказал в последний раз — для строки состояния в профиле. */
let lastError = null;
/** Начатый, но ещё не завершённый вход. Нужен, чтобы выход его дождался. */
let entering = null;

export const fullscreen = {

    /** Умеет ли браузер вообще. На iOS — нет, и это нормально. */
    get supported() {
        return supported();
    },

    get active() {
        return !!document.fullscreenElement;
    },

    /**
     * Войти. Возвращает false, если не вышло, — и это не ошибка:
     * браузер отказывает, когда вызов не связан с действием пользователя,
     * а такое случается при обычной перерисовке.
     */
    async enter() {
        if (!supported() || fullscreen.active) return fullscreen.active;

        /*
         * Второй запрос поверх начатого не нужен и вреден.
         *
         * Одно нажатие даёт два повода войти: сторож на pointerdown и сама
         * кнопка на click. Браузер отвечал на второй отказом, и профиль
         * показывал «Браузер отказал» ровно в тот момент, когда режим
         * успешно включился.
         */
        if (entering) {
            try {
                await entering;
                return fullscreen.active;
            } catch {
                return false;
            }
        }

        try {
            entering = document.documentElement.requestFullscreen({ navigationUI: 'hide' });
            await entering;

            lastError = null;
            return true;
        } catch (e) {
            /*
             * Причина отказа запоминается, а не только пишется в консоль.
             *
             * Отказывают по-разному: браузер не считает касание действием,
             * политика встроенного окна запрещает режим целиком, система не
             * даёт его установленному приложению. Со стороны всё выглядит
             * одинаково — «не работает», — и без причины разобраться нельзя
             * ни мне, ни тому, у кого не включилось.
             */
            // Причина не переводится: и имя, и текст ошибки приходят от
            // браузера по-английски, и переведённое слово рядом с ними
            // выглядело бы переводом всей строки, каким оно не является
            lastError = `${e?.name || 'Error'}: ${e?.message || e}`;
            console.warn('[Экран] Полноэкранный режим не включился:', lastError);
            return false;
        } finally {
            entering = null;
        }
    },

    /** Чем браузер отказал в последний раз. null, если отказа не было. */
    get lastError() {
        return lastError;
    },

    /**
     * Выйти.
     *
     * Сначала дожидается начатого входа, если он ещё в пути. Иначе выход
     * проходил впустую: одно и то же нажатие сперва будило сторожа на
     * pointerdown, а потом выключало настройку на click, и выход случался
     * раньше, чем завершался вход. Приложение оставалось в полном экране, а
     * кнопки выхода на перерисованном экране уже не было — выбраться было
     * нечем.
     */
    async exit() {
        if (entering) {
            try { await entering; } catch { /* вход не удался — тем лучше */ }
        }

        if (!fullscreen.active) return;

        try {
            await document.exitFullscreen();
        } catch (e) {
            console.warn('[Экран] Не удалось выйти из полноэкранного режима:', e?.message || e);
        }
    },

    /**
     * Приложение уже открыто во весь экран самой системой.
     *
     * Это просит манифест: `display: fullscreen`. Так надёжнее всего —
     * панелей нет с первого запуска, без касания и без разрешений. Но
     * значение читается в момент установки, и тому, кто поставил значок
     * раньше, оно не достанется, пока он не переустановит. Для него и
     * остаётся Fullscreen API.
     */
    get byManifest() {
        return typeof matchMedia === 'function'
            && matchMedia('(display-mode: fullscreen)').matches;
    },

    /** Включён ли режим в настройках и доступен ли вообще. */
    get wanted() {
        return supported() && !fullscreen.byManifest && !!config.get('fullscreen');
    },

    /** Войти, если пользователь этого просил. Вызывать из обработчика действия. */
    async enterIfWanted() {
        if (!fullscreen.wanted) return false;
        return fullscreen.enter();
    },

    /**
     * Держать полный экран всё время работы.
     *
     * Само по себе приложение в полный экран не пустят: браузер требует
     * действия пользователя, а при запуске его ещё не было. Первое касание —
     * самый ранний момент, когда это законно, и до него пользователь всё
     * равно ничего не делает.
     *
     * Слушатель не снимается после первого раза, и вот почему. Режим
     * слетает сам: от переключения на другое приложение, от системного
     * окна, от возврата по кнопке «назад». Раньше вместо этого его
     * возвращали экраны выполнения и табаты, каждый за себя, — и переход
     * между экранами выглядел прыжком, потому что панели то пропадали, то
     * появлялись. Держать режим — дело приложения целиком, а не отдельных
     * экранов.
     *
     * Всё это верно для телефона и неверно для компьютера. Там режим сам не
     * слетает: из него выходят — клавишей Esc или кнопкой, — и возвращать
     * его следующим же кликом значит не пускать человека наружу. Со стороны
     * это выглядит как сломанный выход: нажал Esc, панели вернулись, ткнул
     * мышью — и снова полный экран.
     *
     * Поэтому на компьютере выход из режима считается выключением самой
     * настройки: она видна в профиле, и человек сразу понимает, в каком он
     * состоянии.
     */
    watch() {
        if (watching) return;
        watching = true;

        document.addEventListener('fullscreenchange', () => {
            if (fullscreen.active) return;

            // На телефоне режим слетает от системного окна и от перехода в
            // другое приложение — это не «выход», а помеха, и её исправляют
            if (touchDevice()) return;

            config.set('fullscreen', false);
        });

        document.addEventListener('pointerdown', async () => {
            if (!fullscreen.wanted || fullscreen.active) return;

            /*
             * После отказа выжидаем.
             *
             * Браузер отказывает, когда не считает касание действием, и без
             * паузы каждое следующее касание писало бы в консоль по
             * предупреждению.
             */
            if (Date.now() - lastRefusal < RETRY_MS) return;

            const ok = await fullscreen.enter();
            if (!ok) lastRefusal = Date.now();
        }, true);
    }
};
