/**
 * Снимок к вопросу о еде (§68 ТЗ).
 *
 * Единственное место приложения, где наружу уходит не текст. Из-за этого у
 * модуля одна работа и одно правило: **уменьшить перед отправкой**.
 *
 * Снимок с телефона — это четыре-восемь мегабайт: три тысячи точек по
 * длинной стороне, а для вопроса «сколько тут примерно» хватает тысячи.
 * Разница в тридцать раз, и платит за неё человек — временем на мобильной
 * связи и своей же квотой у Google. Уменьшенный снимок отвечает на тот же
 * вопрос не хуже: порция читается по тарелке и вилке рядом, а не по
 * разрешению.
 *
 * Нигде не сохраняется. Ни файла, ни ссылки, ни строки в базе: снимок живёт
 * ровно от выбора до ответа. Временная ссылка на файл отзывается тут же —
 * иначе браузер держал бы его в памяти до перезагрузки страницы.
 *
 * Через `<img>`, а не через `createImageBitmap`: айфон отдаёт снимки в HEIC,
 * и разобрать их умеет только сам браузер — картинкой, а не декодером.
 */

import { t } from './i18n.js';

/**
 * Длинная сторона после уменьшения.
 *
 * Тысяча точек: на ней видно и тарелку, и вилку рядом, и что лежит поверх, —
 * то есть всё, из чего вообще выводится размер порции. Дальше растёт только
 * вес файла.
 */
const СТОРОНА = 1024;

/**
 * Насколько бережно жать.
 *
 * 0,8 — на глаз неотличимо от исходника, а весит впятеро меньше. Ниже
 * начинают плыть границы, и на тесной тарелке перестаёт быть понятно, где
 * кончается одно и начинается другое.
 */
const КАЧЕСТВО = 0.8;

export const photo = {

    СТОРОНА,
    КАЧЕСТВО,

    /**
     * Уменьшить и пережать в JPEG.
     *
     * Возвращает `{ mime, data, width, height }`, где data — основание 64 без
     * приставки `data:`: именно в таком виде его ждёт Google, и отрезать
     * приставку в месте отправки значило бы знать там про способ чтения.
     *
     * JPEG всегда, чем бы ни был исходник: PNG со снимка экрана весит втрое
     * больше при том же содержании, а прозрачности у фотографии еды не
     * бывает.
     */
    async shrink(file, { max = СТОРОНА, quality = КАЧЕСТВО } = {}) {
        if (!file) throw new Error(t('Снимок не выбран.'));

        const ссылка = URL.createObjectURL(file);

        try {
            const картинка = await new Promise((готово, беда) => {
                const img = new Image();

                img.onload = () => готово(img);
                img.onerror = () => беда(new Error(t('Снимок не прочитался. Попробуйте другой.')));

                img.src = ссылка;
            });

            const ширина = картинка.naturalWidth || картинка.width;
            const высота = картинка.naturalHeight || картинка.height;

            if (!(ширина > 0 && высота > 0)) throw new Error(t('Снимок не прочитался. Попробуйте другой.'));

            /*
             * Маленькое не растягивается.
             *
             * Дорисованные точки не добавляют сведений — только вес файла и
             * ложное впечатление подробности.
             */
            const доля = Math.min(1, max / Math.max(ширина, высота));

            const холст = document.createElement('canvas');

            холст.width = Math.max(1, Math.round(ширина * доля));
            холст.height = Math.max(1, Math.round(высота * доля));

            холст.getContext('2d').drawImage(картинка, 0, 0, холст.width, холст.height);

            const строка = холст.toDataURL('image/jpeg', quality);

            return {
                mime: 'image/jpeg',
                data: строка.slice(строка.indexOf(',') + 1),
                width: холст.width,
                height: холст.height
            };
        } finally {
            URL.revokeObjectURL(ссылка);
        }
    }
};
