/**
 * Виброотклик на закреплённое действие (§28.1 ТЗ).
 *
 * Не на каждое нажатие. Вибрация, отвечающая на всё подряд, перестаёт что-либо
 * означать и превращается в шум под пальцем — она нужна ровно там, где
 * приложение что-то записало и обратного хода уже нет: подход записан, план
 * утверждён, тренировка закрыта.
 *
 * Отклик коротким импульсом, а не узором. Узор — это сообщение, и он уместен
 * в конце отдыха, куда человек не смотрит (§16). Здесь человек смотрит на
 * экран и уже видит результат: вибрация только подтверждает, что нажатие
 * дошло, и должна быть на грани заметности.
 *
 * Выключателем служит та же настройка, что и у отдыха. Двух переключателей
 * вибрации в профиле быть не должно: человек решает, хочет ли он вибрацию
 * вообще, а не отдельно про отдых и отдельно про подходы.
 */

import { config } from '../config.js';

/**
 * Длительность импульса.
 *
 * Пятнадцать миллисекунд — щелчок, а не гудок. Всё, что длиннее сорока,
 * читается как сигнал и начинает спорить с сигналом конца отдыха.
 */
const TAP = 15;

export const haptics = {

    TAP,

    /**
     * Короткий отклик. Возвращает, случился ли он.
     *
     * Молча возвращает false там, где вибрации нет: на iPhone Safari
     * navigator.vibrate не поддерживается вовсе, и это не ошибка, а
     * особенность устройства. Вызывающему знать об этом незачем — он
     * записывает подход, а не проверяет железо.
     */
    tap(pattern = TAP) {
        if (!config.get('restVibration')) return false;
        if (!navigator.vibrate) return false;

        try {
            return navigator.vibrate(pattern);
        } catch {
            // Некоторые браузеры бросают при вызове из фона — это не повод
            // ронять запись подхода
            return false;
        }
    }
};
