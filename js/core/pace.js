/**
 * Темп по прошлому разу: подсказка внутри интервальной программы (§50.3, Р-178).
 *
 * В табате нечего решать по ходу — порядок и время заданы заранее. Решать
 * приходится одно, и решается это в первые секунды первого круга: с какого
 * числа начать. Ошибка здесь стоит всей тренировки. Начал слишком бодро —
 * к третьему кругу числа рассыпались, и вместо ровной работы вышел один
 * тяжёлый подход и два вялых. Начал осторожно — прошёл всю программу с
 * запасом и не тронул то, ради чего её делали.
 *
 * Правильное число знает только прошлый раз, и знает совершенно точно.
 *
 *   **Числа росли** (15 → 16 → 17) — до предела не дошли ни разу: запас был
 *   даже в последнем круге. Начинать надо с того, чем кончили.
 *
 *   **Числа падали** (24 → 20 → 18) — начали быстрее, чем держится. Тот же
 *   ответ: с того, чем кончили, — это единственное число, которое человек
 *   выдал уже уставшим, и потому единственное, за которое можно ручаться.
 *
 *   **Линия ровная** — темп угадан, и менять его незачем.
 *
 * Отсюда одно правило на все три случая: **цель — последний круг прошлого
 * раза**. Различается не число, а объяснение, почему оно такое; объяснение
 * и делает подсказку подсказкой, а не приказом.
 *
 * Чего здесь нет: совета прибавить. Прибавка в интервальной работе живёт не
 * в числе повторений, а в амплитуде, темпе и числе кругов, и приложение,
 * увидевшее «17 → 18», не отличит выросшую силу от укоротившегося приседа.
 * Ровная линия — это уже успех, и сказано ровно это.
 */

import { t } from './i18n.js';

/**
 * Разброс, внутри которого линию считаем ровной.
 *
 * Доля, а не постоянное число: единица разницы у пятнадцати приседаний и у
 * пятидесяти прыжков — это разные вещи. Нижняя граница всё равно единица —
 * ниже неё различать нечего, повторения целые.
 */
const ШУМ = (первое) => Math.max(1, Math.round(первое * 0.05));

export const pace = {

    ШУМ,

    /**
     * Числа упражнения из прошлой тренировки.
     *
     * sets — подходы одного упражнения, новые первыми (`listSetsByExercise`).
     * exclude — тренировка, которая идёт сейчас: её подходы ещё пустые, и
     * сравнивать себя с самим собой смысла нет.
     *
     * Возвращает { numbers, first, last, rounds, trend } или null.
     *
     * Берётся одна тренировка, а не среднее по нескольким. Среднее сгладило
     * бы ровно то, ради чего всё считается: форма линии внутри одного захода
     * и есть ответ, а по двум заходам подряд она размажется в прямую.
     */
    read(sets = [], { exclude = null } = {}) {
        const чужие = sets.filter((s) => s && s.workoutId && s.workoutId !== exclude);
        if (чужие.length === 0) return null;

        // Новые первыми — значит прошлая тренировка это первая же чужая
        const прошлая = чужие[0].workoutId;

        const numbers = чужие
            .filter((s) => s.workoutId === прошлая)
            .sort((a, b) => (a.setNumber || 0) - (b.setNumber || 0))
            .map((s) => Number(s.reps))
            .filter((n) => Number.isFinite(n) && n > 0);

        /*
         * Повторений может не быть вовсе, и это обычное дело: интервальный
         * экран их не пишет — считать, не трогая телефон, нельзя, — и
         * проставляют их потом, на итогах (§50). Молчим, а не показываем
         * пустую подсказку: сказать нечего, значит строки нет.
         */
        if (numbers.length === 0) return null;

        const first = numbers[0];
        const last = numbers[numbers.length - 1];

        const разница = last - first;
        const порог = ШУМ(first);

        const trend = numbers.length < 2 ? 'single'
            : разница > порог ? 'rise'
            : разница < -порог ? 'fall'
            : 'flat';

        return { numbers, first, last, rounds: numbers.length, trend };
    },

    /**
     * Подсказка целой фразой — для паузы, когда есть время прочесть.
     *
     * Фраза называет и числа, и вывод из них: одна цель без объяснения
     * читается как требование неизвестно откуда, а объяснение без цели
     * оставляет решать на ходу — то самое, чего в двадцати секундах не
     * сделать.
     */
    line(темп) {
        if (!темп) return '';

        const { first, last, trend } = темп;

        const n = (v) => String(v);

        if (trend === 'single') return t('Прошлый раз — {n}.', { n: n(last) });

        if (trend === 'rise') {
            return t('Прошлый раз {от} → {до} — был запас. Начните с {до}.',
                { от: n(first), до: n(last) });
        }

        if (trend === 'fall') {
            return t('Прошлый раз {от} → {до} — начали быстро. Держите {до}.',
                { от: n(first), до: n(last) });
        }

        return t('Прошлый раз ровно {n} — держите.', { n: n(last) });
    },

    /**
     * То же самое в одно слово с числом — для работы.
     *
     * Двадцать секунд приседаний не оставляют времени на чтение фразы, а
     * число с вытянутой руки читается целиком. Объяснение уже прозвучало в
     * паузе перед этим отрезком, и повторять его некогда и некуда.
     */
    aim(темп) {
        if (!темп) return '';

        return t('держите {n}', { n: String(темп.last) });
    }
};
