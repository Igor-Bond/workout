/**
 * Свёрнутый текст под заголовком карточки (§45, Р-168).
 *
 * Карточек с выводами на экранах стало три, и все они текстовые: «Как идёт
 * программа», «Что изменилось» и разбор данных с часов. Каждая по отдельности
 * коротка и по делу, а вместе они дают несколько абзацев подряд в самом
 * начале страницы — ровно там, где человек ищет числа. Читать такое начинают
 * не сразу, а перестают быстро.
 *
 * Поэтому текст сворачивается, и сворачивает его сам заголовок: отдельная
 * кнопка рядом с названием была бы второй вещью, которую надо разглядеть, а
 * название и так стоит там, куда смотрят.
 *
 * **Свёрнутость помнится на устройстве.** Иначе это не настройка, а
 * упражнение: сворачивать одно и то же при каждом заходе. И именно на
 * устройстве, а не в облаке (§39.1): на телефоне текст мешает, на широком
 * экране — нет, и решать это человек вправе порознь.
 *
 * Разворачивается по умолчанию. Свёрнутая с первого дня карточка — это
 * карточка, которой человек никогда не увидит; один раз показать и дать
 * убрать честнее, чем прятать заранее.
 *
 * Здесь и разметка, и память, и обработчик: свёртка — одна вещь, и
 * разнесённая по трём файлам она разошлась бы при первой же правке.
 */

import { ui } from './ui.js';
import { actions } from './actions.js';
import { config } from '../config.js';

/** Под каким ключом в настройках лежат свёрнутые блоки. */
const КЛЮЧ = 'folded';

export const fold = {

    /** Свёрнут ли блок с этим именем. */
    is(name) {
        const свёрнутые = config.get(КЛЮЧ);
        return !!(свёрнутые && свёрнутые[name]);
    },

    /**
     * Заголовок карточки, он же кнопка свёртки.
     *
     * Подпись остаётся подписью: кнопка названа тем же словом, что и карточка,
     * а не значком — по значку не понять, что он свернёт (Р-151).
     */
    title(name, подпись) {
        const свёрнуто = fold.is(name);

        return ui.html`
            <button class="card-title card-fold ${свёрнуто ? 'is-folded' : ''}"
                    data-action="fold" data-key="${name}"
                    aria-expanded="${свёрнуто ? 'false' : 'true'}">
                ${подпись}
            </button>
        `;
    },

    /** То, что сворачивается. Кладётся в ту же карточку, что и заголовок. */
    body(name, содержимое) {
        return ui.html`
            <div class="fold-body ${fold.is(name) ? 'is-folded' : ''}">${содержимое}</div>
        `;
    }
};

/*
 * Правим узлы, а не перерисовываем экран (Р-142).
 *
 * Перерисовка кондиций читает всю таблицу подходов, все сводки и все замеры —
 * полсекунды на пяти годах истории. Свёртка текста столько стоить не должна,
 * а менять ей нужно ровно два класса.
 */
actions.on('fold', (el) => {
    const name = el.dataset.key;
    if (!name) return;

    const свёрнутые = { ...(config.get(КЛЮЧ) || {}) };
    const теперь = !свёрнутые[name];

    свёрнутые[name] = теперь;
    config.set(КЛЮЧ, свёрнутые);

    el.classList.toggle('is-folded', теперь);
    el.setAttribute('aria-expanded', теперь ? 'false' : 'true');

    el.closest('.card')?.querySelector('.fold-body')?.classList.toggle('is-folded', теперь);
});
