/**
 * Что изменилось — итог кондиций одной-тремя строками (§66, Р-167).
 *
 * Второй по счёту модуль наблюдений, и отделить его от первого надо сразу.
 *
 *   «Как идёт программа» (js/core/progress.js) отвечает на **«что делать
 *   дальше»**: прибавить вес, вы отстаёте от сетки, объём просел, спали мало.
 *   Живёт на статистике, рядом с тренировками, и читается перед занятием.
 *
 *   Здесь — **«что изменилось»**: куда идёт тело, укладываетесь ли в своё же
 *   питание, не забыта ли группа мышц, не прибавили ли слишком резко. Живёт
 *   на кондициях и читается раз в неделю, с вопросом «куда всё идёт».
 *
 * Делить их пришлось не из аккуратности. Два экрана, говорящих об одном и том
 * же разными словами, хуже одного неверного: после такого не верят обоим
 * (Р-159, Р-162). Поэтому сон и пульс покоя сюда не берутся вовсе — они там,
 * где по ним принимают решение.
 *
 * Правило экрана держится и здесь: **говорим только о том, у чего есть
 * основание**, и называем его в той же строке. Сказать нечего — строки нет, а
 * «всё в порядке» от приложения, смотрящего на десяток величин, читается как
 * «оно не работает».
 */

import { t } from './i18n.js';
import { format } from './format.js';
import { health } from './health.js';

/**
 * Сколько недель молчания делают группу забытой.
 *
 * Две: одна пропущенная неделя — это командировка или спина, и объявлять по
 * ней «вы забыли спину» значило бы дёргать человека по любому поводу. Две
 * подряд — уже перекос, и о нём стоит сказать, пока он не стал месяцем.
 */
const ЗАБЫТО = 2;

/** Сколько строк показываем. Больше трёх — это уже не итог, а вторая карточка. */
const СТРОК = 3;

export const digest = {

    ЗАБЫТО,
    СТРОК,

    /**
     * Наблюдения о состоянии. Возвращает [{ kind, text }] — пустой массив,
     * если сказать нечего.
     *
     * Порядок внутри — по важности: сначала то, за чем надо присмотреть,
     * потом то, что просто идёт своим чередом. Забытая группа стоит первой
     * среди тревожных: её видно только здесь, а остальное человек так или
     * иначе заметит по плиткам.
     */
    condition({ body = null, intake = null, forgotten = null, ramp = null } = {}) {
        const строки = [];

        // ---------- забытая группа ----------
        if (forgotten && forgotten.weeks >= ЗАБЫТО && forgotten.name) {
            строки.push({
                kind: 'watch',
                text: t('{группа}: {срок} без единого подхода.', {
                    группа: t(forgotten.name),
                    срок: format.count(forgotten.weeks, format.WORDS.week)
                })
            });
        }

        // ---------- разгон ----------
        if (ramp && Number.isFinite(ramp.value) && ramp.state === health.СМОТРЕТЬ) {
            const [низ, верх] = health.RAMP;

            строки.push({
                kind: 'watch',
                text: ramp.value > верх
                    ? t('Разгон {n} — неделя прибавила резко, ориентир до {верх}.', {
                        n: format.plain(ramp.value), верх: format.plain(верх)
                    })
                    : t('Разгон {n} — вы сбавили, ориентир от {низ}.', {
                        n: format.plain(ramp.value), низ: format.plain(низ)
                    })
            });
        }

        // ---------- питание ----------
        if (intake && Number.isFinite(intake.average) && Number.isFinite(intake.ceiling)) {
            const перебор = intake.average > intake.ceiling;

            строки.push({
                kind: перебор ? 'watch' : 'ok',
                text: перебор
                    ? t('Съедено в среднем {среднее} в день при вашем потолке {потолок}.', {
                        среднее: format.decimal(intake.average, 0),
                        потолок: format.decimal(intake.ceiling, 0)
                    })
                    : t('Съедено в среднем {среднее} в день — в пределах вашего потолка {потолок}.', {
                        среднее: format.decimal(intake.average, 0),
                        потолок: format.decimal(intake.ceiling, 0)
                    })
            });
        }

        // ---------- потолок против весов ----------
        const проверка = digest.check(body, intake);
        if (проверка) строки.push(проверка);

        // ---------- тело ----------
        const телом = digest.body(body);
        if (телом) строки.push(телом);

        /*
         * Тревожное вперёд, остальное следом — порядок внутри каждой половины
         * сохраняется. Это тот же приём, что и у «Как идёт программа»: первое
         * меняет ближайшие дни, последнее объясняет месяц.
         */
        return [
            ...строки.filter((с) => с.kind === 'watch'),
            ...строки.filter((с) => с.kind !== 'watch')
        ].slice(0, СТРОК);
    },

    /**
     * Потолок проверяется весами (§68, Р-175).
     *
     * Дефицит опирается на суточный расход, а тот — на коэффициент активности
     * с грубыми ступенями: одна перепутанная ступень стоила шестисот
     * килокалорий (Р-154). Приложение красит съеденное по такому потолку — и
     * обязано само сказать, когда его собственная оценка не сходится с
     * действительностью.
     *
     * Сходится или нет, показывают весы, и только они. Месяц в пределах
     * потолка при стоящем весе означает ровно одно: числа врут. Какое из двух
     * — расход завышен или съеденное записано не всё, — приложение не знает и
     * не выбирает за человека, а называет оба.
     */
    check(body, intake) {
        if (!intake || !Number.isFinite(intake.average) || !Number.isFinite(intake.ceiling)) return null;
        if (intake.average > intake.ceiling) return null;

        const дельта = body?.weight?.delta;

        // Ход есть — проверять нечего: расход сходится с весами
        if (!Number.isFinite(дельта) || Math.abs(дельта) > health.ШУМ.weight) return null;

        return {
            kind: 'watch',
            text: t('Месяц держите потолок, а вес стоит. Значит числа не сходятся: либо суточный расход посчитан выше вашего, либо съедено записано не всё. Верить тут стоит весам.')
        };
    },

    /**
     * Ход тела за месяц одной строкой.
     *
     * Вес и талия вместе, потому что порознь они отвечают наполовину: вес
     * неделями стоит, пока жир уходит, а мышцы приходят. Направление берётся
     * из отметки, которую уже поставили кондиции, — второй раз решать, куда
     * человеку хорошо, здесь незачем.
     */
    body(body) {
        if (!body) return null;

        /*
         * Каждая величина названа своим именем прямо в куске.
         *
         * «За месяц: −1,5» — это про что? Пара «вес −1,5 кг» читается без
         * заголовка, а строка итога заголовка и не имеет.
         */
        const кусок = (что, значение, единица) => (Number.isFinite(значение) && значение !== 0
            ? t('{что} {знак}{n} {единица}', {
                что,
                знак: значение > 0 ? '+' : '−',
                n: format.weight(Math.abs(значение)),
                единица
            })
            : '');

        const вес = кусок(t('вес'), body.weight?.delta, t('кг'));
        const талия = кусок(t('талия'), body.waist?.delta, t('см'));

        const части = [вес, талия].filter(Boolean);

        if (части.length === 0) return null;

        // Отметку берём у той величины, которая и правда сдвинулась
        const отметка = вес ? body.weight?.state : body.waist?.state;

        const ход = t('За месяц {части}.', { части: части.join(', ') });

        if (отметка === health.ХОРОШО) {
            return { kind: 'ok', text: `${ход} ${t('Идёте, куда собирались.')}` };
        }

        if (отметка === health.СМОТРЕТЬ) {
            return { kind: 'watch', text: `${ход} ${t('Это в другую сторону от цели.')}` };
        }

        return { kind: 'plain', text: ход };
    }
};
