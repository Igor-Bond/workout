/**
 * Сутки без ловушки перевода часов (Р-218).
 *
 * День — это не 86 400 секунд. В ночь перевода часов он длится 25 или 23 часа,
 * и всё, что считало «шесть дней назад» как шесть раз по 86 400 000
 * миллисекунд, после осени попадало на час позже полуночи, а после весны — на
 * час раньше. Метка такого дня не совпадает ни с ключом набора дней, ни с
 * клеткой карты, ни с днём недели плана: на главном подсвечивался один
 * сегодняшний день, на карте не оказывалось тренировок, а развёртка плана
 * теряла понедельник.
 *
 * Поэтому здесь две меры, на которых стоит всё остальное: полночь дня и
 * «через столько-то календарных дней». Модуль без зависимостей намеренно:
 * им пользуются и чистое ядро, и экраны.
 */

/** Полночь того дня, которому принадлежит момент. */
export const startOfDay = (ts) => {
    const d = new Date(ts);
    d.setHours(0, 0, 0, 0);
    return d.getTime();
};

/**
 * Тот же час через n календарных дней (n может быть отрицательным).
 *
 * Через `setDate`, а не через прибавку миллисекунд: календарь сам знает,
 * сколько часов в этом дне. От полуночи получается полночь.
 */
export const addDays = (ts, n) => {
    const d = new Date(ts);
    d.setDate(d.getDate() + n);
    return d.getTime();
};
