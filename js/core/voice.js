/**
 * Название следующего упражнения вслух (§50).
 *
 * Единственное место в приложении, где оно говорит словами. Причина
 * узкая: в интервальной программе смена упражнений — это тот самый момент,
 * когда на экран не смотрят. Тон сообщает, что работа кончилась, но не
 * говорит, к чему готовиться, и на смене приходится искать телефон глазами.
 *
 * Голос — добавка к сигналам, а не замена им. Тоны выкладываются в звуковой
 * движок заранее и потому переживают придержанный в фоне таймер; речь так
 * выложить нельзя — она произносится в тот момент, когда её попросили. Пока
 * экран горит (а на программе он горит, §28), это работает; телефон в
 * кармане — нет. Поэтому всё важное сказано тонами, а голос лишь называет.
 *
 * Голоса нужного языка на устройстве может не быть вовсе. Тогда молчим:
 * сказать «бёрпи» английской фонетикой хуже, чем не сказать ничего.
 */

import { config } from '../config.js';
import { i18n } from './i18n.js';

/** Найденный голос на каждый язык. Ищется один раз и запоминается. */
const found = new Map();

/**
 * Поиск голоса под язык приложения.
 *
 * Язык именно приложения, а не телефона: фразы приходят с экрана, и
 * английский текст, прочитанный русским голосом, не разобрать. Раньше
 * искался только русский — на немецком телефоне, где русского голоса может
 * не быть вовсе, программа замолкала целиком.
 *
 * Список голосов браузер отдаёт не сразу: при первом обращении он часто
 * пуст и наполняется позже, событием voiceschanged. Поэтому поиск не
 * запоминается, пока список пуст, — иначе первый же вопрос навсегда
 * ответил бы «голосов нет».
 */
function forLang(lang) {
    if (found.has(lang)) return found.get(lang);

    const list = speechSynthesis.getVoices();
    if (!list || list.length === 0) return null;

    const match = list.find((v) => new RegExp(`^${lang}`, 'i').test(v.lang)) || null;

    found.set(lang, match);
    return match;
}

export const voice = {

    get available() {
        return typeof speechSynthesis !== 'undefined'
            && typeof SpeechSynthesisUtterance !== 'undefined';
    },

    /**
     * Разрешение на речь, взятое с нажатия.
     *
     * Safari разрешает синтез только начатый из обработчика нажатия, и
     * первая же фраза, сказанная по таймеру, оказалась бы беззвучной —
     * вместе со всеми следующими. Пустая фраза без громкости снимает
     * запрет, ничего не произнося.
     */
    prime() {
        if (!voice.available) return false;

        try {
            const u = new SpeechSynthesisUtterance(' ');
            u.volume = 0;
            speechSynthesis.speak(u);
            return true;
        } catch {
            return false;
        }
    },

    /**
     * Сказать. Возвращает, прозвучало ли — по этому же признаку проверки
     * отличают «выключено» от «сказано».
     */
    say(text) {
        if (!voice.available || !text) return false;

        // Общий выключатель звука один: молчаливая программа не должна
        // внезапно заговорить
        if (!config.get('restSound') || !config.get('voiceNames')) return false;

        const голос = forLang(i18n.lang);
        if (!голос) return false;

        try {
            const u = new SpeechSynthesisUtterance(text);
            u.voice = голос;
            u.lang = голос.lang;
            u.rate = 1;
            u.volume = 1;

            /*
             * Обрывать нужно только то, что звучит.
             *
             * Недосказанное с прошлой смены обрывать обязательно: очередь
             * фраз отстала бы от программы и называла упражнение, которое
             * уже кончилось. Но cancel() и следом speak() в ту же
             * миллисекунду Chrome нередко съедает целиком — обрывается не
             * прошлая фраза, а новая.
             *
             * Именно на это попадала первая фраза программы: сразу после
             * разрешения на речь, взятого с нажатия, — то есть подготовка
             * оставалась беззвучной, а все следующие паузы звучали. Теперь
             * впустую не обрываем, а после настоящего обрыва даём движку
             * вздохнуть.
             */
            if (speechSynthesis.speaking || speechSynthesis.pending) {
                speechSynthesis.cancel();
                setTimeout(() => {
                    try { speechSynthesis.speak(u); } catch { /* движок отказал */ }
                }, 80);
            } else {
                speechSynthesis.speak(u);
            }

            return true;
        } catch {
            return false;
        }
    },

    /** Замолчать — на паузе, пропуске и уходе с экрана. */
    stop() {
        if (!voice.available) return;

        try { speechSynthesis.cancel(); } catch { /* нечего обрывать */ }
    }
};
