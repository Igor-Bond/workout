/**
 * Сколько тренировочных дней плана можно пропустить, прежде чем об этом
 * говорить.
 *
 * Один пропуск за две недели — это жизнь: командировка, ребёнок, работа.
 * Два — уже расхождение с программой, о котором стоит знать, пока оно не
 * стало тремя.
 */
export const MISSED = 2;

/** На сколько должен просесть объём, чтобы это было спадом, а не колебанием. */
export const DROP = 0.25;

/**
 * Прибавка, после которой это уже не успех, а разгон (§63, §66, Р-159).
 *
 * Половина сверху за неделю — это отношение 1,5 к прошлой.
 *
 * **Черту провело приложение, а не исследование** (Р-175). В работах о
 * нагрузке — у Гэббета и тех, кто считал после него, — отношение берут
 * недельное к четырёх- или шестинедельному, и полтора там означает совсем
 * другое сравнение. Числа для пары соседних недель в них нет вовсе.
 *
 * Черту всё равно надо где-то провести: без неё нельзя сказать ничего. Но
 * называть её ориентиром, будто она откуда-то взята, нечестно — и в самом
 * наблюдении теперь сказано, чья она.
 *
 * До этой черты прибавка называется прибавкой. За ней приложение говорило
 * «выше на 127 %» тем же зелёным, каким хвалит выполненный план, — и
 * спорило само с собой: на соседнем экране ровно тот же скачок считается
 * лучшим известным признаком того, что человек вот-вот сорвётся.
 */
export const RAMP = 0.5;

/**
 * Сколько упражнений называть про запас своей строкой (Р-207).
 *
 * Остальное здесь — по строке на вид наблюдения, и только запас растёт без
 * меры: по строке на каждое упражнение. Шесть упражнений с большим запасом
 * давали шесть строк, и исполнение плана с объёмом уезжали под них — туда,
 * куда уже не дочитывают. У итога кондиций предел есть давно (Р-167): больше
 * трёх строк — это уже не итог, а вторая карточка.
 *
 * Две своими строками, с кнопкой и способом; остальные — одной строкой по
 * именам. Число и совет с числами у каждого и так стоят на выполнении (§59).
 */
export const ЗАПАС_СТРОК = 2;

/** Ниже этого сон считается коротким. Семь часов — общая нижняя граница. */
export const SHORT_SLEEP = 7 * 3600;

/**
 * Что значит «тяжелее» у упражнения этого рода (§59, Р-206).
 *
 * «Можно тяжелее» у приседаний своим весом читалось как «возьмите груз» —
 * а груза нет, и прибавляют там повторениями. Слово называет способ, и
 * способ берётся из того же места, что и числа в окне прибавки
 * (`reserve.step`): разойтись им не на чем.
 *
 * Функциями: язык меняется на ходу.
 */
export const ТЯЖЕЛЕЕ = {
    weight: () => t('можно добавить вес'),
    resistance: () => t('можно взять резинку жёстче'),
    reps: () => t('можно прибавить повторения'),
    time: () => t('можно прибавить время')
};

/**
 * Какая часть заявленного числа считается недобором (§63, Р-216).
 *
 * Подход ниже восьми десятых плана — не промах на пару повторений, а число,
 * которое человек на этом упражнении не держит. Разброс внутри этих двадцати
 * процентов — обычная жизнь: сегодня 24 из 25, завтра 25.
 */
export const SHORT_SET = 0.8;

/** Цели меньше этой недобором не меряются: у «3 × 3» восемь десятых — это одно повторение. */
const SHORT_MIN_TARGET = 5;

/** Сколько недоборов называть своими строками (Р-216); остальные — одной строкой по именам. */
export const НЕДОБОР_СТРОК = 2;

/**
 * Во сколько раз подход должен превзойти цель, чтобы это было перевыполнением
 * (Р-220): на пятую часть и не меньше чем на два повторения (пять секунд у
 * времени). «Сделал 16 из 15» — это разброс, а «20 из 15» — другое число.
 */
export const OVER_SET = 1.2;

/** Что считать меньшим превышением: у повторений два, у секунд пять. */
const OVER_MIN = { reps: 2, duration: 5 };

/** Цели меньше этой не меряются: у планки в пять секунд восемь десятых — это секунда. */
const MIN_TARGET = { reps: SHORT_MIN_TARGET, duration: 10 };

/**
 * Что план просил по этому упражнению и что вышло — для недобора и
 * перевыполнения одним разбором (Р-216, Р-220).
 *
 * Меряются повторения, а у упражнения на время — секунды: планка тоже
 * бывает не по плану, и в плане «Планка 3 × 45» сорок пять — те же сорок
 * пять секунд, что записал подход. Без цели или меньше порога — пропуск.
 *
 * Подходы идут по номеру, а не по порядку записи. Меньше двух подходов не
 * судим: по одному вывода нет.
 */
function замеры(plan = [], sets = []) {
    const итог = [];

    for (const item of plan) {
        if (!item || item.skipped) continue;

        const field = Number(item.targetReps) > 0 ? 'reps' : Number(item.targetDuration) > 0 ? 'duration' : null;
        if (!field) continue;

        const target = Number(field === 'reps' ? item.targetReps : item.targetDuration);
        if (!(target >= MIN_TARGET[field])) continue;

        const done = sets
            .filter((s) => s && s.exerciseId === item.exerciseId && !s.deletedAt && Number(s[field]) > 0)
            .sort((a, b) => (a.setNumber || 0) - (b.setNumber || 0))
            .map((s) => Number(s[field]));

        if (done.length < 2) continue;

        const ряд = [...done].sort((a, b) => a - b);
        const середина = ряд.length % 2
            ? ряд[(ряд.length - 1) / 2]
            : (ряд[ряд.length / 2 - 1] + ряд[ряд.length / 2]) / 2;

        итог.push({
            item, field, target, done, середина,
            plannedSets: Number(item.plannedSets) || done.length
        });
    }

    return итог;
}

export const progress = {

    MISSED,
    DROP,
    RAMP,
    SHORT_SLEEP,

    /**
     * Где план не выполнен по числам (§63, Р-216).
     *
     * План знает, сколько и по скольку, факт знает, что вышло, — а друг с
     * другом они не сравнивались. Человек делал программу, не осилил одно
     * упражнение, и приложение молчало: «выполнено 1 из 1» считает дни, а не
     * числа. Недобор виден сразу, как только числа положить рядом.
     *
     * plan — состав тренировки ([{ exerciseId, plannedSets, targetReps, skipped }]);
     * sets — подходы этой же тренировки; names — id → название;
     * earlier — упражнения, которые человек делал до этой тренировки.
     *
     * Недобор — когда не меньше половины сделанных подходов (и не меньше двух)
     * ниже восьми десятых цели. Один слабый подход в конце — усталость, два
     * подряд — число, которого нет.
     *
     * Предлагаемая цель — середина сделанного (медиана), но ниже прежней:
     * человек показал, что держит именно это.
     *
     * Возвращает [{ exerciseId, name, target, plannedSets, done, suggest,
     * lack, firstTime }], где lack — на сколько процентов меньше плана, а
     * firstTime — упражнение сделано впервые, и число в плане было прикидкой.
     */
    shortfall(plan = [], sets = [], { names = {}, earlier = new Set() } = {}) {
        const итог = [];

        for (const { item, field, target, done, середина, plannedSets } of замеры(plan, sets)) {
            const ниже = done.filter((r) => r < target * SHORT_SET).length;
            if (ниже < Math.max(2, Math.ceil(done.length / 2))) continue;

            const всего = done.reduce((a, b) => a + b, 0);

            итог.push({
                exerciseId: item.exerciseId,
                name: names[item.exerciseId] || t('упражнение'),
                field,
                target,
                plannedSets,
                done,
                suggest: Math.max(1, Math.min(target - 1, Math.round(середина))),
                lack: Math.max(1, Math.round((1 - всего / (plannedSets * target)) * 100)),
                firstTime: !earlier.has(item.exerciseId)
            });
        }

        return итог;
    },

    /**
     * Где сделано больше плана (§63, Р-220) — зеркало недобора.
     *
     * Человек сделал в субботу двадцать приседаний вместо пятнадцати и планку
     * дольше плана, а на следующий раз пришлось добавлять опять: приложение
     * знало и план, и факт, но нигде их не сравнивало в эту сторону. Запас по
     * ответам «легко» тут не нужен: цифра выше цели — сама по себе ответ.
     *
     * Перевыполнение — когда не меньше половины сделанных подходов (и не
     * меньше двух) выше цели на пятую часть и больше, не меньше чем на два
     * повторения. Предлагаемая цель — середина сделанного, но выше прежней.
     *
     * Возвращает то же, что `shortfall`, но с `more` — на сколько процентов
     * больше плана, — вместо `lack`.
     */
    overshoot(plan = [], sets = [], { names = {}, earlier = new Set(), steps = {} } = {}) {
        const итог = [];

        for (const { item, field, target, done, середина, plannedSets } of замеры(plan, sets)) {
            const выше = done.filter((r) => r >= target * OVER_SET && r >= target + OVER_MIN[field]).length;
            if (выше < Math.max(2, Math.ceil(done.length / 2))) continue;

            итог.push({
                exerciseId: item.exerciseId,
                name: names[item.exerciseId] || t('упражнение'),
                field,
                target,
                plannedSets,
                done,
                suggest: Math.max(target + 1, Math.round(середина)),
                more: Math.max(1, Math.round((середина / target - 1) * 100)),

                // Чем прибавлять (§59, Р-206): у резинки и снаряда повторения растить нельзя
                step: steps[item.exerciseId] || (field === 'duration' ? 'time' : 'reps'),
                firstTime: !earlier.has(item.exerciseId)
            });
        }

        return итог;
    },

    /**
     * Наблюдения о ходе программы.
     *
     * Каждое — { kind, text }, где kind нужен показу, чтобы отличить хорошее
     * от требующего внимания, а не для толкования: слово в text полное и
     * самодостаточное.
     *
     * Порядок не случаен: сперва тело (запас, восстановление), потом
     * исполнение плана, потом объём. Первое меняет сегодняшнюю тренировку,
     * последнее — разговор с тренером через месяц.
     */
    describe({ reserve = [], recovery = null, adherence = null, volume = null, shortfalls = [], overshoots = [] } = {}) {
        const строки = [];

        /*
         * Восстановление против прибавки — и тогда оно говорит первым (Р-206).
         *
         * Совпадение двух признаков, а не любой из них: короткий сон бывает
         * от кино, высокий пульс покоя — от кофе, и порознь они значат мало.
         * Вместе — это неделя, в которую добавлять нагрузку не стоит.
         *
         * Стояло оно под строкой «можно тяжелее», а у той была кнопка
         * «принять прибавку». Нажатие одним движением правило план — и ничего
         * не знало о доводе строкой ниже, которого человек, нажав, уже не
         * читал. Приложение предлагало прибавку и тут же отговаривало от неё,
         * не связав одно с другим: две подсказки об одном говорили разное
         * (Р-72). Теперь довод стоит выше, а кнопки в такую неделю нет.
         */
        const противПрибавки = !!(recovery?.shortSleep && recovery?.highResting);

        if (противПрибавки) {
            строки.push({
                topic: 'recovery',
                kind: 'down',
                text: t('Сон короче обычного и пульс покоя выше — неделя не для прибавки.')
            });
        }

        /*
         * Запас в подходе — единственное, что говорит про сегодня.
         *
         * Правило прогрессии (§59) считается по упражнению, и упражнений
         * может быть несколько; называем каждое своим именем — «пора тяжелее»
         * без имени человек отнесёт ко всей программе разом. И называем
         * способ (Р-206): у приседаний своим весом «тяжелее» — это больше
         * повторений, а не груз, которого нет.
         *
         * Своей строкой — не больше двух (Р-207), и потерянный запас идёт
         * раньше большого: он про то, что уже тяжело. Внутри — в том
         * порядке, в каком упражнения пришли: собирающий ставит частые
         * вперёд.
         */
        /*
         * Способ не назван — значит снаряд, как и везде в приложении. А вот
         * названный пустым — это кардио (Р-206): «повторения в запасе» к нему
         * не относятся, и о прибавке по ним молчим.
         */
        const годные = reserve
            .map((r) => ({ ...r, step: r.step === undefined ? 'weight' : r.step }))
            .filter((r) => r.verdict === 'easier' || (r.verdict === 'harder' && ТЯЖЕЛЕЕ[r.step]));

        const поПорядку = [
            ...годные.filter((r) => r.verdict === 'easier'),
            ...годные.filter((r) => r.verdict === 'harder')
        ];

        const поимённо = поПорядку.slice(0, ЗАПАС_СТРОК);
        const прочие = поПорядку.slice(ЗАПАС_СТРОК);

        for (const { name, verdict, step = 'weight', first = false, lower = null } of поимённо) {
            if (verdict === 'harder') {
                /*
                 * Впервые — после одного занятия, а не двух (Р-219): число для
                 * упражнения без истории составитель плана взял из головы, и
                 * «легко» с первого раза уже значит, что оно занижено.
                 */
                const основное = first
                    ? t('{упражнение}: впервые, и запас большой — {способ}. Число в плане было прикидкой.', {
                        упражнение: name, способ: ТЯЖЕЛЕЕ[step]()
                    })
                    : t('{упражнение}: два занятия подряд запас большой — {способ}.', {
                        упражнение: name, способ: ТЯЖЕЛЕЕ[step]()
                    });

                строки.push({
                    topic: 'reserve',
                    name,
                    first,
                    kind: 'up',
                    text: противПрибавки
                        ? [основное, t('Но не на этой неделе: сон и пульс против.')].join(' ')
                        : основное,

                    /*
                     * Наблюдение несёт с собой то, чем по нему можно
                     * распорядиться (§59.1).
                     *
                     * Не толкование и не команда: имя упражнения, способ и
                     * вид решения, а что с ними делать, решает показ. Без
                     * этого экрану пришлось бы разбирать готовую фразу
                     * обратно на части — и разбирать переведённую.
                     *
                     * В неделю, когда сон и пульс против, распоряжаться нечем:
                     * кнопка правила бы план вопреки доводу над ней.
                     */
                    action: противПрибавки ? null : { type: 'harder', name, step }
                });
            }

            if (verdict === 'easier') {
                строки.push({
                    topic: 'reserve',
                    name,
                    first,
                    kind: 'down',
                    text: first
                        ? t('{упражнение}: впервые, и почти до отказа — число в плане было прикидкой.', { упражнение: name })
                        : t('{упражнение}: два занятия подряд почти до отказа — запас потерян.', { упражнение: name }),

                    /*
                     * У «запас потерян» теперь есть кнопка (Р-219): цель чуть
                     * ниже тем же путём, что и у недобора (Р-216). Раньше строка
                     * только сообщала — а ровно на этой стороне, «на грани»,
                     * человеку и нужно решение, а не новость.
                     */
                    action: lower
                        ? { type: 'lower', name, from: lower.from, to: lower.to, done: lower.done }
                        : { type: 'easier', name, step }
                });
            }
        }

        /*
         * Остальные — одной строкой на каждый вывод, по именам (Р-207).
         *
         * Не молчанием: срезанное без слова читается как «больше ничего нет»,
         * а оно есть. Кнопки у сводной строки нет — числа и совет у каждого
         * упражнения стоят на выполнении, там, где решение и принимают (§59).
         */
        const потерян = прочие.filter((r) => r.verdict === 'easier').map((r) => r.name);
        const большой = прочие.filter((r) => r.verdict === 'harder').map((r) => r.name);

        if (потерян.length) {
            строки.push({
                topic: 'reserve',
                kind: 'down',
                text: t('Почти до отказа два занятия подряд и у других: {список}.', { список: потерян.join(', ') })
            });
        }

        if (большой.length) {
            строки.push({
                topic: 'reserve',
                kind: 'up',
                text: [
                    t('Запас большой два занятия подряд и у других: {список}. Совет с числами — на выполнении каждого.', { список: большой.join(', ') }),
                    противПрибавки ? t('Но не на этой неделе: сон и пульс против.') : ''
                ].filter(Boolean).join(' ')
            });
        }

        /*
         * Пульс без сна — слабее: стоит присмотреться, но прибавку он не
         * отменяет. Порознь признаки значат мало (см. выше).
         */
        if (!противПрибавки && recovery?.highResting) {
            строки.push({
                topic: 'recovery',
                kind: 'watch',
                text: t('Пульс покоя выше обычного — стоит присмотреться к самочувствию.')
            });
        }

        /*
         * Недобор по числам — упражнением и с цифрами (Р-216).
         *
         * Называет и план, и факт рядом: «в плане 4 × 25, сделано 16, 14, 14,
         * 10». По одному «на 46 % меньше» непонятно, промах это или честный
         * предел; по паре чисел видно сразу.
         *
         * И про первый раз сказано отдельно: число для упражнения, которого
         * человек не делал, составитель плана взял ниоткуда, — и это не
         * слабость человека, а прикидка, которую пора поправить.
         *
         * Своими строками — не больше двух (как у запаса, Р-207); остальные —
         * одной строкой по именам, а не молчанием.
         */
        for (const н of shortfalls.slice(0, НЕДОБОР_СТРОК)) {
            строки.push({
                topic: 'plan',
                kind: 'watch',
                text: [
                    (н.field === 'duration'
                        ? t('{упражнение}: в плане {подходы} × {цель} с, сделано {числа} с — на {процент} % меньше.', {
                            упражнение: н.name, подходы: н.plannedSets, цель: н.target, числа: н.done.join(', '), процент: н.lack
                        })
                        : t('{упражнение}: в плане {подходы} × {цель}, сделано {числа} — на {процент} % меньше.', {
                            упражнение: н.name, подходы: н.plannedSets, цель: н.target, числа: н.done.join(', '), процент: н.lack
                        })),
                    н.firstTime ? t('Раньше вы его не делали: число в плане было прикидкой.') : ''
                ].filter(Boolean).join(' '),

                // Что с этим можно сделать (§59.1): цель по факту, одним нажатием
                action: { type: 'lower', name: н.name, from: н.target, to: н.suggest, done: н.done }
            });
        }

        if (shortfalls.length > НЕДОБОР_СТРОК) {
            строки.push({
                topic: 'plan',
                kind: 'watch',
                text: t('Недобор плана и у других: {список}.', {
                    список: shortfalls.slice(НЕДОБОР_СТРОК).map((н) => н.name).join(', ')
                })
            });
        }

        /*
         * Перевыполнение — зеркало недобора (Р-220).
         *
         * «В плане 3 × 15, сделано 20, 20, 20»: человек добавил сам, и в
         * следующий раз добавлять пришлось бы опять. Приложение знало и план,
         * и факт, но в эту сторону их не сравнивало — и поле просило прежние
         * пятнадцать. Строка называет и то и другое; кнопка «поправить план»
         * ставит цель по факту. Цвет — «вперёд», а не «внимание»: это не
         * беда, а повод подтянуть план к человеку.
         *
         * Свои строки — не больше двух, остальные одной строкой по именам.
         */
        for (const н of overshoots.slice(0, НЕДОБОР_СТРОК)) {
            строки.push({
                topic: 'plan',
                kind: 'up',
                text: [
                    (н.field === 'duration'
                        ? t('{упражнение}: в плане {подходы} × {цель} с, сделано {числа} с — на {процент} % больше.', {
                            упражнение: н.name, подходы: н.plannedSets, цель: н.target, числа: н.done.join(', '), процент: н.more
                        })
                        : t('{упражнение}: в плане {подходы} × {цель}, сделано {числа} — на {процент} % больше.', {
                            упражнение: н.name, подходы: н.plannedSets, цель: н.target, числа: н.done.join(', '), процент: н.more
                        })),
                    /*
                     * У резинки и снаряда прибавляют не повторениями (§59,
                     * Р-206): программа прямо говорит «сопротивлением, а не
                     * повторениями». Поэтому «сделано больше» там превращается в
                     * прибавку по способу, а не в новую цель по повторениям.
                     */
                    ['weight', 'resistance'].includes(н.step)
                        ? t('Прибавлять надо не повторениями: {способ}.', { способ: ТЯЖЕЛЕЕ[н.step]() })
                        : '',
                    н.firstTime ? t('Раньше вы его не делали: число в плане было прикидкой.') : ''
                ].filter(Boolean).join(' '),

                action: ['weight', 'resistance'].includes(н.step)
                    ? { type: 'harder', name: н.name, step: н.step }
                    : { type: 'raise', name: н.name, from: н.target, to: н.suggest, done: н.done }
            });
        }

        if (overshoots.length > НЕДОБОР_СТРОК) {
            строки.push({
                topic: 'plan',
                kind: 'up',
                text: t('Больше плана вы сделали и в других: {список}.', {
                    список: overshoots.slice(НЕДОБОР_СТРОК).map((н) => н.name).join(', ')
                })
            });
        }

        /*
         * Исполнение плана — не упрёк, а число.
         *
         * «Вы пропустили» приложение не говорит: оно не знает почему, и
         * знать не может. Оно называет, сколько дней плана прошло мимо, — и
         * этого довольно, чтобы человек сам решил, тяжела программа или
         * неудачна неделя.
         */
        if (adherence && adherence.planned > 0) {
            const пропущено = adherence.planned - adherence.done;

            if (пропущено >= MISSED) {
                /*
                 * «Программа идёт быстрее вас» — только тому, кто правда
                 * отстаёт (Р-120). Занимавшемуся не меньше плана говорится
                 * другое: разошлись не силы, а дни.
                 */
                const чаще = (adherence.sessions || 0) >= adherence.planned;

                строки.push({
                    topic: 'adherence',
                    kind: 'watch',
                    text: чаще
                        ? t('За две недели {тренировок} при {всего} по плану, но в дни сетки попали {сделано} — сетка разошлась с вашей неделей.', {
                            тренировок: format.count(adherence.sessions, format.WORDS.workout),
                            всего: adherence.planned,
                            сделано: adherence.done
                        })
                        : t('По плану за две недели сделано {сделано} из {всего} — программа идёт быстрее вас.', {
                            сделано: adherence.done, всего: adherence.planned
                        })
                });
            }
            else if (adherence.done === adherence.planned) {
                /*
                 * Сдвиг называется сдвигом (Р-164).
                 *
                 * «Выполнен полностью» у того, кто помнит свой пропущенный
                 * понедельник, читается как ошибка счёта. Число при этом
                 * верное: допуск в сутки заведён нарочно (Р-120), потому что
                 * сетка при пропуске не двигается, а человек двигается. Но
                 * молча засчитывать вторник за понедельник нельзя — это ровно
                 * то место, где приложение обязано назвать основание.
                 */
                строки.push({
                    topic: 'adherence',
                    kind: 'ok',
                    text: [
                        t('План за две недели выполнен полностью — {всего} из {всего}.', { всего: adherence.planned }),

                        adherence.shifted
                            ? t('Со сдвигом на сутки: {дней} — сетка при пропуске не двигается, а вы двигаетесь, и тренировка соседнего дня идёт в зачёт.', {
                                дней: format.count(adherence.shifted, format.WORDS.day)
                            })
                            : ''
                    ].filter(Boolean).join(' ')
                });
            }
        }

        /*
         * Объём — про месяц, а не про сегодня.
         *
         * Он последний намеренно: просевший объём не повод менять ближайшую
         * тренировку, но именно он объясняет, почему через месяц не растут
         * рекорды.
         */
        if (volume && volume.previous > 0) {
            const доля = (volume.current - volume.previous) / volume.previous;

            /*
             * Проценты называют своё основание — оба числа (Р-162).
             *
             * «Выше прошлой на 127 %» — наблюдение без основания, а правило
             * экрана обратное: приложение называет наблюдение и то, из чего
             * оно выведено. Вопрос владельца был ровно этот: «как может быть
             * на 127 % выше, может, сравнивается с полупустой неделей?» —
             * и по одному проценту ответить на него нельзя никак, а по паре
             * «1420 против 625» видно сразу.
             */
            const числа = {
                сейчас: Math.round(volume.current),
                прошлой: Math.round(volume.previous),
                процент: Math.round(Math.abs(доля) * 100)
            };

            /*
             * И отдельно — про то, с чем сравнивали.
             *
             * Неделя, в которую занимались вдвое реже, даёт проценты о себе,
             * а не о работе человека. Догадаться об этом он не обязан:
             * сказать должно приложение.
             */
            const реже = volume.previousDays > 0
                && volume.currentDays > 0
                && volume.previousDays < volume.currentDays;

            const оговорка = реже
                ? t('На прошлой неделе занятий было меньше — {было} против {стало}, и разница во многом от этого.', {
                    было: volume.previousDays, стало: volume.currentDays
                })
                : '';

            const сказать = (kind, основное) => строки.push({
                topic: 'volume',
                kind,
                text: [основное, оговорка].filter(Boolean).join(' ')
            });

            if (доля <= -DROP) {
                сказать('watch', t('Повторений за неделю {сейчас} против {прошлой} — на {процент}% меньше.', числа));
            }
            else if (доля >= RAMP) {
                сказать('watch', t('Повторений за неделю {сейчас} против {прошлой} — на {процент}% больше. Это разгон, а не успех: резкая прибавка и есть лучший известный признак скорого срыва. Черту в половину сверху провело приложение — точного числа для пары соседних недель в исследованиях нет.', числа));
            }
            else if (доля >= DROP) {
                сказать('up', t('Повторений за неделю {сейчас} против {прошлой} — на {процент}% больше.', числа));
            }
        }

        return строки;
    },

    /**
     * Признаки восстановления из замеров с часов (§62).
     *
     * Считается здесь, а не в модуле восстановления: там числа, здесь их
     * толкование, и толкование должно быть в одном месте с остальными
     * выводами — иначе пороги разъедутся.
     */
    recovery({ sleep = null, resting = null } = {}) {
        return {
            shortSleep: sleep !== null && sleep < SHORT_SLEEP,
            highResting: !!resting && resting.shift > 0 && Math.abs(resting.shift) >= (resting.threshold || 3)
        };
    },

    /**
     * Исполнение плана: сколько тренировочных дней прошло и сколько сделано.
     *
     * days — [{ day, session }], где day — полночь дня в миллисекундах: из
     * развёртки плана, только прошедшие дни.
     * done — множество дней (полночь в миллисекундах), в которые тренировка
     * была. Зарядка сюда не входит: она идёт каждый день и по плану не
     * значится (Р-33, Р-64, Р-66).
     */
    adherence(days = [], done = new Set(), { from = null, to = null } = {}) {
        const прошедшие = days.filter((d) => d.session).sort((a, b) => a.day - b.day);

        if (прошедшие.length === 0) return { planned: 0, done: 0, sessions: 0, shifted: 0 };

        /*
         * Попадание считается с допуском в день (Р-120), но в два захода
         * (Р-121).
         *
         * Допуск нужен потому, что сетка при пропуске не двигается (Р-62), а
         * человек двигается: сдвинулся на день — и день плана объявлен
         * пропущенным, а тренировка не засчитана никуда. Занимающийся чаще
         * плана, но не по его дням, читал «0 из 6 — программа идёт быстрее
         * вас» каждый раз, открывая статистику.
         *
         * Но допуск в один заход разбирал дни жадно и ехал цепочкой. План на
         * шесть дней в неделю, понедельник пропущен: понедельник не находил
         * своей тренировки и забирал вторничную, вторник — среду, и так до
         * конца недели. Пропуск исчезал, а карточка отчитывалась «выполнен
         * полностью — 5 из 5».
         *
         * Это хуже недосчёта: недосчёт занижает, а цепочка хвалит за то, чего
         * не было, — и хвалит ровно того, кто пропустил.
         *
         * Поэтому сначала разбираются попадания день в день, и только потом
         * несовпавшие дни смотрят на соседние. Причём соседний берётся только
         * тогда, когда он не свой день другому дню плана: тренировка вторника
         * принадлежит вторнику, даже если вторник её не дождался. У плотного
         * плана свободных соседей не остаётся вовсе — и это верно: если
         * занимаются каждый день, разъехаться не с чем, и пропуск есть пропуск.
         */
        const свои = new Set(прошедшие.map((d) => d.day));
        const занято = new Set();
        const закрыт = new Array(прошедшие.length).fill(false);

        прошедшие.forEach((d, i) => {
            if (!done.has(d.day)) return;

            закрыт[i] = true;
            занято.add(d.day);
        });

        /*
         * Сколько дней закрыто соседними — считаем и отдаём наружу (Р-164).
         *
         * Допуск в сутки нужен и остаётся (Р-120), но человек про него не
         * знает: он помнит, что понедельник пропустил, а карточка пишет
         * «выполнен полностью». Число выходит верным, а читается как ошибка —
         * и первым делом человек перестаёт верить карточке, а не допуску.
         */
        let сдвинуто = 0;

        прошедшие.forEach((d, i) => {
            if (закрыт[i]) return;

            const сосед = [addDays(d.day, -1), addDays(d.day, 1)]
                .find((c) => done.has(c) && !занято.has(c) && !свои.has(c));

            if (сосед === undefined) return;

            закрыт[i] = true;
            занято.add(сосед);
            сдвинуто += 1;
        });

        const попали = закрыт.filter(Boolean).length;

        /*
         * Сколько тренировок было всего за то же окно.
         *
         * Нужно, чтобы отличить «занимался мало» от «занимался не в те дни»:
         * это разные новости, и вторую нельзя подавать как первую.
         *
         * Окно приходит снаружи — это те же две недели, по которым собрана
         * сетка. По краям самой сетки его не вычислить: тренировка через день
         * после последнего дня плана попала бы мимо счёта, а она-то и есть
         * доказательство, что человек занимается, просто не по дням.
         */
        const от = from ?? addDays(прошедшие[0].day, -1);
        const до = to ?? addDays(прошедшие[прошедшие.length - 1].day, 1);

        const sessions = [...done].filter((d) => d >= от && d <= до).length;

        return { planned: прошедшие.length, done: попали, sessions, shifted: сдвинуто };
    }
};
