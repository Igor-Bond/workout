/**
 * Как идёт программа (§63 ТЗ).
 *
 * Всё, чем можно ответить на этот вопрос, у приложения уже есть по частям:
 * объём и ритм из истории (§25), запас в подходе (§59), сон и пульс покоя с
 * часов (§62), сетка плана (§56). Порознь они лежали на пяти экранах, и
 * складывать их приходилось человеку — или тренеру, которого об этом надо
 * было спросить.
 *
 * Здесь они складываются. Модуль чистый: готовые наблюдения на входе,
 * несколько строк на выходе. Ни базы, ни сети — вывод о том, пора ли тяжелее,
 * ошибается так же убедительно, как и попадает, и проверять его надо
 * отдельно от того, откуда взялись числа.
 *
 * Правило одно и оно важнее остальных: **приложение не командует**. Оно
 * называет наблюдение и его основание — «третье занятие подряд запас большой»,
 * — а решает человек. Указание «добавь вес» без основания человек либо
 * исполнит не думая, либо перестанет читать; названное наблюдение он проверит
 * собой, и это единственный способ им распорядиться верно.
 */

import { t } from './i18n.js';

/**
 * Сколько тренировочных дней плана можно пропустить, прежде чем об этом
 * говорить.
 *
 * Один пропуск за две недели — это жизнь: командировка, ребёнок, работа.
 * Два — уже расхождение с программой, о котором стоит знать, пока оно не
 * стало тремя.
 */
export const MISSED = 2;

/** На сколько должен просесть объём, чтобы это было спадом, а не колебанием. */
export const DROP = 0.25;

/** Ниже этого сон считается коротким. Семь часов — общая нижняя граница. */
export const SHORT_SLEEP = 7 * 3600;

export const progress = {

    MISSED,
    DROP,
    SHORT_SLEEP,

    /**
     * Наблюдения о ходе программы.
     *
     * Каждое — { kind, text }, где kind нужен показу, чтобы отличить хорошее
     * от требующего внимания, а не для толкования: слово в text полное и
     * самодостаточное.
     *
     * Порядок не случаен: сперва тело (запас, восстановление), потом
     * исполнение плана, потом объём. Первое меняет сегодняшнюю тренировку,
     * последнее — разговор с тренером через месяц.
     */
    describe({ reserve = [], recovery = null, adherence = null, volume = null } = {}) {
        const строки = [];

        /*
         * Запас в подходе — единственное, что говорит про сегодня.
         *
         * Правило прогрессии (§59) считается по упражнению, и упражнений
         * может быть несколько; называем каждое своим именем — «пора тяжелее»
         * без имени человек отнесёт ко всей программе разом.
         */
        for (const { name, verdict } of reserve) {
            if (verdict === 'harder') {
                строки.push({
                    kind: 'up',
                    text: t('{упражнение}: два занятия подряд запас большой — можно тяжелее.', { упражнение: name }),

                    /*
                     * Наблюдение несёт с собой то, чем по нему можно
                     * распорядиться (§59.1).
                     *
                     * Не толкование и не команда: имя упражнения и вид
                     * решения, а что с ними делать, решает показ. Без этого
                     * экрану пришлось бы разбирать готовую фразу обратно на
                     * части — и разбирать переведённую.
                     */
                    action: { type: 'harder', name }
                });
            }

            if (verdict === 'easier') {
                строки.push({
                    kind: 'down',
                    text: t('{упражнение}: два занятия подряд почти до отказа — запас потерян.', { упражнение: name }),
                    action: { type: 'easier', name }
                });
            }
        }


        /*
         * Восстановление говорит не «отдохни», а что именно оно видит.
         *
         * Совпадение двух признаков, а не любой из них: короткий сон бывает
         * от кино, высокий пульс покоя — от кофе, и порознь они значат мало.
         * Вместе — это неделя, в которую добавлять нагрузку не стоит, и
         * сказать об этом надо прежде, чем человек послушает совет «можно
         * тяжелее» из строки выше.
         */
        if (recovery?.shortSleep && recovery?.highResting) {
            строки.push({
                kind: 'down',
                text: t('Сон короче обычного и пульс покоя выше — неделя не для прибавки.')
            });
        }
        else if (recovery?.highResting) {
            строки.push({
                kind: 'watch',
                text: t('Пульс покоя выше обычного — стоит присмотреться к самочувствию.')
            });
        }

        /*
         * Исполнение плана — не упрёк, а число.
         *
         * «Вы пропустили» приложение не говорит: оно не знает почему, и
         * знать не может. Оно называет, сколько дней плана прошло мимо, — и
         * этого довольно, чтобы человек сам решил, тяжела программа или
         * неудачна неделя.
         */
        if (adherence && adherence.planned > 0) {
            const пропущено = adherence.planned - adherence.done;

            if (пропущено >= MISSED) {
                строки.push({
                    kind: 'watch',
                    text: t('По плану за две недели сделано {сделано} из {всего} — программа идёт быстрее вас.', {
                        сделано: adherence.done, всего: adherence.planned
                    })
                });
            }
            else if (adherence.done === adherence.planned) {
                строки.push({
                    kind: 'ok',
                    text: t('План за две недели выполнен полностью — {всего} из {всего}.', { всего: adherence.planned })
                });
            }
        }

        /*
         * Объём — про месяц, а не про сегодня.
         *
         * Он последний намеренно: просевший объём не повод менять ближайшую
         * тренировку, но именно он объясняет, почему через месяц не растут
         * рекорды.
         */
        if (volume && volume.previous > 0) {
            const доля = (volume.current - volume.previous) / volume.previous;

            if (доля <= -DROP) {
                строки.push({
                    kind: 'watch',
                    text: t('Повторений за неделю ниже прошлой на {процент}%.', { процент: Math.round(-доля * 100) })
                });
            }
            else if (доля >= DROP) {
                строки.push({
                    kind: 'up',
                    text: t('Повторений за неделю выше прошлой на {процент}%.', { процент: Math.round(доля * 100) })
                });
            }
        }

        return строки;
    },

    /**
     * Признаки восстановления из замеров с часов (§62).
     *
     * Считается здесь, а не в модуле восстановления: там числа, здесь их
     * толкование, и толкование должно быть в одном месте с остальными
     * выводами — иначе пороги разъедутся.
     */
    recovery({ sleep = null, resting = null } = {}) {
        return {
            shortSleep: sleep !== null && sleep < SHORT_SLEEP,
            highResting: !!resting && resting.shift > 0 && Math.abs(resting.shift) >= (resting.threshold || 3)
        };
    },

    /**
     * Исполнение плана: сколько тренировочных дней прошло и сколько сделано.
     *
     * days — [{ day, session }], где day — полночь дня в миллисекундах: из
     * развёртки плана, только прошедшие дни.
     * done — множество дней (полночь в миллисекундах), в которые тренировка
     * была. Зарядка сюда не входит: она идёт каждый день и по плану не
     * значится (Р-33, Р-64, Р-66).
     */
    adherence(days = [], done = new Set()) {
        const прошедшие = days.filter((d) => d.session);

        return {
            planned: прошедшие.length,
            done: прошедшие.filter((d) => done.has(d.day)).length
        };
    }
};
