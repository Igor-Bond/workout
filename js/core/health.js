/**
 * Коэффициенты состояния тела и обмена (§66 ТЗ).
 *
 * Модуль чистый: числа на входе, числа и оценки на выходе. Ни базы, ни
 * разметки — потому что здесь живёт единственное место приложения, где оно
 * говорит человеку «хорошо» или «не очень», и такое место обязано быть
 * проверяемым целиком.
 *
 * Главное правило, ради которого всё и написано: **цвет вешается на
 * сравнение, а не на число**. Покрасить можно только то, у чего есть с чем
 * сравнить, — названная норма или собственный ход человека. У воды в теле
 * нормы нет; покрасив её, приложение изобразило бы медицинское знание,
 * которого у него нет.
 *
 * Отсюда три разряда величин:
 *
 *   норма     — талия/рост, ИМТ, доля жира. Норма названа вслух: это разница
 *               между арифметикой и советом;
 *   свой ход  — вес, талия, сон, пульс покоя. Сравнение с самим собой месяц
 *               назад, а не с таблицей;
 *   справка   — вода, мышцы, BMR. Число без краски: оно объясняет другие, а
 *               само ни хорошо, ни плохо.
 */

import { t } from './i18n.js';

/**
 * Оценки. Ключи, а не подписи: подпись переводится, а цвет — нет.
 *
 * Четвёртой «плохо» нет намеренно. Приложение считает по ленте и весам, у
 * которых своя погрешность, и объявлять человеку плохое по такому основанию
 * оно не вправе. «Стоит посмотреть» — предел того, что можно сказать честно.
 */
export const ХОРОШО = 'good';
export const СМОТРЕТЬ = 'watch';
export const СПРАВКА = 'plain';

/** Пол, при котором таблицы различаются. Неизвестный — значит без нормы. */
const МУЖ = 'male';
const ЖЕН = 'female';

/**
 * Запас на погрешность прибора у доли жира, в процентных пунктах.
 *
 * Биоимпеданс врёт на три–пять пунктов и зависит от того, сколько человек
 * выпил и когда ел. Узкая зелёная зона при такой погрешности мигала бы день
 * ото дня, а мигающая отметка перестаёт читаться.
 */
const ЖИР_ЗАПАС = 2;

/**
 * Гистерезис: насколько надо выйти за границу, чтобы отметка сменилась.
 *
 * Без него значение, стоящее на самой границе, прыгает туда-сюда от
 * стакана воды. С ним отметка держится, пока перемена не станет настоящей.
 */
const ГИСТЕРЕЗИС = 0.5;

export const health = {

    ХОРОШО,
    СМОТРЕТЬ,
    СПРАВКА,

    /**
     * Индекс массы тела и его оценка по ВОЗ.
     *
     * Норма названа вслух — «ВОЗ», — потому что ИМТ не универсален: у
     * человека с большой мышечной массой он завышен, и знать, чья это мерка,
     * важнее самого числа.
     */
    bmi(вес, ростСм) {
        const рост = Number(ростСм) / 100;
        const кг = Number(вес);

        if (!(рост > 0.5 && рост < 2.5) || !(кг > 20 && кг < 400)) return null;

        const значение = кг / (рост * рост);

        return {
            value: Math.round(значение * 10) / 10,

            // 18,5–25 — норма ВОЗ. Ниже и выше — «стоит посмотреть», а не
            // «плохо»: у ИМТ хватает известных промахов, чтобы не выносить по
            // нему приговор
            state: значение >= 18.5 && значение < 25 ? ХОРОШО : СМОТРЕТЬ,
            norm: t('норма ВОЗ — от 18,5 до 25')
        };
    },

    /**
     * Отношение талии к росту.
     *
     * Самая надёжная из трёх: лента не врёт, а отношение не зависит ни от
     * мышечной массы, ни от прибора. Порог 0,5 — «талия меньше половины
     * роста» — держится в исследованиях лучше ИМТ и запоминается с первого
     * раза.
     */
    waistToHeight(талияСм, ростСм) {
        const талия = Number(талияСм);
        const рост = Number(ростСм);

        if (!(талия > 30 && талия < 250) || !(рост > 50 && рост < 250)) return null;

        const значение = талия / рост;

        return {
            value: Math.round(значение * 100) / 100,
            state: значение < 0.5 ? ХОРОШО : СМОТРЕТЬ,
            norm: t('норма — меньше половины роста')
        };
    },

    /**
     * Доля жира и её оценка по полу и возрасту.
     *
     * Таблица Gallagher и соавторов (AJCN, 2000) — она возрастная, в отличие
     * от ходовых «спортивных» шкал: с годами доля жира растёт и у здорового
     * человека, и мерить сорокалетнего по мерке двадцатилетнего значит
     * объявлять возраст болезнью.
     *
     * Границы раздвинуты на запас прибора: весы врут на три–пять пунктов, и
     * зелёная зона обязана быть шире их промаха.
     */
    bodyFat(процент, { sex, age } = {}, прежнее = null) {
        const жир = Number(процент);

        if (!(жир > 2 && жир < 70)) return null;
        if ((sex !== МУЖ && sex !== ЖЕН) || !(age > 0)) {
            return { value: Math.round(жир * 10) / 10, state: СПРАВКА, norm: null };
        }

        const [низ, верх] = health.fatRange(sex, age);

        const мягкийНиз = низ - ЖИР_ЗАПАС;
        const мягкийВерх = верх + ЖИР_ЗАПАС;

        /*
         * Гистерезис работает только в сторону ухудшения (Р-134).
         *
         * Вернуться в зелёное можно сразу, а выйти из него — только заметно
         * перешагнув границу. Иначе половина дней объявлялась бы «стоит
         * посмотреть» из-за стакана воды, а вторая — «хорошо».
         */
        const былоХорошо = прежнее === ХОРОШО;
        const запас = былоХорошо ? ГИСТЕРЕЗИС : 0;

        const хорошо = жир >= мягкийНиз - запас && жир <= мягкийВерх + запас;

        return {
            value: Math.round(жир * 10) / 10,
            state: хорошо ? ХОРОШО : СМОТРЕТЬ,
            norm: t('для пола и возраста — от {низ} до {верх} %', { низ, верх })
        };
    },

    /**
     * Границы нормальной доли жира по полу и возрасту (Gallagher, 2000).
     *
     * Возвращает пару в процентах. Возраст берётся тремя ступенями — так они
     * и опубликованы; выдумывать промежуточные значения было бы точностью,
     * которой в источнике нет.
     */
    fatRange(sex, age) {
        const молодой = age < 40;
        const средний = age < 60;

        if (sex === ЖЕН) {
            if (молодой) return [21, 33];
            return средний ? [23, 34] : [24, 36];
        }

        if (молодой) return [8, 20];
        return средний ? [11, 22] : [13, 25];
    },

    /**
     * Основной обмен по Миффлину — Сан-Жеору.
     *
     * Сколько тело тратит в сутки в полном покое. Формула выбрана не за
     * точность — точной тут нет ни одной, — а за то, что она ходовая: число
     * из приложения сойдётся с числом из любого калькулятора, и человеку не
     * придётся гадать, кто из них врёт.
     *
     * Не красится никогда: у основного обмена нет ни нормы, ни «хорошо». Это
     * опора для следующего числа, а не оценка.
     */
    bmr({ weight, height, age, sex } = {}) {
        const кг = Number(weight);
        const см = Number(height);
        const лет = Number(age);

        if (!(кг > 20) || !(см > 50) || !(лет > 0)) return null;
        if (sex !== МУЖ && sex !== ЖЕН) return null;

        const основа = 10 * кг + 6.25 * см - 5 * лет;

        return Math.round(основа + (sex === МУЖ ? 5 : -161));
    },

    /**
     * Коэффициент активности — из шагов и тренировок, а не из опроса.
     *
     * Спрашивать «насколько вы активны» бессмысленно: человек отвечает о том,
     * каким себя считает, а приложение и так знает, сколько он ходит и сколько
     * занимается. Берётся большее из двух: активность — это не сумма ходьбы и
     * зала, а то, чего из них больше.
     *
     * Ступени — ходовые, из тех же калькуляторов, что и формула обмена.
     */
    activityFactor({ steps = 0, workoutsPerWeek = 0 } = {}) {
        const поШагам = steps >= 14000 ? 1.9
            : steps >= 11000 ? 1.725
            : steps >= 8000 ? 1.55
            : steps >= 6000 ? 1.375
            : 1.2;

        const поЗанятиям = workoutsPerWeek >= 7 ? 1.9
            : workoutsPerWeek >= 5 ? 1.725
            : workoutsPerWeek >= 3 ? 1.55
            : workoutsPerWeek >= 1 ? 1.375
            : 1.2;

        return Math.max(поШагам, поЗанятиям);
    },

    /**
     * Суточный расход: основной обмен, помноженный на активность.
     *
     * Тоже без краски. Число это оценочное вдвойне — и формула приблизительна,
     * и коэффициент ступенчатый, — но именно от него считают, есть ли дефицит.
     * Приложение его называет и говорит, из чего оно собрано.
     */
    amr(основной, коэффициент) {
        const база = Number(основной);
        const k = Number(коэффициент);

        if (!(база > 0) || !(k > 0)) return null;

        return Math.round(база * k);
    },

    /**
     * Ход величины к себе же месяц назад (§66).
     *
     * Здесь нормы нет и быть не может: у веса, талии и тоннажа есть только
     * своё направление. Поэтому и оценка другая — не «в норме», а «идёт туда,
     * куда человек собирался».
     *
     * Куда «туда» — решает не приложение: цель названа в профиле. Без неё
     * возвращается справка, и это честно: у одного и того же минус килограмма
     * два противоположных смысла.
     */
    trend(было, стало, { goodDirection = null, noise = 0 } = {}) {
        /*
         * Пустое — не ноль (Р-134).
         *
         * Number(null) — это 0, и проверка «конечное ли число» его
         * пропускает. У остальных величин ноль отсеивается сам собой: веса в
         * ноль килограммов не бывает. А здесь ноль законен — вес мог и не
         * измениться, — и отсутствие замера прикидывалось бы падением на
         * девяносто два килограмма.
         */
        const число = (v) => (v === null || v === undefined || v === '' ? NaN : Number(v));

        const a = число(было);
        const b = число(стало);

        if (!Number.isFinite(a) || !Number.isFinite(b)) return null;

        const разница = Math.round((b - a) * 100) / 100;

        if (!goodDirection || Math.abs(разница) <= noise) {
            return { delta: разница, state: СПРАВКА };
        }

        const туда = goodDirection === 'down' ? разница < 0 : разница > 0;

        return { delta: разница, state: туда ? ХОРОШО : СМОТРЕТЬ };
    }
};
