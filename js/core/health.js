/**
 * Коэффициенты состояния тела и обмена (§66 ТЗ).
 *
 * Модуль чистый: числа на входе, числа и оценки на выходе. Ни базы, ни
 * разметки — потому что здесь живёт единственное место приложения, где оно
 * говорит человеку «хорошо» или «не очень», и такое место обязано быть
 * проверяемым целиком.
 *
 * Главное правило, ради которого всё и написано: **цвет вешается на
 * сравнение, а не на число**. Покрасить можно только то, у чего есть с чем
 * сравнить, — названная норма или собственный ход человека. У воды в теле
 * нормы нет; покрасив её, приложение изобразило бы медицинское знание,
 * которого у него нет.
 *
 * Отсюда три разряда величин:
 *
 *   норма     — талия/рост, ИМТ, доля жира. Норма названа вслух: это разница
 *               между арифметикой и советом;
 *   свой ход  — вес, талия, сон, пульс покоя. Сравнение с самим собой месяц
 *               назад, а не с таблицей;
 *   справка   — вода, мышцы, BMR. Число без краски: оно объясняет другие, а
 *               само ни хорошо, ни плохо.
 */

import { t } from './i18n.js';
import { format } from './format.js';
import { toNumber } from './num.js';

/**
 * Оценки. Ключи, а не подписи: подпись переводится, а цвет — нет.
 *
 * Четвёртой «плохо» нет намеренно. Приложение считает по ленте и весам, у
 * которых своя погрешность, и объявлять человеку плохое по такому основанию
 * оно не вправе. «Стоит посмотреть» — предел того, что можно сказать честно.
 */
export const ХОРОШО = 'good';
export const СМОТРЕТЬ = 'watch';
export const СПРАВКА = 'plain';

/** Пол, при котором таблицы различаются. Неизвестный — значит без нормы. */
const МУЖ = 'male';
const ЖЕН = 'female';

/**
 * Запас на погрешность прибора у доли жира, в процентных пунктах.
 *
 * Биоимпеданс врёт на три–пять пунктов и зависит от того, сколько человек
 * выпил и когда ел. Узкая зелёная зона при такой погрешности мигала бы день
 * ото дня, а мигающая отметка перестаёт читаться.
 */
const ЖИР_ЗАПАС = 2;

/**
 * Гистерезис: насколько надо выйти за границу, чтобы отметка сменилась.
 *
 * Без него значение, стоящее на самой границе, прыгает туда-сюда от
 * стакана воды. С ним отметка держится, пока перемена не станет настоящей.
 */
const ГИСТЕРЕЗИС = 0.5;

/**
 * Насколько величина должна сдвинуться, чтобы это считалось ходом.
 *
 * Иначе приложение объявляло бы направление по шуму прибора: двести граммов
 * веса — это вода, а полсантиметра талии — то, как держали ленту.
 *
 * Живёт здесь, а не в экране кондиций, потому что спрашивают его двое: сам
 * экран и проверка потолка калорий (Р-175). Два числа об одной погрешности
 * разошлись бы при первой правке.
 */
export const ШУМ = { weight: 0.5, waist: 1 };

export const health = {

    ШУМ,
    ХОРОШО,
    СМОТРЕТЬ,
    СПРАВКА,

    /**
     * Норма индекса массы тела по ВОЗ — одна вилка на всех взрослых.
     *
     * Лежит отдельной величиной, потому что по ней считаются две разные
     * вещи: оценка самого индекса и здоровый вес для роста в килограммах
     * (Р-141). Разъехаться этим двум числам нельзя.
     */
    BMI_НОРМА: [18.5, 25],

    /**
     * Индекс массы тела и его оценка по ВОЗ.
     *
     * Норма названа вслух — «ВОЗ», — потому что ИМТ не универсален: у
     * человека с большой мышечной массой он завышен, и знать, чья это мерка,
     * важнее самого числа.
     */
    bmi(вес, ростСм) {
        const рост = Number(ростСм) / 100;
        const кг = Number(вес);

        if (!(рост > 0.5 && рост < 2.5) || !(кг > 20 && кг < 400)) return null;

        const значение = кг / (рост * рост);

        return {
            value: Math.round(значение * 10) / 10,

            // Ниже и выше нормы — «стоит посмотреть», а не «плохо»: у ИМТ
            // хватает известных промахов, чтобы не выносить по нему приговор
            state: значение >= health.BMI_НОРМА[0] && значение < health.BMI_НОРМА[1]
                ? ХОРОШО : СМОТРЕТЬ,
            norm: t('норма ВОЗ — от 18,5 до 25')
        };
    },

    /**
     * Отношение талии к росту.
     *
     * Самая надёжная из трёх: лента не врёт, а отношение не зависит ни от
     * мышечной массы, ни от прибора. Порог 0,5 — «талия меньше половины
     * роста» — держится в исследованиях лучше ИМТ и запоминается с первого
     * раза.
     */
    waistToHeight(талияСм, ростСм) {
        const талия = Number(талияСм);
        const рост = Number(ростСм);

        if (!(талия > 30 && талия < 250) || !(рост > 50 && рост < 250)) return null;

        const значение = талия / рост;

        return {
            value: Math.round(значение * 100) / 100,
            state: значение < 0.5 ? ХОРОШО : СМОТРЕТЬ,
            norm: t('норма — меньше половины роста')
        };
    },

    /**
     * Доля жира и её оценка по полу и возрасту.
     *
     * Таблица Gallagher и соавторов (AJCN, 2000) — она возрастная, в отличие
     * от ходовых «спортивных» шкал: с годами доля жира растёт и у здорового
     * человека, и мерить сорокалетнего по мерке двадцатилетнего значит
     * объявлять возраст болезнью.
     *
     * Границы раздвинуты на запас прибора: весы врут на три–пять пунктов, и
     * зелёная зона обязана быть шире их промаха.
     */
    bodyFat(процент, { sex, age } = {}, прежнее = null) {
        const жир = Number(процент);

        if (!(жир > 2 && жир < 70)) return null;
        if ((sex !== МУЖ && sex !== ЖЕН) || !(age > 0)) {
            return { value: Math.round(жир * 10) / 10, state: СПРАВКА, norm: null };
        }

        const [низ, верх] = health.fatRange(sex, age);

        const мягкийНиз = низ - ЖИР_ЗАПАС;
        const мягкийВерх = верх + ЖИР_ЗАПАС;

        /*
         * Гистерезис работает только в сторону ухудшения (Р-134).
         *
         * Вернуться в зелёное можно сразу, а выйти из него — только заметно
         * перешагнув границу. Иначе половина дней объявлялась бы «стоит
         * посмотреть» из-за стакана воды, а вторая — «хорошо».
         */
        const былоХорошо = прежнее === ХОРОШО;
        const запас = былоХорошо ? ГИСТЕРЕЗИС : 0;

        const хорошо = жир >= мягкийНиз - запас && жир <= мягкийВерх + запас;

        return {
            value: Math.round(жир * 10) / 10,
            state: хорошо ? ХОРОШО : СМОТРЕТЬ,
            norm: t('для пола и возраста — от {низ} до {верх} %', { низ, верх })
        };
    },

    /**
     * Границы нормальной доли жира по полу и возрасту (Gallagher, 2000).
     *
     * Возвращает пару в процентах. Возраст берётся тремя ступенями — так они
     * и опубликованы; выдумывать промежуточные значения было бы точностью,
     * которой в источнике нет.
     */
    fatRange(sex, age) {
        const молодой = age < 40;
        const средний = age < 60;

        if (sex === ЖЕН) {
            if (молодой) return [21, 33];
            return средний ? [23, 34] : [24, 36];
        }

        if (молодой) return [8, 20];
        return средний ? [11, 22] : [13, 25];
    },

    /**
     * Здоровый вес для роста — в килограммах (§66, Р-141).
     *
     * Это норма ВОЗ по индексу массы тела, переведённая обратно в
     * килограммы. Смысл перевода в том, что «27,1» человеку не говорит
     * ничего, а «для вашего роста здоровым считают от 63 до 86» говорит всё.
     *
     * От пола и возраста не зависит: у ВОЗ для взрослых одна вилка на всех.
     * Выдумывать поправку на возраст, которой в источнике нет, приложение не
     * станет — этим оно занимается только там, где поправка опубликована
     * (доля жира, fatRange).
     */
    weightRange(ростСм) {
        const рост = Number(ростСм) / 100;

        if (!(рост > 0.5 && рост < 2.5)) return null;

        const [низ, верх] = health.BMI_НОРМА;

        /*
         * Округление внутрь вилки, а не по правилам арифметики.
         *
         * Для 185 см нижний край — 63,31625 кг, и обычное округление давало
         * 63,3. Ровно на этом весе индекс выходит 18,4995 — и плитка ИМТ
         * ставила «стоит посмотреть» на вес, который соседняя строка только
         * что назвала здоровым. Внутрь — и любой килограмм из названной вилки
         * действительно внутри нормы.
         */
        return {
            from: Math.ceil(низ * рост * рост * 10) / 10,
            to: Math.floor(верх * рост * рост * 10) / 10
        };
    },

    /**
     * Пороги талии по полу — сантиметры (ВОЗ, 2008).
     *
     * Два порога, а не один: у ВОЗ первый — «повышенный риск», второй —
     * «заметно повышенный». У мужчин 94 и 102, у женщин 80 и 88.
     *
     * От роста не зависят, и это их слабое место: у высокого и низкого
     * человека они одни и те же. Рост учитывает соседняя мерка — талия к
     * росту, — и потому обе стоят на экране рядом.
     */
    waistLimits(sex) {
        if (sex === МУЖ) return { watch: 94, risk: 102 };
        if (sex === ЖЕН) return { watch: 80, risk: 88 };

        return null;
    },

    /**
     * Ориентир разгона — во сколько раз неделя больше накопленного.
     *
     * Взят из работ Гэббета о соотношении свежей и накопленной нагрузки:
     * резкая прибавка — лучший известный признак того, что человек вот-вот
     * сорвётся. Числа там 0,8–1,3, и они же взяты здесь.
     *
     * Оговорка, которую нельзя терять: у Гэббета неделя делится на четыре
     * недели, а Intervals.icu копит шесть. Направление то же, точность —
     * меньше, и потому это ориентир, а не порог.
     */
    RAMP: [0.8, 1.3],

    /**
     * Разгон: свежая нагрузка к накопленной (§66, Р-140).
     *
     * Отвечает не на «в форме ли я» — на это отвечает готовность, — а на
     * «не слишком ли резко я прибавил».
     */
    rampUp(свежая, накопленная) {
        const неделя = Number(свежая);
        const шесть = Number(накопленная);

        if (!(неделя > 0) || !(шесть > 0)) return null;

        const значение = Math.round((неделя / шесть) * 100) / 100;
        const [низ, верх] = health.RAMP;

        return {
            value: значение,
            state: значение < низ || значение > верх ? СМОТРЕТЬ : ХОРОШО,
            norm: t('ориентир — {низ}–{верх}', {
                низ: format.plain(низ), верх: format.plain(верх)
            })
        };
    },

    /**
     * Ориентир недельного объёма на одну группу мышц — подходов в неделю.
     *
     * Десять — нижняя граница, ниже которой прирост силы и массы в обзорах
     * почти не отличается от нуля; двадцать — верхняя, за которой добавка
     * перестаёт окупаться усталостью (обзоры Шёнфельда, 2017 и позже).
     *
     * Это ориентир, а не норма: он выведен на группах людей и о конкретном
     * человеке ничего не знает. Потому и границы широкие, и сказано это
     * рядом с числом.
     */
    WEEK_SETS: [10, 20],

    /**
     * Недельный объём на группу мышц (§66, Р-138).
     *
     * Единственная величина на экране, чья мерка взята из тренировочных
     * обзоров, а не из медицины, — и единственная, где «слишком много» такая
     * же новость, как «слишком мало».
     */
    weeklySets(подходов) {
        const n = Number(подходов);

        if (!Number.isFinite(n) || n <= 0) return null;

        const [низ, верх] = health.WEEK_SETS;

        return {
            value: Math.round(n * 10) / 10,
            state: n < низ || n > верх ? СМОТРЕТЬ : ХОРОШО,
            norm: t('ориентир — {низ}–{верх} в неделю', { низ, верх })
        };
    },

    /**
     * Основной обмен по Миффлину — Сан-Жеору.
     *
     * Сколько тело тратит в сутки в полном покое. Формула выбрана не за
     * точность — точной тут нет ни одной, — а за то, что она ходовая: число
     * из приложения сойдётся с числом из любого калькулятора, и человеку не
     * придётся гадать, кто из них врёт.
     *
     * Не красится никогда: у основного обмена нет ни нормы, ни «хорошо». Это
     * опора для следующего числа, а не оценка.
     */
    bmr({ weight, height, age, sex } = {}) {
        const кг = Number(weight);
        const см = Number(height);
        const лет = Number(age);

        if (!(кг > 20) || !(см > 50) || !(лет > 0)) return null;
        if (sex !== МУЖ && sex !== ЖЕН) return null;

        const основа = 10 * кг + 6.25 * см - 5 * лет;

        return Math.round(основа + (sex === МУЖ ? 5 : -161));
    },

    /**
     * Коэффициент активности — из шагов и тренировок, а не из опроса.
     *
     * Спрашивать «насколько вы активны» бессмысленно: человек отвечает о том,
     * каким себя считает, а приложение и так знает, сколько он ходит и сколько
     * занимается. Берётся большее из двух: активность — это не сумма ходьбы и
     * зала, а то, чего из них больше.
     *
     * Ступени — ходовые, из тех же калькуляторов, что и формула обмена.
     */
    activityFactor({ steps = 0, workoutsPerWeek = 0 } = {}) {
        const поШагам = steps >= 14000 ? 1.9
            : steps >= 11000 ? 1.725
            : steps >= 8000 ? 1.55
            : steps >= 6000 ? 1.375
            : 1.2;

        const поЗанятиям = workoutsPerWeek >= 7 ? 1.9
            : workoutsPerWeek >= 5 ? 1.725
            : workoutsPerWeek >= 3 ? 1.55
            : workoutsPerWeek >= 1 ? 1.375
            : 1.2;

        return Math.max(поШагам, поЗанятиям);
    },

    /**
     * Суточный расход: основной обмен, помноженный на активность.
     *
     * Тоже без краски. Число это оценочное вдвойне — и формула приблизительна,
     * и коэффициент ступенчатый, — но именно от него считают, есть ли дефицит.
     * Приложение его называет и говорит, из чего оно собрано.
     */
    amr(основной, коэффициент) {
        const база = Number(основной);
        const k = Number(коэффициент);

        if (!(база > 0) || !(k > 0)) return null;

        return Math.round(база * k);
    },

    /**
     * Ход величины к себе же месяц назад (§66).
     *
     * Здесь нормы нет и быть не может: у веса, талии и тоннажа есть только
     * своё направление. Поэтому и оценка другая — не «в норме», а «идёт туда,
     * куда человек собирался».
     *
     * Куда «туда» — решает не приложение: цель названа в профиле. Без неё
     * возвращается справка, и это честно: у одного и того же минус килограмма
     * два противоположных смысла.
     */
    /**
     * Ход величины по её собственным замерам (Р-179).
     *
     * `trend` сравнивает два числа, а взять эти два числа из истории —
     * отдельная работа, и именно в ней приложение ошибалось. Замер тела —
     * это одна запись на день, и величин в ней несколько: вес есть каждый
     * день, талию меряют лентой раз в неделю, состав привозят весы. Выбирать
     * «что было месяц назад» по записи целиком нельзя: запись месячной
     * давности почти наверняка есть, а талии в ней почти наверняка нет.
     *
     * Так и вышло: у человека под рукой была линия талии из десятка точек, а
     * подпись под ней говорила «не с чем сравнить: замер один». Линию строил
     * ряд, отобранный по самой талии, а подпись — сравнение, отобранное по
     * записям. Два ответа об одном, и оба из приложения.
     *
     * Поэтому здесь отбор идёт по величине: сперва остаются записи, где она
     * есть, и только потом среди них ищется прошлая.
     *
     * Возвращает { value, at, trend } или null, если величины нет вовсе.
     * `trend` — null, когда замер ровно один: сравнивать не с чем, и сказать
     * это надо прямо, а не выдать ноль перемен.
     */
    course(замеры = [], взять = (r) => r, {
        goodDirection = null, noise = 0, window: окно = 30, now = Date.now()
    } = {}) {
        const число = (r) => {
            const v = toNumber(взять(r));
            return Number.isFinite(v) && v > 0 ? v : null;
        };

        // По времени, а не по порядку в массиве: «прошлое» и «последний»
        // здесь — про даты, и молча полагаться на порядок в чужом списке
        // значит поставить весь счёт в зависимость от того, кто его собрал
        const свои = (замеры || [])
            .filter((r) => r && Number.isFinite(r.at) && число(r) !== null)
            .sort((a, b) => a.at - b.at);

        if (свои.length === 0) return null;

        const последний = свои[свои.length - 1];
        const итог = { value: число(последний), at: последний.at, trend: null };

        /*
         * Сам с собой не сравнивается.
         *
         * Прежде прошлым брался «последний замер не позже границы окна», и
         * при единственном замере им оказывался он же: приложение сравнивало
         * сегодняшнее с сегодняшним и объявляло «за месяц без перемен»
         * (Р-134). Та же ловушка срабатывала и на давней паре замеров —
         * оба старше месяца, оба по ту сторону границы.
         */
        const кандидаты = свои.slice(0, -1);
        if (кандидаты.length === 0) return итог;

        const граница = now - окно * 86400000;
        const старые = кандидаты.filter((r) => r.at <= граница);

        // Нет замера старше окна — берётся самый ранний, какой есть: сравнить
        // с двухнедельной давностью честнее, чем не сравнивать вовсе
        const было = старые[старые.length - 1] || кандидаты[0];

        итог.trend = health.trend(число(было), итог.value, { goodDirection, noise });

        return итог;
    },

    trend(было, стало, { goodDirection = null, noise = 0 } = {}) {
        /*
         * Пустое — не ноль (Р-134).
         *
         * Number(null) — это 0, и проверка «конечное ли число» его
         * пропускает. У остальных величин ноль отсеивается сам собой: веса в
         * ноль килограммов не бывает. А здесь ноль законен — вес мог и не
         * измениться, — и отсутствие замера прикидывалось бы падением на
         * девяносто два килограмма.
         */
        const a = toNumber(было);
        const b = toNumber(стало);

        if (!Number.isFinite(a) || !Number.isFinite(b)) return null;

        const разница = Math.round((b - a) * 100) / 100;

        if (!goodDirection || Math.abs(разница) <= noise) {
            return { delta: разница, state: СПРАВКА };
        }

        const туда = goodDirection === 'down' ? разница < 0 : разница > 0;

        return { delta: разница, state: туда ? ХОРОШО : СМОТРЕТЬ };
    }
};
