/**
 * Восстановление: сон и пульс покоя (§62 ТЗ).
 *
 * Приложение считает нагрузку, но о восстановлении не знает ничего, а
 * программа зависит от него не меньше. Ночь в пять часов и пульс покоя на
 * шесть ударов выше обычного — это не «плохое самочувствие», а цифры, по
 * которым тяжёлый день переносят на завтра.
 *
 * Числа приходят с часов через Intervals.icu (§62.1), а этот модуль — чистый:
 * получает ряд замеров, возвращает то, что о нём стоит сказать. Ни сети, ни
 * базы: неверный вывод о восстановлении выглядит так же убедительно, как
 * верный, и проверять его надо отдельно от того, откуда взялись данные.
 *
 * Средним, а не последней ночью. Одна короткая ночь не значит ничего — она
 * бывает у всех и ни на что не влияет; неделя коротких ночей значит многое.
 * Поэтому в выводах неделя, а последняя ночь показывается отдельно и без
 * толкований.
 */

import { t } from './i18n.js';

const DAY = 86400000;

/** Окно наблюдения: та же неделя, которой меряют ритм. */
export const WINDOW = 7;

/** С чем сравнивать пульс покоя: месяц — это база, неделя — это событие. */
export const BASE = 28;

/**
 * На сколько ударов пульс покоя должен отличаться, чтобы об этом говорить.
 *
 * Три: меньшее укладывается в разброс самих часов, и сообщать о нём значит
 * пугать шумом. Больше — и приложение промолчит там, где надо сказать.
 */
export const SHIFT = 3;

/** На сколько должна измениться ВСР, чтобы об этом говорить: десятая часть. */
export const HRV_SHIFT = 0.1;

const число = (v) => (Number.isFinite(v) && v > 0 ? v : null);

/** Полночь дня: окна считаются днями, а не отрезками в миллисекундах. */
const startOfDay = (ts) => {
    const d = new Date(ts);
    d.setHours(0, 0, 0, 0);
    return d.getTime();
};

/** Среднее по непустым значениям. Null, если сказать не о чем. */
function среднее(values) {
    const свои = values.map(число).filter((v) => v !== null);
    if (!свои.length) return null;

    return свои.reduce((s, v) => s + v, 0) / свои.length;
}

export const recovery = {

    WINDOW,
    BASE,
    SHIFT,
    HRV_SHIFT,

    /**
     * Замеры за последние days дней, свежие первыми.
     *
     * Окно считается днями, а не миллисекундами: «за неделю» — это сегодня и
     * шесть предыдущих дней, а не «всё, что новее момента неделю назад». По
     * миллисекундам в недельное окно попадал восьмой день, и среднее ехало.
     *
     * rows — [{ date, sleep, rhr, hrv }], date в миллисекундах.
     */
    recent(rows = [], { now = Date.now(), days = WINDOW } = {}) {
        const с = startOfDay(now) - (days - 1) * DAY;

        return rows
            .filter((r) => Number.isFinite(r?.date) && r.date >= с && r.date <= now + DAY)
            .sort((a, b) => b.date - a.date);
    },


    /** Последняя ночь, о которой вообще есть что сказать. */
    last(rows = []) {
        return [...rows]
            .filter((r) => число(r?.sleep) || число(r?.rhr))
            .sort((a, b) => b.date - a.date)[0] || null;
    },

    /** Средний сон за окно, в секундах. */
    sleep(rows = [], options = {}) {
        return среднее(recovery.recent(rows, options).map((r) => r.sleep));
    },

    /**
     * Пульс покоя: сколько сейчас и насколько это отличается от базы.
     *
     * База — месяц, окно — неделя. Сравнивать неделю с ней самой бессмысленно,
     * а с месяцем — это и есть вопрос «не устал ли я больше обычного».
     */
    resting(rows = [], { now = Date.now() } = {}) {
        const неделя = среднее(recovery.recent(rows, { now, days: WINDOW }).map((r) => r.rhr));
        const месяц = среднее(recovery.recent(rows, { now, days: BASE }).map((r) => r.rhr));

        if (неделя === null || месяц === null) return null;

        return {
            now: Math.round(неделя),
            base: Math.round(месяц),
            shift: Math.round(неделя - месяц)
        };
    },

    /**
     * Вариабельность пульса: сколько сейчас и как это относится к базе.
     *
     * Zepp считает её как rMSSD и отдаёт наружу вместе с прочим. Толковать её
     * приложение не берётся — величина личная, и «хорошо» у каждого своё, — но
     * своё же прошлое даёт единственное сравнение, которое тут осмысленно.
     *
     * Порог долей, а не ударами: разброс ВСР у разных людей отличается втрое,
     * и одно число на всех значило бы молчать у одного и кричать у другого.
     */
    variability(rows = [], { now = Date.now() } = {}) {
        const неделя = среднее(recovery.recent(rows, { now, days: WINDOW }).map((r) => r.hrv));
        const месяц = среднее(recovery.recent(rows, { now, days: BASE }).map((r) => r.hrv));

        if (неделя === null || месяц === null || месяц === 0) return null;

        return {
            now: Math.round(неделя),
            base: Math.round(месяц),
            shift: (неделя - месяц) / месяц
        };
    },

    /**
     * Что сказать о восстановлении — строками, готовыми к показу и к отправке.
     *
     * Пустой массив, если сказать нечего: часы не привязаны, данные не
     * приезжали или в них одни пропуски. Молчание тут честнее выдуманного
     * «данных нет» в каждом разделе.
     */
    describe(rows = [], { now = Date.now() } = {}) {
        const строки = [];

        const сон = recovery.sleep(rows, { now });
        const пульс = recovery.resting(rows, { now });

        if (сон !== null) {
            const часы = Math.floor(сон / 3600);
            const минуты = Math.round((сон % 3600) / 60);

            /*
             * Оценка сна приходит от самих часов и не толкуется.
             *
             * Считает её Zepp по своим соображениям — фазам, пробуждениям,
             * дыханию, — и повторять этот счёт приложение не станет: у него
             * нет ни данных, ни права спорить. Но передать её собеседнику
             * стоит: это единственная величина, которая говорит не сколько
             * человек спал, а как.
             */
            const оценка = среднее(recovery.recent(rows, { now }).map((r) => r.score));

            строки.push(оценка !== null
                ? t('Сон за неделю: в среднем {часы} ч {минуты} мин, оценка {оценка}', {
                    часы, минуты, оценка: Math.round(оценка)
                })
                : t('Сон за неделю: в среднем {часы} ч {минуты} мин', { часы, минуты }));
        }


        if (пульс) {
            строки.push(Math.abs(пульс.shift) >= SHIFT
                ? t('Пульс покоя: {сейчас}, обычно {база}', { сейчас: пульс.now, база: пульс.base })
                : t('Пульс покоя: {сейчас}, как обычно', { сейчас: пульс.now }));
        }

        const всп = recovery.variability(rows, { now });

        if (всп) {
            строки.push(Math.abs(всп.shift) >= HRV_SHIFT
                ? t('Вариабельность пульса: {сейчас}, обычно {база}', { сейчас: всп.now, база: всп.base })
                : t('Вариабельность пульса: {сейчас}, как обычно', { сейчас: всп.now }));
        }

        /*
         * Шаги — про день вне зала (§62.2).

         *
         * Тренировка занимает час, а устаёт человек за сутки: десять тысяч
         * шагов на ногах и три тысячи сидя — это два разных человека с
         * одинаковой историей подходов. Собеседнику это говорит больше, чем
         * ещё одно число об объёме.
         */
        const шаги = среднее(recovery.recent(rows, { now }).map((r) => r.steps));

        if (шаги !== null) {
            строки.push(t('Шаги: в среднем {n} в день', { n: Math.round(шаги) }));
        }


        return строки;
    }
};
