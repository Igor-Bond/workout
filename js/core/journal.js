/**
 * Журнал ошибок (§54 ТЗ).
 *
 * Упавшее действие человек видит окном и забывает через минуту. До
 * разработчика оно не доходит вовсе: рассказать «что-то не сработало» можно,
 * а что именно — уже нет. Журнал держит последние ошибки, чтобы их можно
 * было посмотреть и отправить одной кнопкой.
 *
 * Хранится в localStorage, а не в базе, и это не лень. База — самое частое
 * место, где приложение и падает: нет места на устройстве, приватное окно,
 * открытая вторая вкладка. Журнал, лежащий там же, замолчал бы ровно тогда,
 * когда он нужнее всего.
 *
 * Ничего не уходит наружу само. Отправка — отдельное действие человека, и
 * перед ней он видит, что именно отправляет: собирать молча то, чего он не
 * видел, нельзя (§52).
 */

const KEY = 'wt_errors';

/**
 * Сколько записей хранить.
 *
 * Три десятка — это заметно больше, чем случается за неделю, и заведомо
 * меньше, чем упрётся в объём localStorage. Переполнение вытесняет старое:
 * свежая ошибка полезнее давней, а место кончиться не должно никогда.
 */
const LIMIT = 30;

/** Длина следа вызовов. Целиком он не нужен, а место занимает изрядно. */
const STACK = 600;

function read() {
    try {
        const raw = localStorage.getItem(KEY);
        const list = raw ? JSON.parse(raw) : [];

        return Array.isArray(list) ? list : [];
    } catch {
        // Испорченный журнал — не повод падать в журнале ошибок
        return [];
    }
}

function write(list) {
    try {
        localStorage.setItem(KEY, JSON.stringify(list.slice(-LIMIT)));
    } catch {
        /*
         * Места нет — а причиной ошибки как раз и могло быть его отсутствие.
         * Пробуем сохранить хотя бы последнюю: половина журнала лучше, чем
         * исключение внутри обработчика исключений.
         */
        try { localStorage.setItem(KEY, JSON.stringify(list.slice(-1))); } catch { /* и это не вышло */ }
    }
}

/**
 * Во что превратить то, что прилетело.
 *
 * В обработчик ошибки приходит что угодно: настоящая ошибка, строка,
 * отменённое обещание с объектом вместо причины. У объекта без поля message
 * обычное приведение к строке даёт «[object Object]» — запись, которая
 * занимает место и не говорит ничего. Поэтому такой объект записывается
 * своим содержимым: даже пустые фигурные скобки честнее.
 */
function describe(error) {
    if (!error) return '';

    if (error.message) return String(error.message).slice(0, 300);

    const text = String(error);
    if (text !== '[object Object]') return text.slice(0, 300);

    try {
        return JSON.stringify(error).slice(0, 300);
    } catch {
        // Кольцевые ссылки: сказать про них нечего, но и молчать нельзя
        return '[object Object]';
    }
}

export const journal = {

    LIMIT,

    /** Сколько записей лежит. Для строки в профиле. */
    get count() {
        return read().length;
    },

    /** Записи от старых к свежим. */
    list() {
        return read();
    },

    /**
     * Записать ошибку.
     *
     * Повтор той же ошибки не плодит записи, а увеличивает счётчик: цикл,
     * падающий на каждом такте, иначе вытеснил бы из журнала всё остальное
     * за секунду — и заодно скрыл бы то, с чего всё началось.
     */
    add(error, where = '') {
        try {
            const message = describe(error);
            if (!message) return;

            const list = read();
            const last = list[list.length - 1];

            if (last && last.message === message && last.where === where) {
                last.repeats = (last.repeats || 1) + 1;
                last.at = Date.now();

                write(list);
                return;
            }

            list.push({
                at: Date.now(),
                where,
                message,
                stack: String(error?.stack || '').slice(0, STACK)
            });

            write(list);
        } catch {
            // Журнал ошибок, упавший сам, — худшее, что тут может случиться
        }
    },

    clear() {
        try { localStorage.removeItem(KEY); } catch { /* нечего убирать */ }
    }
};
