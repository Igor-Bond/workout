/**
 * Пульс и калории занятий с часов (§62.2 ТЗ).
 *
 * Приложение знает, что человек сделал: подходы, повторения, вес. Часы знают,
 * чего это ему стоило: пульс и потраченное. Ни то ни другое по отдельности
 * на вопрос «не слишком ли тяжело идёт программа» не отвечает — а вместе
 * отвечают, и это ровно тот вопрос, ради которого план правят.
 *
 * Модуль чистый: занятия с часов на входе, сопоставление и выводы на выходе.
 * Ни сети, ни базы — как и у восстановления (§62), неверный вывод тут
 * выглядит так же убедительно, как верный.
 *
 * Сопоставление по времени, а не по названию. Часы называют занятие
 * «Strength» или «Тренировка», приложение — «Силовая» или «Ноги»; совпасть
 * этому неоткуда. А вот время совпадает всегда: человек занимался один раз, и
 * оба прибора это записали.
 */

import { t } from './i18n.js';

const MINUTE = 60000;
const DAY = 86400000;

/**
 * Насколько занятие с часов может не совпасть с тренировкой по краям.
 *
 * Двадцать минут: часы включают до разминки и выключают после душа, а
 * приложение считает с первого подхода до последнего. Меньший допуск терял
 * бы половину совпадений, больший — склеивал бы утреннюю зарядку с вечерней
 * тренировкой.
 */
export const SLACK = 20 * MINUTE;

/** Окно выводов: та же неделя, что у восстановления и у ритма. */
export const WINDOW = 7;

const число = (v) => (Number.isFinite(v) && v > 0 ? v : null);

const startOfDay = (ts) => {
    const d = new Date(ts);
    d.setHours(0, 0, 0, 0);
    return d.getTime();
};

function среднее(values) {
    const свои = values.map(число).filter((v) => v !== null);
    if (!свои.length) return null;

    return свои.reduce((s, v) => s + v, 0) / свои.length;
}

/**
 * Виды занятий, как их называет Intervals.icu, — по-русски (§62.2, Р-188).
 *
 * Сервис отдаёт их по-английски и своим набором: «Ride», «WeightTraining»,
 * «Workout». Показывать это в русском приложении рядом с «Баскетболом» из
 * справочника значило бы говорить на двух языках в одной строке.
 *
 * Незнакомое остаётся как есть, без перевода: это честнее выдумки. Часы
 * когда-нибудь пришлют вид, которого здесь нет, и «Padel» читается лучше, чем
 * «Прочее», под которым может оказаться что угодно.
 */
const ВИДЫ = {
    ride: 'Велосипед',
    virtualride: 'Велотренажёр',
    run: 'Бег',
    trailrun: 'Бег по тропам',
    virtualrun: 'Беговая дорожка',
    walk: 'Ходьба',
    hike: 'Поход',
    swim: 'Плавание',
    weighttraining: 'Силовая',
    workout: 'Тренировка',
    yoga: 'Йога',
    elliptical: 'Эллипс',
    rowing: 'Гребля',
    crossfit: 'Кроссфит',
    hiit: 'Интервальная',
    soccer: 'Футбол',
    basketball: 'Баскетбол',
    tennis: 'Теннис',
    other: 'Прочее'
};

export const effort = {

    SLACK,
    WINDOW,

    /** Вид занятия по-русски. Незнакомый — как пришёл. */
    typeName(type) {
        const сырое = String(type || '').trim();
        if (!сырое) return t('Без вида');

        const ключ = сырое.toLowerCase().replace(/[\s_-]/g, '');

        return ВИДЫ[ключ] ? t(ВИДЫ[ключ]) : сырое;
    },

    /**
     * Занятие с часов, отвечающее этой тренировке, — или null.
     *
     * Берётся то, что перекрывается по времени сильнее прочих: в один вечер
     * бывает и прогулка, и тренировка, и выбирать между ними по первому
     * попавшемуся нельзя.
     */
    match(workout, activities = []) {
        if (!Number.isFinite(workout?.startedAt)) return null;

        const от = workout.startedAt - SLACK;
        const до = (workout.finishedAt || workout.startedAt) + SLACK;

        let лучшее = null;
        let больше = 0;

        for (const занятие of activities) {
            if (!Number.isFinite(занятие?.start)) continue;

            const конец = Number.isFinite(занятие.end) ? занятие.end : занятие.start;
            const перекрытие = Math.min(до, конец) - Math.max(от, занятие.start);

            if (перекрытие > больше) {
                больше = перекрытие;
                лучшее = занятие;
            }
        }

        return больше > 0 ? лучшее : null;
    },

    /** Занятия за последние days дней, свежие первыми. */
    recent(activities = [], { now = Date.now(), days = WINDOW } = {}) {
        const с = startOfDay(now) - (days - 1) * DAY;

        return activities
            .filter((a) => Number.isFinite(a?.start) && a.start >= с && a.start <= now + DAY)
            .sort((a, b) => b.start - a.start);
    },

    /**
     * Из чего сложилась нагрузка недели — по видам занятий (§62.2, Р-188).
     *
     * Разгон отвечает «не слишком ли резко прибавил», и когда он выходит за
     * ориентир, следующий вопрос один: **что именно его разогнало**. Одно
     * число на это не отвечает — и человек правит наугад ту тренировку, о
     * которой вспомнил, а не ту, которая стоила дороже всех.
     *
     * Складываются нагрузки занятий, каждая из которых посчитана часами по
     * поминутному пульсу. Доли считаются от суммы за ту же неделю.
     *
     * **Это не арифметика разгона, и путать нельзя.** Разгон считает
     * Intervals.icu от ATL и CTL, а те — скользящие средние с затуханием, а
     * не суммы за семь дней. Здесь — доли: кто в этой неделе тяжелее, кто
     * легче. Направление то же, числа разные.
     *
     * Занятия без нагрузки не считаются нулём, а пересчитываются отдельно:
     * ноль в сумме занизил бы долю своего вида молча, а названное «ещё три
     * занятия без нагрузки» человек взвесит сам.
     *
     * Возвращает { rows, total, missing, days } или null, если складывать
     * нечего.
     */
    byType(activities = [], { now = Date.now(), days = WINDOW } = {}) {
        const свежие = effort.recent(activities, { now, days });

        const счёт = new Map();

        let всего = 0;
        let без = 0;

        for (const a of свежие) {
            const load = число(a?.load);

            if (load === null) {
                без += 1;
                continue;
            }

            const вид = String(a?.type || '').trim();
            const своё = счёт.get(вид) || { type: вид, load: 0, count: 0 };

            своё.load += load;
            своё.count += 1;

            счёт.set(вид, своё);
            всего += load;
        }

        if (всего <= 0) return null;

        const rows = [...счёт.values()]
            .map((с) => ({
                type: с.type,
                count: с.count,
                load: Math.round(с.load),

                // Доля от суммы недели: вопрос к разбору именно такой — не
                // «сколько», а «чья это неделя»
                share: Math.round((с.load / всего) * 100)
            }))
            .sort((a, b) => b.load - a.load || b.count - a.count);

        return { rows, total: Math.round(всего), missing: без, days };
    },

    /**
     * Что сказать о том, как идут занятия.
     *
     * Только про занятия с пульсом: прогулка без нагрудного датчика даёт
     * пустую строку, и считать её наравне с тренировкой значит занижать
     * средний пульс до бессмыслицы.
     *
     * Калории названы честно — «на занятиях». Часы считают и суточный расход,
     * но приложение его не спрашивает: оно ведёт тренировки, а не образ
     * жизни, и число, которым нельзя распорядиться, — шум в сводке.
     */
    describe(activities = [], { now = Date.now(), days = WINDOW } = {}) {
        const свежие = effort.recent(activities, { now, days });
        if (!свежие.length) return [];

        const строки = [];

        const пульс = среднее(свежие.map((a) => a.avgHr));
        const пик = свежие.map((a) => число(a.maxHr)).filter(Boolean);
        const калории = свежие.map((a) => число(a.calories)).filter(Boolean);

        if (пульс !== null) {
            строки.push(пик.length
                ? t('Пульс на занятиях: средний {ср}, максимум {макс}', {
                    ср: Math.round(пульс), макс: Math.max(...пик)
                })
                : t('Пульс на занятиях: средний {ср}', { ср: Math.round(пульс) }));
        }

        if (калории.length) {
            строки.push(t('Потрачено на занятиях за неделю: {n} ккал', {
                n: калории.reduce((s, v) => s + v, 0)
            }));
        }

        /*
         * Из чего сложилась неделя (Р-188).
         *
         * Тому, кто правит программу, разгон сам по себе не говорит, что
         * резать: он одно число на все занятия сразу. Доли называют виновника
         * прямо — и это единственная строка сводки, из которой следует
         * решение, а не наблюдение.
         */
        const разбор = effort.byType(activities, { now, days });

        if (разбор && разбор.rows.length > 1) {
            строки.push(t('Нагрузка за неделю {всего}: {доли}', {
                всего: разбор.total,
                доли: разбор.rows
                    .map((р) => t('{вид} {n} %', { вид: effort.typeName(р.type), n: р.share }))
                    .join(', ')
            }));
        }

        return строки;
    }
};
