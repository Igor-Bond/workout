/**
 * План в календарь: превращение недельной сетки в занятия по дням (§62.5).
 *
 * Программа живёт в приложении, а тренируется человек с часами на руке — и о
 * плане они не знают ничего: он на телефоне, в кармане. Напоминание календаря
 * телефон показывает всегда, и часы, зеркалящие уведомления, показывают его
 * следом.
 *
 * Прежде отсюда же план отправлялся прямо в Intervals.icu, чтобы сервис отдал
 * его часам. Путь убран (Р-189): у владельца он не доходил до запястья ни
 * разу, а силовой день не принимают ни Amazfit, ни Huawei. Остался календарь
 * — дорога, не зависящая ни от чьей прошивки.
 *
 * Модуль чистый: план и срок на входе, список занятий на выходе. Ни сети, ни
 * базы — файл собирает ical.js, а решать, что именно в него класть, надо
 * отдельно и проверяемо.
 */

import { plan as planCore } from './plan.js';
import { t } from './i18n.js';

const DAY = 86400000;

/**
 * На сколько вперёд кладём в календарь.
 *
 * Две недели — тот же горизонт, что у развёртки на экране плана. Больше
 * незачем: план правят, и уехавшее на месяц вперёд пришлось бы переписывать
 * при каждой правке. Меньше — и выгружать придётся каждую неделю.
 */
export const HORIZON = 14;

/**
 * Приставка к своему опознавателю занятия.
 *
 * По нему календарь узнаёт уже добавленное и обновляет его, а не заводит
 * второе такое же (§62.5). Приставка отделяет своё от чужого: в календаре
 * лежит не только этот план.
 */
export const PREFIX = 'tracker-plan-';

/** Дата в виде «2026-09-07»: им же опознаётся событие календаря. */
export function ymd(ts) {
    const d = new Date(ts);
    const pad = (n) => String(n).padStart(2, '0');

    return `${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(d.getDate())}`;
}

export const schedule = {

    HORIZON,
    PREFIX,
    ymd,

    /**
     * Что положить в календарь: по занятию на каждый тренировочный день.
     *
     * Дни отдыха не кладутся. Запись «отдых» в календаре — это не подсказка,
     * а лишнее уведомление о том, что делать ничего не надо; человек и без
     * часов знает, что сегодня выходной.
     *
     * Название — краткое описание дня («Бицепс резинка 6 × 50»): на часах
     * видно ровно строку, и она обязана отвечать на вопрос «что сегодня» без
     * разворачивания.
     *
     * В описание идут пауза дня и правила программы: на экране часов их не
     * видно, но человек, открывший занятие в Zepp или в самом сервисе,
     * получит то же, что стоит в плане, — а не голое название.
     */
    build(план, { from = Date.now(), days = HORIZON, rules = [] } = {}) {
        if (!план?.from) return [];

        const развёртка = planCore.expand(план, { from, days });
        const занятия = [];

        for (const день of развёртка) {
            if (!день.session) continue;

            const дата = ymd(день.at);
            const пауза = день.session.rest
                ? [t('Пауза: {n} мин', { n: Math.round(день.session.rest / 60) })]
                : [];

            const этап = день.stage?.label ? [день.stage.label] : [];

            занятия.push({
                date: день.at,
                day: дата,
                externalId: `${PREFIX}${дата}`,
                name: planCore.describe(день.session),
                description: [...этап, ...пауза, ...rules.map((r) => `— ${r}`)].join('\n')
            });
        }

        return занятия;
    },
};
