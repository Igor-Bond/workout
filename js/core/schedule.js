/**
 * План на часы: превращение недельной сетки в запланированные занятия (§62.4).
 *
 * Обратный ход всей цепочки. До сих пор данные шли к приложению — сон, пульс,
 * шаги; здесь они идут от него: Intervals.icu умеет отдавать запланированное
 * на часы, и у Zepp этот тумблер («Загружать плановые тренировки») стоит
 * рядом с тем, которым забирают активность.
 *
 * Смысл простой. Программа живёт в приложении, а тренируется человек с
 * часами на руке, и до сих пор часы о плане не знали ничего: он был на
 * телефоне, в кармане. Уехавший план — это подсказка на запястье в тот
 * момент, когда она нужна, и она же превращает часы из измерителя в
 * участника.
 *
 * Модуль чистый: план и срок на входе, список занятий на выходе. Ни сети, ни
 * базы — отправку делает служба, а решать, что именно отправлять, надо
 * отдельно и проверяемо: ошибка здесь уедет наружу, в чужой сервис, и
 * вернётся оттуда чужими руками.
 */

import { plan as planCore } from './plan.js';
import { t } from './i18n.js';

const DAY = 86400000;

/**
 * На сколько вперёд отправляем.
 *
 * Две недели — тот же горизонт, что у развёртки на экране плана. Больше
 * незачем: план правят, и уехавшее на месяц вперёд пришлось бы стирать при
 * каждой правке. Меньше — и отправлять придётся каждую неделю, то есть
 * вернуться ровно к тому, от чего уходили.
 */
export const HORIZON = 14;

/**
 * Приставка к своему опознавателю занятия.
 *
 * По ней приложение узнаёт в сервисе своё: при повторной отправке чужое
 * трогать нельзя — там могут лежать тренировки, поставленные руками или
 * другим сервисом, — а своё прежнее надо убрать, иначе на день встанут две
 * одинаковые записи.
 */
export const PREFIX = 'tracker-plan-';

/** Дата в виде, который понимает Intervals.icu: 2026-09-07. */
export function ymd(ts) {
    const d = new Date(ts);
    const pad = (n) => String(n).padStart(2, '0');

    return `${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(d.getDate())}`;
}

export const schedule = {

    HORIZON,
    PREFIX,
    ymd,

    /**
     * Что отправить на часы: по занятию на каждый тренировочный день.
     *
     * Дни отдыха не отправляются. Запись «отдых» на часах — это не подсказка,
     * а лишнее уведомление о том, что делать ничего не надо; человек и без
     * часов знает, что сегодня выходной.
     *
     * Название — краткое описание дня («Бицепс резинка 6 × 50»): на часах
     * видно ровно строку, и она обязана отвечать на вопрос «что сегодня» без
     * разворачивания.
     *
     * В описание идут пауза дня и правила программы: на экране часов их не
     * видно, но человек, открывший занятие в Zepp или в самом сервисе,
     * получит то же, что стоит в плане, — а не голое название.
     */
    build(план, { from = Date.now(), days = HORIZON, rules = [] } = {}) {
        if (!план?.from) return [];

        const развёртка = planCore.expand(план, { from, days });
        const занятия = [];

        for (const день of развёртка) {
            if (!день.session) continue;

            const дата = ymd(день.at);
            const пауза = день.session.rest
                ? [t('Пауза: {n} мин', { n: Math.round(день.session.rest / 60) })]
                : [];

            const этап = день.stage?.label ? [день.stage.label] : [];

            занятия.push({
                date: день.at,
                day: дата,
                externalId: `${PREFIX}${дата}`,
                name: planCore.describe(день.session),
                description: [...этап, ...пауза, ...rules.map((r) => `— ${r}`)].join('\n')
            });
        }

        return занятия;
    },

    /** Своё ли это занятие в сервисе — по опознавателю, а не по названию. */
    mine(event) {
        return String(event?.external_id || '').startsWith(PREFIX);
    },

    /**
     * Тело запроса для Intervals.icu.
     *
     * Отдельно от сборки: сборка — про то, что отправлять, а это про то, в
     * каком виде сервис ждёт. Первое проверяется, второе выясняется опытом, и
     * смешивать их значит переписывать проверки при каждой правке формата.
     */
    event(занятие) {
        return {
            start_date_local: `${занятие.day}T00:00:00`,
            category: 'WORKOUT',
            type: 'WeightTraining',
            name: занятие.name,
            description: занятие.description,
            external_id: занятие.externalId
        };
    },

    /**
     * Сколько дней отправленного ещё впереди.
     *
     * Отправка накрывает две недели от дня нажатия, и дальше край уезжает в
     * прошлое сам собой. Часы об этом не скажут: они просто перестанут
     * показывать занятия, и человек решит, что план кончился.
     */
    left(at, { now = Date.now(), days = HORIZON } = {}) {
        if (!at) return null;

        const startOfDay = (ts) => {
            const d = new Date(ts);
            d.setHours(0, 0, 0, 0);
            return d.getTime();
        };

        return days - Math.floor((startOfDay(now) - startOfDay(at)) / DAY);
    },

    /** Границы отправки: с какого по какое число уедет план. */
    span({ from = Date.now(), days = HORIZON } = {}) {
        return { oldest: ymd(from), newest: ymd(from + (days - 1) * DAY) };
    }
};
