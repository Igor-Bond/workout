/**
 * План тренировок: разбор текста и развёртка по дням (§56 ТЗ).
 *
 * План — это объявленная недельная сетка, которой приложение следует, вместо
 * того чтобы выводить ритм из истории. Очередь составов (§29.1) отвечает на
 * вопрос «до чего дольше всего не доходили» и расписанием не является: у
 * плавающего круга промежутки неравные, и порядок в очереди неизбежно
 * расходится с задуманным. Замер на плане владельца дал 17 попаданий из 31.
 * Та же программа, переложенная на жёсткую недельную сетку, — 36 из 36.
 *
 * Хранится правило, а не развёртка: одна неделя плюс срок. Восемь недель по
 * дням — это 56 записей, из которых 49 повторяются, и правка потребовала бы
 * пройти по всем. Даты вычисляются при показе — тем же приёмом, что доля
 * собственного веса (Р-49) и тоннаж (Р-52).
 *
 * Текстом, а не JSON. План читает и правит человек, а составляет его тренер
 * или языковая модель в переписке; текст все трое понимают одинаково, и
 * ошибку в нём видно глазами. Тот же вид приложение просит в сводке (§55) —
 * один и тот же на обоих концах, чтобы ответ не пришлось переписывать.
 */

/**
 * Дни недели как их нумерует Date: 0 — воскресенье.
 *
 * Рядом с сокращением стоит полное имя на всех трёх языках: языковая модель
 * пишет то «Пн», то «Понедельник», то «Monday», и отвергать верный по
 * существу ответ из-за формы слова нельзя.
 */
const ДНИ = [
    { index: 0, keys: ['вс', 'воскресенье', 'su', 'sunday', 'so', 'sonntag'] },
    { index: 1, keys: ['пн', 'понедельник', 'mo', 'monday', 'montag'] },
    { index: 2, keys: ['вт', 'вторник', 'tu', 'tuesday', 'di', 'dienstag'] },
    { index: 3, keys: ['ср', 'среда', 'we', 'wednesday', 'mi', 'mittwoch'] },
    { index: 4, keys: ['чт', 'четверг', 'th', 'thursday', 'do', 'donnerstag'] },
    { index: 5, keys: ['пт', 'пятница', 'fr', 'friday', 'freitag'] },
    { index: 6, keys: ['сб', 'суббота', 'sa', 'saturday', 'samstag'] }
];

/** Слова, которыми обозначают день без тренировки. */
const ОТДЫХ = ['отдых', 'rest', 'ruhe', 'пусто', '—', '-', '–'];

/** Сколько недель по умолчанию: то же окно, на котором приложение видит кондиции. */
const WEEKS = 8;

const DAY = 86400000;

/** Полночь дня. */
const startOfDay = (ts) => {
    const d = new Date(ts);
    d.setHours(0, 0, 0, 0);
    return d.getTime();
};

/**
 * Номер дня недели по первому слову строки.
 *
 * Слово сравнивается целиком, а не первыми двумя буквами: у сокращения и
 * полного имени они разные («пн» против «по»), и срез отвергал бы всё, что
 * написано словом.
 *
 * Начало и продолжение имени тоже годятся — «Пятн» и «понедельника» указывают
 * на день не хуже точного написания, — но только от трёх букв. На двух
 * прозаическая строка «По плану делайте…» стала бы понедельником, и
 * приложение молча приняло бы за задание фразу, которая заданием не была.
 */
function деньНедели(слово) {
    const ключ = слово.toLowerCase().replace(/ё/g, 'е').replace(/[^a-zа-я]/g, '');
    if (ключ.length < 2) return null;

    return ДНИ.find((д) => д.keys.some((k) => k === ключ || (ключ.length >= 3
        && (k.startsWith(ключ) || (k.length >= 3 && ключ.startsWith(k))))))?.index ?? null;
}

/** Число из строки, если она им и является. */
const число = (s) => {
    const n = Number(String(s).replace(',', '.'));
    return Number.isFinite(n) && n > 0 ? n : null;
};

export const plan = {

    WEEKS,

    /**
     * Разбор текста плана.
     *
     * Возвращает { from, weeks, days, stages, problems }. Проблемы — не
     * ошибки разбора, а места, где приложение не поняло строку: их показывают
     * человеку, а не глотают. План с проблемами всё равно применим — просто
     * в нём меньше дней, чем написано.
     */
    parse(text = '') {
        const grids = [];
        const stages = [];
        const problems = [];
        const rules = [];

        let from = null;
        let weeks = WEEKS;
        let next = null;

        /*
         * Текущая сетка — та, в которую падают строки дней.
         *
         * Сеток может быть несколько: этапы со своими неделями и чередование
         * недель внутри этапа (§56.4). Пока заголовков нет, сетка одна — и
         * это самый частый план: одна неделя, повторяющаяся до конца срока.
         */
        let сетка = null;

        const новая = (label, диапазон) => {
            сетка = { label, from: диапазон?.from ?? null, to: диапазон?.to ?? null, days: {} };
            grids.push(сетка);
            return сетка;
        };

        const строки = String(text).split('\n');

        for (let i = 0; i < строки.length; i++) {
            const строка = строки[i].trim();
            if (!строка) continue;

            // Шапка: «С 06.09.2026, 8 недель»
            const дата = строка.match(/(\d{1,2})[.\/](\d{1,2})[.\/](\d{4})/);

            if (дата) {
                const at = startOfDay(new Date(+дата[3], +дата[2] - 1, +дата[1]).getTime());

                /*
                 * Вторая дата начала — это второй план, и разбор здесь
                 * кончается (Р-65).
                 *
                 * Собеседник, которого просят дать различающиеся недели
                 * отдельными блоками, присылает их подряд одним текстом — и
                 * это правильный ответ на правильную просьбу. А приложение
                 * читало его насквозь: дату брало из первого блока, а дни
                 * второго молча затирали дни первого. Получался план, которого
                 * не писал никто: начало сентябрьское, занятия октябрьские.
                 *
                 * Остаток отдаётся целиком, чтобы экран мог предложить второй
                 * блок отдельно, а не заставлял искать его в переписке.
                 */
                if (from !== null) {
                    next = { from: at, text: строки.slice(i).join('\n').trim() };
                    break;
                }

                from = at;

                const срок = строка.match(/(\d+)\s*(недел|week|woche)/i);
                if (срок) weeks = Math.max(1, Math.min(52, +срок[1]));

                continue;
            }

            /*
             * Этап: с этой строки начинается своя сетка (§56.4).
             *
             * Раньше строка только показывалась — она объясняла замысел и не
             * значила ничего. Но программа на двенадцать недель тем и
             * отличается от восьминедельной, что в ней три разных этапа, и
             * приложение, исполняющее только первый, требовало утверждать
             * новый план каждый месяц.
             *
             * Граница слова \b здесь не годится: она определена по латинице,
             * и после «этап» не срабатывает вовсе — строки уезжали в
             * «не понято». Проверяем прямо: за словом идёт пробел или число.
             */
            if (/^(этап|stage|phase)[\s\d]/i.test(строка)) {
                stages.push(строка);
                новая(строка, plan.stageWeeks(строка));
                continue;
            }

            /*
             * Заголовок недели: «Неделя 1», «Неделя А», «Week 2» (§56.4).
             *
             * Им объявляют чередование: у владельца тяжёлая неделя и лёгкая
             * различаются целиком, и одной сеткой их не записать. Внутри
             * этапа недели наследуют его срок и чередуются в его пределах.
             */
            const неделя = строка.match(/^(?:недел[яию]|week|woche)\s*([0-9]{1,2}|[абab])\s*:?\s*$/i);

            if (неделя) {
                новая(строка, { from: сетка?.from ?? null, to: сетка?.to ?? null });
                continue;
            }

            /*
             * Правило программы (§56.2).
             *
             * Строка, начатая тире или звёздочкой, — это правило: «RIR 2»,
             * «прогресс сопротивлением, не повторениями», «зарядку держать в
             * диапазоне». Приложение их не толкует, а хранит и показывает — и,
             * главное, отдаёт вместе с планом тому, кто составляет следующий.
             *
             * До этого правила уезжали в «не понято» и выглядели там ошибкой
             * разбора. Хуже того, их вовсе не писали: заголовок «Правила»
             * приложение не просило, и вся программа сводилась к расписанию.
             * Тренер, не увидевший правила, честно предложил наращивать
             * повторения — ровно то, чего программа запрещала.
             *
             * Заголовок «Правила:» просто съедается: он объявляет раздел, а
             * сам правилом не является.
             */
            if (/^(правила|rules|regeln)\s*:?\s*$/i.test(строка)) continue;

            if (/^[—–\-*•]\s*\S/.test(строка)) {
                rules.push(строка.replace(/^[—–\-*•]\s*/, '').trim());
                continue;
            }

            const [первое, ...остальное] = строка.split(/\s+/);
            const день = деньНедели(первое);

            if (день === null) {
                // Строки до шапки и прочая проза разбору не мешают
                if (from !== null) problems.push(строка);
                continue;
            }

            if (!сетка) новая('', null);

            const хвост = остальное.join(' ').trim();

            if (!хвост || ОТДЫХ.includes(хвост.toLowerCase())) {
                сетка.days[день] = null;
                continue;
            }

            сетка.days[день] = plan.parseDay(хвост);
        }

        /*
         * Этапы без указанных недель делят срок поровну.
         *
         * Собеседника просят писать «Этап 1 (недели 1–4)», и обычно он так и
         * пишет. Но если не написал, объявленные этапы всё равно надо как-то
         * исполнить — а единственное честное толкование трёх этапов на
         * двенадцать недель это по четыре недели каждому.
         */
        plan.spread(grids, weeks);

        const days = grids[0]?.days || {};

        return { from, weeks, days, grids, stages, rules, problems, next };
    },

    /**
     * Недели этапа из его заголовка: «Этап 2 (недели 5–8)» → { from: 5, to: 8 }.
     *
     * Null, если не написаны: тогда срок этапа выведет spread().
     */
    stageWeeks(строка = '') {
        const m = String(строка).match(/(?:недел|week|woche)\S*\s*(\d{1,2})\s*[-–—]\s*(\d{1,2})/i);
        if (!m) return null;

        return { from: Math.min(+m[1], +m[2]), to: Math.max(+m[1], +m[2]) };
    },

    /**
     * Раздать срок этапам, у которых он не написан.
     *
     * Делим поровну и только когда не написан ни у одного: половина этапов со
     * своими неделями и половина поделённых — это план, о котором никто не
     * договаривался, и лучше исполнить как написано первый, чем угадать все.
     */
    spread(grids = [], weeks = WEEKS) {
        const этап = (g) => /^(этап|stage|phase)/i.test(g.label || '');
        const этапы = grids.filter(этап);

        if (этапы.length < 2 || этапы.some((g) => g.from !== null)) return grids;

        const доля = Math.max(1, Math.floor(weeks / этапы.length));

        этапы.forEach((g, i) => {
            g.from = i * доля + 1;
            g.to = i === этапы.length - 1 ? weeks : (i + 1) * доля;
        });

        /*
         * Недели внутри этапа наследуют его срок: при разборе они создавались
         * раньше, чем срок этапа стал известен.
         */
        let текущий = null;

        for (const сетка of grids) {
            if (этап(сетка)) {
                текущий = сетка;
                continue;
            }

            if (текущий && сетка.from === null) {
                сетка.from = текущий.from;
                сетка.to = текущий.to;
            }
        }

        return grids;
    },


    /**
     * Занятие одного дня — одно упражнение или несколько через «+».
     *
     * «Бицепс резинка 6 × 50 + Пресс 6 × 25» — это один день, а не два.
     * Программы так и пишут: основной блок плюс добор, которым день
     * выравнивают до общего числа подходов. Держать в дне ровно одно
     * упражнение значило бы терять вторую половину задания молча.
     *
     * Днём по-прежнему распоряжается первое упражнение: его именем день
     * узнаётся в истории, по нему же считается, сделан он или нет. Остальные
     * едут в items и попадают в тренировку вместе с ним.
     */
    parseDay(строка) {
        /*
         * Пауза дня (§56.2): «…, пауза 10 мин».
         *
         * Живёт в самом дне, а не общим правилом на план: у шестисетового дня
         * пауза десять минут, у двенадцатисетового пять, и это разные дни
         * одной недели. Общая настройка отдыха такого различия не знает — она
         * одна на всё приложение (§16).
         *
         * Отрезается до разбора упражнений, иначе «10» из «пауза 10 мин»
         * прочиталось бы как число подходов последнего упражнения.
         */
        const текст = String(строка);
        /*
         * Границы слова здесь нет намеренно.
         *
         * \b определена по латинице и после кириллического «мин» не
         * срабатывает вовсе: движок откатывался, оставлял единицу пустой, и
         * «пауза 90 сек» превращалась в полтора часа. Та же ловушка уже
         * ловила разбор этапов. Единицы перечислены от длинной к короткой,
         * чтобы «м» не откусывал начало «мин».
         */
        const пауза = текст.match(/(?:[,;]\s*)?(?:пауза|отдых|rest|pause)\s*:?\s*(\d+)\s*(мин|min|сек|sec|м|с|s)?/i);

        const чистая = пауза ? текст.slice(0, пауза.index).trim() : текст.trim();

        const части = чистая.split('+').map((s) => s.trim()).filter(Boolean);
        const items = части.map(plan.parseItem);

        const день = { ...items[0], items };

        if (пауза) {
            const число = Number(пауза[1]);
            const секунды = /^(сек|sec|с|s)$/i.test(пауза[2] || '') ? число : число * 60;

            if (Number.isFinite(секунды) && секунды > 0) день.rest = Math.min(1800, секунды);
        }

        return день;
    },

    /**
     * Одно упражнение задания: «Бицепс резинка 6 × 50».
     *
     * Объём необязателен: «Баскетбол» — тоже занятие, просто подходов у него
     * нет. Разделителем принимается любой из ×, x, х и *: они неразличимы на
     * вид, и требовать один значит спорить о невидимом.
     */
    parseItem(строка) {
        const текст = String(строка).trim();

        /*
         * Разделитель ищется между числами, а не по всей строке (Р-75).
         *
         * Раньше строка резалась по набору «× x х * пробел», и кириллическое
         * «х» внутри слова резало слово: «Отжимания узким хватом 6 × 25»
         * превращалось в «Отжимания узким ватом». Приложение не понимало, что
         * потеряло букву, — оно просто заводило упражнение с опечаткой, и
         * план переставал узнавать своё же название.
         *
         * Русское «х» из набора не убрано: люди пишут «6 х 50», и отвергать
         * это значило бы придираться к раскладке. Но теперь оно считается
         * знаком умножения только там, где стоит между двумя числами.
         */
        const объём = текст.match(/^(.*?)\s+(\d+)\s*[×xх*]\s*(\d+)$/i);

        if (объём && +объём[2] > 0 && +объём[3] > 0) {
            return { name: объём[1].trim(), sets: +объём[2], reps: +объём[3] };
        }

        // «Бицепс 6» — только подходы
        const хвост = текст.match(/^(.*?)\s+(\d+)$/);
        if (хвост && +хвост[2] > 0) return { name: хвост[1].trim(), sets: +хвост[2], reps: null };

        return { name: текст, sets: null, reps: null };
    },


    /** Номер недели плана для даты. Первая неделя — первая. */
    weekOf(план, at = Date.now()) {
        if (!план?.from) return 0;

        return Math.floor((startOfDay(at) - startOfDay(план.from)) / (7 * DAY)) + 1;
    },

    /**
     * Сетки плана.
     *
     * План, разобранный прежней версией, сеток не знает — у него есть только
     * days. Считаем его планом из одной сетки: иначе утверждённая программа
     * перестала бы работать после обновления приложения, а рушить работающее
     * ради нового устройства нельзя.
     */
    grids(план) {
        return план?.grids?.length
            ? план.grids
            : [{ label: '', from: null, to: null, days: план?.days || {} }];
    },

    /**
     * Объявлены ли в сетке дни.
     *
     * Заголовок этапа, у которого дни расписаны по неделям («Этап 2», а под
     * ним «Неделя 1» и «Неделя 2»), своих дней не несёт вовсе — у него нет ни
     * одного ключа. Полностью выходная неделя — несёт: семь ключей, все
     * пустые. Разница существенная: первую в чередование пускать нельзя,
     * вторую нужно.
     */
    declared(сетка) {
        return Object.keys(сетка?.days || {}).length > 0;
    },

    /**
     * Какая сетка действует в этот день (§56.4).
     *
     * Два правила разом, и оба нужны настоящим программам:
     *
     * Этапы. Сетка со сроком «недели 5–8» действует только в свои недели —
     * этап перестал быть подписью и стал расписанием. Без этого программу на
     * двенадцать недель приходилось утверждать заново каждый месяц.
     *
     * Чередование. Несколько сеток без срока (или с одним и тем же) сменяют
     * друг друга по неделям: тяжёлая неделя, лёгкая, снова тяжёлая. Одной
     * сеткой это не записать, а именно так устроена половина программ.
     */
    gridFor(план, at = Date.now()) {
        const все = plan.grids(план);
        const неделя = Math.max(1, plan.weekOf(план, at));

        const свои = все.filter((g) => (g.from === null || неделя >= g.from)
            && (g.to === null || неделя <= g.to));

        /*
         * Ни одна сетка не подходит — берём все. Так бывает у плана, который
         * пережил свой срок: неделя девятая, а этапов объявлено восемь.
         * Показать последнее известное честнее, чем показать пустой день.
         */
        const набор = свои.length ? свои : все;

        // Заголовок этапа без своих дней в чередовании не участвует: иначе
        // каждая третья неделя оказывалась бы пустой
        const живые = набор.filter(plan.declared);
        const итог = живые.length ? живые : набор;

        if (итог.length === 1) return итог[0];

        const начало = итог.reduce((min, g) => Math.min(min, g.from ?? 1), Infinity);
        const первая = Number.isFinite(начало) ? начало : 1;

        return итог[(неделя - первая) % итог.length];
    },

    /**
     * Все упражнения плана — из всех сеток разом.
     *
     * Нужно всюду, где план сверяется со справочником: незнакомые названия,
     * спор с ограничениями, заведение упражнений. Обходить одну сетку мало —
     * упражнение, появляющееся только на третьем этапе, так и осталось бы
     * незамеченным до самого этого этапа.
     */
    items(план) {
        const out = [];

        for (const сетка of plan.grids(план)) {
            for (const день of Object.values(сетка.days || {})) {
                for (const у of (день?.items || (день ? [день] : []))) out.push(у);
            }
        }

        return out;
    },

    /** Занятие этого дня по плану — с учётом этапа и чередования недель. */
    dayAt(план, at = Date.now()) {
        return plan.gridFor(план, at).days[new Date(startOfDay(at)).getDay()] || null;
    },

    /**
     * Этап, идущий в этот день, — или null, если этапов не объявлено.
     *
     * Нужен показу и сводке: «сейчас этап 2 из 3» объясняет и человеку, и
     * собеседнику, почему неделя выглядит не так, как предыдущая.
     */
    stageAt(план, at = Date.now()) {
        const неделя = Math.max(1, plan.weekOf(план, at));

        const этапы = plan.grids(план).filter((g) => /^(этап|stage|phase)/i.test(g.label || ''));

        return этапы.find((g) => (g.from === null || неделя >= g.from)
            && (g.to === null || неделя <= g.to)) || null;
    },

    /** Есть ли в плане хоть один тренировочный день. */
    usable(разобранный) {
        return !!разобранный?.from
            && plan.grids(разобранный).some((g) => Object.values(g.days || {}).some(Boolean));
    },

    /** Последний день плана. */
    until(план) {
        return план?.from ? план.from + план.weeks * 7 * DAY - 1 : 0;
    },

    /** Идёт ли план прямо сейчас. */
    active(план, now = Date.now()) {
        return !!план?.from && now >= план.from && now <= plan.until(план);
    },

    /**
     * За сколько дней до конца плана о нём предупреждать.
     *
     * Неделя: следующий план человек не пишет сам — он его просит, и на
     * переписку с тренером или моделью нужно время. Сказать в последний день
     * значит поставить перед выбором «сегодня без плана или сегодня же
     * садись писать».
     */
    ENDING: 7,

    /**
     * Состояние плана относительно сегодня (§56.1).
     *
     * Приложение обязано говорить о плане на всех трёх границах, а не только
     * пока он идёт. Объявленный, но не начавшийся план молчал так же, как
     * его отсутствие: человек утверждал план в субботу, смотрел на главный
     * экран и не понимал, принят ли он вообще. Кончившийся молчал тем же
     * молчанием — приложение просто возвращалось к подсказкам по истории,
     * не сказав, что программа исчерпана.
     */
    state(план, now = Date.now()) {
        if (!план?.from) return 'none';

        if (startOfDay(now) < startOfDay(план.from)) return 'upcoming';
        if (now > plan.until(план)) return 'over';

        return plan.daysLeft(план, now) <= plan.ENDING ? 'ending' : 'running';
    },

    /** Сколько дней плана осталось, считая сегодняшний. */
    daysLeft(план, now = Date.now()) {
        if (!план?.from) return 0;

        return Math.max(0, Math.round((startOfDay(plan.until(план)) - startOfDay(now)) / DAY));
    },

    /** Через сколько дней план начнётся. Ноль — уже начался. */
    startsIn(план, now = Date.now()) {
        if (!план?.from) return 0;

        return Math.max(0, Math.round((startOfDay(план.from) - startOfDay(now)) / DAY));
    },

    /** Первый тренировочный день плана — им и открывается объявленный план. */
    first(план) {
        if (!план?.from) return null;

        for (let i = 0; i < 7; i++) {
            const at = план.from + i * DAY;
            const занятие = plan.dayAt(план, at);
            if (занятие) return { at, session: занятие };
        }

        return null;
    },

    /**
     * Развёртка на даты: что и когда по плану.
     *
     * Считается, а не хранится: правка одной строки недели меняет все восемь
     * недель разом.
     */
    expand(план, { from = план?.from, days = 14 } = {}) {
        if (!план?.from) return [];

        const начало = Math.max(startOfDay(from), план.from);
        const конец = plan.until(план);
        const ряд = [];

        for (let i = 0; i < days; i++) {
            const at = начало + i * DAY;
            if (at > конец) break;

            const неделя = Math.floor((at - план.from) / (7 * DAY)) + 1;
            ряд.push({ at, week: неделя, session: plan.dayAt(план, at), stage: plan.stageAt(план, at) });
        }

        return ряд;
    },

    /**
     * Что делать сегодня по плану (§56).
     *
     * Ровно то, что стоит в сетке на сегодня, — и ничего больше. Пропущенный
     * день пропущен: он не переносится и не копится долгом, а возвращается
     * через неделю на своём же месте.
     *
     * Сначала было наоборот — пропущенное сдвигалось внутри недели. Это
     * оказалось хуже, и ровно в том, ради чего сетку заводили (Р-62).
     * Пропуск понедельника уводил баскетбол со среды на четверг, а
     * воскресный отдых съедался целиком: каждый день недели оказывался
     * занят вчерашним. Сетка объявлена именно затем, чтобы день недели
     * держался, — двигать её при первом же пропуске значит её отменить.
     *
     * Без плана всё наоборот: там ритм выводится из истории, и очередь
     * составов (§29.1) сама расходится на длину пропуска — так и надо, ей
     * держать нечего.
     *
     * done — названия занятий, сделанных сегодня.
     */
    today(план, { now = Date.now(), done = [] } = {}) {
        if (!plan.active(план, now)) return null;

        const занятие = plan.dayAt(план, now);
        if (!занятие) return null;

        const сделано = done.some((имя) => plan.same(имя, занятие.name));

        return сделано ? null : { ...занятие };
    },

    /**
     * Ближайший тренировочный день начиная с завтра (§26.2).
     *
     * Нужен прогнозу: при объявленной сетке гадать нечего — день недели уже
     * всё сказал. Дальше недели не смотрим: сетка повторяется, и восьмой день
     * это тот же первый.
     */
    next(план, { now = Date.now() } = {}) {
        if (!план?.from) return null;

        const конец = plan.until(план);
        let at = Math.max(startOfDay(now) + DAY, план.from);

        for (let i = 0; i < 7; i++, at += DAY) {
            if (at > конец) return null;

            const занятие = plan.dayAt(план, at);
            if (занятие) return { at, session: занятие };
        }

        return null;
    },

    /**
     * Переписать повторения упражнения прямо в тексте плана (§59.1).
     *
     * Нужно прибавке: приложение говорит «можно тяжелее», знает, какими
     * станут числа, — и до сих пор человек переписывал их руками. Правится
     * текст, а не разбор: план хранится текстом и правится человеком в том же
     * поле, и подмена в разборе была бы для него невидимой.
     *
     * Меняется только второе число — повторения. Подходы остаются: смена
     * сопротивления это не смена схемы, и трогать её приложение не вправе.
     *
     * Совпадение по названию требует объёма следом. Иначе «Пресс» переписал бы
     * заодно и «Пресс стоя»: имя короче и входит в длинное целиком.
     */
    retune(text = '', name = '', fn = (reps) => reps) {
        const ключ = (s) => String(s).toLowerCase().replace(/ё/g, 'е');
        const цель = ключ(name).trim();

        if (!цель) return String(text);

        return String(text).split('\n').map((строка) => {
            const норма = ключ(строка);

            let итог = '';
            let i = 0;

            for (;;) {
                const at = норма.indexOf(цель, i);

                if (at === -1) {
                    итог += строка.slice(i);
                    return итог;
                }

                const конецИмени = at + цель.length;
                const объём = строка.slice(конецИмени).match(/^(\s*\d+\s*[×xх*]\s*)(\d+)/);

                if (!объём) {
                    итог += строка.slice(i, конецИмени);
                    i = конецИмени;
                    continue;
                }

                const новое = fn(+объём[2]);

                итог += строка.slice(i, конецИмени) + объём[1]
                    + (Number.isFinite(новое) && новое > 0 ? новое : объём[2]);

                i = конецИмени + объём[0].length;
            }
        }).join('\n');
    },

    /**
     * Заменить название упражнения в тексте плана (§56.3).
     *
     * Нужно, когда собеседник узнал в незнакомом названии уже заведённое:
     * «Отжимания от пола» — те же «Отжимания». Заводить второе значило бы
     * раздувать справочник двумя записями об одном движении, а история
     * разошлась бы по ним пополам.
     *
     * Правится текст, а не разбор: план хранится своим текстом и правится
     * человеком в том же поле. Подмена в разборе была бы невидимой — человек
     * открыл бы план и увидел прежнее название.
     *
     * Сравнение без придирок к регистру и «ё», но длина при этом сохраняется:
     * иначе места замены съехали бы относительно исходного текста.
     */
    rename(text = '', from = '', to = '') {
        const ключ = (s) => String(s).toLowerCase().replace(/ё/g, 'е');
        const цель = ключ(from);

        if (!цель.trim() || !String(to).trim()) return String(text);

        const исходный = String(text);
        const поиск = ключ(исходный);

        let итог = '';
        let i = 0;

        for (;;) {
            const at = поиск.indexOf(цель, i);

            if (at === -1) {
                итог += исходный.slice(i);
                return итог;
            }

            итог += исходный.slice(i, at) + to;
            i = at + цель.length;
        }
    },

    /** Одно ли это занятие: сравнение по названию, без придирок к регистру. */
    same(a = '', b = '') {
        const ключ = (s) => String(s).toLowerCase().replace(/ё/g, 'е').replace(/\s+/g, ' ').trim();
        return ключ(a) === ключ(b);
    },

    /**
     * Короткое описание занятия: «Бицепс резинка 6 × 50 + Пресс 6 × 25».
     *
     * Объём не прячется: он часть задания на день, и человек смотрит на
     * строку именно ради него. Добор к блоку не прячется тоже — иначе день
     * на карточке выглядит вдвое легче, чем он есть.
     *
     * Пустая строка вместо слова «отдых»: ядро не переводит, а подпись
     * дню без занятия даёт тот, кто его показывает.
     */
    describe(занятие) {
        if (!занятие) return '';

        return (занятие.items || [занятие]).map(plan.item).join(' + ');
    },

    /** Одно упражнение задания словами. */
    item(упражнение) {
        if (!упражнение?.sets) return упражнение?.name || '';

        return упражнение.reps
            ? `${упражнение.name} ${упражнение.sets} × ${упражнение.reps}`
            : `${упражнение.name} ${упражнение.sets}`;
    }
};
