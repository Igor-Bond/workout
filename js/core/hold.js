/**
 * Отсчёт подхода на время (§57 ТЗ).
 *
 * Планка на сорок пять секунд — это ровно та же беда, из-за которой появился
 * интервальный экран (§50): держать планку и одновременно смотреть на часы
 * нельзя. Приложение просило вписать число после подхода, и число это было
 * выдумкой — сколько человек продержал на самом деле, не знал никто, включая
 * его самого.
 *
 * Поэтому здесь приложение ведёт, а не записывает: отсчитывает подход вслух
 * и записывает то, что правда прошло.
 *
 * Интервальной программой это не сделано намеренно. Интервальная программа —
 * это круги с общим ритмом на всю тренировку, а планка стоит одним подходом
 * среди десяти обычных: в субботу десять подходов на повторения и два на
 * время. Общего ритма у них нет и быть не может.
 *
 * Зато сигналы те же самые, из того же словаря (§50.1): три щелчка, удар
 * «начали», пульс во время работы, три щелчка и удар «стоп». Человек уже
 * знает их по табате, и учить второй язык сигналов ему незачем.
 *
 * Состояние выводится из прошедшего времени, а не копится тиками: тик в
 * свёрнутом приложении браузер придерживает, часы — нет.
 */

/**
 * Подготовка перед началом.
 *
 * Пять секунд, а не десять как в интервальной программе: там встают на
 * место между кругами, здесь — ложатся в упор сразу после нажатия. И не
 * три: в три секунды не успеть отложить телефон и принять положение.
 */
const LEAD = 5;

/** Сколько секунд в конце отрезка занимает отсчёт «три-два-один». */
const COUNT = 3;

/** Шаг пульса во время работы — тот же, что в интервальной программе. */
const PULSE = 3;

export const hold = {

    LEAD,
    COUNT,
    PULSE,

    /**
     * Сигналы подхода: время в секундах от нажатия «Пуск».
     *
     * Словарь общий с интервальной программой, поэтому очередь кладётся тем
     * же beeper.schedule. Своя сборка, а не interval.cues, потому что здесь
     * не программа из отрезков: у секундомера конца нет вовсе, и втискивать
     * его в список фаз значило бы придумать фазу неизвестной длины.
     *
     * target === null — секундомер: отсчитывать нечего, звучит только
     * подготовка и «начали».
     */
    cues(target = null) {
        const list = [];

        for (let n = COUNT; n >= 1; n--) list.push({ at: LEAD - n, type: 'count' });
        list.push({ at: LEAD, type: 'go' });

        if (!target) return list;

        /*
         * Пульс отмеряется от конца, а не от начала.
         *
         * Считая от начала, последний пульс попадал бы куда придётся и на
         * слух сливался с отсчётом «три-два-один». От конца он всегда
         * отстоит от отсчёта ровно на шаг.
         */
        for (let left = COUNT + PULSE; left < target; left += PULSE) {
            list.push({ at: LEAD + target - left, type: 'pulse' });
        }

        for (let n = COUNT; n >= 1; n--) {
            const when = LEAD + target - n;
            if (when > LEAD) list.push({ at: when, type: 'count' });
        }

        list.push({ at: LEAD + target, type: 'done' });

        return list.sort((a, b) => a.at - b.at);
    },

    /**
     * Где мы сейчас: подготовка, работа или конец.
     *
     * elapsed — секунды от нажатия «Пуск», дробные.
     *
     * worked — сколько работы прошло. Именно оно записывается подходом,
     * если остановить раньше срока: соврать в меньшую сторону здесь так же
     * плохо, как в большую.
     */
    at(target, elapsed = 0) {
        if (elapsed < LEAD) {
            return { phase: 'lead', left: Math.max(1, Math.ceil(LEAD - elapsed)), worked: 0 };
        }

        const worked = elapsed - LEAD;

        if (!target) {
            return { phase: 'work', left: null, worked: Math.floor(worked) };
        }

        if (worked >= target) {
            return { phase: 'done', left: 0, worked: target };
        }

        return { phase: 'work', left: Math.ceil(target - worked), worked: Math.floor(worked) };
    },

    /**
     * Годится ли число как цель отсчёта.
     *
     * Верхняя граница та же, по смыслу, что у отдыха: полчаса удержания —
     * это не подход, а опечатка в поле, где ждали «45».
     */
    LONGEST: 1800,

    clamp(seconds) {
        const value = Math.round(Number(seconds));
        if (!Number.isFinite(value) || value <= 0) return null;

        return Math.min(hold.LONGEST, value);
    }
};
