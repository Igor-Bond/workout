/**
 * Прикидка стартового веса (§10.1 ТЗ).
 *
 * Только для упражнения, которого человек ещё ни разу не делал. Для всего
 * остального у приложения есть предсказатель точнее любых коэффициентов —
 * собственная история: повтор прошлой подставляет ровно те веса, что были,
 * а на экране выполнения виден прошлый раз и рекорд.
 *
 * Коэффициенты же — средние по популяции. Для конкретного человека они врут
 * на десятки процентов, и подставлять их туда, где есть факт, значило бы
 * менять знание на догадку. Пустое поле честнее неверного числа — но там,
 * где ориентира нет вообще, грубая прикидка всё же лучше пустоты.
 *
 * Отсюда два правила, которые здесь не нарушаются никогда:
 * прикидка появляется только при нулевой истории, и она всегда подписана
 * как прикидка.
 *
 * Числа — заведомо осторожные, ближе к нижней границе новичковых норм:
 * взять меньше и добавить безопаснее, чем сорваться на первом подходе.
 */

/** Доля собственного веса, с которой начинают. Ключ — нормализованное название. */
const BY_NAME = {
    'жим лежа': 0.5,
    'жим гантелей лежа': 0.18,          // на каждую гантель
    'разведение гантелей': 0.08,
    'приседания со штангой': 0.6,
    'становая тяга': 0.7,
    'жим ногами': 0.9,
    'выпады': 0.15,
    'разгибание ног': 0.3,
    'сгибание ног': 0.25,
    'подъем на носки': 0.5,
    'тяга верхнего блока': 0.5,
    'тяга штанги в наклоне': 0.45,
    'тяга горизонтального блока': 0.5,
    'жим стоя': 0.35,
    'жим гантелей сидя': 0.15,
    'махи гантелями в стороны': 0.05,
    'подъем штанги на бицепс': 0.25,
    'подъем гантелей на бицепс': 0.1,
    'французский жим': 0.2,
    'разгибание на блоке': 0.25
};

/** Запасной вариант по группе мышц, когда название незнакомо. */
const BY_GROUP = {
    'Грудь': 0.4,
    'Спина': 0.45,
    'Ноги': 0.6,
    'Плечи': 0.25,
    'Руки': 0.2
};

/** Шаг округления: на штангу вешают блины, а не произвольные килограммы. */
const STEP = 2.5;

/**
 * Какая доля собственного веса приходится на упражнение (§15.2).
 *
 * Только для упражнений со своим весом. Там снаряда нет, и по записи
 * «25 повторений» о нагрузке не сказать ничего: отжимания — это не весь
 * вес тела, а около двух третей, часть опирается на носки; подтягивания —
 * вес целиком; скручивания — треть.
 *
 * У упражнений со снарядом такой вопрос не стоит: нагрузка названа в самой
 * записи, и приписывать к ней вес тела приложение не берётся.
 *
 * Числа усреднённые, и других здесь быть не может: доля зависит от роста,
 * длины рычагов и техники. Поэтому на экране она всегда со словом
 * «примерно».
 */
const BODY_SHARE = {
    // Вес целиком: висишь или держишь себя на руках
    'подтягивания': 1,
    'брусья': 1,
    'подъем ног в висе': 1,

    // Часть опирается на пол
    'отжимания': 0.64,
    'берпи': 0.64,
    'приседания': 0.65,
    'выпады': 0.65,
    'планка': 0.6,

    // Работает верх корпуса, ноги лежат
    'скручивания': 0.35,
    'пресс': 0.35
};

/**
 * Доля по виду упражнения, когда название незнакомо.
 *
 * У снаряда её нет вовсе: нагрузка там названа числом, и добавлять к ней
 * вес тела наугад значило бы завышать её у половины упражнений.
 */
const SHARE_BY_KIND = {
    reps: 0.65,
    time: 0.6
};

export const estimate = {

    BY_NAME,
    BY_GROUP,
    BODY_SHARE,
    SHARE_BY_KIND,
    STEP,

    /**
     * Примерная нагрузка за одно повторение упражнения со своим весом.
     *
     * null там, где считать нечего или незачем: у упражнений со снарядом
     * нагрузка названа числом, у кардио она вообще не в килограммах, а без
     * отмеченного веса тела считать не от чего.
     *
     * Довес прибавляется целиком: пояс на подтягиваниях тянет вниз ровно
     * столько, сколько весит, — доля тут ни при чём.
     */
    bodyLoad({ nameKey = '', kind = 'reps', bodyWeight = 0, weight = 0 } = {}) {
        const share = BODY_SHARE[nameKey] ?? SHARE_BY_KIND[kind];
        if (share === undefined) return null;

        if (!bodyWeight || bodyWeight <= 0) return null;

        // До половины килограмма: точность выше этой — выдумка, а «51,2 кг»
        // читается как измерение
        return Math.round((share * bodyWeight + (weight || 0)) * 2) / 2;
    },

    /**
     * Стартовый вес по собственному весу. null, если прикинуть не из чего.
     *
     * nameKey — нормализованное название (см. migrations.normalizeName):
     * по нему таблица и ищется, чтобы «Жим лёжа» и «жим лежа» были одним.
     */
    startWeight({ nameKey = '', group = '', kind = 'weight', bodyWeight = 0 } = {}) {
        if (kind !== 'weight') return null;
        if (!bodyWeight || bodyWeight <= 0) return null;

        const share = BY_NAME[nameKey] ?? BY_GROUP[group];
        if (!share) return null;

        const raw = bodyWeight * share;
        const rounded = Math.round(raw / STEP) * STEP;

        // Ниже шага округлять некуда: гантель в килограмм — это не прикидка,
        // а насмешка. Тогда честнее промолчать
        return rounded >= STEP ? rounded : null;
    }
};
