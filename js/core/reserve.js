/**
 * Запас в подходе и правило прогрессии (§59 ТЗ).
 *
 * Запас — сколько повторений человек мог бы сделать сверх того, что сделал.
 * В литературе это RIR, reps in reserve; здесь он называется запасом, потому
 * что так его и спрашивают: «сколько ещё осталось?».
 *
 * Зачем понадобился. Программа говорит «прогрессируй сопротивлением, а не
 * повторениями», и это направление, а не действие: когда именно брать
 * резинку потяжелее, из неё не следует. Без правила «когда» этап
 * прогрессии превращается в «когда-нибудь возьму». Запас — единственная
 * величина, по которой это решается, и единственная, которой у приложения
 * не было.
 *
 * Спрашивается тремя ответами, а не числом. Число обещает точность, которой
 * нет: между «ещё два» и «ещё три» человек не различает, а вот «почти до
 * отказа», «около двух» и «было легко» различает уверенно. Три ответа —
 * это ровно то, что он способен сказать честно, а правило большего и не
 * требует.
 *
 * Правило считается по последнему подходу занятия. Он и есть то место, где
 * запас что-то значит: в первом подходе запас велик у всех, а к последнему
 * видно, тяжела нагрузка или нет.
 */

/** Меньше двух: подход шёл почти до отказа. */
export const LOW = 1;

/** Около двух — то, к чему стремятся (RIR 2). */
export const TARGET = 2;

/** Больше двух: было легко. */
export const HIGH = 3;

/**
 * Сколько занятий подряд должно совпасть, чтобы правило сработало.
 *
 * Два, а не одно: одно занятие — это самочувствие, два подряд — уже
 * нагрузка. И не три: к третьему разу человек сам всё поймёт, и подсказка
 * опоздает ровно на то занятие, ради которого затевалась.
 */
const NEED = 2;

export const reserve = {

    LOW,
    TARGET,
    HIGH,
    NEED,

    /** Годится ли значение как запас. */
    valid(value) {
        return value === LOW || value === TARGET || value === HIGH;
    },

    /**
     * Запас занятия — по последнему подходу, у которого он отмечен.
     *
     * Именно последнему отмеченному, а не последнему вообще: человек мог
     * ответить на предпоследнем и молча закрыть последний. Молчание — не
     * ответ, и подменять им сказанное нельзя.
     *
     * sets — подходы одного занятия по порядку выполнения.
     */
    of(sets = []) {
        for (let i = sets.length - 1; i >= 0; i--) {
            if (reserve.valid(sets[i]?.rir)) return sets[i].rir;
        }

        return null;
    },

    /**
     * Что сказать про нагрузку упражнения (§59).
     *
     * sessions — занятия по времени вперёд, каждое массивом подходов.
     *
     * Возвращает { verdict, streak, seen }:
     *
     *   'harder' — два занятия подряд запас был большой: пора тяжелее;
     *   'easier' — два подряд почти до отказа: RIR 2 не держится;
     *   null     — либо в норме, либо сказать нечего.
     *
     * Занятия без отметки не обрывают ряд, а пропускаются. Иначе одно
     * забытое нажатие обнуляло бы наблюдение, и правило не срабатывало бы
     * никогда у того, кто отвечает не всегда, — то есть у всех.
     */
    verdict(sessions = [], { need = NEED } = {}) {
        const ряд = [];

        for (let i = sessions.length - 1; i >= 0 && ряд.length < need; i--) {
            const запас = reserve.of(sessions[i]);
            if (запас !== null) ряд.push(запас);
        }

        if (ряд.length < need) return { verdict: null, streak: 0, seen: ряд.length };

        if (ряд.every((v) => v === HIGH)) return { verdict: 'harder', streak: ряд.length, seen: ряд.length };
        if (ряд.every((v) => v === LOW)) return { verdict: 'easier', streak: ряд.length, seen: ряд.length };

        return { verdict: null, streak: 0, seen: ряд.length };
    },

    /**
     * На сколько снизить повторения при переходе на сопротивление потяжелее.
     *
     * Пятая часть — из правила программы. Число здесь, а не в тексте книги,
     * чтобы приложение могло назвать конкретную цифру: «было 6 × 50, станет
     * 6 × 40» человек понимает сразу, а «снизь примерно на двадцать
     * процентов» ему придётся считать самому, стоя с резинкой в руках.
     */
    STEP: 0.2,

    /** Повторения после смены сопротивления. Ноль и пустое остаются собой. */
    lighter(reps) {
        const n = Number(reps);
        if (!Number.isFinite(n) || n <= 0) return null;

        return Math.max(1, Math.round(n * (1 - reserve.STEP)));
    }
};
