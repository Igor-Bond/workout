/**
 * Правила слияния при синхронизации (§39 ТЗ).
 *
 * Отдельно от самой синхронизации и без обращений к Firestore: это то
 * место, где ошибка молча теряет данные пользователя, и его надо проверять
 * тестами, а не на живой базе.
 *
 * Правило разрешения конфликтов одно: побеждает запись с большим updatedAt.
 * Для приложения, которым пользуется один человек с нескольких устройств,
 * этого достаточно, а удаления не воскресают, потому что стираются мягко.
 */

/** Таблицы, которые уезжают в облако. Настройки привязаны к устройству. */
export const SYNCED = ['exercises', 'templates', 'workouts', 'bodyWeight'];

export const merge = {

    SYNCED,

    /**
     * Что делать со входящей записью.
     *
     * При равных метках побеждает локальная: она уже на месте, и переписывать
     * её тем же самым — лишняя запись в базу и лишний расход операций.
     */
    resolve(local, remote) {
        if (!local) return 'take-remote';
        return (remote?.updatedAt || 0) > (local.updatedAt || 0) ? 'take-remote' : 'keep-local';
    },

    /**
     * Записи на отправку.
     *
     * applied — идентификаторы того, что только что пришло из облака. Их
     * отправлять обратно нельзя: у такой записи updatedAt заведомо больше
     * since, и push вернул бы её тем же значением, удваивая расход операций
     * на каждой синхронизации.
     */
    outgoing(records = [], since = 0, applied = new Set()) {
        return records.filter((r) => (r.updatedAt || 0) > since && !applied.has(r.id));
    },

    /**
     * Firestore не принимает undefined. Наши записи полны необязательных
     * полей — вес у планки, заметка, отметка удаления, — и без очистки
     * запись просто не уйдёт.
     */
    clean(record) {
        const result = {};

        for (const [key, value] of Object.entries(record)) {
            if (value === undefined) continue;
            result[key] = value;
        }

        return result;
    },

    /**
     * Тренировка вместе с подходами — один документ (§39).
     *
     * Год занятий даёт около двухсот тренировок и несколько тысяч подходов;
     * отдельными документами первая синхронизация на новом устройстве читала
     * бы тысячи документов вместо двухсот.
     */
    packWorkout(workout, sets = []) {
        return merge.clean({
            ...workout,
            sets: sets
                .slice()
                .sort((a, b) => a.order - b.order)
                .map(merge.clean)
        });
    },

    /** Обратное преобразование: документ снова в тренировку и подходы. */
    unpackWorkout(doc) {
        const { sets = [], ...workout } = doc;

        return {
            workout,
            sets: sets.map((set) => ({ ...set, workoutId: workout.id }))
        };
    },

    /**
     * Активная тренировка в облако не уезжает (§39).
     *
     * Конфликты решаются целым документом, а не по подходам: если телефон
     * дописал подход после того, как компьютер забрал тренировку себе, при
     * следующем обмене один из наборов подходов пропал бы целиком. Поэтому
     * тренировка отправляется один раз — когда её состав больше не меняется.
     */
    syncable(name, records = []) {
        if (name !== 'workouts') return records;
        return records.filter((w) => w.status !== 'active');
    },

    /**
     * Отметка времени, до которой обмен считается выполненным.
     *
     * Берётся момент начала обмена, а не «сейчас»: запись, сделанная во
     * время самой синхронизации, иначе оказалась бы «старее» отметки и
     * никогда бы не уехала.
     */
    nextSince(startedAt, applied = []) {
        const newest = applied.reduce((max, r) => Math.max(max, r.updatedAt || 0), 0);
        return Math.max(startedAt, newest);
    }
};
