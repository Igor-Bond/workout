/**
 * Сводка кондиций для тренера (§55 ТЗ).
 *
 * Человеку, который составляет программу, нужна не выгрузка базы, а два
 * десятка строк: что делается, как часто, каким объёмом и куда движется вес
 * тела. Консультант владельца именно это и считал руками по выгрузке —
 * приложение знает всё то же самое и может написать сразу.
 *
 * Текстом, а не JSON, и это главное решение здесь. Сводку читает человек:
 * тренер в переписке, языковая модель в разговоре, сам владелец перед тем
 * как отдать. Текст все трое понимают одинаково, а ошибку в нём видно
 * глазами.
 *
 * Модуль чистый: получает данные, возвращает строку. Ни базы, ни разметки —
 * иначе сводку нельзя было бы проверить, а неверные числа в ней выглядят
 * так же убедительно, как верные.
 */

import { t } from './i18n.js';
import { rhythm } from './rhythm.js';
import { stats } from './stats.js';
import { records } from './records.js';
import { format } from './format.js';
import { dates } from './dates.js';

const DAY = 86400000;

/** Сколько недель охватывает сводка: то же окно, что у очереди составов. */
const WEEKS = rhythm.RECENT_WEEKS;

/** Медиана по целым: обычный объём — это не среднее, его перекосит один рекорд. */
const обычно = (values) => Math.round(rhythm.median(values));

/**
 * Килограммы с разделителем разрядов.
 *
 * Только здесь: на экранах числа мельче и разделитель им ни к чему, а в
 * сводке нагрузка за восемь недель — это шесть-семь цифр подряд, и без
 * разделителя их никто не прочтёт.
 */
const кг = (v) => format.load(v).replace(/\B(?=(\d{3})+(?!\d))/g, ' ');

export const report = {

    WEEKS,

    /**
     * Сводка одной строкой на упражнение.
     *
     * shareOf нужен, чтобы посчитать нагрузку собственным весом (§15.2):
     * ядро отчёта про справочник не знает, долю ему приносят.
     */
    build({
        entries = [], sets = [], exercises = {}, weights = [],
        now = Date.now(), weeks = WEEKS, shareOf = () => 1, background = null
    } = {}) {
        const since = dates.startOfDay(now) - weeks * 7 * DAY;

        const свежие = entries.filter((e) => e.workout.startedAt >= since);
        const подходы = sets.filter((s) => !s.deletedAt && s.performedAt >= since);

        // Полная дата, а не «сегодня»: сводку читают не в тот же день, когда
        // сняли, и «сегодня» в переписке через неделю ничего не значит
        const строки = [t('Сводка тренировок — {день}', { день: dates.formatDate(now) }), ''];

        if (свежие.length === 0) {
            строки.push(t('За последние {недели} тренировок не было.', { недели: format.count(weeks, format.WORDS.week) }));
            return строки.join('\n');
        }

        // ================== ИТОГИ ==================

        const дни = new Set(свежие.map((e) => dates.startOfDay(e.workout.startedAt)));

        /*
         * Фон считается отдельно (§29.1).
         *
         * Зарядка делается каждое утро, и в общем счёте она забивает всё:
         * «84 тренировки, 10,5 в неделю» — это не про тренировки, а про то,
         * что человек ещё и разминается. Тренеру нужны обе цифры, но порознь.
         */
        const фоновых = background ? свежие.filter((e) => background(e.workout)).length : 0;
        const рабочих = свежие.length - фоновых;

        строки.push(t('За {недели}: {тренировки}, {дни} с тренировкой, {всреднем} в неделю.', {
            недели: format.count(weeks, format.WORDS.week),
            тренировки: format.count(рабочих, format.WORDS.workout),
            дни: format.count(дни.size, format.WORDS.day),
            всреднем: format.decimal(рабочих / weeks, 1)
        }));

        if (фоновых) {
            строки.push(t('Плюс зарядка: {сколько} раз.', { сколько: фоновых }));
        }

        // ================== НАГРУЗКА ==================

        const железо = подходы.reduce((sum, s) => sum + (s.weight ? (s.reps || 0) * s.weight : 0), 0);
        const свой = stats.bodyVolume(подходы, exercises, weights, { from: since, to: now }, shareOf);

        if (железо > 0) {
            строки.push(t('Нагрузка: {всего} кг, из них собственным весом {свой} кг.', {
                всего: кг(железо + свой), свой: кг(свой)
            }));
        }
        else if (свой > 0) {
            строки.push(t('Нагрузка: {всего} кг, вся собственным весом.', { всего: кг(свой) }));
        }

        // ================== ВЕС ТЕЛА ==================

        const ряд = stats.bodySeries(weights, { from: since, to: now });
        const последний = weights[weights.length - 1];

        if (последний) {
            const изменение = stats.bodyChange(ряд);

            строки.push(изменение && изменение.delta !== 0
                ? t('Вес тела: {вес} кг, за период {знак}{сколько} кг.', {
                    вес: format.weight(последний.weight),
                    знак: изменение.delta > 0 ? '+' : '−',
                    сколько: format.weight(Math.abs(изменение.delta))
                })
                : t('Вес тела: {вес} кг, без изменений за период.', { вес: format.weight(последний.weight) }));
        }
        else {
            строки.push(t('Вес тела не отмечался — нагрузка упражнений со своим весом не считается.'));
        }

        // ================== УПРАЖНЕНИЯ ==================

        const занятия = report.byExercise(подходы);
        const ритм = new Map(rhythm.exerciseRhythm(свежие, now).map((r) => [r.exerciseId, r]));

        const фоновые = new Set();
        if (background) {
            for (const e of свежие) {
                if (!background(e.workout)) continue;
                for (const id of e.exerciseIds || []) фоновые.add(id);
            }
        }

        const рабочие = [...занятия.entries()].filter(([id]) => !фоновые.has(id));

        if (рабочие.length) {
            строки.push('', t('Упражнения:'));

            for (const [id, список] of report.ordered(рабочие)) {
                строки.push(`— ${report.line(id, список, { exercises, ритм: ритм.get(id), now })}`);
            }
        }

        // ================== ФОН ==================

        const фон = [...занятия.entries()].filter(([id]) => фоновые.has(id));

        if (фон.length) {
            строки.push('', t('Фон (зарядка), обычно за раз:'));

            for (const [id, список] of report.ordered(фон)) {
                const повторы = обычно(список.map((з) => з.reduce((sum, s) => sum + (s.reps || 0), 0)));
                строки.push(`— ${exercises[id]?.name || t('упражнение')}: ${повторы}`);
            }
        }

        return [...строки, ...report.request({ свежие, weeks, now })].join('\n');
    },

    /**
     * Задание тому, кто составляет план (§55).
     *
     * Без него сводка — просто справка, и разговор начинается с выяснения,
     * чего от собеседника хотят. С ним это готовый запрос: кондиции, задача
     * и вид ответа. Языковая модель отвечает планом сразу, а живой тренер
     * видит, в каком виде его ждут.
     *
     * Числа берутся из истории, а не спрашиваются: сколько тренировок в
     * неделю человек уже делает, приложение знает лучше него самого.
     */
    request({ свежие = [], weeks = WEEKS, now = Date.now() } = {}) {
        const дни = new Set(свежие.map((e) => dates.startOfDay(e.workout.startedAt)));
        const вНеделю = Math.round(дни.size / weeks);

        const завтра = new Date(now);
        завтра.setDate(завтра.getDate() + 1);

        return [
            '',
            t('Задание'),
            '',
            t('Составь план тренировок на {недели}. Ответь только планом, без пояснений.', {
                недели: format.count(weeks, format.WORDS.week)
            }),
            '',
            t('— упражнения бери из перечисленных выше;'),
            t('— тренировочных дней в неделю: {дни};', { дни: Math.max(1, вНеделю) }),
            t('— зарядку в план не включай, она идёт фоном каждый день;'),
            t('— объём чередуй: тяжёлый день — меньше подходов и больше повторений, лёгкий наоборот.'),
            '',
            t('Ответь ровно в таком виде, ничего не добавляя:'),
            '',
            t('С {дата}, {недели}', { дата: dates.formatDate(завтра.getTime()), недели: format.count(weeks, format.WORDS.week) }),
            '',
            t('Пн  <упражнение> <подходы> × <повторения>'),
            t('Вт  <упражнение> <подходы> × <повторения>'),
            t('Ср  <упражнение или отдых>'),
            t('Чт  <упражнение> <подходы> × <повторения>'),
            t('Пт  <упражнение> <подходы> × <повторения>'),
            t('Сб  <упражнение> <подходы> × <повторения>'),
            t('Вс  отдых'),
            '',
            t('Этап 1 (недели 1–4): чем отличается'),
            t('Этап 2 (недели 5–8): чем отличается')
        ];
    },

    /**
     * Подходы, разложенные по упражнениям и занятиям: id → массив занятий.
     *
     * Занятия идут по времени вперёд, и это не косметика: по этому ряду
     * ищется чередование, а в перепутанном порядке цикла не увидеть.
     */
    byExercise(sets = []) {
        const по = new Map();

        for (const set of sets) {
            if (!по.has(set.exerciseId)) по.set(set.exerciseId, new Map());

            const занятия = по.get(set.exerciseId);
            if (!занятия.has(set.workoutId)) занятия.set(set.workoutId, []);
            занятия.get(set.workoutId).push(set);
        }

        return new Map([...по.entries()].map(([id, занятия]) => [
            id,
            [...занятия.values()]
                .map((own) => [...own].sort((a, b) => a.order - b.order))
                .sort((a, b) => a[0].performedAt - b[0].performedAt)
        ]));
    },

    /** Впереди то, что делается чаще: тренеру важнее основное, а не редкое. */
    ordered(пары) {
        return [...пары].sort((a, b) => b[1].length - a[1].length);
    },

    /**
     * Объём одного занятия словами: «6 × 50», «12 × 35 с 20 кг».
     *
     * Берётся первый подход, а не медиана внутри занятия: к концу упражнения
     * повторения падают, и тренеру важна заявленная работа, а не усталость.
     */
    volume(занятие) {
        const подходов = занятие.length;
        const повторов = занятие[0]?.reps;
        const вес = занятие[0]?.weight;

        if (!Number.isFinite(повторов)) return String(подходов);

        return вес
            ? t('{подходы} × {повторы} с {вес} кг', { подходы: подходов, повторы: повторов, вес })
            : t('{подходы} × {повторы}', { подходы: подходов, повторы: повторов });
    },

    /** Строка одного упражнения: сколько, как часто, каким объёмом. */
    line(id, занятия, { exercises = {}, ритм = null, now = Date.now() } = {}) {
        const exercise = exercises[id] || {};
        const последний = Math.max(...занятия.flatMap((з) => з.map((s) => s.performedAt)));

        const части = [
            exercise.name || t('упражнение'),
            format.count(занятия.length, format.WORDS.session)
        ];

        if (ритм?.enough) {
            части.push(t('раз в {дни}', { дни: format.count(ритм.medianInterval, format.WORDS.day) }));
        }

        /*
         * Чередование называется целиком, а не усредняется (Р-60).
         *
         * У владельца лёгкий и тяжёлый день различаются парой сразу:
         * 6 × 50 и 12 × 35. Медиана между ними даёт «9 × 43» — день, которого
         * не бывает, и тренер строил бы программу по несуществующему числу.
         *
         * Поэтому цикл ищется по строке объёма целиком: пара меняется вместе,
         * и разваливать её на два независимых ряда нельзя.
         */
        const ряд = занятия.map(report.volume);
        const цикл = rhythm.cycle(ряд);

        части.push(цикл && цикл.length > 1
            ? t('чередует {варианты}', { варианты: цикл.values.join(t(' и ')) })
            : t('обычно {объём}', { объём: цикл ? цикл.values[0] : report.typical(занятия) }));

        части.push(t('последний раз {день}', {
            день: dates.formatDayLabel(последний, now, { lower: true })
        }));

        return части.join(', ');
    },

    /** Обычный объём, когда цикла не видно: медиана по занятиям. */
    typical(занятия) {
        const подходов = обычно(занятия.map((з) => з.length));
        const повторов = обычно(занятия.map((з) => з[0]?.reps).filter(Number.isFinite));
        const вес = обычно(занятия.map((з) => з[0]?.weight).filter(Number.isFinite));

        if (!повторов) return String(подходов);

        return вес > 0
            ? t('{подходы} × {повторы} с {вес} кг', { подходы: подходов, повторы: повторов, вес })
            : t('{подходы} × {повторы}', { подходы: подходов, повторы: повторов });
    }
};
