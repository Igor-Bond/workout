/**
 * Съеденное за день и дефицит (§68 ТЗ).
 *
 * Приложение считает расход — основной обмен, помноженный на коэффициент
 * активности (§66). Вторая половина разговора о весе — приход, и до сих пор
 * о нём оно не знало ничего.
 *
 * Правило здесь одно и оно жёстче обычного: **число называет человек**.
 * Приложение может помочь его прикинуть — вилкой, наводящими вопросами,
 * потом и по фотографии, — но записывается то, что человек решил. Поэтому
 * модуль складывает и сравнивает, а не оценивает съеденное: оценивать в
 * килокалориях по описанию — занятие с ошибкой в треть, и выдавать такую
 * оценку за факт приложение не станет.
 *
 * Хранится только число и, если человек захотел, короткая заметка. Ни
 * фотографии, ни разбора блюда: снимок уходит в модель в момент вопроса и
 * нигде не остаётся.
 */

import { dates } from './dates.js';
import { toNumber } from './num.js';

const DAY = 86400000;

/** За сколько дней считать среднее. Неделя: один праздник её не переворачивает. */
const ОКНО = 7;

export const intake = {

    ОКНО,

    /**
     * Съеденное за сутки указанного дня.
     *
     * null, а не ноль, когда записей нет: ноль значил бы «не ел», а на деле
     * это «не записал», и разница здесь важнее всего остального. День без
     * записи не должен выглядеть голоданием ни человеку, ни дефициту.
     */
    day(rows = [], { now = Date.now() } = {}) {
        const начало = dates.startOfDay(now);
        const конец = начало + DAY;

        const свои = rows.filter((r) => Number.isFinite(r?.at) && r.at >= начало && r.at < конец);

        if (свои.length === 0) return null;

        return свои.reduce((сумма, r) => сумма + (Number(r.kcal) || 0), 0);
    },

    /**
     * Среднее за окно — по дням, в которые записывали.
     *
     * Пустые дни не идут в счёт и не тянут среднее вниз: человек, забывший
     * записать вторник, не ел в этот вторник ноль. Зато их число
     * возвращается рядом — по нему видно, чего стоит само среднее.
     */
    average(rows = [], { now = Date.now(), days = ОКНО } = {}) {
        const дни = [];

        for (let i = 0; i < days; i++) {
            const сумма = intake.day(rows, { now: now - i * DAY });
            if (сумма !== null) дни.push(сумма);
        }

        if (дни.length === 0) return null;

        return {
            kcal: Math.round(дни.reduce((a, b) => a + b, 0) / дни.length),
            days: дни.length,
            of: days
        };
    },

    /**
     * Дефицит: расход минус приход.
     *
     * Положительный — съедено меньше, чем потрачено. Считается только когда
     * известны оба числа: расход без прихода — это половина разговора, и
     * показывать её как дефицит значило бы называть дефицитом весь расход.
     */
    deficit({ spent, eaten } = {}) {
        const расход = toNumber(spent);
        const приход = toNumber(eaten);

        if (!Number.isFinite(расход) || !Number.isFinite(приход)) return null;

        return Math.round(расход - приход);
    },

    /**
     * Сколько дней подряд записывали, считая с сегодняшнего.
     *
     * Нужно ровно для одного: сказать человеку, чего стоит его средний
     * дефицит. Две записи за неделю — это не счёт калорий, а два
     * любопытных дня, и делать из них выводы не стоит.
     */
    streak(rows = [], { now = Date.now(), limit = 60 } = {}) {
        let дней = 0;

        for (let i = 0; i < limit; i++) {
            if (intake.day(rows, { now: now - i * DAY }) === null) break;
            дней += 1;
        }

        return дней;
    }
};
