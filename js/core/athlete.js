/**
 * Профиль тренирующегося (§58 ТЗ).
 *
 * То, что приложение знает о человеке помимо его истории: рамки, инвентарь и
 * ограничения. История говорит, что он делал; профиль — что он может и чего
 * не станет.
 *
 * Зачем это понадобилось. Программу составляет не приложение, а тренер или
 * языковая модель, и каждый раз им приходилось объяснять одно и то же: что
 * колено травмировано, что турника и брусьев нет, что резинки — весь
 * инвентарь. Объяснять это заново при каждом обращении человек не обязан, а
 * забудет — получит план с выпадами и подтягиваниями. Профиль едет в сводку
 * (§55) сам.
 *
 * Но главное не сводка. Ограничение, которое приложение только пересказывает
 * собеседнику, — это заметка. Ограничение, которое приложение исполняет само,
 * — это правило: исключённое упражнение не попадает ни в очередь, ни в
 * забытое, а план, назвавший его, скажет об этом при разборе.
 *
 * Устройство подсмотрено у Fitbod и упрощено: там ограничение показывают
 * списком «что исключено и что предложено взамен», с отметкой «прошло». Это
 * правильная форма — человек видит последствие своего слова, а не верит, что
 * оно куда-то учтено.
 *
 * Ядро ограничений не толкует: какие упражнения исключает колено, решает
 * человек, а приложение исполняет. Догадываться о медицине приложению
 * нечем — и не нужно.
 */

/**
 * Пустой профиль: у того, кто ничего не сказал, ограничений нет.
 *
 * Веса тела здесь нет намеренно. Приложение ведёт его отдельно и по датам
 * (§26.3), и он уже уходит в сводку вместе с изменением за период. Второе
 * поле для того же числа разошлось бы с первым при первом же взвешивании, и
 * собеседник получил бы два разных веса в одном письме.
 *
 * Год рождения, а не возраст: возраст молча устаревает, а год — нет.
 */
export const EMPTY = {
    goal: '',
    sex: '',
    birthYear: null,
    height: null,
    days: null,
    minutes: null,
    equipment: [],
    limits: [],
    notes: ''
};

/** Пол: ключи, а не подписи — подписи переводятся при показе. */
export const SEXES = ['male', 'female'];

/**
 * Ограничение: { id, name, at, healedAt, exclude: [id], prefer: [id], note }.
 *
 * exclude и prefer — идентификаторы упражнений, а не названия. Название
 * человек переименует, и правило молча перестанет действовать; ссылка
 * переживёт переименование, потому что ей всё равно, как упражнение зовут.
 */
const живое = (limit) => !!limit && !limit.healedAt;

export const athlete = {

    EMPTY,
    SEXES,

    /** Сколько лет — по году рождения и текущему году. */
    age(профиль, now = Date.now()) {
        const год = Number(профиль?.birthYear);
        if (!Number.isFinite(год) || год < 1900) return null;

        const лет = new Date(now).getFullYear() - год;
        return лет > 0 && лет < 120 ? лет : null;
    },

    /** Профиль с заполненными по умолчанию полями: хранимый мог быть частичным. */
    normalize(stored) {
        return {
            ...EMPTY,
            ...(stored || {}),
            equipment: [...(stored?.equipment || [])],
            limits: [...(stored?.limits || [])]
        };
    },

    /** Действующие ограничения — без тех, что отмечены прошедшими. */
    active(профиль) {
        return (профиль?.limits || []).filter(живое);
    },

    /**
     * Упражнения, исключённые действующими ограничениями.
     *
     * Множеством, а не списком: одно упражнение может быть исключено сразу
     * двумя — подтягивания уходят и по турнику, и по плечу, — а исключено
     * оно от этого не дважды.
     */
    excluded(профиль) {
        const out = new Set();

        for (const limit of athlete.active(профиль)) {
            for (const id of limit.exclude || []) out.add(id);
        }

        return out;
    },

    /** Чем ограничение предлагает заменить исключённое. */
    preferred(профиль) {
        const out = new Set();

        for (const limit of athlete.active(профиль)) {
            for (const id of limit.prefer || []) out.add(id);
        }

        return out;
    },

    /** Каким ограничением исключено это упражнение — чтобы объяснить, а не просто скрыть. */
    limitFor(профиль, exerciseId) {
        return athlete.active(профиль).find((l) => (l.exclude || []).includes(exerciseId)) || null;
    },

    /** Сказано ли в профиле хоть что-нибудь. */
    filled(профиль) {
        const p = athlete.normalize(профиль);

        return !!(p.goal || p.days || p.minutes || p.notes || p.sex || p.birthYear || p.height
            || p.equipment.length || athlete.active(p).length);
    },

    /**
     * Профиль словами — для сводки тренеру (§55).
     *
     * Ядро не переводит: строки собирает тот, кто показывает. Здесь только
     * порядок и отбор — что вообще стоит сказать о человеке, прежде чем
     * просить у собеседника программу.
     *
     * names — Map «упражнение → название»: ядро в базу не ходит.
     */
    describe(профиль, names = new Map(), words = {}, now = Date.now()) {
        const p = athlete.normalize(профиль);
        const строки = [];

        const имя = (id) => names.get(id) || null;
        const список = (ids) => (ids || []).map(имя).filter(Boolean).join(', ');

        /*
         * Кто человек — первой строкой, до целей и рамок.
         *
         * Возраст, пол и рост собеседник учитывает прежде всего остального:
         * от них зависит и объём, и восстановление, и выбор движений. Веса
         * тела здесь нет — он приходит своей строкой из истории взвешиваний.
         */
        const кто = [
            p.sex ? words[p.sex] : null,
            athlete.age(p, now) ? `${athlete.age(p, now)} ${words.years}` : null,
            p.height ? `${p.height} ${words.cm}` : null
        ].filter(Boolean);

        if (кто.length) строки.push(кто.join(', '));

        if (p.goal) строки.push(`${words.goal}: ${p.goal}`);

        if (p.days || p.minutes) {
            const части = [
                p.days ? `${words.days}: ${p.days}` : null,
                p.minutes ? `${words.minutes}: ${p.minutes}` : null
            ].filter(Boolean);

            строки.push(части.join(', '));
        }

        if (p.equipment.length) строки.push(`${words.equipment}: ${p.equipment.join(', ')}`);

        for (const limit of athlete.active(p)) {
            const части = [`${words.limit}: ${limit.name}`];

            const убрано = список(limit.exclude);
            const взамен = список(limit.prefer);

            if (убрано) части.push(`${words.exclude}: ${убрано}`);
            if (взамен) части.push(`${words.prefer}: ${взамен}`);
            if (limit.note) части.push(limit.note);

            строки.push(части.join('. '));
        }

        if (p.notes) строки.push(p.notes);

        return строки;
    }
};
