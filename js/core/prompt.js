/**
 * Что уходит собеседнику (§60 ТЗ).
 *
 * Разговор с тренером внутри приложения отличается от переписки в чужом окне
 * ровно одним: приложение подкладывает дело само. Человеку не приходится
 * каждый раз объяснять про колено, про турник и про то, что он уже делает, —
 * а собеседнику не приходится это выспрашивать.
 *
 * Дело — не расшифровка прошлых бесед. Языковая модель не помнит ничего
 * между разговорами, и непрерывность создаёт не она, а приложение: оно ведёт
 * дело и подаёт его целиком при каждом обращении. Тренер каждый раз новый,
 * дело — то же самое.
 *
 * Собирается здесь, а не в модуле экрана, по двум причинам. Проверяемость:
 * это единственное место, где решается, что именно уходит из приложения
 * наружу, и ошибка тут стоит дороже прочих. И честность: человек должен
 * видеть тот же текст, что уйдёт, — экран показывает результат этой сборки,
 * а не свой пересказ.
 */

/**
 * Наставление собеседнику.
 *
 * Короткое и о рамках, а не о тоне. Длинное наставление модель разбавляет
 * собой ответ, а нам нужен ответ по делу: программа или совет, а не эссе о
 * пользе движения.
 *
 * Про формат плана сказано прямо: если человек просит программу, она должна
 * прийти в том виде, который приложение примет, — иначе разговор кончится
 * тем, что план придётся переписывать руками, ради чего всё и затевалось.
 */
export const INSTRUCTION = [
    'Ты помогаешь человеку вести его тренировки.',
    '',
    'Ниже — его дело: кондиции по истории занятий, ограничения и действующая программа. Опирайся на него, а не на общие соображения.',
    '',
    'Отвечай на языке вопроса.',
    'Отвечай коротко и по существу. Не пересказывай дело обратно и не хвали.',
    'Ограничения соблюдай безусловно: исключённые упражнения не предлагай даже как вариант.',
    '',
    'Если просят программу или её правку — отвечай планом в таком виде, ничего не добавляя до и после:',
    '',
    'С 06.09.2026, 8 недель',
    'Этап 1 (недели 1–4): чем отличается',
    'Пн  <упражнение> <подходы> × <повторения>',
    'Вт  <упражнение> <подходы> × <повторения> + <упражнение> <подходы> × <повторения>',
    'Ср  <упражнение без объёма или отдых>',
    'Чт  <упражнение> <подходы> × <повторения>',
    'Пт  <упражнение> <подходы> × <повторения>',
    'Сб  <упражнение> <подходы> × <повторения>',
    'Вс  отдых',
    '',
    'Правила',
    '— чем прогрессировать и когда',
    '— какой оставлять запас в подходе',
    '— что ещё важно соблюдать',
    '',
    'Строки, начатые тире, приложение хранит как правила программы и отдаёт вместе с планом. Без них останется одно расписание.',
    'День может нести свою паузу: «Пн Бицепс резинка 6 × 50 + Пресс 6 × 25, пауза 10 мин».',
    '',
    'Несколько упражнений в дне соединяй знаком «+». План — одна недельная сетка: если недели различаются, дай их отдельными блоками, каждый со своей датой начала.',
    'Пропущенный день приложение не переносит — он вернётся через неделю на своём месте.'
].join('\n');

export const prompt = {

    INSTRUCTION,

    /**
     * Дело: то, что уходит вместе с вопросом.
     *
     * summary — сводка (§55) без задания: задание там готовый запрос, и в
     * разговоре оно спорило бы с живым вопросом человека.
     *
     * plan — текст действующей программы, если она объявлена. Без неё
     * собеседник, которого просят «поправить среду», не знает, что в среде.
     */
    dossier({ summary = '', plan = '' } = {}) {
        const части = [];

        if (summary.trim()) части.push(summary.trim());

        if (plan.trim()) {
            части.push(['Действующая программа:', '', plan.trim()].join('\n'));
        }

        return части.join('\n\n');
    },

    /**
     * Полный текст первого обращения: дело плюс вопрос.
     *
     * Дело подаётся один раз, первым сообщением разговора, а не при каждом
     * вопросе: собеседник видит всю переписку целиком, и повторять дело
     * значит платить за него столько раз, сколько задано вопросов.
     */
    first({ summary = '', plan = '', question = '' } = {}) {
        const дело = prompt.dossier({ summary, plan });

        return [дело, дело ? '' : null, question.trim()].filter((s) => s !== null).join('\n').trim();
    },

    /**
     * Есть ли в ответе план, который приложение примет.
     *
     * Проверяется тем же разбором, что и вставка руками (§56): иначе
     * приложение обещало бы кнопку «перенести в план» там, где переносить
     * нечего, — и человек узнавал бы об этом уже на экране плана.
     *
     * parse и usable приходят снаружи: ядро запроса не должно тянуть за
     * собой разбор плана ради одной проверки.
     */
    hasPlan(text = '', { parse, usable } = {}) {
        if (!text.trim() || typeof parse !== 'function') return false;

        try {
            return !!usable(parse(text));
        } catch {
            return false;
        }
    }
};
