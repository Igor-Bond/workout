/**
 * Число или ничего (§34, Р-156).
 *
 * `Number(null)` — это 0, а `Number.isFinite(0)` — это правда. Вдвоём они
 * дают ловушку, в которую приложение попадало трижды, и каждый раз тихо:
 *
 *   Р-134 — пропущенный замер веса прочитался нулём, и человеку показали
 *           падение на девяносто два килограмма;
 *   Р-155 — цель, объявленная неизвестно от чего, показала сто процентов
 *           пути пройденными;
 *   Р-156 — дефицит без записанной еды объявил дефицитом весь суточный
 *           расход.
 *
 * Общее у всех трёх: пустое место читалось как ноль, а ноль — величина
 * осмысленная, и дальше по коду его уже ничем не отличить от измеренного.
 * Поэтому пустое обращается в NaN — единственное значение, которое не
 * притворяется данными.
 *
 * Пустым считается и пустая строка: из поля ввода приходит именно она.
 */
export const toNumber = (v) => (v === null || v === undefined || v === '' ? NaN : Number(v));
