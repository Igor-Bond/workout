/**
 * Сколько займёт тренировка (§29.1, §12, Р-225).
 *
 * Человек, у которого день — это двенадцать подходов с пятиминутными паузами,
 * не мог узнать до начала, час это или полтора: приложение знало и план, и
 * историю, но времени нигде не называло, кроме табаты. А решает оно, когда
 * начинать и влезет ли тренировка в вечер.
 *
 * Два способа, и первый точнее. По истории: те же упражнения человек уже делал,
 * и длились они почти одинаково — у одного плана вторник занимает 56–67 минут,
 * понедельник 61–69. По паузам плана — для дня, которого ещё не было: подходы
 * плюс то, что человек написал между ними. Второй грубее, и называется он иначе.
 *
 * Модуль чистый: данные на входе, число или строка на выходе.
 */

import { t } from './i18n.js';
import { engine } from './engine.js';

/** Секунд на повторение: резинка, свой вес — размеренно, не рывком. */
const SEC_PER_REP = 2;

/** Секунд на то, чтобы взять резинку, встать и начать, — на каждый подход. */
const SET_SETUP = 15;

/** Сколько последних занятий того же дня берётся в расчёт. */
const HISTORY_N = 5;

/** Дольше этого — не тренировка, а забытая незавершённая: в счёт не идёт. */
const LONGEST_MIN = 360;

/** Разброс, после которого одно число уже вводит в заблуждение. */
const SPREAD = 0.25;

const median = (values) => {
    const ряд = [...values].sort((a, b) => a - b);
    const m = ряд.length >> 1;

    return ряд.length % 2 ? ряд[m] : (ряд[m - 1] + ряд[m]) / 2;
};

export const duration = {

    SEC_PER_REP,
    SET_SETUP,

    /**
     * Сколько минут длилась тренировка; null, если неизвестно.
     *
     * Забытая «Завершить» растянула бы день на сутки, и одна такая запись
     * съела бы медиану. Поэтому дольше шести часов и короче минуты не берём.
     */
    minutes(workout) {
        if (!Number.isFinite(workout?.startedAt) || !Number.isFinite(workout?.finishedAt)) return null;

        const минут = (workout.finishedAt - workout.startedAt) / 60000;

        return минут >= 1 && минут <= LONGEST_MIN ? минут : null;
    },

    /**
     * По истории: последние занятия с тем же составом (§15, Р-219).
     *
     * Медиана, а не среднее: один затянувшийся день не должен сдвигать
     * ожидание. Границы — самое короткое и самое длинное из взятых, для
     * показа, когда день ходит широко (баскетбол: 79 и 117 минут).
     */
    fromHistory(workout, workouts = [], { background = () => false } = {}) {
        const такие = engine.sameDays(workout, workouts, { background })
            .slice(0, HISTORY_N)
            .map(duration.minutes)
            .filter((m) => m !== null);

        if (!такие.length) return null;

        return {
            source: 'history',
            minutes: Math.round(median(такие)),
            from: Math.round(Math.min(...такие)),
            to: Math.round(Math.max(...такие)),
            n: такие.length
        };
    },

    /** Секунд работы в подходе: время — само по себе, повторения — по темпу. */
    workSeconds({ reps = 0, exercise = null } = {}) {
        const число = Number(reps) || 0;

        if (exercise?.kind === 'time') return число * (exercise.timeUnit === 'min' ? 60 : 1);

        return число * SEC_PER_REP;
    },

    /**
     * По плану: подходы и паузы между ними, минут.
     *
     * items — { sets, work, rest }: подходов, секунд работы в подходе и пауза
     * после него. Для дня «по одному» всё просто: подход, пауза, подход.
     *
     * Круговой день устроен хитрее, и это то, что строка плана пишет прямо:
     * «Сгибание 6 × 50 (пауза 1 мин) + Пресс 6 × 25, пауза 10 мин». Пресс делается
     * в паузу сгибания, а десять минут — это отдых между кругами. Поэтому круг
     * длится не сумму подходов, а работу первого плюс бо́льшее из его паузы и
     * всего, что делается следом: если следом укладывается в паузу, она и
     * решает. Между кругами — пауза круга, а без неё пауза последнего упражнения.
     */
    fromPlan({ items = [], linear = false, roundRest = 0 } = {}) {
        const строки = items.filter((и) => Number(и.sets) > 0);
        if (!строки.length) return null;

        const работа = (и) => (Number(и.work) || 0) + SET_SETUP;
        const пауза = (и) => Number(и.rest) || 0;

        let секунд = 0;

        if (linear) {
            for (const и of строки) секунд += и.sets * (работа(и) + пауза(и));

            // Паузы после последнего подхода нет
            секунд -= пауза(строки[строки.length - 1]);

            return Math.max(1, Math.round(секунд / 60));
        }

        const кругов = Math.max(...строки.map((и) => и.sets));

        // Время круга из упражнений, которые в нём остались: от последнего к первому
        const круг = (список) => список.reduceRight(
            (хвост, и, i) => работа(и) + (i === список.length - 1 ? 0 : Math.max(пауза(и), хвост)),
            0
        );

        for (let r = 1; r <= кругов; r++) секунд += круг(строки.filter((и) => и.sets >= r));

        const между = roundRest > 0 ? roundRest : пауза(строки[строки.length - 1]);

        секунд += (кругов - 1) * между;

        return Math.max(1, Math.round(секунд / 60));
    },

    /**
     * Сколько ещё осталось — по темпу этой тренировки или по прошлым (Р-225).
     *
     * Темп считается с третьего подхода: по двум подходам он ничего не
     * говорит. Тогда ещё не сделанные подходы умножаются на средний промежуток
     * между сделанными — и это верно и для дня «по одному» с пятиминутными
     * паузами, и для круга, где минута и десять чередуются: среднее у них
     * общее.
     *
     * Раньше третьего подхода — по прошлым занятиям с тем же составом: сколько
     * они обычно длились минус сколько уже прошло. Нечем считать — null.
     */
    remaining({ planned = 0, done = 0, times = [], now = Date.now(), startedAt = null, typical = null } = {}) {
        const осталось = planned - done;
        if (!(осталось > 0)) return null;

        const моменты = [...times].filter(Number.isFinite).sort((a, b) => a - b);

        if (моменты.length >= 3) {
            const промежутков = моменты.length - 1;
            const средний = (моменты[моменты.length - 1] - моменты[0]) / промежутков;

            return Math.max(1, Math.round((осталось * средний) / 60000));
        }

        if (typical && Number.isFinite(startedAt)) {
            const ещё = typical.minutes - (now - startedAt) / 60000;

            return ещё >= 3 ? Math.round(ещё) : null;
        }

        return null;
    },

    /** Время словами: «45 мин», «1 ч 10 мин», «2 ч». */
    words(минут) {
        const n = Math.round(минут);

        if (n < 90) return t('{n} мин', { n });

        const ч = Math.floor(n / 60);
        const м = n % 60;

        return м ? t('{ч} ч {м} мин', { ч, м }) : t('{ч} ч', { ч });
    },

    /**
     * Строка для карточки: «≈ 65 мин», «от 80 до 115 мин» или «≈ 70 мин по паузам плана».
     *
     * Широкий разброс называется границами, а не одним числом: «≈ 110» у
     * баскетбола, который идёт то час двадцать, то два, — это обещание, которое
     * не сбудется. По плану число грубее и так и подписано.
     */
    label(оценка) {
        if (!оценка) return '';

        if (оценка.source === 'plan') {
            return t('≈ {время} по паузам плана', { время: duration.words(оценка.minutes) });
        }

        if (оценка.n > 1 && (оценка.to - оценка.from) > оценка.minutes * SPREAD) {
            return t('от {от} до {до} мин', { от: оценка.from, до: оценка.to });
        }

        return t('≈ {время}', { время: duration.words(оценка.minutes) });
    }
};
