/**
 * План в календарь телефона (§62.5 ТЗ).
 *
 * Запасной путь к запястью, и он не зависит ни от кого. Intervals.icu отдаёт
 * запланированное часам, но покажет ли их прошивка силовое занятие — решает
 * не приложение; у владельца оно до часов не дошло. А напоминание календаря
 * телефон показывает всегда, и часы, зеркалящие уведомления, показывают его
 * следом — даже те, у которых сломана кнопка.
 *
 * Календарь ещё и честнее по сути: план — это расписание, а расписанию место
 * в календаре. Приложение не пытается быть будильником, а отдаёт файл тому,
 * кто занимается напоминаниями по должности.
 *
 * Формат — iCalendar (RFC 5545), тот же, которым обмениваются все календари.
 * Модуль чистый: занятия на входе, текст файла на выходе.
 */

const CRLF = '\r\n';

/** Дата в виде 20260907 — как того требует формат для событий на весь день. */
function stamp(ts) {
    const d = new Date(ts);
    const pad = (n) => String(n).padStart(2, '0');

    return `${d.getFullYear()}${pad(d.getMonth() + 1)}${pad(d.getDate())}`;
}

/** Метка времени в UTC: 20260906T101500Z. */
function utc(ts) {
    return `${new Date(ts).toISOString().replace(/[-:]/g, '').split('.')[0]}Z`;
}

/**
 * Экранирование текста.
 *
 * Запятая и точка с запятой в формате разделяют значения, а перевод строки
 * пишется двумя знаками. Без экранирования «Бицепс 6 × 50, пауза 10 мин»
 * развалилось бы на два поля, и календарь показал бы половину.
 */
function esc(text) {
    return String(text || '')
        .replace(/\\/g, '\\\\')
        .replace(/;/g, '\\;')
        .replace(/,/g, '\\,')
        .replace(/\r?\n/g, '\\n');
}

export const ical = {

    /**
     * Часы напоминания: за сколько от начала дня.
     *
     * Восемь утра. Событие на весь день начинается в полночь, и напоминание
     * в неё же означало бы уведомление посреди ночи — ровно то, за что такие
     * файлы и удаляют не глядя.
     */
    ALARM: 'PT8H',

    /**
     * Файл календаря из занятий плана.
     *
     * События на весь день, а не на час: приложение не знает, когда человек
     * тренируется, и выдуманное время спорило бы с настоящим — а на весь
     * день это то же расписание, только без вранья о часе.
     *
     * Опознаватель события берётся из плана и не меняется от отправки к
     * отправке: календарь по нему узнаёт уже добавленное и обновляет его, а
     * не заводит второе такое же.
     */
    build(занятия = [], { name = 'План тренировок', now = Date.now() } = {}) {
        const строки = [
            'BEGIN:VCALENDAR',
            'VERSION:2.0',
            'PRODID:-//Workout Tracker//Plan//RU',
            'CALSCALE:GREGORIAN',
            'METHOD:PUBLISH',
            `X-WR-CALNAME:${esc(name)}`
        ];

        for (const занятие of занятия) {
            const день = stamp(занятие.date);

            строки.push(
                'BEGIN:VEVENT',
                `UID:${занятие.externalId}@workout-tracker`,
                `DTSTAMP:${utc(now)}`,
                `DTSTART;VALUE=DATE:${день}`,
                `DTEND;VALUE=DATE:${stamp(занятие.date + 86400000)}`,
                `SUMMARY:${esc(занятие.name)}`,
                ...(занятие.description ? [`DESCRIPTION:${esc(занятие.description)}`] : []),
                'TRANSP:TRANSPARENT',
                'BEGIN:VALARM',
                'ACTION:DISPLAY',
                `DESCRIPTION:${esc(занятие.name)}`,
                `TRIGGER;RELATED=START:${ical.ALARM}`,
                'END:VALARM',
                'END:VEVENT'
            );
        }

        строки.push('END:VCALENDAR');

        return строки.join(CRLF) + CRLF;
    },

    /** Имя файла: с датой, чтобы в загрузках их можно было различить. */
    filename(now = Date.now()) {
        return `plan-${stamp(now)}.ics`;
    }
};
