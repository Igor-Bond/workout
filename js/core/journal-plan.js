/**
 * Журнал решений по программе (§64 ТЗ).
 *
 * Приложение помнит, что человек делал: подходы, повторения, вес. Оно не
 * помнило, **что и почему поменялось в программе** — когда перешли на резинку
 * потяжелее, когда сняли выпады из-за колена, когда сбавили объём после
 * плохой недели. Это лежало в переписке с тренером, а переписка не хранится
 * намеренно (§60): она черновик вокруг одного ответа.
 *
 * Хранить надо не разговор, а вывод. Пять строк за программу, отвечающих на
 * вопрос «почему сейчас так»: их читает человек через месяц и собеседник,
 * которого просят составить следующий этап. Именно этих строк ему и не
 * хватало — он видел, что делается, и не видел, что уже пробовали и чем это
 * кончилось.
 *
 * Модуль чистый: записи на входе, записи и строки на выходе. Ни базы, ни
 * сети — журнал переживает и обмен, и перенос, и его порядок важнее, чем
 * место хранения.
 */

import { t } from './i18n.js';

/**
 * Сколько записей держим.
 *
 * Сорок: за год программы это примерно по решению в неделю, и столько же
 * человек способен прочесть подряд. Дальше журнал перестаёт быть журналом и
 * становится историей, которая у приложения и так есть.
 */
export const LIMIT = 40;

/**
 * Виды записей.
 *
 * Не для украшения: по виду решается, что попадёт в дело тренеру целиком, а
 * что останется человеку. Правка программы уходит всегда, заметка о
 * самочувствии — тоже, а вот утверждение плана собеседник и так видит по
 * тексту программы.
 */
export const KINDS = ['plan', 'change', 'note'];

const чисто = (s) => String(s || '').replace(/\s+/g, ' ').trim();

export const planJournal = {

    LIMIT,
    KINDS,

    /**
     * Новая запись впереди старых.
     *
     * Свежие первыми: журнал читают сверху, и вопрос «почему сейчас так»
     * начинается с последнего решения, а не с первого.
     */
    add(записи = [], { kind = 'note', text = '', why = '', at = Date.now() } = {}) {
        const строка = чисто(text);
        if (!строка) return записи;

        const запись = {
            id: `j${at}${Math.random().toString(36).slice(2, 7)}`,
            at,
            kind: KINDS.includes(kind) ? kind : 'note',
            text: строка,
            why: чисто(why)
        };

        return [запись, ...записи].slice(0, LIMIT);
    },

    /** Убрать запись: решение бывает и ошибочным, а журнал не летопись. */
    remove(записи = [], id) {
        return записи.filter((з) => з.id !== id);
    },

    /**
     * Журнал словами — для сводки и для дела тренеру (§55, §60).
     *
     * Дата и решение, причина через тире. Без причины запись бессмысленна для
     * читающего со стороны: «перешёл на резинку потяжелее» он и так увидит по
     * числам, а вот «потому что три занятия подряд запас был большой» —
     * единственное, чего в числах нет.
     *
     * format приходит снаружи: ядро не переводит и дат не рисует.
     */
    describe(записи = [], { format = (at) => String(at), limit = 10 } = {}) {
        return записи
            .slice(0, limit)
            .map((з) => [format(з.at), з.text].join(' — ') + (з.why ? ` (${з.why})` : ''));
    },

    /** Подпись вида — для показа. */
    label(kind) {
        if (kind === 'plan') return t('Программа');
        if (kind === 'change') return t('Правка');

        return t('Заметка');
    }
};
