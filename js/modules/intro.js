/** Ключ настройки, под которым лежит состояние знакомства. */
export const INTRO_KEY = 'intro';

/**
 * Нужно ли знакомство.
 *
 * Условий два, и оба обязательны. Знакомство не пройдено — иначе оно лезло бы
 * при каждом запуске. И база пуста — иначе оно однажды встретило бы человека,
 * который пользуется приложением полгода, и объяснило бы ему, что такое
 * тренировка.
 */
export async function нужноЗнакомство() {
    const состояние = await dbService.getSetting(INTRO_KEY, null);
    if (состояние?.done) return false;

    // status пустой — любые, включая незаконченную: начатая тренировка это
    // тоже история, и знакомиться такому человеку уже поздно
    const тренировки = await dbService.listWorkouts({ limit: 1, status: '' });
    return тренировки.length === 0;
}

/** Отметить знакомство пройденным: больше оно само не появится. */
async function закрыть() {
    const состояние = await dbService.getSetting(INTRO_KEY, null);
    await dbService.setSetting(INTRO_KEY, { ...(состояние || {}), done: true, at: Date.now() });
}

/**
 * Шаги знакомства по порядку.
 *
 * Каждый знает три вещи: что это, что даёт и чего не будет без него. Третье
 * важнее первых двух — это единственный способ отказаться осознанно, а не
 * наугад.
 *
 * Порядок — от того, что влияет на всё, к тому, что необязательно вовсе. Вес
 * тела стоит вторым не по важности для человека, а по важности для счёта: без
 * него нагрузка упражнений со своим весом равна нулю, и половина истории
 * считается впустую с первого же дня.
 */
async function шаги() {
    const [профиль, вес, ключ, план, справочник] = await Promise.all([
        currentAthlete(),
        dbService.listBodyWeight(),
        dbService.getSetting(KEY_SETTING, ''),
        currentPlan(),
        dbService.listExercises()
    ]);

    return [
        {
            id: 'athlete',
            screen: 'athlete',
            name: t('О себе'),
            text: t('Пол, возраст, рост, инвентарь и ограничения — то, чего не видно по истории.'),
            без: t('Без этого приложение не знает про больное колено и спокойно предложит выпады, а тренер составит программу для кого-то другого.'),
            кнопка: t('Заполнить'),
            готов: ядро.filled(профиль)
        },
        {
            id: 'weight',
            action: 'intro-weight',
            name: t('Вес тела'),
            text: t('Один раз сейчас, дальше — когда захотите. Отмечать удобно раз в неделю в один и тот же день.'),
            без: t('Без веса нагрузка отжиманий, планки и складки считается нулём: приложение берёт её долей от веса тела. Половина вашей работы просто не попадёт в счёт.'),
            кнопка: t('Отметить вес'),
            готов: вес.length > 0
        },
        {
            id: 'exercises',
            screen: 'exercises',
            name: t('Упражнения'),
            text: t('Справочник уже заполнен: {n} на первое время. Свои добавляются в любой момент, там же.', { n: format.count(справочник.length, format.WORDS.exercise) }),
            без: t('Заглянуть стоит хотя бы раз: приложение считает рекорды и объём по видам упражнений, и вид у нового упражнения задаёте вы.'),
            кнопка: t('Посмотреть'),
            готов: true
        },
        {
            id: 'coach',
            screen: 'coach',
            name: t('Тренер'),
            text: t('Разговор с языковой моделью прямо в приложении: она видит вашу историю и составляет программу. Нужен ключ Google, он бесплатный — приложение покажет, где его взять.'),
            без: t('Без ключа работает всё остальное. Не будет только разговора и заполнения карточек упражнений.'),
            кнопка: t('Настроить'),
            готов: ai.ready(ключ)
        },
        {
            id: 'plan',
            screen: 'planner',
            name: t('План'),
            text: t('Недельная сетка: какой день чему отведён. Вставляется текстом — от тренера, от модели или свой.'),
            без: t('Без плана приложение ведёт по истории: само предлагает, к чему пора вернуться. Это рабочий способ, а не запасной.'),
            кнопка: t('Вставить план'),
            готов: !!план
        }
    ];
}

/** Первый шаг, который ещё не сделан и не отложен. */
function текущий(список, отложено) {
    return список.find((ш) => !ш.готов && !отложено.has(ш.id)) || null;
}

export const intro = {

    title: 'Знакомство',
    nav: 'workout',

    async render() {
        const состояние = await dbService.getSetting(INTRO_KEY, null);
        const отложено = new Set(состояние?.skipped || []);
        const список = await шаги();

        // Вернулись — значит шаг больше не «в отлучке» (Р-94)
        if (состояние?.pending) {
            await dbService.setSetting(INTRO_KEY, { ...состояние, pending: null });
        }

        const шаг = текущий(список, отложено);
        const номер = шаг ? список.indexOf(шаг) + 1 : список.length;

        return ui.html`
            ${ui.raw(ui.title(t('Знакомство'),
                t('Пять шагов, каждый можно пропустить. Приложение работает и без них — просто по-разному')))}

            ${шаг ? ui.html`
                <!--
                    Один шаг на экране, а не список из пяти (Р-77). Списком
                    это было оглавлением, которое закрывают целиком: человек
                    не знает, с чего начать, а ему предлагают выбрать.
                -->
                <div class="card">
                    <div class="card-title">
                        ${шаг.name}
                        <span class="intro-mark">${t('шаг {n} из {всего}', { n: номер, всего: список.length })}</span>
                    </div>

                    <p>${шаг.text}</p>
                    <p class="hint">${шаг.без}</p>

                    <div class="row-links">
                        ${шаг.screen ? ui.html`
                            <!--
                                Уход на шаг помечается (Р-94): иначе человек
                                заполняет профиль и остаётся на нём навсегда —
                                знакомство обрывается на первом же шаге, а
                                дороги назад к нему нет.
                            -->
                            <button class="btn btn-accent" data-action="intro-go"
                                    data-screen="${шаг.screen}" data-step="${шаг.id}">
                                ${шаг.кнопка}
                            </button>
                        ` : ui.html`
                            <button class="btn btn-accent" data-action="${шаг.action}">${шаг.кнопка}</button>
                        `}

                        <button class="btn btn-ghost" data-action="intro-skip" data-step="${шаг.id}">
                            ${t('Пропустить')}
                        </button>
                    </div>
                </div>

                <!--
                    Пройденное видно строками: человек должен понимать, где он
                    в ряду, — и что назад дороги никто не закрывал.
                -->
                ${список.filter((ш) => ш !== шаг).map((ш) => ui.html`
                    <div class="plan-day ${ш.готов || отложено.has(ш.id) ? 'is-rest' : ''}">
                        <span class="plan-day-body">
                            ${ш.name}
                            ${ш.готов
                                ? ui.html`<span class="plan-day-rest">${t('готово')}</span>`
                                : отложено.has(ш.id)
                                    ? ui.html`<span class="plan-day-rest">${t('пропущено')}</span>`
                                    : ''}
                        </span>
                    </div>
                `)}
            ` : ui.html`
                <div class="card">
                    <div class="card-title">${t('Всё, можно тренироваться')}</div>
                    <p>${t('Это журнал тренировок: подходы, повторения, вес и то, что из них следует, — рекорды, объём и подсказки, к чему пора вернуться.')}</p>
                    <p class="hint">${t('Работает без сети и хранит всё на устройстве. Облако и тренер — по желанию.')}</p>
                </div>
            `}

            <button class="btn ${шаг ? 'btn-ghost' : 'btn-accent btn-lg'}" data-action="intro-done">
                ${шаг ? t('Пропустить остальное и начать') : t('Начать тренироваться')}
            </button>

            <button class="btn btn-ghost" data-action="nav" data-screen="guide">
                ${t('Подробнее — «Как пользоваться»')}
            </button>
        `;
    }
};

/**
 * Уйти на шаг и не потерять знакомство (Р-94).
 *
 * Шаги «О себе», «Упражнения», «Тренер» и «План» — это чужие экраны, и
 * вернуться с них знакомству было нечем: человек заполнял профиль и оставался
 * в нём, а остальные четыре шага не показывались никогда. Со стороны это
 * выглядело так, будто знакомство состоит из одного шага.
 *
 * Поэтому уход помечается, и пока метка стоит, приложение держит на всех
 * экранах полосу «Знакомство: шаг N из 5 — вернуться». Снимается она сама,
 * когда человек возвращается, — или вместе со всем знакомством, если он
 * нажал «Начать тренироваться».
 */
actions.on('intro-go', async (el) => {
    const состояние = await dbService.getSetting(INTRO_KEY, null);

    await dbService.setSetting(INTRO_KEY, { ...(состояние || {}), pending: el.dataset.step });

    haptics.tap();
    app.go(el.dataset.screen);
});

/**
 * Полоса возврата к знакомству: показывать ли её и что на ней написать.
 *
 * null — показывать нечего: знакомство пройдено, не начиналось или человек
 * уже вернулся. Считается по тем же шагам, что и сам экран, чтобы номер на
 * полосе и номер на карточке не разошлись.
 */
export async function знакомствоЖдёт() {
    const состояние = await dbService.getSetting(INTRO_KEY, null);
    if (!состояние?.pending || состояние.done) return null;

    const список = await шаги();
    const отложено = new Set(состояние.skipped || []);

    const шаг = текущий(список, отложено);
    if (!шаг) return { номер: список.length, всего: список.length };

    return { номер: список.indexOf(шаг) + 1, всего: список.length };
}

/** Отложить шаг. Отказ запоминается: спрашивать дважды об одном — не спрашивать. */
actions.on('intro-skip', async (el) => {
    const состояние = await dbService.getSetting(INTRO_KEY, null);
    const отложено = new Set(состояние?.skipped || []);

    отложено.add(el.dataset.step);

    await dbService.setSetting(INTRO_KEY, { ...(состояние || {}), skipped: [...отложено] });
    haptics.tap();
    await app.render();
});

/**
 * Вес спрашивается прямо здесь, а не отсылкой на другой экран (§61).
 *
 * Это один вопрос с одним числом: уводить за ним на главный экран и обратно
 * значило бы потерять человека на полпути. Всё остальное в знакомстве —
 * ссылки, потому что там правда есть что заполнять.
 */
actions.on('intro-weight', async () => {
    const values = await dialog.form({
        title: t('Вес тела'),
        text: t('Приложение считает по нему нагрузку упражнений со своим весом. Взвешиваться лучше утром, до еды.'),
        fields: [
            { name: 'weight', label: t('Вес, кг'), type: 'number', required: true, placeholder: '80' }
        ],
        confirmText: t('Отметить')
    });

    if (!values) return;

    const вес = Number(String(values.weight).replace(',', '.'));

    if (!Number.isFinite(вес) || вес <= 0) {
        return dialog.alert({ title: t('Не похоже на вес'), text: t('Впишите число, например 80.') });
    }

    await dbService.setBodyWeight({ weight: вес });
    haptics.tap();
    await app.render();
});

actions.on('intro-done', async () => {
    await закрыть();
    haptics.tap();
    app.go('home');
});
