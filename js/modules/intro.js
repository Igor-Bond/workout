/**
 * Знакомство при первом запуске (§61 ТЗ).
 *
 * Приложение молчаливое: оно считает подходы и не командует. Тому, кто уже
 * знает порядок, так удобнее — но открывший его впервые видит пустой экран с
 * кнопкой «Новая тренировка» и не знает ни про план, ни про профиль, ни про
 * тренера. Половина возможностей остаётся ненайденной, а вторая половина
 * работает вполсилы: приложение не знает про колено и предлагает выпады.
 *
 * Поэтому один экран при первом запуске, и на нём — четыре шага с честным
 * последствием отказа у каждого. Не мастер, который ведёт за руку и не
 * выпускает: каждый шаг можно отложить, и приложение после этого работает.
 * Именно это и надо сказать вслух — «без этого будет вот так», — а не
 * требовать заполнить всё до первой тренировки.
 *
 * Порядок шагов — от того, что влияет на всё, к тому, что необязательно
 * вовсе: профиль, справочник, тренер, план. Первый молча меняет подсказки на
 * всех экранах, последний можно не заводить никогда.
 *
 * Показывается один раз и только на пустой базе (см. main.js): человеку с
 * историей знакомиться не с чем, а вернуться сюда можно из профиля.
 */

import { ui } from '../core/ui.js';
import { actions } from '../core/actions.js';
import { dbService } from '../services/db.js';
import { athlete as ядро } from '../core/athlete.js';
import { ai, KEY_SETTING } from '../services/ai.js';
import { haptics } from '../core/haptics.js';
import { format } from '../core/format.js';
import { t } from '../core/i18n.js';
import { app } from '../app.js';
import { currentAthlete } from './athlete.js';
import { currentPlan } from './planner.js';

/** Ключ настройки, под которым лежит состояние знакомства. */
export const INTRO_KEY = 'intro';

/**
 * Нужно ли знакомство.
 *
 * Условий два, и оба обязательны. Знакомство не пройдено — иначе оно лезло бы
 * при каждом запуске. И база пуста — иначе оно однажды встретило бы человека,
 * который пользуется приложением полгода, и объяснило бы ему, что такое
 * тренировка.
 */
export async function нужноЗнакомство() {
    const состояние = await dbService.getSetting(INTRO_KEY, null);
    if (состояние?.done) return false;

    // status пустой — любые, включая незаконченную: начатая тренировка это
    // тоже история, и знакомиться такому человеку уже поздно
    const тренировки = await dbService.listWorkouts({ limit: 1, status: '' });
    return тренировки.length === 0;
}

/** Отметить знакомство пройденным: больше оно само не появится. */
async function закрыть() {
    const состояние = await dbService.getSetting(INTRO_KEY, null);
    await dbService.setSetting(INTRO_KEY, { ...(состояние || {}), done: true, at: Date.now() });
}

/**
 * Шаги знакомства.
 *
 * Каждый знает три вещи: что это, что даёт и чего не будет без него. Третье
 * важнее первых двух — это единственный способ отказаться осознанно, а не
 * наугад.
 */
async function шаги() {
    const [профиль, ключ, план, справочник] = await Promise.all([
        currentAthlete(),
        dbService.getSetting(KEY_SETTING, ''),
        currentPlan(),
        dbService.listExercises()
    ]);

    return [
        {
            id: 'athlete',
            screen: 'athlete',
            name: t('О себе'),
            text: t('Пол, возраст, рост, инвентарь и ограничения — то, чего не видно по истории.'),
            без: t('Без этого приложение не знает про больное колено и спокойно предложит выпады, а тренер составит программу для кого-то другого.'),
            кнопка: t('Заполнить'),
            готов: ядро.filled(профиль)
        },
        {
            id: 'exercises',
            screen: 'exercises',
            name: t('Упражнения'),
            text: t('Справочник уже заполнен: {n} на первое время. Свои добавляются в любой момент, там же.', { n: format.count(справочник.length, format.WORDS.exercise) }),
            без: t('Заглянуть стоит хотя бы раз: приложение считает рекорды и объём по видам упражнений, и вид у нового упражнения задаёте вы.'),
            кнопка: t('Посмотреть'),
            готов: true
        },
        {
            id: 'coach',
            screen: 'coach',
            name: t('Тренер'),
            text: t('Разговор с языковой моделью прямо в приложении: она видит вашу историю и составляет программу. Нужен ключ Google, он бесплатный.'),
            без: t('Без ключа работает всё остальное. Не будет только разговора и заполнения карточек упражнений.'),
            кнопка: t('Настроить'),
            готов: ai.ready(ключ)
        },
        {
            id: 'plan',
            screen: 'planner',
            name: t('План'),
            text: t('Недельная сетка: какой день чему отведён. Вставляется текстом — от тренера, от модели или свой.'),
            без: t('Без плана приложение ведёт по истории: само предлагает, к чему пора вернуться. Это рабочий способ, а не запасной.'),
            кнопка: t('Вставить план'),
            готов: !!план
        }
    ];
}

/** Шаг карточкой. Пройденный и отложенный выглядят спокойно: с ними покончено. */
function карточка(шаг, отложен) {
    const тихо = шаг.готов || отложен;

    return ui.html`
        <div class="card ${тихо ? 'is-quiet' : ''}">
            <div class="card-title">
                ${шаг.name}
                ${шаг.готов
                    ? ui.html`<span class="intro-mark">${t('готово')}</span>`
                    : отложен ? ui.html`<span class="intro-mark">${t('потом')}</span>` : ''}
            </div>

            <p>${шаг.text}</p>
            <p class="hint">${шаг.без}</p>

            <div class="row-links">
                <button class="btn btn-sm ${шаг.готов ? 'btn-ghost' : 'btn-accent'}"
                        data-action="nav" data-screen="${шаг.screen}">
                    ${шаг.готов ? t('Открыть') : шаг.кнопка}
                </button>

                ${!шаг.готов && !отложен ? ui.html`
                    <button class="btn btn-ghost btn-sm" data-action="intro-skip" data-step="${шаг.id}">
                        ${t('Потом')}
                    </button>
                ` : ''}
            </div>
        </div>
    `;
}

export const intro = {

    title: 'Знакомство',
    nav: 'workout',

    async render() {
        const состояние = await dbService.getSetting(INTRO_KEY, null);
        const отложено = new Set(состояние?.skipped || []);
        const список = await шаги();

        const осталось = список.filter((ш) => !ш.готов && !отложено.has(ш.id));

        return ui.html`
            ${ui.raw(ui.title(t('Знакомство'),
                t('Четыре шага, каждый можно отложить. Приложение работает и без них — просто по-разному')))}

            <div class="card">
                <p>${t('Это журнал тренировок: подходы, повторения, вес и то, что из них следует, — рекорды, объём и подсказки, к чему пора вернуться.')}</p>
                <p class="hint">${t('Работает без сети и хранит всё на устройстве. Облако и тренер — по желанию.')}</p>
            </div>

            ${список.map((ш) => карточка(ш, отложено.has(ш.id)))}

            <!--
                Кнопка внизу закрывает знакомство независимо от того, сколько
                шагов сделано: отложить можно всё сразу, и это законный выбор,
                а не побег. Надпись при этом честная — она говорит, что
                осталось незаполненным.
            -->
            <button class="btn btn-accent btn-lg" data-action="intro-done">
                ${осталось.length ? t('Пропустить остальное и начать') : t('Начать тренироваться')}
            </button>

            <button class="btn btn-ghost" data-action="nav" data-screen="guide">
                ${t('Подробнее — «Как пользоваться»')}
            </button>
        `;
    }
};

/** Отложить шаг. Отказ запоминается: спрашивать дважды об одном — не спрашивать. */
actions.on('intro-skip', async (el) => {
    const состояние = await dbService.getSetting(INTRO_KEY, null);
    const отложено = new Set(состояние?.skipped || []);

    отложено.add(el.dataset.step);

    await dbService.setSetting(INTRO_KEY, { ...(состояние || {}), skipped: [...отложено] });
    haptics.tap();
    await app.render();
});

actions.on('intro-done', async () => {
    await закрыть();
    haptics.tap();
    app.go('home');
});
