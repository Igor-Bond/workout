/**
 * Программа и тренер — один экран для всего, что настраивают редко (§30.1).
 *
 * В профиле накопилось пять кнопок к экранам, до которых обычный человек
 * доходит раз в месяц: «О себе», план, тренер, сводка, часы. Каждая по
 * отдельности осмысленна, вместе они превращали профиль в список ссылок, где
 * тонет то, что нужно всем, — язык, отдых, звук, справочник.
 *
 * Разделение простое: в профиле остаётся то, чем пользуются, здесь — то, что
 * настраивают. Тот, кто ведёт журнал и не хочет ни планов, ни тренера,
 * сюда не заходит вовсе и ничего не теряет.
 *
 * У каждой строки — объяснение в одну фразу. Без него список кнопок
 * заставляет открывать всё подряд, чтобы понять, что где; с ним человек
 * выбирает, не нажимая.
 */

import { ui } from '../core/ui.js';
import { t } from '../core/i18n.js';

/** Строка: кнопка и одна фраза о том, что за ней. */
function строка(screen, name, hint) {
    return ui.html`
        <button class="btn btn-ghost" data-action="nav" data-screen="${screen}">${name}</button>
        <p class="hint">${hint}</p>
    `;
}

export const program = {

    title: 'Программа и тренер',
    nav: 'profile',

    async render() {
        return ui.html`
            ${ui.raw(ui.title(t('Программа и тренер'),
                t('Всё, что настраивают редко: программа, ограничения, разговор с тренером и обмен с часами')))}

            <div class="card">
                <div class="card-title">${t('Программа')}</div>

                ${строка('athlete', t('О себе'),
                    t('Пол, возраст, рост, инвентарь и ограничения. Названное ограничение убирает упражнения из подсказок и уезжает в сводку.'))}

                ${строка('planner', t('План тренировок'),
                    t('Недельная сетка, которой приложение следует вместо того, чтобы угадывать ритм по истории. Здесь же журнал решений.'))}

                ${строка('report', t('Сводка для тренера'),
                    t('Кондиции, ограничения и восстановление одним текстом — для переписки с живым тренером.'))}
            </div>

            <div class="card">
                <div class="card-title">${t('Тренер и часы')}</div>

                ${строка('coach', t('Тренер'),
                    t('Разговор о программе прямо в приложении. Нужен бесплатный ключ Google; без него работает всё остальное.'))}

                ${строка('watch', t('Данные с часов'),
                    t('Сон, пульс покоя, вариабельность и шаги через Intervals.icu. Отсюда же план уходит на часы и в календарь.'))}
            </div>

            <button class="btn btn-ghost" data-action="nav" data-screen="intro">
                ${t('Знакомство: с чего начать')}
            </button>

            <button class="btn btn-ghost" data-action="nav" data-screen="profile">${t('← В профиль')}</button>
        `;
    }
};
