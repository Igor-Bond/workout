/**
 * Сохранить ключ и сразу проверить его (§60.2).
 *
 * Проверяем, а не просто сохраняем. Ключ — строка из шестидесяти знаков,
 * скопированная наполовину или с чужого проекта, выглядит точно так же, как
 * рабочий; человек узнавал об этом при первом вопросе, через минуту ожидания
 * и с сообщением, которое относил к вопросу, а не к ключу.
 *
 * Проверка — самый дешёвый настоящий запрос: одно слово, короткий ответ.
 * Поддельной проверки «на глаз» тут быть не может: строка правильного вида
 * ничем не отличается от строки, которую Google не примет.
 */
actions.on('coach-key-save', async () => {
    if (ждём) return;

    const поле = document.getElementById('ai-key');
    const key = поле?.value.trim();

    if (!key) {
        ошибка = t('Поле пустое: вставьте ключ целиком, он начинается на AIza.');
        return app.render();
    }

    ждём = true;
    ошибка = '';
    await app.render();

    /*
     * Ожидание видно окном, а не только надписью на кнопке (Р-192).
     *
     * Проверка ключа ходит в Google и занимает секунды. Кнопка при этом
     * говорила «Проверяю…» мелко и внизу экрана — человек, вставивший ключ и
     * нажавший, видел ровно то же, что и до нажатия, и жал ещё раз.
     */
    dialog.waiting({
        title: t('Проверяю ключ'),
        text: t('Спрашиваю у Google, какие модели этот ключ вправе спрашивать. Обычно ответ приходит за пару секунд.')
    });

    try {
        /*
         * Ключ проверяется списком моделей, а не пробным вопросом (Р-191).
         *
         * Дешевле — список не тратит квоту, — и заодно отвечает на второй
         * вопрос: та ли модель записана. Новому человеку зашитая умолчанием
         * модель, которой у Google больше нет, закрывала вход целиком: ключ
         * верный, а приложение отвечает ошибкой и советует вписать другую —
         * ту, названия которой он знать не может.
         */
        const доступные = await запомнитьСписок(await ai.models({ key }));

        if (доступные.length === 0) {
            throw new Error(t('Ключ принят, но ни одной отвечающей модели Google по нему не даёт. Проверьте, что у проекта включён доступ к Gemini API.'));
        }

        // Пустое в настройке — это умолчание, а не пустая модель: `getSetting`
        // отдаёт записанное как есть, и записанным бывает ничто
        // Пустое в настройке — это умолчание, а не пустая модель: `getSetting`
        // отдаёт записанное как есть, и записанным бывает ничто
        const записанная = (await dbService.getSetting(MODEL_SETTING, DEFAULT_MODEL)) || DEFAULT_MODEL;

        // Записанная не предлагается — выбираем сами и говорим об этом
        const модель = доступные.includes(записанная) ? записанная : ai.pick(доступные);

        /*
         * И только потом — настоящий вопрос (Р-195).
         *
         * Список моделей отвечает на «тот ли ключ» и «та ли модель», но не на
         * главное: «спросить-то можно?». Ключ бывает виден списку и закрыт для
         * ответов — Gemini API не включён у проекта, ключ ограничен адресом,
         * страна не та. Проверка, кончающаяся списком, объявляла бы «принят»
         * там, где первый же вопрос отвечает ошибкой, — а это хуже честного
         * отказа: человек уходит с экрана настройки, уверенный, что настроил.
         *
         * Стоит вторым, а не первым: без списка непонятно, какую модель
         * спрашивать, и провал был бы про модель, а не про ключ.
         */
        dialog.say(t('Ключ годится. Пробую задать вопрос моделью «{модель}».', { модель: модель }));

        await ai.ask({ key, model: модель, messages: [{ text: 'ok' }] });

        await dbService.setSetting(KEY_SETTING, key);
        if (модель !== записанная) await dbService.setSetting(MODEL_SETTING, модель);

        принято = модель === записанная
            ? ''
            : t('Ключ принят. Модель «{было}» Google больше не предлагает — выбрана «{стало}». Поменять можно в настройках разговора.', {
                было: записанная, стало: модель
            });

        haptics.tap();
    } catch (e) {
        ошибка = e.message;
    } finally {
        dialog.close();
        ждём = false;
        await app.render();
    }
});

/**
 * Смена поля ключа больше ничего не сохраняет (§60.2).
 *
 * Раньше сохраняла — и это выглядело как молчание: человек вставлял ключ, а
 * приложение не отвечало ничем. Хуже, на телефоне событие смены при вставке
 * из буфера не приходит вовсе, пока поле не потеряет фокус. Теперь сохраняет
 * кнопка, и она же говорит, принят ключ или нет.
 */

/**
 * Спросить у Google, какие модели он предлагает сейчас (§60.2, Р-191).
 *
 * Тот же список, что и при вводе ключа, но показанный выбором: здесь человек
 * уже работает и вправе решать сам, а не получать выбранное за него. Выбранное
 * при вводе ключа — это про то, чтобы вход вообще открылся.
 */
actions.on('coach-models', async () => {
    if (ждём) return;

    const key = await dbService.getSetting(KEY_SETTING, '');
    if (!ai.ready(key)) return;

    ждём = true;
    ошибка = '';
    принято = '';
    await app.render();

    dialog.waiting({
        title: t('Спрашиваю Google'),
        text: t('Какие модели этот ключ вправе спрашивать.')
    });

    try {
        const доступные = await запомнитьСписок(await ai.models({ key }));

        if (доступные.length === 0) {
            ошибка = t('Ключ принят, но ни одной отвечающей модели Google по нему не даёт. Проверьте, что у проекта включён доступ к Gemini API.');
        } else {
            /*
             * Записанной больше не предлагают — переставляем на советуемую
             * (Р-198). Оставить её значило бы оставить разговор сломанным,
             * зато «как человек велел»: он велел работать, а не хранить
             * название.
             *
             * Молчим, когда всё сошлось: человек нажал «Обновить список» и
             * видит обновлённый список — это и есть ответ.
             */
            const записанная = (await dbService.getSetting(MODEL_SETTING, DEFAULT_MODEL)) || DEFAULT_MODEL;

            if (!доступные.includes(записанная)) {
                const советуем = ai.pick(доступные);

                await dbService.setSetting(MODEL_SETTING, советуем);

                принято = t('Модель «{было}» Google больше не предлагает — выбрана «{стало}».', {
                    было: записанная, стало: советуем
                });
            }

            haptics.tap();
        }
    } catch (e) {
        ошибка = e.message;
    } finally {
        dialog.close();
        ждём = false;
        await app.render();
    }
});

/**
 * Выбор модели — списком или строкой (Р-198).
 *
 * Один обработчик на оба: пока список не привезён, поле остаётся полем
 * ввода, и человек не должен оказаться без единого способа назвать модель.
 */
/**
 * Выбор модели — своим окном (§60.3, Р-200).
 *
 * Список уже привезён и лежит в памяти: окно открывается сразу, без обращения
 * к сети. Обновить его — отдельная кнопка рядом, и это разные дела: выбрать
 * из известного и сходить спросить заново.
 */
actions.on('coach-model-pick', async () => {
    const список = (await dbService.getSetting(MODELS_SETTING, null))?.names || [];
    if (!список.length) return;

    const записанная = (await dbService.getSetting(MODEL_SETTING, DEFAULT_MODEL)) || DEFAULT_MODEL;
    const советуем = ai.pick(список);

    /*
     * Советуемая первой: человек почти всегда соглашается с первой строкой, и
     * она обязана быть той же, которую приложение выбрало бы само.
     */
    const порядок = [советуем, ...список.filter((имя) => имя !== советуем)];

    const выбор = await dialog.choose({
        title: t('Модель'),
        text: t('Столько моделей Google предлагает по вашему ключу.'),
        options: порядок.map((имя) => ({
            value: имя,
            label: имя,
            hint: имя === советуем ? t('советуем')
                : имя === записанная ? t('записана сейчас')
                : null
        }))
    });

    if (!выбор) return;

    await dbService.setSetting(MODEL_SETTING, выбор);
    принято = '';
    haptics.tap();

    await app.render();
});

actions.onChange('coach-model', async (el) => {
    await dbService.setSetting(MODEL_SETTING, el.value.trim() || DEFAULT_MODEL);
});

actions.on('coach-forget', async () => {
    const ok = await dialog.confirm({
        title: t('Забыть ключ?'),
        text: t('Разговор перестанет работать, пока не вставите ключ снова. Сам ключ в Google останется.'),
        confirmText: t('Забыть'),
        danger: true
    });

    if (!ok) return;

    await dbService.setSetting(KEY_SETTING, '');
    нить = [];
    app.render();
});

/**
 * Снять набранный вопрос перед перерисовкой (Р-113).
 *
 * Разметка подставляется целиком, а поле рисуется из `заготовлено`, которое
 * после каждой отрисовки обнуляется. Значит, любая перерисовка, случившаяся
 * пока человек набирает, стирала набранное — и стирали её честные кнопки,
 * которые приложение само и предлагает.
 */
function снятьВопрос() {
    const поле = document.getElementById('coach-text');
    if (поле) заготовлено = поле.value;
}

actions.on('coach-reveal', () => {
    снятьВопрос();
    раскрыто = !раскрыто;
    app.render();
});

actions.on('coach-clear', () => {
    нить = [];
    ошибка = '';
    app.render();
});

const ЗАГОТОВКИ = {
    plan: 'Составь программу на восемь недель.',
    review: 'Что бы ты поправил в моей нынешней программе и почему?',
    next: 'Программа скоро кончится. Что делать дальше — что оставить, что менять?'
};

/**
 * Заготовка про следующий этап собирается из того, как прошёл предыдущий
 * (§63.1).
 *
 * Общий вопрос «что дальше» получает общий ответ: собеседник видит числа за
 * восемь недель и не знает, что из задуманного вышло. А вышло ли — приложение
 * как раз знает: сколько дней плана сделано, где запас рос, какие недели были
 * плохими по сну. Это и есть разница между «составь следующий этап» и
 * «составь ещё одну программу».
 */
async function следующийЭтап() {
    const наблюдения = await observations();

    if (!наблюдения.length) return t(ЗАГОТОВКИ.next);

    return [
        t(ЗАГОТОВКИ.next),
        '',
        t('Вот что приложение видит по прошедшему этапу:'),
        ...наблюдения.map((н) => `— ${н.text}`)
    ].join('\n');
}

actions.on('coach-preset', async (el) => {
    const поле = document.getElementById('coach-text');
    if (!поле) return;

    поле.value = el.dataset.preset === 'next'
        ? await следующийЭтап()
        : t(ЗАГОТОВКИ[el.dataset.preset] || '');

    поле.focus();
});


/**
 * Спросить (§60).
 *
 * Дело подкладывается только к первому вопросу разговора: собеседник видит
 * всю переписку целиком, и повторять дело значит платить за него столько раз,
 * сколько задано вопросов.
 */
actions.on('coach-ask', async () => {
    if (ждём) return;

    const поле = document.getElementById('coach-text');
    const вопрос = поле?.value.trim();
    if (!вопрос) return;

    /*
     * Клавиатуру убираем сами, до перерисовки.
     *
     * На айфоне поле остаётся в фокусе и после нажатия кнопки, а перерисовка
     * подменяет его новым узлом — фокус слетает, клавиатура уезжает, окно
     * меняет высоту, и экран будто плывёт. Снять фокус заранее дешевле, чем
     * потом объяснять пляску разметки.
     */
    поле.blur();

    const key = await dbService.getSetting(KEY_SETTING, '');
    const model = await dbService.getSetting(MODEL_SETTING, DEFAULT_MODEL);

    const первый = нить.length === 0;
    const текст = первый ? prompt.first({ summary: await дело(), question: вопрос }) : вопрос;

    нить.push({ role: 'user', text: первый ? вопрос : вопрос, sent: текст });

    ждём = true;
    ошибка = '';
    await app.render();

    /*
     * Ожидание видно окном (Р-192).
     *
     * Программа на восемь недель считается дольше короткого ответа, и это
     * та самая минута, в которую человек решает, работает приложение или
     * нет. Строка «Спрашиваю…» стояла под перепиской, то есть там, куда он
     * в эту минуту не смотрит.
     */
    dialog.waiting({
        title: t('Спрашиваю тренера'),
        text: первый
            ? t('Ушло дело целиком: кондиции, ограничения и программа. Программа на восемь недель считается дольше короткого ответа — бывает до минуты.')
            : t('Ушёл вопрос и вся переписка. Обычно ответ приходит за несколько секунд.')
    });

    try {
        const ответ = await ai.ask({
            key,
            model,
            system: prompt.INSTRUCTION,
            messages: нить.map((m) => ({ role: m.role, text: m.sent || m.text }))
        });

        нить.push({ role: 'model', text: ответ });
        haptics.tap();
    } catch (e) {
        ошибка = e.message;

        // Неотправленный вопрос из нити убираем: иначе он уедет вторым
        // обращением как ни на что не ответивший
        const неушедший = нить.pop();

        /*
         * И возвращаем его в поле (Р-113).
         *
         * Он не отправлен — значит, он ещё принадлежит человеку. Набирать
         * длинный вопрос на телефоне второй раз из-за чужой осечки со связью
         * — это плата не по адресу.
         */
        заготовлено = неушедший?.text || заготовлено;
    } finally {
        dialog.close();
        ждём = false;
        await app.render();
    }
});

/**
 * Перенести пришедший план (§60).
 *
 * В поле экрана плана, а не сразу в действующий: план утверждает человек, и
 * подменять утверждение переносом значило бы принять за него решение на
 * восемь недель. Он увидит развёртку, список непонятого и спор с
 * ограничениями — и только потом нажмёт.
 */
actions.on('coach-to-plan', (el) => {
    const m = нить[Number(el.dataset.index)];
    if (!m) return;

    putDraft(m.text);
    app.go('planner');
});
