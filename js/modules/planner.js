/*
 * Черновик не сбрасывается в unmount, хотя туда просится.
 *
 * unmount вызывается перед каждой отрисовкой, а не только при уходе с
 * экрана: «разобрать» ставило черновик, вызывало перерисовку — и та стирала
 * его прежде, чем показать. Кнопка выглядела мёртвой, хотя разбор проходил.
 *
 * Поэтому черновик живёт до утверждения или отказа. Вернувшемуся человеку он
 * покажет его же вставку, и это лучше пустого поля: текст он получил в
 * переписке и второй раз копировать не должен.
 */

actions.on('sheet-parse', async () => {
    const текст = document.getElementById('plan-text')?.value?.trim();

    if (!текст) {
        return dialog.alert({ title: t('Пусто'), text: t('Вставьте текст плана в поле.') });
    }

    const разобран = ядро.parse(текст);

    if (!ядро.usable(разобран)) {
        return dialog.alert({
            title: t('План не разобран'),
            text: t('Не нашлось ни даты начала, ни занятий по дням. Проверьте образец ответа в сводке.')
        });
    }

    черновик = { text: текст };
    await app.render();
});

actions.onChange('sheet-file', async (el) => {
    const файл = el.files?.[0];
    if (!файл) return;

    const текст = await файл.text();

    черновик = { text: текст };
    await app.render();

    // Тот же файл повторно не выберется, пока поле помнит прежний
    el.value = '';
});

/**
 * Утвердить план — и завести его упражнения тем же нажатием (§56.3).
 *
 * Заведение прицеплено к утверждению, а не оставлено на потом: план без
 * половины упражнений — это половина плана, и обнаруживается она в тот вечер,
 * когда человек собрался тренироваться. Одно нажатие вместо двух, и оба
 * действия про одно и то же — принять программу целиком.
 *
 * Правило «данные не уходят сами» (§60) держится: обращение идёт от нажатия
 * человека, и до нажатия на экране написано, что тренер заполнит карточки.
 *
 * Осечка утверждению не мешает. План уже сохранён, упражнения уже заведены —
 * тренеру доверена только начинка карточек, и без неё программа работает.
 */
actions.on('sheet-apply', async () => {
    /*
     * Пустое поле — это пустое поле, а не «возьми прежнее» (Р-113).
     *
     * Стереть текст — первое, что делает человек, решивший не брать этот план:
     * отменить черновик больше нечем. Он стирал, нажимал «Утвердить», чтобы
     * убедиться, что кнопка погасла, — и приложение утверждало ровно тот план,
     * от которого он отказывался, писало «План утверждён» и уводило на
     * главный.
     */
    const поле = document.getElementById('plan-text');
    const текст = поле ? поле.value.trim() : (черновик?.text || '');

    if (!текст) {
        return dialog.alert({ title: t('Пусто'), text: t('Вставьте текст плана в поле.') });
    }

    const разобран = ядро.parse(текст);

    /*
     * Негодный разбор объясняется тем же окном, что и «Разобрать».
     *
     * Молчаливый выход выглядел поломкой: человек правил строку, жал
     * «Утвердить» — и не происходило ничего. Понять, зависло приложение или он
     * что-то сломал, было неоткуда.
     */
    if (!ядро.usable(разобран)) {
        return dialog.alert({
            title: t('План не разобран'),
            text: t('Не нашлось ни даты начала, ни занятий по дням. Проверьте образец ответа в сводке.')
        });
    }

    await dbService.setSetting(PLAN_KEY, { ...разобран, text: текст });

    // План утверждён — восемь недель, за которые приложение теперь отвечает
    haptics.tap();

    const итог = await завести(разобран);

    // Узнанные названия правятся в самом тексте плана: он хранится текстом и
    // им же правится человеком, и подмена в разборе была бы невидимой
    if (итог.замены.length) {
        const правленый = подставить(текст, итог.замены);
        await dbService.setSetting(PLAN_KEY, { ...ядро.parse(правленый), text: правленый });
    }

    /*
     * Правленый план уезжает на часы сам (§62.4).
     *
     * Только если он уже уезжал: тот, кто ни разу не отправлял, не просил
     * приложение ходить в чужой сервис при каждом утверждении, и делать это
     * за него было бы нарушением правила «данные не уходят сами» (§60). А
     * тот, кто отправлял, обратного и ждёт: план правят чаще, чем открывают
     * экран часов, и несведённые часы врали бы про сегодняшний день.
     */
    const наЧасы = await planPushed()
        ? await pushPlan(await currentPlan())
        : null;

    /*
     * Утверждение — тоже решение, и записывает его приложение (§64).
     *
     * Записывать самому то, что приложение и так знает, человек не станет, а
     * без этой строки журнал начинается с середины: правки есть, а с чего всё
     * началось — нет.
     */
    await noteDecision({
        kind: 'plan',
        text: t('Утверждён план с {начало}, {недели}', {
            начало: dates.formatDate(разобран.from),
            недели: format.count(разобран.weeks, format.WORDS.week)
        }),
        why: (разобран.stages || [])[0] || ''
    });

    черновик = null;
    await app.render();

    await dialog.alert({
        title: t('План утверждён'),
        text: [
            t('Сейчас откроется главный экран — дальше он ведёт по плану. Пропущенный день не переносится: сетка держится, а пропущенное вернётся через неделю на своём месте.'),
            итогЗаведения(итог),

            // Про часы говорим и когда получилось, и когда нет: молчаливая
            // осечка оставила бы на запястье прошлую программу (§62.4)
            наЧасы?.placed
                ? t('На часы отправлено дней плана: {n}.', { n: наЧасы.placed })
                : наЧасы?.error || ''
        ].filter(Boolean).join('\n\n')
    });

    /*
     * Утверждение кончается главным экраном (Р-106).
     *
     * Экран плана — место, где план правят, и после утверждения человеку там
     * делать нечего: он только что сказал «да» и ждёт, что программа начнётся.
     * А приложение оставляло его на том же экране, рядом с полем ввода и
     * кнопкой «Разобрать» — будто утверждение не засчиталось и надо что-то
     * ещё. Отдельной кнопкой это не лечится: кнопку «теперь на главный»
     * пришлось бы искать среди тех, что план правят.
     */
    app.go('home');
});

