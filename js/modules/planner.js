/**
 * Завести упражнения плана, которых нет в справочнике (Р-68).
 *
 * Вид, группу и описание подбирает тренер по образцу справочника (§60.1).
 * Приложение угадывать не берётся — «Планка» на время, «Планка с весом»
 * силовая, — а заведённые пустыми карточки человек всё равно пойдёт
 * дописывать руками, по одной, ровно тем знанием, которое у собеседника уже
 * есть. Образцом идут свои упражнения: группы у каждого свои, и карточка,
 * попавшая в чужую группу, стоит того же переноса руками.
 *
 * Без ключа и при любой осечке заводим как есть, обычным видом: незаполненная
 * карточка — мелкая неточность, а несозданное упражнение сорвёт тренировку.
 *
 * Возвращает { added, filled, осечка } — чтобы сказать человеку, что вышло.
 */
async function завести(разобран) {
    const список = await dbService.listExercises({ includeArchived: true });
    const имена = [];

    for (const у of ядро.items(разобран)) {
        const есть = список.some((e) => ядро.same(e.name, у.name));
        if (!есть && !имена.includes(у.name)) имена.push(у.name);
    }

    if (имена.length === 0) return { added: 0, filled: 0, замены: [], осечка: '' };

    const key = await dbService.getSetting(KEY_SETTING, '');

    const заведено = [];
    const замены = [];

    let карточки = [];
    let осечка = '';

    if (ai.ready(key)) {
        заводим = true;
        await app.render();

        try {
            const ответ = await ai.ask({
                key,
                model: await dbService.getSetting(MODEL_SETTING, DEFAULT_MODEL),
                messages: [{ text: prompt.cards({ names: имена, known: список.filter((e) => !e.archived) }) }]
            });

            карточки = prompt.readCards(ответ, { names: имена, same: ядро.same });
        } catch (e) {
            осечка = e.message;
        } finally {
            заводим = false;
        }
    }

    for (const имя of имена) {
        const карточка = карточки.find((c) => ядро.same(c.name, имя)) || {};

        /*
         * Узнанное не заводим, а правим в плане (§56.3).
         *
         * «Отжимания от пола» — те же «Отжимания»: вторая запись раздула бы
         * справочник и разделила бы между ними историю. Правится текст плана,
         * а не разбор: план хранится текстом и правится человеком в том же
         * поле, и подмена в разборе была бы для него невидимой.
         *
         * Узнанным считаем только то, что и правда есть в справочнике:
         * собеседник может назвать «уже заведённым» то, чего у нас нет. А
         * упражнение, которого правда нет, заводится — новое движение в
         * программе дело обычное.
         */
        const узнано = карточка.same
            ? список.find((e) => ядро.same(e.name, карточка.same))
            : null;

        if (узнано) {
            замены.push({ from: имя, to: узнано.name });
            continue;
        }

        const { kind, group, howTo } = карточка;

        await dbService.ensureExercise({ name: имя, kind, group, howTo });
        заведено.push(имя);
    }

    return { added: заведено.length, filled: карточки.filter((c) => !c.same).length, замены, осечка };
}

/**
 * Что сказать о заведённых упражнениях. Пусто, если ничего не произошло.
 *
 * Про узнанные названия говорим отдельно и обязательно: приложение поправило
 * текст плана, который писал не оно, и молчать об этом нельзя — человек
 * откроет план и не поймёт, почему там не то, что он вставлял.
 */
function итогЗаведения({ added = 0, filled = 0, замены = [], осечка = '' }) {
    const части = [];

    if (added && осечка) {
        части.push(t('Добавлено упражнений: {n}. Тренер не ответил ({что}), поэтому вид у всех обычный — поправьте в справочнике.', { n: added, что: осечка }));
    }
    else if (added) {
        части.push(filled
            ? t('Добавлено упражнений: {n}. Вид, группу и описание подобрал тренер по образцу справочника — загляните, всё ли верно.', { n: added })
            : t('Добавлено упражнений: {n}. Вид у всех обычный — поправьте в справочнике, если какое-то на время или кардио.', { n: added }));
    }

    if (замены.length) {
        части.push(t('Названия, которые тренер узнал как уже заведённые, в плане поправлены: {список}.', {
            список: замены.map((з) => `«${з.from}» → «${з.to}»`).join(', ')
        }));
    }

    return части.join('\n\n');
}

/** Подставить узнанные названия в текст плана. */
function подставить(текст, замены = []) {
    return замены.reduce((итог, з) => ядро.rename(итог, з.from, з.to), String(текст || ''));
}


