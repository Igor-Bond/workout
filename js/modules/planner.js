/** Ключ настройки, под которым лежит утверждённый план. */
export const PLAN_KEY = 'plan';

/**
 * Журнал решений по программе (§64).
 *
 * Синхронизируется вместе с планом: решение «перешёл на резинку потяжелее»
 * принято один раз, а тренируется человек с двух устройств.
 */
export const JOURNAL_KEY = 'planJournal';

/** Прочитать журнал. Всегда массив: пустой журнал — это пустой список. */
export async function currentJournal() {
    const записи = await dbService.getSetting(JOURNAL_KEY, null);
    return Array.isArray(записи) ? записи : [];
}

/**
 * Записать решение.
 *
 * Зовётся и руками, и приложением: утверждение плана — тоже решение, и
 * записывать его человеку было бы работой за приложение.
 */
export async function noteDecision({ kind = 'note', text = '', why = '', at = Date.now() } = {}) {
    const записи = planJournal.add(await currentJournal(), { kind, text, why, at });

    await dbService.setSetting(JOURNAL_KEY, записи);

    return записи;
}

/** Когда план выгружали в календарь и каким он тогда был (§62.5). */
export const ICS_KEY = 'planCalendar';

/**
 * Прочитать утверждённый план.
 *
 * Разбор делается заново из текста, а не берётся из хранилища (Р-104).
 *
 * Текст — то единственное, что человек писал и правил; разбор при нём
 * служебный. Записывают их вместе, и обычно это одно и то же — но ровно до
 * того дня, когда разбор становится умнее. Тогда утверждённый план остаётся
 * с прежним пониманием навсегда: приложение уже знает, что «пауза 1.5 мин» —
 * это пауза, а действующая программа по-прежнему считает это частью названия
 * упражнения. Заставлять человека утверждать план заново ради починки, о
 * которой он не просил, — значит перекладывать на него свою работу.
 *
 * Текст при этом не трогается: он и так тот же. Меняется только понимание.
 */
export async function currentPlan() {
    const план = await dbService.getSetting(PLAN_KEY, null);
    if (!план?.text) return план;

    return { ...план, ...ядро.parse(план.text) };
}

/**
 * Переименование упражнения правит и план (§56.6).
 *
 * План связан со справочником строкой: он хранит названия, а не ссылки.
 * Поэтому переименование в справочнике молча рвало связь — план продолжал
 * звать «Жим лёжа», которого больше нет, и приложение предлагало завести его
 * заново. Получались два упражнения об одном движении и разделённая между
 * ними история — ровно то, ради чего справочник и заводился.
 *
 * Правится текст плана, а не разбор: план хранится своим текстом и правится
 * человеком в том же поле; подмена в разборе была бы для него невидимой.
 *
 * Возвращает true, если план правда изменился, — вызывающий обязан об этом
 * сказать: приложение поправило текст, который писал не оно.
 */
export async function renameInPlan(from, to) {
    const план = await currentPlan();

    if (!план?.text || !String(from).trim() || ядро.same(from, to)) return false;

    const правленый = ядро.rename(план.text, from, to);
    if (правленый === план.text) return false;

    await dbService.setSetting(PLAN_KEY, { ...ядро.parse(правленый), text: правленый });

    return true;
}

/** Зовёт ли действующий план это упражнение — по названию, как и всё в плане. */
export async function planCalls(name) {
    const план = await currentPlan();

    return ядро.items(план).some((у) => ядро.same(у.name, name));
}

