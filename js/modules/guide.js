/** Раздел-гармошка. open — только у первого: он же ответ на «с чего начать». */
function part(title, body, open = false) {
    return ui.html`
        <details class="guide" ${ui.raw(open ? 'open' : '')}>
            <summary>${title}</summary>
            <div class="guide-body">${body}</div>
        </details>
    `;
}

/** Нумерованный порядок действий. */
function steps(list) {
    return ui.html`
        <ol class="guide-steps">
            ${list.map((s) => ui.html`<li>${ui.raw(s)}</li>`)}
        </ol>
    `;
}

/** Строка «что — где»: слева понятие, справа пояснение. */
function rows(pairs) {
    return ui.html`
        <div class="guide-rows">
            ${pairs.map(([name, text]) => ui.html`
                <div class="guide-row">
                    <div class="guide-row-name">${name}</div>
                    <div class="guide-row-text">${ui.raw(text)}</div>
                </div>
            `)}
        </div>
    `;
}

