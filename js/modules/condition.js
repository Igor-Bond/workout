/*
 * За каждым числом — его ход и объяснение (§66, Р-136).
 *
 * Оценка без основания — это приговор без разбирательства: человек видит
 * жёлтое и не знает ни чьей меркой его мерили, ни насколько эта мерка точна.
 * Поэтому нажимается каждая плитка, включая те, что не покрашены: «почему тут
 * нет цвета» — такой же законный вопрос.
 *
 * Разворот на месте, а не окном поверх экрана (Р-136). Окно приходилось
 * закрывать, чтобы посмотреть на соседнее число, — а вопрос «куда идёт» как
 * раз и задают всем числам подряд. Нажатие на раскрытую плитку её закрывает:
 * иначе разворот было бы нечем убрать.
 */
/*
 * Запись съеденного — одним окном и без разбора блюда (§68).
 *
 * Спрашивается ровно одно число, потому что хранится ровно одно число.
 * Заметка не обязательна и нужна человеку, а не приложению: через месяц по
 * ней вспоминается, откуда взялся день на две с половиной тысячи.
 */
actions.on('intake-add', async () => {
    haptics.tap();

    const ответ = await dialog.form({
        title: t('Сколько съели'),
        text: t('Число называете вы. Приложение его складывает, но не выводит само: оценка калорийности по описанию блюда ошибается на треть, и выдавать такую оценку за факт оно не станет.'),
        fields: [
            {
                name: 'kcal', label: t('Килокалории'), type: 'number',
                required: true, placeholder: t('например, 650')
            },
            {
                name: 'note', label: t('Заметка — если нужна'), type: 'text',
                placeholder: t('обед')
            }
        ],
        confirmText: t('Записать')
    });

    if (!ответ) return;

    const число = Number(ответ.kcal);

    /*
     * Ноль и минус не записываются, и молча.
     *
     * Окно уже закрыто, ругаться поздно, а нового окна человек не звал.
     * Пустое поле ловится самим окном — оно и назовёт, чего не хватает.
     */
    if (!Number.isFinite(число) || число <= 0) return;

    await dbService.addIntake({ kcal: число, note: ответ.note });
    await app.render();
});

/*
 * Запись убирается с подтверждением, а не по касанию.
 *
 * Кнопки записей стоят тесным рядом под пальцем, и промах по соседней стоил
 * бы дня счёта. Вернуть удалённое нечем: мягкое удаление — про обмен между
 * устройствами, а не про отмену.
 */
actions.on('intake-drop', async (el) => {
    const id = el.dataset.id;
    if (!id) return;

    const да = await dialog.confirm({
        title: t('Убрать запись?'),
        text: t('Число уйдёт из сегодняшнего счёта и из среднего за неделю.'),
        confirmText: t('Убрать'), danger: true
    });

    if (!да) return;

    await dbService.deleteIntake(id);
    await app.render();
});

actions.on('cond-why', (el) => {
    const ключ = el.dataset.key;
    if (!ключ) return;

    раскрыто = раскрыто === ключ ? null : ключ;

    /*
     * Правим узел, а не перерисовываем экран (Р-142).
     *
     * Перерисовка читает всю таблицу подходов, все сводки, все замеры и
     * данные часов. Замерено на 3160 подходах: отрисовка 30 мс, из них 32 —
     * чтение подходов, то есть почти всё время; на телефоне втрое-впятеро
     * дольше, а на пяти годах истории это около полусекунды на каждое
     * касание плитки. Переключение шторки столько стоить не должно.
     *
     * Кэшировать прочитанное было бы хуже: пока экран открыт, данные меняет
     * обмен с облаком, и шторка держала бы на экране позавчерашние числа.
     * Разворот же собирается из рядов, которые уже посчитаны отрисовкой, —
     * читать для него нечего вовсе.
     */
    document.querySelector('.cond-detail')?.remove();

    for (const плитка of document.querySelectorAll('.cond-tile.is-open')) {
        плитка.classList.remove('is-open');
        плитка.setAttribute('aria-expanded', 'false');
    }

    if (!раскрыто) return;

    el.classList.add('is-open');
    el.setAttribute('aria-expanded', 'true');

    const сетка = el.closest('.cond-grid');
    if (!сетка) return;

    сетка.insertAdjacentHTML('afterend', String(разворот(раскрыто)));

    /*
     * И разворот показывает себя сам (Р-130, Р-142).
     *
     * Он раскрывается под сеткой, а сетка бывает в четыре ряда: на экране
     * 360×800 у нижней плитки «Тела» из разворота оставалось видно только
     * начало графика — восемьдесят шесть точек уходило за нижний край, и
     * объяснения под линией человек не видел вовсе. Ровно эта беда была у
     * полосы отдыха (Р-130).
     *
     * «Ближайший» край, а не «в начало»: если разворот и так виден целиком,
     * ничего не двигается. Без плавности намеренно — там, где включено
     * «уменьшить движение», плавная прокрутка молча не делает ничего, это
     * замерено в Р-130.
     */
    сетка.nextElementSibling?.scrollIntoView({ block: 'nearest' });
});
