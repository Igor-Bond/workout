/*
 * За каждым числом — его ход и объяснение (§66, Р-136).
 *
 * Оценка без основания — это приговор без разбирательства: человек видит
 * жёлтое и не знает ни чьей меркой его мерили, ни насколько эта мерка точна.
 * Поэтому нажимается каждая плитка, включая те, что не покрашены: «почему тут
 * нет цвета» — такой же законный вопрос.
 *
 * Разворот на месте, а не окном поверх экрана (Р-136). Окно приходилось
 * закрывать, чтобы посмотреть на соседнее число, — а вопрос «куда идёт» как
 * раз и задают всем числам подряд. Нажатие на раскрытую плитку её закрывает:
 * иначе разворот было бы нечем убрать.
 */
actions.on('cond-why', (el) => {
    const ключ = el.dataset.key;
    if (!ключ) return;

    раскрыто = раскрыто === ключ ? null : ключ;

    app.render();
});
