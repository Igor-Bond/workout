/**
 * Кондиции — расширенная статистика одним экраном (§66 ТЗ).
 *
 * Обычная статистика отвечает на вопрос «сколько я сделал». Этот экран — на
 * другой: «в каком я состоянии». Числа здесь приходят из трёх разных мест —
 * весы, часы, сама тренировка, — и порознь каждое из них ничего не значит:
 * вес без талии, сон без нагрузки, тоннаж без восстановления. Собранные
 * вместе, они и есть кондиции.
 *
 * Отдельным экраном, а не карточкой в статистике: сюда приходят раз в
 * неделю, с вопросом «куда всё идёт», и рядом с недельным тоннажем такой
 * разговор не помещается. Главный экран об этом не знает вовсе — там место
 * тому, что нужно сегодня.
 *
 * Правило, которое здесь главное: **цвет вешается на сравнение, а не на
 * число** (js/core/health.js). Красится только то, у чего названа норма или
 * есть собственный ход; остальное стоит числом. Ни одна оценка не выносится
 * молча: рядом с каждой сказано, с чем сравнивали.
 */

