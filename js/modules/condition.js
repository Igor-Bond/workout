/*
 * За каждым числом — объяснение (§66).
 *
 * Оценка без основания — это приговор без разбирательства: человек видит
 * жёлтое и не знает ни чьей меркой его мерили, ни насколько эта мерка точна.
 * Поэтому нажимается каждая плитка, включая те, что не покрашены: «почему
 * тут нет цвета» — такой же законный вопрос.
 */
actions.on('cond-why', async (el) => {
    const что = ПОЧЕМУ[el.dataset.key];
    if (!что) return;

    const { title, text } = что();

    await dialog.alert({ title, text });
});
