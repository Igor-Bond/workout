const ГРУППА = 'group:';

/**
 * Куда человек собирался — из цели в профиле (§58).
 *
 * Без цели приложение не красит вес и талию вовсе: минус килограмм для
 * набирающего массу и для убирающего живот — это разные новости, и решать за
 * человека, какая из них хорошая, оно не вправе.
 */
function куда(профиль, цели = {}, последний = null) {
    /*
     * Цифра важнее слов (§67, Р-155).
     *
     * Словесная цель разбирается выражением и ошибается: «поправить спину»
     * читается как «поправиться». Названное число не ошибается вовсе — из
     * него направление видно точно, и спрашивать слова уже незачем.
     */
    const вес = цели.weight;

    if (вес && Number.isFinite(вес.target) && Number.isFinite(последний?.weight)) {
        if (вес.target < последний.weight) return 'down';
        if (вес.target > последний.weight) return 'up';
    }

    const цель = String(профиль?.goal || '').toLowerCase();

    const вниз = /похуд|живот|жир|сброс|сушк|вес вниз/.test(цель);
    const вверх = /набрать масс|набор масс|поправ/.test(цель);

    if (вниз && !вверх) return 'down';
    if (вверх && !вниз) return 'up';

    return null;
}

/**
 * Какая плитка раскрыта сейчас (Р-136).
 *
 * Одна на экран: у двух графиков рядом разные единицы и разные масштабы,
 * сравнивать их нечем, а места они занимают столько, что до нижних карточек
 * уже не доскроллить.
 */
let раскрыто = null;

/**
 * Ряды для графиков — собираются один раз за отрисовку (Р-136).
 *
 * Лежат в модуле, а не передаются в карточки: раскрыта из них всегда одна, и
 * протаскивать ряды через каждую значило бы поднимать их в каждую подпись
 * ради одной.
 */
let РЯДЫ = {};

/**
 * Объявленные цифровые цели — на ту же отрисовку, что и ряды (§67).
 *
 * Лежат рядом с рядами и по той же причине: их спрашивает разворот, а он
 * собирается глубоко внутри карточки.
 */
let ЦЕЛИ = {};


/**
 * Плитка кондиции: число, подпись и — если есть с чем сравнить — отметка.
 *
 * Нажимается всегда: за каждым числом лежит его ход и объяснение, откуда оно
 * и с чем сравнивалось. Число без объяснения на этом экране было бы
 * приговором без разбирательства.
 *
 * Ключ у каждой плитки свой, даже когда объяснение общее: по ключу берётся
 * ряд для графика, и «Вода» с «Мышцами» под одним ключом показывали бы одну
 * и ту же линию — воду в ответ на нажатие мышц.
 */
function плитка({ ключ, подпись, значение, единица = '', state, основание }) {
    const отметка = state === health.ХОРОШО ? 'is-good'
        : state === health.СМОТРЕТЬ ? 'is-watch'
        : '';

    /*
     * Линия хода — прямо в плитке, без нажатия (Р-153).
     *
     * Число отвечает «сколько сейчас», и до сих пор ответ на «куда идёт»
     * приходилось добывать нажатием. А приходят сюда именно со вторым
     * вопросом, и задают его всем плиткам подряд: раскрывать каждую, чтобы
     * увидеть наклон, — это десять нажатий на экран.
     *
     * В развороте линия остаётся: там у неё шкала, даты, полоса «как
     * обычно» и объяснение. Здесь — только форма.
     */
    const ряд = РЯДЫ[ключ];

    const линия = ряд && ряд.points.length >= 2
        ? chart.spark(
            calc.segments(ряд.points).map((кусок) => кусок.map((p) => ({ x: p.at, y: p.value }))),
            { color: ряд.color || 'var(--accent)', floor: ряд.floor ?? null }
        )
        : '';

    return ui.html`
        <button class="cond-tile ${отметка} ${раскрыто === ключ ? 'is-open' : ''}"
                data-action="cond-why" data-key="${ключ}"
                aria-expanded="${раскрыто === ключ ? 'true' : 'false'}">
            <strong>${значение}${единица ? ui.html`<small>${единица}</small>` : ''}</strong>
            ${линия || ''}
            <span>${подпись}</span>
            ${основание ? ui.html`<em>${основание}</em>` : ''}
        </button>
    `;
}

/**
 * Разворот под карточкой: график хода и объяснение.
 *
 * График первый, объяснение под ним: что это за величина, спрашивают один
 * раз, а куда она идёт — каждый.
 *
 * Название величины стоит заголовком, хотя оно уже написано на плитке.
 * Разворот раскрывается не под самой плиткой, а под всей сеткой — иначе он
 * разрывал бы ряд пополам, — и без заголовка от нижнего ряда не понять, к
 * какому из чисел карточки относится линия.
 */
function разворот(ключ) {
    const ряд = РЯДЫ[ключ];
    const что = ПОЧЕМУ[ключ] || (ключ.startsWith(ГРУППА) ? ПОЧЕМУ.groups : null);

    if (!ряд && !что) return '';

    const заголовок = ряд?.title || что?.().title || '';

    /*
     * Полоса «как обычно» — только у величин, которые колеблются (Р-139).
     *
     * У веса, талии и жира есть направление, а не уровень: полоса по ним
     * накрыла бы весь график и сказала бы ровно ничего. Сон, пульс покоя и
     * недельный объём, наоборот, ходят вокруг своего уровня — и вопрос к ним
     * именно такой: сегодняшнее число обычное или нет.
     */
    const полоса = ряд?.band ? calc.middleHalf(ряд.points.map((p) => p.value)) : null;

    return ui.html`
        <div class="cond-detail">
            ${заголовок ? ui.html`<div class="chart-title">${заголовок}</div>` : ''}

            ${ряд && ряд.points.length >= 2 ? chart.line([{
                color: ряд.color || 'var(--accent)',
                segments: calc.segments(ряд.points).map((кусок) => кусок.map((p) => ({
                    x: p.at, y: p.value, key: `${ключ}-${p.at}`,
                    label: dates.formatShort(p.at)
                })))
            }], {
                height: 130, scale: true,
                minSpan: ряд.minSpan || 1,
                floor: ряд.floor ?? null,
                band: полоса,
                label: заголовок
            }) : ''}

            ${полоса ? ui.html`
                <p class="hint">${t('Затенена ваша обычная полоса: половина всей истории лежит внутри неё. Смотреть стоит на то, что из неё вышло.')}</p>
            ` : ''}

            <!--
                Одна точка — это ещё не ход (Р-136).

                Рисовать по ней линию значило бы изображать движение там, где
                его не видно: человек прочтёт наклон, которого нет. А у
                суточного расхода ряда нет вовсе — коэффициент активности
                считается по нынешнему месяцу, и задним числом его не
                восстановить; обещать график там, где его не будет, незачем.
            -->
            ${ряд && ряд.points.length < 2 ? ui.html`
                <p class="hint">${t('Ход показать пока не из чего: нужно хотя бы два измерения.')}</p>
            ` : ''}

            ${цельСтрокой(ключ, ряд)}

            ${что ? ui.html`<p class="hint">${что().text}</p>` : ''}

            <!--
                Мерка — в килограммах и сантиметрах, а не в индексах (Р-141).

                «ИМТ 27,1» человеку не говорит ничего, «для вашего роста
                здоровым считают от 63 до 86 кг» говорит всё. Стоит она
                отдельной строкой и только там, где её есть из чего посчитать:
                вилка веса — из роста, пороги талии — из пола.
            -->
            ${мерка(ключ) ? ui.html`<p class="hint">${мерка(ключ)}</p>` : ''}
        </div>
    `;
}

/**
 * Чей рост и пол брать для мерок разворота (Р-141).
 *
 * В модуле, как и ряды: объяснения лежат отдельной таблицей и профиля не
 * видят, а таскать его через каждую подпись ради двух строк — дорого.
 */
let ПРО = {};

/**
 * Абсолютная мерка величины — словами и в её же единицах (§66, Р-141).
 *
 * Возвращает пустое там, где мерки нет: у веса без роста и у талии без пола
 * приложение молчит, а не подставляет мужскую вилку по умолчанию.
 */
function мерка(ключ) {
    if (ключ === 'weight') {
        const вилка = health.weightRange(ПРО.рост);

        return вилка && t('Для вашего роста {рост} см здоровым считается вес от {от} до {до} кг — это норма ВОЗ по индексу массы тела, переведённая в килограммы. От пола и возраста она не зависит: у ВОЗ для взрослых одна вилка на всех.', {
            рост: format.decimal(ПРО.рост, 0),
            от: format.weight(вилка.from), до: format.weight(вилка.to)
        });
    }

    if (ключ === 'waist') {
        const пороги = health.waistLimits(ПРО.sex);

        return пороги && t('Пороги ВОЗ для вашего пола — {повод} и {риск} см: за первым риск считают повышенным, за вторым — заметно повышенным. От роста они не зависят, и это их слабое место; рост учитывает соседняя плитка «талия к росту».', {
            повод: пороги.watch, риск: пороги.risk
        });
    }

    return '';
}

/**
 * Что сделано и что осталось до объявленной цели (§67, Р-155).
 *
 * Стоит в развороте, а не на плитке: на плитке место числу и его оценке, а
 * здесь — разговор о пути. Сначала пройденное, потом остаток: человек,
 * снявший полтора килограмма, обязан видеть их раньше, чем оставшиеся
 * четыре.
 *
 * Срок называется только там, где он честно считается. Идёте в другую
 * сторону или стоите — приложение так и говорит, а даты не выдумывает.
 */
function цельСтрокой(ключ, ряд) {
    const объявлено = ЦЕЛИ[ключ];
    if (!объявлено || !ряд || !ряд.points.length) return '';

    const сейчас = ряд.points[ряд.points.length - 1].value;

    const ход = goal.progress({ from: объявлено.from, target: объявлено.target, current: сейчас });
    if (!ход) return '';

    const вНеделю = goal.pace(ряд.points);
    const куда = goal.heading({ target: объявлено.target, current: сейчас, perWeek: вНеделю });

    const срок = вНеделю === null ? null : goal.eta({
        current: сейчас, target: объявлено.target, perWeek: вНеделю
    });

    const весь = Math.abs(объявлено.target - объявлено.from);
    const пройдено = Math.max(0, весь - ход.left);

    return ui.html`
        <p class="hint">
            ${ход.done
                ? t('Цель {цель} достигнута.', { цель: format.plain(объявлено.target) })
                : t('Цель {цель}: прошли {пройдено} из {весь}, осталось {осталось}.', {
                    цель: format.plain(объявлено.target),
                    пройдено: format.decimal(пройдено, 1),
                    весь: format.decimal(весь, 1),
                    осталось: format.decimal(ход.left, 1)
                })}

            ${ход.done ? '' : куда === 'toward' && срок
                ? t(' Своим ходом придёте к {день}.', { день: dates.formatDate(срок) })
                : куда === 'away'
                    ? t(' Последний месяц идёте в другую сторону.')
                    : t(' Пока стоите на месте — срок назвать нечем.')}
        </p>
    `;
}

