/**
 * Ряды для графиков — из замеров и из данных часов (Р-136).
 *
 * Точки берутся по свидетельствам, а не по календарю: у веса это дни
 * взвешиваний, у сна — дни, когда часы что-то записали. Пропуски остаются
 * пропусками, и линия на них рвётся (§25) — прямая через пропуск выглядит
 * так, будто ничего не происходило.
 */
function собратьРяды({ замеры, rows, профиль, рост, возраст, группы, еда }) {
    const изЗамеров = (взять) => замеры
        .map((r) => ({ at: r.at, value: Number(взять(r)) }))
        .filter((p) => Number.isFinite(p.value) && p.value > 0);

    const поДням = [...rows].sort((a, b) => a.date - b.date);

    const изЧасов = (поле) => поДням
        .map((r) => ({ at: r.date, value: r[поле] }))
        .filter((p) => Number.isFinite(p.value) && p.value > 0);

    /*
     * Съеденное складывается по суткам, а не по записям (§68).
     *
     * Записей за день бывает пять, и точка на каждую превратила бы линию в
     * пилу из завтраков и перекусов. Вопрос к ряду один — сколько вышло за
     * день, — и точка ставится на день.
     *
     * Дни без записей пропускаются, а не обнуляются: ноль значил бы
     * голодание. Разрыв в линии честнее прямой, проведённой через забытый
     * вторник.
     */
    const поСуткам = () => {
        const суммы = new Map();

        for (const r of еда) {
            if (!Number.isFinite(r?.at) || !Number.isFinite(Number(r.kcal))) continue;

            const день = dates.startOfDay(r.at);
            суммы.set(день, (суммы.get(день) || 0) + Number(r.kcal));
        }

        return [...суммы.entries()]
            .sort((a, b) => a[0] - b[0])
            .map(([at, value]) => ({ at, value }));
    };

    const ряды = {
        weight: {
            title: t('Вес'), points: изЗамеров((r) => r.weight),
            minSpan: 2, color: 'var(--purple)'
        },
        waist: {
            title: t('Талия'), points: изЗамеров((r) => r.waist),
            minSpan: 4
        },
        fat: {
            title: t('Доля жира'), points: изЗамеров((r) => r.body?.fat),
            minSpan: 2
        },
        water: {
            title: t('Вода'), points: изЗамеров((r) => r.body?.water),
            minSpan: 2
        },
        muscle: {
            title: t('Мышцы'), points: изЗамеров((r) => r.body?.muscle),
            minSpan: 2
        },

        /*
         * Сон в часах, а не в секундах: на плитке он стоит как «6:10», и
         * шкала графика в тысячах секунд рядом с этим ничего не значила бы.
         */
        sleep: {
            title: t('Сон'),
            points: изЧасов('sleep').map((p) => ({ at: p.at, value: Math.round(p.value / 36) / 100 })),
            minSpan: 2, band: true, color: 'var(--blue)'
        },
        rhr: {
            title: t('Пульс покоя'), points: изЧасов('rhr'),
            minSpan: 6, band: true, color: 'var(--blue)'
        },
        hrv: {
            title: t('Вариабельность'), points: изЧасов('hrv'),
            minSpan: 10, floor: 0, band: true, color: 'var(--blue)'
        },
        score: {
            title: t('Оценка сна'), points: изЧасов('score'),
            minSpan: 10, floor: 0, band: true, color: 'var(--blue)'
        },

        /*
         * Форма может быть и нулём, и минусом, поэтому собирается отдельно:
         * общий отбор «больше нуля» выбросил бы ровно те дни, ради которых на
         * неё и смотрят.
         */
        form: {
            title: t('Готовность'),
            points: поДням
                .filter((r) => Number.isFinite(r.ctl) || Number.isFinite(r.atl))
                .map((r) => ({ at: r.date, value: Math.round((r.ctl || 0) - (r.atl || 0)) })),
            minSpan: 10, band: true, color: 'var(--blue)'
        },
        ramp: {
            title: t('Разгон'),
            points: поДням
                .filter((r) => r.ctl > 0 && r.atl > 0)
                .map((r) => ({ at: r.date, value: Math.round((r.atl / r.ctl) * 100) / 100 })),
            minSpan: 0.6, floor: 0, band: true, color: 'var(--blue)'
        },
        intake: {
            title: t('Съеденное'), points: поСуткам(),
            minSpan: 500, floor: 0, band: true, color: 'var(--purple)'
        },
        ctl: {
            title: t('Нагрузка за шесть недель'), points: изЧасов('ctl'),
            minSpan: 10, color: 'var(--blue)'
        },
        atl: {
            title: t('Нагрузка за неделю'), points: изЧасов('atl'),
            minSpan: 10, color: 'var(--blue)'
        }
    };

    /*
     * Производные величины считаются по каждому замеру заново (Р-136).
     *
     * Ради них график и нужен больше всего: «27,1» говорит «выше нормы» и
     * молчит о том, что месяц назад было 27,5. Мерка грубая, но её ход — уже
     * свидетельство.
     *
     * Суточного расхода среди них нет: коэффициент активности выводится из
     * нынешних шагов и тренировок, и задним числом его не восстановить.
     * Нарисовать ряд можно было бы только приложив сегодняшний коэффициент к
     * прошлым весам — то есть придумав историю, которой не было.
     */
    if (рост) {
        ряды.bmi = {
            title: t('Индекс массы тела'),
            points: изЗамеров((r) => health.bmi(r.weight, рост)?.value),
            minSpan: 1
        };

        ряды.wht = {
            title: t('Талия к росту'),
            points: изЗамеров((r) => health.waistToHeight(r.waist, рост)?.value),
            minSpan: 0.06
        };

        ряды.bmr = {
            title: t('Основной обмен'),
            points: изЗамеров((r) => health.bmr({
                weight: r.weight, height: рост, age: возраст, sex: профиль?.sex
            })),
            minSpan: 50
        };
    }

    /*
     * У групп мышц нули — это данные, а не пропуски (Р-138).
     *
     * У всех остальных величин ноль значит «не мерили», и такие точки
     * выбрасываются. Здесь наоборот: неделя без единого подхода на спину — это
     * ровно то, ради чего на график и смотрят. Поэтому ряд берётся целиком,
     * как посчитан, и разрывов в нём не бывает.
     */
    for (const г of группы) {
        ряды[ГРУППА + г.group] = {
            title: t(г.group), points: г.points, minSpan: 6, floor: 0, band: true, color: 'var(--purple)'
        };
    }

    return ряды;
}

/** Всё, что экрану нужно из базы, — одним заходом. */
async function прочитать() {
    const [профиль, замеры, сводки, { rows }, подходы, упражнения, цели, еда] = await Promise.all([
        currentAthlete(),
        dbService.listBodyWeight(),
        dbService.listWorkoutSummaries(),
        currentWellness(),
        dbService.allSets(),
        dbService.listExercises({ includeArchived: true }),
        currentGoals(),
        dbService.listIntake()
    ]);

    return { профиль, замеры, сводки, rows, подходы, упражнения, цели, еда };
}

