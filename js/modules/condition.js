const DAY = 86400000;

/**
 * За сколько дней смотреть ход величины.
 *
 * Месяц, а не неделя: вес за неделю говорит о воде и соли, а не о человеке.
 * Талия меняется ещё медленнее, и на недельном окне её ход неотличим от того,
 * как затянули ленту.
 */
const ОКНО = 30;

/**
 * Насколько величина должна сдвинуться, чтобы это считалось ходом.
 *
 * Иначе приложение объявляло бы направление по шуму прибора: двести граммов
 * веса — это вода, а полсантиметра талии — то, как держали ленту.
 */
const ШУМ = { weight: 0.5, waist: 1 };

/** Ключ, под которым помним прошлую отметку жира — ради гистерезиса (§66). */
const ЖИР_ОТМЕТКА = 'fatState';

/**
 * Куда человек собирался — из цели в профиле (§58).
 *
 * Без цели приложение не красит вес и талию вовсе: минус килограмм для
 * набирающего массу и для убирающего живот — это разные новости, и решать за
 * человека, какая из них хорошая, оно не вправе.
 */
function куда(профиль) {
    const цель = String(профиль?.goal || '').toLowerCase();

    const вниз = /похуд|живот|жир|сброс|сушк|вес вниз/.test(цель);
    const вверх = /набрать масс|набор масс|поправ/.test(цель);

    if (вниз && !вверх) return 'down';
    if (вверх && !вниз) return 'up';

    return null;
}

/**
 * Плитка кондиции: число, подпись и — если есть с чем сравнить — отметка.
 *
 * Нажимается всегда: за каждым числом лежит объяснение, откуда оно и с чем
 * сравнивалось. Число без объяснения на этом экране было бы приговором без
 * разбирательства.
 */
function плитка({ ключ, подпись, значение, единица = '', state, основание }) {
    const отметка = state === health.ХОРОШО ? 'is-good'
        : state === health.СМОТРЕТЬ ? 'is-watch'
        : '';

    return ui.html`
        <button class="cond-tile ${отметка}" data-action="cond-why" data-key="${ключ}">
            <strong>${значение}${единица ? ui.html`<small>${единица}</small>` : ''}</strong>
            <span>${подпись}</span>
            ${основание ? ui.html`<em>${основание}</em>` : ''}
        </button>
    `;
}

