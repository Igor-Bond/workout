/** Тело: то, что меряют лентой и весами. */
async function телоБлок({ профиль, замеры, последний, рост, возраст, цель }) {
    if (!последний) return null;

    const прежняя = await dbService.getSetting(ЖИР_ОТМЕТКА, null);

    const bmi = рост ? health.bmi(последний.weight, рост) : null;
    const wht = рост && последний.waist ? health.waistToHeight(последний.waist, рост) : null;

    const жир = последний.body?.fat
        ? health.bodyFat(последний.body.fat, { sex: профиль?.sex, age: возраст }, прежняя)
        : null;

    // Отметка жира помнится ради гистерезиса: без прошлой она мигала бы
    if (жир && жир.state !== прежняя) await dbService.setSetting(ЖИР_ОТМЕТКА, жир.state);

    /*
     * «Месяц назад» — последний замер не позже этого срока (Р-134).
     *
     * Сначала брался первый замер после границы окна — и когда замеров всего
     * два, свежий сам же в это окно и попадал: приложение сравнивало
     * сегодняшний вес с сегодняшним и объявляло, что ничего не происходит.
     *
     * Нет замера старше месяца — берётся самый ранний, какой есть: сравнить с
     * двухнедельной давностью честнее, чем не сравнивать вовсе, а срок рядом
     * назван.
     */
    const граница = Date.now() - ОКНО * DAY;
    const старые = замеры.filter((r) => r.at <= граница);
    const было = старые[старые.length - 1] || замеры[0];

    const весХод = health.trend(было?.weight, последний.weight,
        { goodDirection: цель, noise: ШУМ.weight });

    const талияХод = было?.waist && последний.waist
        ? health.trend(было.waist, последний.waist, { goodDirection: цель, noise: ШУМ.waist })
        : null;

    const плитки = [
        плитка({
            ключ: 'weight', подпись: t('Вес'), единица: t('кг'),
            значение: format.weight(последний.weight),
            state: весХод?.state,
            основание: весХод && весХод.delta !== 0
                ? t('{знак}{n} за месяц', {
                    знак: весХод.delta > 0 ? '+' : '−',
                    n: format.weight(Math.abs(весХод.delta))
                })
                : null
        }),

        последний.waist ? плитка({
            ключ: 'waist', подпись: t('Талия'), единица: t('см'),
            значение: format.weight(последний.waist),
            state: талияХод?.state,
            основание: талияХод && талияХод.delta !== 0
                ? t('{знак}{n} за месяц', {
                    знак: талияХод.delta > 0 ? '+' : '−',
                    n: format.weight(Math.abs(талияХод.delta))
                })
                : null
        }) : '',

        wht ? плитка({
            ключ: 'waist', подпись: t('Талия к росту'),
            значение: String(wht.value).replace('.', ','),
            state: wht.state, основание: wht.norm
        }) : '',

        bmi ? плитка({
            ключ: 'bmi', подпись: t('Индекс массы тела'),
            значение: String(bmi.value).replace('.', ','),
            state: bmi.state, основание: bmi.norm
        }) : '',

        жир ? плитка({
            ключ: 'fat', подпись: t('Доля жира'), единица: '%',
            значение: format.decimal(жир.value, 1),
            state: жир.state, основание: жир.norm
        }) : '',

        последний.body?.water ? плитка({
            ключ: 'water', подпись: t('Вода'), единица: '%',
            значение: format.decimal(последний.body.water, 1),
            state: health.СПРАВКА, основание: null
        }) : '',

        последний.body?.muscle ? плитка({
            ключ: 'water', подпись: t('Мышцы'), единица: '%',
            значение: format.decimal(последний.body.muscle, 1),
            state: health.СПРАВКА, основание: null
        }) : ''
    ].filter(Boolean);

    return карточка(t('Тело'), плитки,
        t('Замер {когда}.', { когда: dates.formatDayLabel(последний.at, Date.now(), { lower: true }) }),
        !цель && t('Вес и талия не отмечены цветом: в профиле не названа цель, а без неё «минус килограмм» — это и хорошо, и плохо.'));
}

/** Обмен: сколько тело тратит. */
function обменБлок({ профиль, последний, рост, возраст, сводки, rows }) {
    if (!последний || !рост || !возраст) return null;

    const основной = health.bmr({
        weight: последний.weight, height: рост, age: возраст, sex: профиль?.sex
    });

    if (!основной) return null;

    const шаги = recovery.steps(rows);

    /*
     * Тренировок в неделю — по последнему месяцу, а не по всей истории:
     * коэффициент отвечает на вопрос «сколько человек тратит сейчас».
     */
    const месяц = сводки.filter((e) => e.workout.startedAt >= Date.now() - 28 * DAY);
    const вНеделю = Math.round((месяц.length / 4) * 10) / 10;

    const коэффициент = health.activityFactor({
        steps: шаги || 0, workoutsPerWeek: вНеделю
    });

    const расход = health.amr(основной, коэффициент);

    return карточка(t('Обмен'), [
        плитка({
            ключ: 'bmr', подпись: t('Основной обмен'), единица: t('ккал'),
            значение: format.decimal(основной, 0),
            state: health.СПРАВКА, основание: t('в полном покое')
        }),
        плитка({
            ключ: 'amr', подпись: t('Суточный расход'), единица: t('ккал'),
            значение: format.decimal(расход, 0),
            state: health.СПРАВКА,
            основание: t('активность {k}', { k: String(коэффициент).replace('.', ',') })
        })
    ], t('Коэффициент выведен из {шаги} шагов в день и {n} тренировок в неделю.', {
        шаги: format.decimal(шаги || 0, 0), n: String(вНеделю).replace('.', ',')
    }));
}

/** Восстановление: то, что приносят часы. */
function восстановлениеБлок(rows) {
    const сон = recovery.sleep(rows);
    const пульс = recovery.resting(rows);

    if (сон === null && !пульс) return null;

    const часы = сон !== null ? Math.floor(сон / 3600) : 0;
    const минуты = сон !== null ? Math.round((сон % 3600) / 60) : 0;

    const плитки = [
        сон !== null ? плитка({
            ключ: 'sleep', подпись: t('Сон'),
            значение: `${часы}:${String(минуты).padStart(2, '0')}`,
            state: health.СПРАВКА, основание: t('в среднем за неделю')
        }) : '',

        пульс ? плитка({
            ключ: 'rhr', подпись: t('Пульс покоя'),
            значение: String(пульс.now),
            /*
             * У пульса покоя рост — плохой знак, и сравнение здесь обратное
             * обычному: выше базы значит хуже. Разница меньше порога самих
             * часов не красится вовсе.
             */
            state: Math.abs(пульс.shift) < recovery.SHIFT ? health.ХОРОШО
                : пульс.shift > 0 ? health.СМОТРЕТЬ : health.ХОРОШО,
            основание: Math.abs(пульс.shift) < recovery.SHIFT
                ? t('как обычно')
                : t('{знак}{n} к месяцу', { знак: пульс.shift > 0 ? '+' : '−', n: Math.abs(пульс.shift) })
        }) : ''
    ].filter(Boolean);

    return карточка(t('Восстановление'), плитки, t('С часов, среднее за неделю.'));
}

/** Форма: то, что считает Intervals.icu. */
function формаБлок(rows) {
    const свежие = [...rows].filter((r) => r.ctl || r.atl).sort((a, b) => a.date - b.date);
    const последняя = свежие[свежие.length - 1];

    if (!последняя) return null;

    const форма = Math.round((последняя.ctl || 0) - (последняя.atl || 0));

    return карточка(t('Форма'), [
        плитка({
            ключ: 'form', подпись: t('Готовность'),
            значение: форма > 0 ? `+${форма}` : String(форма),
            /*
             * Больше нуля — отдохнул, меньше — копится усталость. Порог не
             * ноль, а небольшой минус: тренирующийся человек почти всегда в
             * лёгком минусе, и красить это «стоит посмотреть» значило бы
             * ругать за саму тренировку.
             */
            state: форма >= -10 ? health.ХОРОШО : health.СМОТРЕТЬ,
            основание: форма >= 0 ? t('отдохнули') : t('копится усталость')
        }),
        плитка({
            ключ: 'form', подпись: t('Нагрузка за шесть недель'),
            значение: format.decimal(последняя.ctl || 0, 0),
            state: health.СПРАВКА, основание: null
        }),
        плитка({
            ключ: 'form', подпись: t('Нагрузка за неделю'),
            значение: format.decimal(последняя.atl || 0, 0),
            state: health.СПРАВКА, основание: null
        })
    ], t('Считает Intervals.icu по занятиям с часов.'));
}

/** Карточка с плитками и приписками. */
function карточка(заголовок, плитки, приписка = '', оговорка = '') {
    if (!плитки.length) return null;

    return ui.html`
        <div class="card">
            <div class="card-title">${заголовок}</div>

            <div class="cond-grid">${плитки}</div>

            ${приписка ? ui.html`<p class="hint">${приписка}</p>` : ''}
            ${оговорка ? ui.html`<p class="hint">${оговорка}</p>` : ''}
        </div>
    `;
}

