/**
 * Полнота перевода по исходникам (§53).
 *
 * Проверка отрисовкой отвечает на вопрос «нет ли кириллицы на экране»,
 * и это правильный вопрос — но задаётся он только тем экранам, которые
 * удалось нарисовать, и только на тех данных, которые для этого сложили.
 * Диалог, редкая ветка, сообщение об ошибке остаются вне её поля зрения, и
 * именно там русский текст доживал до людей.
 *
 * Здесь вопрос другой: не «что видно», а «что написано». Приложение
 * читается как текст, и каждая русская строка обязана быть либо ключом
 * перевода, либо помеченным сообщением в журнал. Такой проверке всё равно,
 * дошёл ли кто-нибудь до нужного окна.
 *
 * Две проверки дополняют друг друга и ни одна не заменяет вторую: эта не
 * видит строк, собранных из кусков на ходу, а та не видит ненарисованного.
 */

import { describe, it, assert } from '../runner.js';
import { sources, untranslated, keysIn } from '../helpers/source.js';
import { EN } from '../../js/i18n/en.js';
import { DE } from '../../js/i18n/de.js';
import { guideContent } from '../../js/i18n/guide.js';

/**
 * Файлы, где русский текст — не интерфейс.
 *
 * Каждый должен быть назван с причиной: список без причин через полгода
 * превращается в место, куда прячут неудобные находки.
 */
const МИМО = {
    'js/core/dates.js':          'месяцы и дни недели лежат таблицей на каждый язык',
    'js/core/format.js':         'формы слов лежат таблицей на каждый язык',
    'js/core/estimate.js':       'коэффициенты по нормализованным названиям — ключи поиска, не текст',
    'js/core/i18n.js':           'языки в списке названы на себе самих, это и есть замысел',
    'js/services/migrations.js': 'базовый справочник по-русски, переводится при установке',
    'js/services/scale.js':      'служебные слова профиля Bluetooth — не интерфейс, а язык устройства',
    'js/services/howto.js':      'описания техники по-русски, переводятся при доставке',
    'js/core/plan.js':           'дни недели и слова отдыха — ключи разбора чужого текста, не интерфейс',
    'js/core/presets.js':        'готовые ответы анкеты по-русски: ложатся в профиль как есть, переводятся при показе',

    /*
     * Наставление собеседнику на экран не попадает: его читает языковая
     * модель, а не человек. Переводить его незачем — модель понимает русский
     * не хуже прочего, а сам ответ приходит на языке вопроса, потому что так
     * в наставлении и сказано. Вопрос же и дело человек пишет и видит на
     * своём языке: они идут через перевод как всё остальное.
     */
    'js/core/prompt.js':         'наставление языковой модели — не интерфейс; ответ приходит на языке вопроса'
};

/** Ключи, у которых есть перевод на оба языка. */
const ПЕРЕВЕДЁННЫЕ = new Set(Object.keys(EN).filter((key) => key in DE));

describe('Полнота перевода в коде', () => {

    it('весь видимый текст проходит через перевод', async () => {
        const находки = [];

        for (const { path, code } of await sources()) {
            if (МИМО[path]) continue;

            for (const item of untranslated(code, ПЕРЕВЕДЁННЫЕ)) {
                находки.push(`${path}:${item.line} (${item.kind}) ${item.text}`);
            }
        }

        assert(находки.length === 0,
            `текст мимо перевода — ${находки.length}:\n${находки.join('\n')}`);
    });

    it('у каждого ключа есть оба перевода', async () => {
        const нет = [];

        for (const { path, code } of await sources()) {
            for (const key of keysIn(code)) {
                const пусто = [];
                if (!(key in EN)) пусто.push('англ.');
                if (!(key in DE)) пусто.push('нем.');

                if (пусто.length) нет.push(`${path}: «${key}» — нет ${пусто.join(' и ')}`);
            }
        }

        assert(нет.length === 0, `без перевода — ${нет.length}:\n${[...new Set(нет)].join('\n')}`);
    });

    /**
     * Ключ, которого больше нет в коде, — след правки русского текста.
     *
     * Словарь построен на самом русском тексте, и это его слабое место:
     * поправил слово на экране — связь с переводом порвалась молча. Здесь
     * такой разрыв виден с другой стороны: перевод остался, а строки, к
     * которой он был, уже нет.
     */
    it('в словарях нет ключей, которых нет в коде', async () => {
        const весь = (await sources()).map((f) => f.code).join('\n');

        const забытые = [...ПЕРЕВЕДЁННЫЕ].filter((key) => !весь.includes(key));

        assert(забытые.length === 0,
            `ключей нет в коде — ${забытые.length}:\n${забытые.map((k) => `«${k}»`).join('\n')}`);
    });
});

/**
 * Один голос на всё приложение (§53, Р-120).
 *
 * Приложение говорило с человеком на «ты», на «вы» и на «Вы» — иногда на
 * одном экране: в справочнике «те, что ты правил», а через полминуты «Вид вы
 * уже выбрали»; на статистике «сначала проведи тренировку» и рядом «решаете
 * вы»; на экране часов третья форма, «Вам» с прописной.
 *
 * Читается это не как небрежность, а как смена собеседника: будто одну
 * подсказку писал автор, а другую подставил переводчик. Доверие к написанному
 * держится на том, что написано одной рукой.
 *
 * Выбрано «вы» со строчной: её больше всего, и она уже стоит во всех длинных
 * объяснениях. Проверка смотрит на русский текст — и в ключах перевода, и в
 * справке, которая лежит документом, а не словарём.
 */
describe('Одна форма обращения', () => {

    const ТЫ = /(^|[^а-яёА-ЯЁ])(ты|тебе|тебя|тобой|твой|твоя|твоё|твои|твою|твоего|твоей|твоим|твоих|твоими|твоём)([^а-яёА-ЯЁ]|$)/i;
    const ВЫ = /(^|[^а-яёА-ЯЁ])(Вы|Вам|Вас|Ваш|Ваша|Ваше|Ваши|Вами|Вашего|Вашей|Вашим|Ваших)([^а-яёА-ЯЁ]|$)/;

    /** Весь русский текст справки одной кучей: она лежит документом, а не словарём. */
    function текстСправки(узел, собрано = []) {
        if (typeof узел === 'string') собрано.push(узел);
        else if (Array.isArray(узел)) for (const э of узел) текстСправки(э, собрано);
        else if (узел && typeof узел === 'object') for (const э of Object.values(узел)) текстСправки(э, собрано);

        return собрано;
    }

    it('на «ты» приложение не переходит', async () => {
        const находки = [];

        for (const { path, code } of await sources()) {
            for (const key of keysIn(code)) {
                if (ТЫ.test(key)) находки.push(`${path}: «${key}»`);
            }
        }

        for (const строка of текстСправки(guideContent('ru'))) {
            if (ТЫ.test(строка)) находки.push(`справка: «${строка.slice(0, 80)}…»`);
        }

        assert(находки.length === 0,
            `на «ты» — ${находки.length}:\n${[...new Set(находки)].join('\n')}`);
    });

    /*
     * Прописное «Вы» на фоне остального текста выглядит чужой вставкой: так
     * пишут в деловом письме, а не в приложении, которое человек открывает
     * между подходами.
     */
    it('«вы» пишется со строчной', async () => {
        const находки = [];

        for (const { path, code } of await sources()) {
            for (const key of keysIn(code)) {
                // В начале предложения прописная законна — смотрим только середину
                const середина = key.replace(/(^|[.!?…]\s+|«|„)\s*[А-ЯЁ]\S*/g, ' ');

                if (ВЫ.test(середина)) находки.push(`${path}: «${key}»`);
            }
        }

        for (const строка of текстСправки(guideContent('ru'))) {
            const середина = строка.replace(/(^|[.!?…]\s+|«|„)\s*[А-ЯЁ]\S*/g, ' ');

            if (ВЫ.test(середина)) находки.push(`справка: «${строка.slice(0, 80)}…»`);
        }

        assert(находки.length === 0,
            `прописное «Вы» — ${находки.length}:\n${[...new Set(находки)].join('\n')}`);
    });
});
