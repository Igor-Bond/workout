/**
 * Сутки в календаре, а не в миллисекундах (Р-218).
 *
 * День не всегда длится 86 400 секунд: в ночь осеннего перевода часов он
 * длится 25 часов, весеннего — 23. Всё, что считало «шесть дней назад» как
 * шесть раз по 86 400 000, после осени попадало на час позже полуночи, а
 * после весны — на час раньше. Метка такого дня не совпадает ни с ключом
 * набора дней, ни с клеткой карты, ни с днём недели плана — и на главном
 * подсвечивался один сегодняшний день из семи, на карте не оказывалось
 * тренировок, а развёртка плана теряла понедельник.
 *
 * Хуже всего, что ловится это только в часовом поясе с переводом часов и
 * только неделю в году: на бегунке в UTC такого просто нет. Поэтому проверки
 * строят даты календарём (`new Date(год, месяц, день)`) — в поясе с переводом
 * они упираются в переход, в UTC проходят вхолостую, — а CI запускает
 * страницу проверок в поясе Europe/Berlin (tools/ci-tests.mjs).
 */

import { describe, it, equal, assert } from '../runner.js';
import { dates } from '../../js/core/dates.js';
import { addDays } from '../../js/core/days.js';
import { stats } from '../../js/core/stats.js';
import { plan } from '../../js/core/plan.js';
import { progress } from '../../js/core/progress.js';
import { recovery } from '../../js/core/recovery.js';
import { intake } from '../../js/core/intake.js';
import { prompt } from '../../js/core/prompt.js';
import { ical } from '../../js/core/ical.js';
import { home } from '../../js/modules/home.js';
import { screen, seed, workout } from '../helpers/dom.js';

/** Полночь календарной даты. Месяц с нуля, как у Date. */
const день = (год, месяц, число, час = 0, минута = 0) => new Date(год, месяц, число, час, минута).getTime();

/** Часы местного времени: у полуночи это ноль в любом поясе. */
const час = (ts) => new Date(ts).getHours();

describe('Сутки: прибавка календарных дней', () => {

    it('от полуночи — полночь, и через осенний перевод часов', () => {
        equal(addDays(день(2026, 9, 24), 2), день(2026, 9, 26));
        equal(addDays(день(2026, 9, 26), -2), день(2026, 9, 24));
        equal(addDays(день(2026, 9, 19), 7), день(2026, 9, 26));
    });

    it('и через весенний', () => {
        equal(addDays(день(2026, 2, 28), 3), день(2026, 2, 31));
        equal(addDays(день(2026, 3, 1), -3), день(2026, 2, 29));
    });

    it('через конец года и месяца', () => {
        equal(addDays(день(2026, 11, 30), 3), день(2027, 0, 2));
        equal(addDays(день(2026, 2, 1), -1), день(2026, 1, 28));
    });

    it('шесть дней назад — шесть полуночей подряд, ни одной «на час позже»', () => {
        const сегодня = dates.startOfDay(день(2026, 9, 26, 15));

        for (let i = -6; i <= 0; i++) {
            assert(час(addDays(сегодня, i)) === 0, `день ${i}: ${new Date(addDays(сегодня, i))}`);
        }
    });

    it('dates.addDays — та же мера', () => {
        equal(dates.addDays(день(2026, 9, 24), 2), день(2026, 9, 26));
    });
});

describe('Сутки: полоса «Последние семь дней»', () => {

    /** Отрисовать главный, будто сейчас этот час. */
    async function главныйВ(момент) {
        const настоящее = Date.now;
        Date.now = () => момент;

        try {
            return await screen(home);
        } finally {
            Date.now = настоящее;
        }
    }

    it('в первую неделю после осеннего перевода подсвечены все дни с тренировкой, а не один сегодняшний', async () => {
        const ex = await seed({ name: 'Жим лёжа' });

        // Понедельник 26 октября, сутки назад часы перевели
        const сейчас = день(2026, 9, 26, 15);

        for (const d of [20, 21, 22, 24, 25]) {
            await workout(ex, [[10, 60]], { at: день(2026, 9, d, 12) });
        }

        const вид = await главныйВ(сейчас);
        const сделаны = [...вид.querySelectorAll('.wk-day.is-done')].length;

        equal(сделаны, 5, 'пять дней из шести предыдущих — с тренировкой, и все пять должны светиться');
        equal(вид.querySelectorAll('.wk-day').length, 7);
        equal(вид.querySelectorAll('.wk-day.is-today').length, 1);
    });

    it('и после весеннего', async () => {
        const ex = await seed({ name: 'Жим лёжа' });

        // Понедельник 30 марта, часы переведены вперёд в воскресенье
        const сейчас = день(2026, 2, 30, 15);

        for (const d of [24, 26, 27, 29]) {
            await workout(ex, [[10, 60]], { at: день(2026, 2, d, 12) });
        }

        const вид = await главныйВ(сейчас);

        equal([...вид.querySelectorAll('.wk-day.is-done')].length, 4);
    });
});

describe('Сутки: тепловая карта', () => {

    it('тренировка до перевода часов попадает в свою клетку', () => {
        const entries = [{ workout: { startedAt: день(2026, 9, 22, 12) }, sets: 5 }];
        const клетки = stats.heatmap(entries, день(2026, 9, 26, 12), { weeks: 2 });

        const своя = клетки.find((c) => c.day === день(2026, 9, 22));

        assert(своя, 'клетки за 22 октября нет — метка не совпала с полуночью');
        equal(своя.sets, 5);
    });

    it('все клетки карты стоят на полуночи', () => {
        const клетки = stats.heatmap([], день(2026, 9, 26, 12), { weeks: 4 });

        const кривые = клетки.filter((c) => час(c.day) !== 0);

        assert(кривые.length === 0, `не на полуночи: ${кривые.slice(0, 3).map((c) => new Date(c.day))}`);
    });

    it('неделя начинается с понедельника, и через переход тоже', () => {
        equal(stats.weekStart(день(2026, 9, 26, 12)), день(2026, 9, 26));
        equal(stats.weekStart(день(2026, 9, 25, 12)), день(2026, 9, 19));
    });
});

describe('Сутки: развёртка плана', () => {

    const ТЕКСТ = [
        'С 07.09.2026, 12 недель',
        'Пн Бицепс 6 × 50',
        'Вт Плечи 6 × 30',
        'Ср Баскетбол',
        'Чт Отжимания 6 × 50',
        'Пт Спина 6 × 40',
        'Сб Круг 3 × 20',
        'Вс отдых'
    ].join('\n');

    const П = plan.parse(ТЕКСТ);

    it('четырнадцать дней через осенний перевод: каждый день на полуночи и со своим занятием', () => {
        const ряд = plan.expand(П, { from: день(2026, 9, 13), days: 14 });

        equal(ряд.length, 14);
        assert(ряд.every((д) => час(д.at) === 0), `не на полуночи: ${ряд.filter((д) => час(д.at) !== 0).map((д) => new Date(д.at))}`);

        const понедельник = ряд.find((д) => д.at === день(2026, 9, 26));

        assert(понедельник, 'понедельник 26 октября пропал из развёртки');
        equal(понедельник.session?.name, 'Бицепс', 'после перехода день вставал на воскресенье');
    });

    it('и через весенний', () => {
        const весной = plan.parse(ТЕКСТ.replace('С 07.09.2026', 'С 02.03.2026'));
        const ряд = plan.expand(весной, { from: день(2026, 2, 23), days: 14 });

        equal(ряд.find((д) => д.at === день(2026, 2, 30))?.session?.name, 'Бицепс');
        assert(ряд.every((д) => час(д.at) === 0));
    });

    it('следующий день плана — на полуночи нужной даты', () => {
        // Суббота: после неё воскресенье отдых, затем понедельник — через перевод часов
        const следом = plan.next(П, { now: день(2026, 9, 24, 12) });

        equal(следом?.at, день(2026, 9, 26));
        equal(следом?.session?.name, 'Бицепс');
    });

    it('первый день плана и номер недели не едут', () => {
        equal(plan.first(П)?.at, день(2026, 8, 7));
        equal(plan.weekOf(П, день(2026, 9, 26, 12)), 8, 'неделя 26 октября — восьмая');
        equal(plan.weekOf(П, день(2026, 9, 25, 12)), 7, 'воскресенье перед ней — ещё седьмая');
    });

    /*
     * После весеннего перевода неделя от полуночи понедельника короче 168 часов
     * на час, и в сам понедельник частное оказывалось чуть меньше целого: плану
     * казалась ещё прежняя неделя — а с ней и прежняя сетка «Неделя 1 / 2».
     */
    it('в понедельник после весеннего перевода неделя уже новая', () => {
        const весной = plan.parse(ТЕКСТ.replace('С 07.09.2026', 'С 02.03.2026'));

        equal(plan.weekOf(весной, день(2026, 2, 29, 12)), 4, 'воскресенье перевода — ещё четвёртая');
        equal(plan.weekOf(весной, день(2026, 2, 30, 12)), 5, 'понедельник — пятая, а не четвёртая');
        equal(plan.weekOf(весной, день(2026, 3, 6, 12)), 6);
    });

    it('последний день плана кончается в конце суток, а не на час раньше', () => {
        const конец = new Date(plan.until(П));

        equal([конец.getMonth(), конец.getDate(), конец.getHours(), конец.getMinutes()], [10, 29, 23, 59]);
    });
});

describe('Сутки: окна и допуск в день', () => {

    it('допуск «сдвиг на сутки» работает и через перевод часов', () => {
        // Запланировано воскресенье 25-го, сделано в понедельник 26-го
        const итог = progress.adherence(
            [{ day: день(2026, 9, 25), session: { name: 'Х' } }],
            new Set([день(2026, 9, 26)])
        );

        equal(итог.done, 1, 'соседний день засчитывается');
        equal(итог.shifted, 1, 'и называется сдвигом');
    });

    it('окно восстановления в семь дней содержит все семь, и самый старый тоже', () => {
        const rows = [20, 21, 22, 23, 24, 25, 26].map((d) => ({ date: день(2026, 9, d), sleep: 25200 }));

        equal(recovery.recent(rows, { now: день(2026, 9, 26, 12), days: 7 }).length, 7);
    });

    it('съеденное за двадцать пятое включает последний час длинных суток', () => {
        const rows = [
            { at: день(2026, 9, 25, 9), kcal: 500 },
            { at: день(2026, 9, 25, 23, 30), kcal: 300 },
            { at: день(2026, 9, 26, 0, 30), kcal: 700 }
        ];

        equal(intake.day(rows, { now: день(2026, 9, 25, 12) }), 800, 'последние полчаса длинных суток не потеряны');
        equal(intake.day(rows, { now: день(2026, 9, 26, 12) }), 700, 'и в следующие сутки не попали');
    });

    it('образец плана для тренера в длинные сутки начинается завтра, а не сегодня', () => {
        const текст = prompt.instruction({ now: день(2026, 9, 25, 12) });

        assert(текст.includes('С 26.10.2026'), текст.split('\n').find((s) => s.startsWith('С ')));
    });

    it('событие на весь день кончается на следующую дату — и в длинные сутки', () => {
        const текст = ical.build([{
            date: день(2026, 9, 25), externalId: 'x', name: 'Н', description: ''
        }], { now: день(2026, 9, 25, 12) });

        assert(текст.includes('DTSTART;VALUE=DATE:20261025'), текст);
        assert(текст.includes('DTEND;VALUE=DATE:20261026'), 'иначе событие нулевой длины: календарь его прячет');
    });
});

describe('Сутки: серии и недельные ряды', () => {

    it('дни подряд через перевод часов — серия, а не обрыв', () => {
        const days = [day(24), day(25), day(26)];
        const итог = stats.streaks(days, день(2026, 9, 26, 12));

        equal(итог.longestDays, 3, 'сутки 25 октября длились 25 часов, но это один день подряд');
        equal(итог.days, 3);

        function day(d) { return день(2026, 9, d); }
    });

    it('недели подряд: неделя с перевода часов не обнуляет серию', () => {
        // Тренировки во вторник 13-го и во вторник 20-го; сейчас понедельник 26-го
        const итог = stats.streaks([день(2026, 9, 13), день(2026, 9, 20)], день(2026, 9, 26, 12));

        equal(итог.longestWeeks, 2);
        equal(итог.weeks, 2, 'прошлая неделя тренировалась — серия жива, хотя до понедельника на час больше недели');
    });

    it('подходы по неделям: каждая неделя находит свою метку на шкале', () => {
        const упражнения = { е: { id: 'е', group: 'Грудь' } };
        const sets = [день(2026, 9, 7, 12), день(2026, 9, 14, 12), день(2026, 9, 21, 12)]
            .map((performedAt, i) => ({ id: `s${i}`, exerciseId: 'е', performedAt }));

        const [группа] = stats.groupWeeks(sets, упражнения, { now: день(2026, 9, 28, 12), weeks: 4, tail: 4 });

        equal(группа.points.map((p) => p.value), [0, 1, 1, 1], 'недели 5, 12 и 19 октября — по одному подходу');
        assert(группа.points.every((p) => час(p.at) === 0), 'метки недель стоят на полуночи');
    });
});
