/**
 * Справка на трёх языках (§51, §53).
 *
 * Справка — единственное место, где текст лежит не словарём, а тремя
 * отдельными документами: связная проза, переведённая по фразе, читается как
 * переведённая. Плата за это — три места вместо одного, и разъезжаются они
 * молча: проверка полноты перевода словари и справку не смотрит, потому что
 * там нечему быть непереведённым по определению.
 *
 * Поэтому сверяется не текст, а устройство. Раздел, добавленный в русскую
 * справку и забытый в немецкой, виден здесь сразу — как и строка, выпавшая
 * из таблицы, и сигнал, которому не написали описание.
 */

import { describe, it, equal, assert } from '../runner.js';
import { guideContent } from '../../js/i18n/guide.js';
import { beeper } from '../../js/core/beeper.js';

const ЯЗЫКИ = ['en', 'de'];

/** Вид блока: по единственному ключу, который в нём есть. */
const видБлока = (block) => Object.keys(block)[0];

/** Сколько в блоке строк: у прозы одна, у списка — сколько в списке. */
function размер(block) {
    const value = Object.values(block)[0];
    return Array.isArray(value) ? value.length : 1;
}

describe('Справка на трёх языках', () => {

    const ru = guideContent('ru');

    for (const lang of ЯЗЫКИ) {
        const свой = guideContent(lang);

        it(`«${lang}» — тот же состав разделов`, () => {
            equal(свой.sections.length, ru.sections.length,
                `разделов ${свой.sections.length} против ${ru.sections.length} в русской`);

            assert(!!свой.title && !!свой.sub, 'у справки должны быть заголовок и подпись');
        });

        it(`«${lang}» — та же разбивка внутри разделов`, () => {
            const расхождения = [];

            свой.sections.forEach((section, i) => {
                const образец = ru.sections[i];
                if (!образец) return;

                const где = `раздел ${i + 1} («${образец.name}»)`;

                if (!!section.open !== !!образец.open) расхождения.push(`${где}: открыт по-разному`);

                if (section.blocks.length !== образец.blocks.length) {
                    расхождения.push(`${где}: блоков ${section.blocks.length} против ${образец.blocks.length}`);
                    return;
                }

                section.blocks.forEach((block, j) => {
                    const вид = видБлока(block);
                    const ждали = видБлока(образец.blocks[j]);

                    if (вид !== ждали) {
                        расхождения.push(`${где}, блок ${j + 1}: ${вид} вместо ${ждали}`);
                        return;
                    }

                    if (размер(block) !== размер(образец.blocks[j])) {
                        расхождения.push(
                            `${где}, блок ${j + 1} (${вид}): строк ${размер(block)} против ${размер(образец.blocks[j])}`);
                    }
                });
            });

            assert(расхождения.length === 0, `справка разъехалась:\n${расхождения.join('\n')}`);
        });

        /*
         * Ключ сигнала не переводится: по нему кнопка прослушивания находит,
         * что играть. Разъехавшись, они дали бы кнопку, которая молчит.
         */
        it(`«${lang}» — те же сигналы в таблице прослушивания`, () => {
            const ключи = (документ) => документ.sections
                .flatMap((s) => s.blocks)
                .filter((b) => b.sounds)
                .flatMap((b) => b.sounds.map((row) => row[0]));

            equal(ключи(свой), ключи(ru));
        });
    }

    /*
     * Описание должно быть у каждого сигнала, который приложение умеет
     * играть. Новый сигнал легко добавить в звук и забыть в справке — и
     * человек услышит в программе то, чему нигде нет объяснения.
     */
    it('в справке описаны все сигналы программы', () => {
        const описаны = new Set(ru.sections
            .flatMap((s) => s.blocks)
            .filter((b) => b.sounds)
            .flatMap((b) => b.sounds.map((row) => row[0])));

        const забытые = Object.keys(beeper.VOICES).filter((type) => !описаны.has(type));

        assert(забытые.length === 0, `сигналы без описания: ${забытые.join(', ')}`);
    });

    /*
     * И наоборот: кнопка, которой нечего играть, молчит без объяснений.
     */
    it('в справке нет сигналов, которых приложение не умеет', () => {
        const лишние = [...new Set(ru.sections
            .flatMap((s) => s.blocks)
            .filter((b) => b.sounds)
            .flatMap((b) => b.sounds.map((row) => row[0])))]
            .filter((type) => !beeper.VOICES[type]);

        assert(лишние.length === 0, `нечего играть: ${лишние.join(', ')}`);
    });
});
