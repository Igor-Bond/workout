describe('Сводка: заметки', () => {

    it('три вида заметок — к подходу, к упражнению и к тренировке, свежие первыми', () => {
        const старое = занятие('w1', 9, 'бицепс', 2, 50);
        старое.sets[1].note = 'локоть щёлкал';
        старое.entry.workout.note = 'после командировки';

        const новое = занятие('w2', 2, 'бицепс', 2, 50);
        новое.entry.workout.plan = [{ exerciseId: 'бицепс', note: 'резинка синяя + зелёная' }];

        const текст = собрать([старое, новое]);
        const раздел = текст.slice(текст.indexOf('Заметки за период'));

        assert(раздел.includes('Бицепс резинка: резинка синяя + зелёная'), раздел);
        assert(раздел.includes('Бицепс резинка: локоть щёлкал'), раздел);
        assert(раздел.includes('тренировка «Силовая»: после командировки'), раздел);
        assert(раздел.indexOf('синяя') < раздел.indexOf('локоть'), 'свежие первыми');
    });

    it('одна заметка, вписанная к пяти подходам, — одна строка', () => {
        const з = занятие('w1', 2, 'бицепс', 5, 50, { note: 'колено ныло' });

        equal(собрать([з]).split('\n').filter((s) => s.includes('колено ныло')).length, 1);
    });

    it('больше дюжины — свежие, остальные числом', () => {
        const много = Array.from({ length: 15 }, (_, i) => {
            const з = занятие(`w${i}`, i + 1, 'бицепс', 1, 50);
            з.sets[0].note = `заметка номер ${i}`;
            return з;
        });

        const текст = собрать(много);

        assert(текст.includes('заметка номер 0') && !текст.includes('заметка номер 14'), 'свежие остаются, старые уходят');
        assert(текст.includes('И ещё 3 заметки раньше.'), текст.slice(-400));
    });

    it('длинная заметка режется по словам, а не посреди слова', () => {
        const з = занятие('w1', 2, 'бицепс', 1, 50, { note: 'очень '.repeat(60) + 'конец' });
        const строка = собрать([з]).split('\n').find((s) => s.includes('очень')) || '';

        assert(строка.endsWith('…'), строка.slice(-40));
        assert(строка.length < 260, `сводка не дневник: ${строка.length}`);
    });

    it('без заметок раздела нет', () => {
        assert(!собрать([занятие('w1', 2, 'бицепс', 2, 50)]).includes('Заметки за период'));
    });
});

/**
 * Сводка: упражнения на время и по дистанции (§55, Р-222).
 *
 * У такого упражнения нет повторений, и сводка выдавала вместо объёма одно
 * число подходов: «Баскетбол, обычно 1», «Планка, обычно 3». Тренер видел, что
 * человек играл в баскетбол, но не сколько.
 */
describe('Сводка: упражнения на время и по дистанции', () => {

    const ex = {
        п: { id: 'п', name: 'Планка', kind: 'time' },
        б: { id: 'б', name: 'Баскетбол', kind: 'time', timeUnit: 'min' },
        р: { id: 'р', name: 'Бег', kind: 'distance' },
        о: { id: 'о', name: 'Отжимания', kind: 'reps' }
    };

    /** Занятие по времени: каждый подход — своя длительность в секундах. */
    const по_времени = (id, дней, ...секунды) => секунды.map((duration, i) => ({
        exerciseId: id, setNumber: i + 1, duration, performedAt: NOW - дней * DAY + i * 60000
    }));

    const строка = (id, занятия, over = {}) => report.line(id, занятия, { exercises: { ...ex, ...over }, now: NOW });

    it('планка 3 × 45 → 3 × 60: в сводке секунды, а не число подходов', () => {
        const занятия = [
            по_времени('п', 14, 45, 45, 45),
            по_времени('п', 7, 60, 60, 60),
            по_времени('п', 2, 60, 60, 60)
        ];

        const текст = строка('п', занятия);

        assert(текст.includes('обычно 3 × 60 с'), `иначе тренер не видит, что планка выросла: ${текст}`);
        assert(!текст.includes('обычно 3,'), 'не голое число подходов');
    });

    it('баскетбол в минутах: «1 × 90 мин», а не «1»', () => {
        const занятия = [по_времени('б', 14, 5400), по_времени('б', 7, 4500), по_времени('б', 2, 5400)];
        const текст = строка('б', занятия);

        assert(текст.includes('обычно 1 × 90 мин'), текст);
    });

    it('90 и 75 минут по очереди — «чередует»', () => {
        const занятия = [14, 10, 6, 2].map((д, i) => по_времени('б', д, i % 2 ? 4500 : 5400));
        const текст = строка('б', занятия);

        assert(текст.includes('чередует 1 × 90 мин и 1 × 75 мин'), текст);
    });

    it('секундное упражнение от десяти минут называется минутами', () => {
        const текст = строка('п', [по_времени('п', 4, 900), по_времени('п', 2, 900)]);

        assert(текст.includes('обычно 1 × 15 мин'), `«900 с» никто не скажет вслух: ${текст}`);
    });

    it('подходы разные — последнее занятие перечислено словами, не «01:00»', () => {
        const занятия = [по_времени('п', 6, 45, 45, 45), по_времени('п', 2, 60, 50, 40)];
        const текст = строка('п', занятия);

        assert(текст.includes('последний раз 3 сентября: 60 с, 50 с, 40 с'), текст);
        assert(!текст.includes('01:00'), 'формат часов тренер прочёл бы как минуты');
    });

    it('подходы одинаковые — последнее занятие не перечисляется: «обычно» уже сказало всё', () => {
        const текст = строка('п', [по_времени('п', 6, 60, 60), по_времени('п', 2, 60, 60)]);

        assert(текст.includes('обычно 2 × 60 с'), текст);
        assert(!/последний раз [^,]*:/.test(текст), текст);
    });

    it('бег: дистанция и время — «1 × 5 км за 30 мин»', () => {
        const бег = (дней, метров, сек) => [{ exerciseId: 'р', setNumber: 1, distance: метров, duration: сек, performedAt: NOW - дней * DAY }];
        const текст = строка('р', [бег(9, 5000, 1800), бег(2, 5000, 1800)]);

        assert(текст.includes('обычно 1 × 5 км за 30 мин'), текст);
    });

    it('бег только по времени — без выдуманной дистанции', () => {
        const текст = строка('р', [по_времени('р', 9, 1200), по_времени('р', 2, 1200)]);

        assert(текст.includes('обычно 1 × 20 мин'), текст);
        assert(!текст.includes('км'), текст);
    });

    it('подходов без времени — прежнее число подходов, а не «0 с»', () => {
        const пустые = [{ exerciseId: 'п', setNumber: 1, performedAt: NOW - 3 * DAY }, { exerciseId: 'п', setNumber: 2, performedAt: NOW - 3 * DAY }];
        const текст = строка('п', [пустые, пустые]);

        assert(текст.includes('обычно 2,'), текст);
    });

    it('у повторений ничего не меняется', () => {
        const отж = (дней) => Array.from({ length: 4 }, (_, i) => ({ exerciseId: 'о', setNumber: i + 1, reps: 30, performedAt: NOW - дней * DAY + i * 60000 }));
        const текст = строка('о', [отж(6), отж(2)]);

        assert(текст.includes('обычно 4 × 30'), текст);
        assert(!текст.includes(' с,'), текст);
    });

    it('запас «около двух» у времени называется «небольшой»: повторений у него нет', () => {
        const с_запасом = (id, дней, rir) => по_времени(id, дней, 60, 60).map((s) => ({ ...s, rir }));
        const время = строка('п', [с_запасом('п', 6, 2), с_запасом('п', 2, 2)]);
        const повторы = report.line('о', [
            [{ exerciseId: 'о', setNumber: 1, reps: 30, rir: 2, performedAt: NOW - 6 * DAY }],
            [{ exerciseId: 'о', setNumber: 1, reps: 30, rir: 2, performedAt: NOW - 2 * DAY }]
        ], { exercises: ex, now: NOW });

        assert(время.includes('запас небольшой') && !время.includes('около двух'), время);
        assert(повторы.includes('запас около двух'), повторы);
    });
});
