describe('Сводка: табата отдельно и по кругам', () => {

    /** Табата: круги приседаний в одной тренировке. */
    function табата(id, дней, круги, устройство = { work: 20, rest: 10 }) {
        const at = NOW - дней * DAY;

        return {
            entry: {
                workout: { id, startedAt: at, finishedAt: at + 900000, type: 'Табата', interval: устройство, plan: [{ exerciseId: 'присед' }] },
                sets: круги.length, reps: 0, volume: 0, exerciseIds: ['присед']
            },
            sets: круги.map((reps, i) => ({
                id: `${id}-${i}`, workoutId: id, exerciseId: 'присед', order: i + 1, setNumber: i + 1,
                reps, duration: устройство.work, performedAt: at + i * 30000
            }))
        };
    }

    const exercises = { присед: { id: 'присед', name: 'Приседания', kind: 'reps', group: 'Ноги' } };

    it('табата идёт своим разделом — по кругам, с длиной работы и отдыха', () => {
        const текст = собрать([табата('t1', 2, [15, 16, 17], { work: 20, rest: 15 })], { exercises });

        assert(текст.includes('Интервальные, последние — по кругам:'), текст);
        assert(текст.includes('работа 20 с, отдых 15 с: Приседания 15 → 16 → 17'), текст);
    });

    it('силовые приседания не смешиваются с табатой в одной строке', () => {
        const силовые = [4, 8, 12].map((d, i) => занятие(`s${i}`, d, 'присед', 3, 40));
        const текст = собрать([...силовые, табата('t1', 2, [15, 16, 17])], { exercises });

        const строка = текст.split('\n').find((s) => s.startsWith('— Приседания,')) || '';

        assert(строка.includes('3 занятия'), `табата в счёт занятий не идёт: ${строка}`);
        assert(строка.includes('обычно 3 × 40'), строка);
        assert(!строка.includes('чередует'), 'чередования силовой и табаты не бывает');
    });

    it('сделанное только в табате — не «за период не делались»', () => {
        const текст = собрать([табата('t1', 2, [15, 16, 17])], {
            exercises, catalogue: [exercises.присед]
        });

        assert(!текст.includes('не делались: Приседания'), текст);
    });

    it('непроставленные круги так и названы, а не выдуманы', () => {
        const текст = собрать([табата('t1', 2, [0, 0, 0])], { exercises });

        assert(текст.includes('повторения не проставлены'), текст);
    });

    it('называются три последних табаты, а не все', () => {
        const текст = собрать([1, 2, 3, 4, 5].map((d) => табата(`t${d}`, d, [10 + d, 11 + d])), { exercises });

        equal(текст.split('\n').filter((s) => s.includes('работа 20 с')).length, 3);
    });
});

