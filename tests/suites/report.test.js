/**
 * Ревизия, пятый заход (Р-115).
 */
describe('Сводка без истории', () => {

    it('перечень справочника и задание приходят и тому, кто ещё не тренировался', () => {
        const ex = { id: 'u1', name: 'Отжимания', kind: 'reps', group: 'Грудь' };

        const текст = report.build({
            entries: [],
            sets: [],
            exercises: { [ex.id]: ex },
            weights: [],
            catalogue: [ex],
            shareOf: () => 0.65
        });

        assert(текст.includes('тренировок не было'), 'честно сказано, что истории нет');
        assert(текст.includes('Отжимания'), 'иначе собеседник выдумает названия');
        assert(текст.includes('Задание'), 'а без образца просить план нечем');
    });

    /*
     * Сводка не должна спорить сама с собой (Р-147).
     *
     * В задании стоял предел «не меньше единицы», и новичок, объявивший в
     * профиле пять дней в неделю, получал текст, где тремя строками выше
     * стоит его пять, а в задании требуется один. Собеседник читает задание.
     */
    it('без истории берётся объявленное в профиле, а не единица', () => {
        const ex = { id: 'u1', name: 'Отжимания', kind: 'reps', group: 'Грудь' };

        const текст = report.build({
            entries: [], sets: [], exercises: { [ex.id]: ex }, weights: [],
            catalogue: [ex], shareOf: () => 0.65,
            daysPerWeek: 5
        });

        assert(текст.includes('дней в неделю: 5;'), `объявленное пять: ${(текст.match(/— тренировочных[^\n]*/) || [''])[0]}`);
    });

    /*
     * Когда не знает ни история, ни профиль, приложение молчит: выдуманное
     * число хуже отсутствующего, собеседник спросит сам.
     */
    it('без истории и без профиля строки о днях нет вовсе', () => {
        const ex = { id: 'u1', name: 'Отжимания', kind: 'reps', group: 'Грудь' };

        const текст = report.build({
            entries: [], sets: [], exercises: { [ex.id]: ex }, weights: [],
            catalogue: [ex], shareOf: () => 0.65
        });

        assert(!текст.includes('тренировочных дней в неделю'), 'придумывать число нечем');
        assert(текст.includes('Задание'), 'а само задание на месте');
        assert(!текст.includes('\n\n\n'), 'и пустой строки вместо выброшенной не осталось');
    });

});


/**
 * Как идёт программа и питание — в деле тренера (Р-210).
 *
 * Тренер правил программу, не зная, что из пяти дней делается три, и на
 * «почему стоит вес» отвечал про тренировки: о еде он не знал ничего.
 */
describe('Ход программы и питание в сводке', () => {

    const занятия = [5, 10, 15].map((d, i) => занятие(`w${i}`, d, 'бицепс', 6, 50));

    it('ход программы — своим разделом', () => {
        const текст = собрать(занятия, { progress: ['По плану за две недели сделано 2 из 6 — программа идёт быстрее вас.'] });

        assert(текст.includes('Как идёт программа:'), текст.slice(0, 400));
        assert(текст.includes('— По плану за две недели сделано 2 из 6'), 'строки списком, как и остальные разделы');
    });

    it('питание — своим разделом', () => {
        const текст = собрать(занятия, { nutrition: ['Съедено в среднем 2100 ккал в день — по 6 дням с записями из последних 7.'] });

        assert(текст.includes('Питание:'), текст.slice(0, 400));
        assert(текст.includes('2100 ккал'));
    });

    it('оба стоят до чисел истории: это то, чего из чисел не вывести', () => {
        const текст = собрать(занятия, { progress: ['ход'], nutrition: ['еда'] });

        assert(текст.indexOf('Питание:') < текст.indexOf('Упражнения:'), текст);
    });

    it('питание видно и тому, кто ещё не тренировался', () => {
        const текст = собрать([], { nutrition: ['Съедено в среднем 2100 ккал в день.'] });

        assert(текст.includes('тренировок не было') && текст.includes('Питание:'), текст);
    });

    it('пустое — без заголовков в пустоте', () => {
        const текст = собрать(занятия);

        assert(!текст.includes('Как идёт программа:') && !текст.includes('Питание:'), 'пустой раздел сказал бы, что он есть и пуст');
    });
});

