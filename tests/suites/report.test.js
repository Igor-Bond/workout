/**
 * Сводка кондиций для тренера (§55 ТЗ).
 *
 * Модуль чистый — данные на входе, строка на выходе, — и проверять его надо
 * именно так: неверные числа в сводке выглядят убедительно ровно как верные,
 * а читает её человек, который в базу заглянуть не может.
 */

import { describe, it, equal, assert } from '../runner.js';
import { report } from '../../js/core/report.js';
import { rhythm } from '../../js/core/rhythm.js';

const DAY = 86400000;
const NOW = new Date(2026, 8, 5, 12).getTime();

/** Занятие: сводка тренировки и её подходы. */
function занятие(id, дней, exerciseId, подходов, повторов, over = {}) {
    const at = NOW - дней * DAY;

    const sets = Array.from({ length: подходов }, (_, i) => ({
        id: `${id}-${i}`, workoutId: id, exerciseId,
        order: i + 1, setNumber: i + 1, reps: повторов, performedAt: at + i * 60000,
        ...over
    }));

    return {
        entry: {
            workout: { id, startedAt: at, finishedAt: at + 1800000, type: over.type || 'Силовая' },
            sets: подходов, reps: подходов * повторов, volume: 0, exerciseIds: [exerciseId]
        },
        sets
    };
}

function собрать(занятия, over = {}) {
    return report.build({
        entries: занятия.map((з) => з.entry),
        sets: занятия.flatMap((з) => з.sets),
        exercises: { бицепс: { id: 'бицепс', name: 'Бицепс резинка', kind: 'reps', group: 'Руки' } },
        weights: [{ at: NOW - 30 * DAY, weight: 90 }, { at: NOW - DAY, weight: 92 }],
        now: NOW,
        shareOf: () => 0.25,
        ...over
    });
}

describe('Сводка для тренера', () => {

    it('без тренировок так и говорит', () => {
        const текст = собрать([]);

        assert(текст.includes('тренировок не было'), `неожиданно: ${текст}`);
    });

    it('называет упражнение, ритм и обычный объём', () => {
        const занятия = [5, 10, 15, 20].map((d, i) => занятие(`w${i}`, d, 'бицепс', 6, 50));
        const текст = собрать(занятия);

        assert(текст.includes('Бицепс резинка'), 'название обязательно');
        assert(текст.includes('4 занятия'), `сколько раз: ${текст}`);
        assert(текст.includes('раз в 5 дней'), `ритм: ${текст}`);
        assert(текст.includes('6 × 50'), `объём: ${текст}`);
    });

    /*
     * Главное в сводке (Р-60). Лёгкий и тяжёлый день различаются парой сразу:
     * 6 × 50 и 12 × 35. Медиана между ними даёт «9 × 43» — день, которого не
     * бывает, и тренер строил бы программу по несуществующему числу.
     */
    it('чередование называет обоими вариантами, а не средним', () => {
        const занятия = [20, 15, 10, 5].map((d, i) => (i % 2 === 0
            ? занятие(`w${i}`, d, 'бицепс', 6, 50)
            : занятие(`w${i}`, d, 'бицепс', 12, 35)));

        const текст = собрать(занятия);

        assert(текст.includes('чередует'), `должно быть названо чередованием: ${текст}`);
        assert(текст.includes('6 × 50'), 'тяжёлый день');
        assert(текст.includes('12 × 35'), 'лёгкий день');
        assert(!текст.includes('9 × 43'), 'середины между ними не бывает ни в один день');
    });

    it('вес тела и его изменение попадают в сводку', () => {
        const текст = собрать([занятие('w', 3, 'бицепс', 6, 50)]);

        assert(текст.includes('92'), `нынешний вес: ${текст}`);
        assert(текст.includes('+2'), `изменение за период: ${текст}`);
    });

    /*
     * Зарядка делается каждое утро, и в общем счёте она забивает всё: без
     * разделения выходит «84 тренировки, 10 в неделю» — это не про
     * тренировки, а про то, что человек ещё и разминается.
     */
    it('фон считается отдельно от тренировок', () => {
        const силовые = [5, 10].map((d, i) => занятие(`s${i}`, d, 'бицепс', 6, 50));
        const зарядки = [1, 2, 3].map((d, i) => занятие(`z${i}`, d, 'бицепс', 1, 40, { type: 'Зарядка' }));

        const текст = собрать([...силовые, ...зарядки], {
            background: (w) => w.type === 'Зарядка'
        });

        assert(текст.includes('2 тренировки'), `рабочих должно быть две: ${текст}`);
        assert(текст.includes('Плюс зарядка: 3'), `фон отдельной строкой: ${текст}`);
    });

    /*
     * Сводка — не справка, а запрос: без задания разговор с тренером
     * начинается с выяснения, чего от него хотят.
     */
    it('заканчивается заданием и видом ответа', () => {
        const текст = собрать([занятие('w', 3, 'бицепс', 6, 50)]);

        assert(текст.includes('Задание'), 'задание обязательно');
        assert(текст.includes('Ответь только планом'), 'иначе в ответ придут рассуждения');
        assert(текст.includes('Вс  отдых'), `образец ответа: ${текст}`);
    });

    it('служебных чисел в сводке нет', () => {
        const текст = собрать([занятие('w', 3, 'бицепс', 6, 50)]);

        assert(!текст.includes('бицепс'), 'идентификатор упражнения читателю ни к чему');
        assert(!текст.includes('w0'), 'идентификатор тренировки тоже');
    });
});

describe('Цикл в ряду значений', () => {

    it('возвращает сам цикл, а не только следующее', () => {
        equal(rhythm.cycle([6, 12, 6, 12]).values, [6, 12]);
        equal(rhythm.cycle([6, 12, 6, 12]).next, 6);
        equal(rhythm.cycle([6, 12, 6, 12]).length, 2);
    });

    it('работает не только с числами', () => {
        const ряд = ['6|50', '12|35', '6|50', '12|35'];

        equal(rhythm.cycle(ряд).values, ['6|50', '12|35'], 'пара меняется вместе и рядом быть не должна');
        equal(rhythm.cycle(ряд).next, '6|50');
    });

    it('без цикла молчит', () => {
        equal(rhythm.cycle([5, 9, 3, 7]), null);
    });
});
