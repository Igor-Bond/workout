/**
 * Прикидка стартового веса (§10.1 ТЗ).
 *
 * Главное здесь — не точность коэффициентов, а границы применения. Средние
 * по популяции врут для конкретного человека на десятки процентов, и
 * подставлять их туда, где у приложения есть факт, значило бы менять знание
 * на догадку. Поэтому проверяется прежде всего, где прикидка молчит.
 */

import { describe, it, equal, assert } from '../runner.js';
import { estimate } from '../../js/core/estimate.js';

const прикинуть = (over) => estimate.startWeight({
    nameKey: 'жим лежа', group: 'Грудь', kind: 'weight', bodyWeight: 80, ...over
});

describe('Прикидка стартового веса', () => {

    it('считается от веса тела по известному упражнению', () => {
        equal(прикинуть(), 40, '80 кг × 0,5');
    });

    it('незнакомое название берётся по группе мышц', () => {
        equal(прикинуть({ nameKey: 'какая-то новая тяга', group: 'Спина' }), 35, '80 кг × 0,45');
    });

    it('без веса тела не прикидывает', () => {
        equal(прикинуть({ bodyWeight: 0 }), null);
        equal(прикинуть({ bodyWeight: undefined }), null,
            'взвешиваний может не быть вовсе — тогда честнее промолчать');
    });

    it('не силовому упражнению вес не нужен', () => {
        equal(прикинуть({ kind: 'reps' }), null);
        equal(прикинуть({ kind: 'time' }), null);
        equal(прикинуть({ kind: 'distance' }), null);
    });

    it('незнакомая группа прикидки не даёт', () => {
        equal(прикинуть({ nameKey: 'жим чего-то', group: 'Шея' }), null);
        equal(прикинуть({ nameKey: 'жим чего-то', group: '' }), null);
    });

    it('округляется до шага блинов', () => {
        // 62 × 0,5 = 31 → ближайшие 2,5 это 30
        equal(прикинуть({ bodyWeight: 62 }), 30);
        assert(прикинуть({ bodyWeight: 77 }) % estimate.STEP === 0);
    });

    /*
     * Гантель в килограмм — это не прикидка, а насмешка: пустое поле
     * честнее числа, которое всё равно придётся стереть.
     */
    it('слишком малое значение не предлагается вовсе', () => {
        // 20 × 0,05 = 1 кг, а округляется это в ноль
        equal(прикинуть({ nameKey: 'махи гантелями в стороны', bodyWeight: 20 }), null);

        // А вот 2,5 кг — уже осмысленный старт, и его предложить можно
        equal(прикинуть({ nameKey: 'махи гантелями в стороны', bodyWeight: 50 }), 2.5);
    });

    it('все коэффициенты — доли собственного веса, а не килограммы', () => {
        const все = [...Object.values(estimate.BY_NAME), ...Object.values(estimate.BY_GROUP)];

        assert(все.every((v) => v > 0 && v <= 1),
            'доля больше единицы означала бы, что новичок жмёт больше своего веса');
    });
});
