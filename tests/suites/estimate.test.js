/**
 * Прикидка стартового веса (§10.1 ТЗ).
 *
 * Главное здесь — не точность коэффициентов, а границы применения. Средние
 * по популяции врут для конкретного человека на десятки процентов, и
 * подставлять их туда, где у приложения есть факт, значило бы менять знание
 * на догадку. Поэтому проверяется прежде всего, где прикидка молчит.
 */

import { describe, it, equal, assert } from '../runner.js';
import { estimate } from '../../js/core/estimate.js';

const прикинуть = (over) => estimate.startWeight({
    nameKey: 'жим лежа', group: 'Грудь', kind: 'weight', bodyWeight: 80, ...over
});

describe('Прикидка стартового веса', () => {

    it('считается от веса тела по известному упражнению', () => {
        equal(прикинуть(), 40, '80 кг × 0,5');
    });

    it('незнакомое название берётся по группе мышц', () => {
        equal(прикинуть({ nameKey: 'какая-то новая тяга', group: 'Спина' }), 35, '80 кг × 0,45');
    });

    it('без веса тела не прикидывает', () => {
        equal(прикинуть({ bodyWeight: 0 }), null);
        equal(прикинуть({ bodyWeight: undefined }), null,
            'взвешиваний может не быть вовсе — тогда честнее промолчать');
    });

    it('не силовому упражнению вес не нужен', () => {
        equal(прикинуть({ kind: 'reps' }), null);
        equal(прикинуть({ kind: 'time' }), null);
        equal(прикинуть({ kind: 'distance' }), null);
    });

    it('незнакомая группа прикидки не даёт', () => {
        equal(прикинуть({ nameKey: 'жим чего-то', group: 'Шея' }), null);
        equal(прикинуть({ nameKey: 'жим чего-то', group: '' }), null);
    });

    it('округляется до шага блинов', () => {
        // 62 × 0,5 = 31 → ближайшие 2,5 это 30
        equal(прикинуть({ bodyWeight: 62 }), 30);
        assert(прикинуть({ bodyWeight: 77 }) % estimate.STEP === 0);
    });

    /*
     * Гантель в килограмм — это не прикидка, а насмешка: пустое поле
     * честнее числа, которое всё равно придётся стереть.
     */
    it('слишком малое значение не предлагается вовсе', () => {
        // 20 × 0,05 = 1 кг, а округляется это в ноль
        equal(прикинуть({ nameKey: 'махи гантелями в стороны', bodyWeight: 20 }), null);

        // А вот 2,5 кг — уже осмысленный старт, и его предложить можно
        equal(прикинуть({ nameKey: 'махи гантелями в стороны', bodyWeight: 50 }), 2.5);
    });

    it('все коэффициенты — доли собственного веса, а не килограммы', () => {
        const все = [...Object.values(estimate.BY_NAME), ...Object.values(estimate.BY_GROUP)];

        assert(все.every((v) => v > 0 && v <= 1),
            'доля больше единицы означала бы, что новичок жмёт больше своего веса');
    });
});


describe('Примерная нагрузка своим весом', () => {

    const нагрузка = (over) => estimate.bodyLoad({
        exercise: { nameKey: 'отжимания', kind: 'reps', ...over },
        bodyWeight: over?.bodyWeight ?? 80
    });

    it('считается долей собственного веса, а не всем весом', () => {
        equal(нагрузка(), 51, '80 × 0,64 — часть опирается на носки');
        equal(нагрузка({ nameKey: 'подтягивания' }), 80, 'а тут вес целиком');
        equal(нагрузка({ nameKey: 'скручивания' }), 28, 'работает верх корпуса');
    });

    /*
     * Довес сюда не входит намеренно (Р-49): он записан в подходе числом и
     * считается тоннажем. Прибавь его здесь — и одно и то же железо
     * посчиталось бы дважды, в двух соседних плитках одной карточки.
     */
    it('довес в эту величину не входит', () => {
        equal(нагрузка({ nameKey: 'подтягивания', weight: 20 }), 80,
            'вес подхода к доле собственного веса не относится');
    });

    /*
     * У снаряда нагрузка названа числом в самой записи. Приписывать к ней
     * вес тела наугад значило бы завышать её у половины упражнений.
     */
    it('упражнению со снарядом нагрузка не пересчитывается', () => {
        equal(нагрузка({ nameKey: 'жим лежа', kind: 'weight' }), null);
        equal(нагрузка({ nameKey: 'бег', kind: 'distance' }), null);
    });

    it('без веса тела не считается', () => {
        equal(нагрузка({ bodyWeight: 0 }), null);
    });

    it('незнакомое упражнение берётся по виду', () => {
        equal(нагрузка({ nameKey: 'какие-то новые отжимания' }), 52, '80 × 0,65');
        equal(нагрузка({ nameKey: 'новая планка', kind: 'time' }), 48, '80 × 0,6');
    });

    /*
     * Своя доля — свободное поле упражнения (§35): схему хранилища трогать
     * нельзя. Отсутствие поля значит «как в справочнике», а не ноль, иначе
     * сброс превращал бы нагрузку в нулевую.
     */
    it('своя доля упражнения важнее справочника', () => {
        equal(нагрузка({ nameKey: 'отжимания', bodyShare: 0.75 }), 60);
        equal(estimate.shareOf({ nameKey: 'отжимания', kind: 'reps' }), 0.64, 'без своей — из справочника');
        equal(estimate.shareOf({ nameKey: 'отжимания', kind: 'reps', bodyShare: 0 }), 0.64, 'ноль значит «как в справочнике»');
    });

    it('округляется до половины килограмма', () => {
        const v = нагрузка({ bodyWeight: 77 });

        equal(v * 2 === Math.round(v * 2), true, 'точность выше этой — выдумка');
    });

    it('все доли — от нуля до единицы', () => {
        const все = [...Object.values(estimate.BODY_SHARE), ...Object.values(estimate.SHARE_BY_KIND)];

        assert(все.every((v) => v > 0 && v <= 1),
            'больше единицы означало бы, что человек тяжелее самого себя');
    });
});
