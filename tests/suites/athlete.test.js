/**
 * Профиль тренирующегося (§58 ТЗ).
 *
 * Главное, что проверяется: ограничение не заметка, а правило. Названное
 * ограничение обязано исключать упражнения, отмеченное прошедшим — перестать
 * их исключать, и всё это должно переживать переименование упражнения.
 */

import { describe, it, equal, assert } from '../runner.js';
import { athlete } from '../../js/core/athlete.js';

const КОЛЕНО = {
    id: 'l1',
    name: 'Колено',
    at: 1,
    exclude: ['выпады', 'приседания'],
    prefer: ['мостик'],
    note: 'неполная амплитуда'
};

const ТУРНИК = {
    id: 'l2',
    name: 'Нет турника и брусьев',
    at: 2,
    exclude: ['подтягивания', 'приседания'],
    prefer: []
};

const ПРОФИЛЬ = {
    goal: 'выносливость',
    days: 5,
    equipment: ['резинки', 'коврик'],
    limits: [КОЛЕНО, ТУРНИК]
};

describe('Нормализация профиля', () => {

    it('пустой профиль не роняет ничего', () => {
        const p = athlete.normalize(null);

        equal(p.limits, []);
        equal(p.equipment, []);
        equal(athlete.filled(p), false);
    });

    it('частично заполненный дополняется, а не заменяется', () => {
        const p = athlete.normalize({ goal: 'сила' });

        equal(p.goal, 'сила');
        equal(p.limits, [], 'недостающее берётся из пустого профиля');
    });

    it('списки копируются, а не переиспользуются', () => {
        const исходный = { limits: [КОЛЕНО] };
        const p = athlete.normalize(исходный);

        p.limits.push(ТУРНИК);
        equal(исходный.limits.length, 1, 'правка копии не должна трогать хранимое');
    });

});

describe('Действующие ограничения', () => {

    it('перечисляет все, пока ни одно не прошло', () => {
        equal(athlete.active(ПРОФИЛЬ).length, 2);
    });

    it('отмеченное прошедшим больше не действует', () => {
        const p = { limits: [{ ...КОЛЕНО, healedAt: 100 }, ТУРНИК] };

        equal(athlete.active(p).map((l) => l.id), ['l2']);
    });

    it('прошедшее не удаляется, а помечается', () => {
        const p = athlete.normalize({ limits: [{ ...КОЛЕНО, healedAt: 100 }] });

        equal(p.limits.length, 1, 'история ограничений — тоже история, стирать её незачем');
    });

});

describe('Исключения', () => {

    it('собирает исключённое всеми ограничениями', () => {
        equal([...athlete.excluded(ПРОФИЛЬ)].sort(), ['выпады', 'подтягивания', 'приседания']);
    });

    it('упражнение, исключённое дважды, исключено один раз', () => {
        const все = [...athlete.excluded(ПРОФИЛЬ)];

        equal(все.filter((id) => id === 'приседания').length, 1);
    });

    it('прошедшее ограничение исключений не даёт', () => {
        const p = { limits: [{ ...КОЛЕНО, healedAt: 100 }, ТУРНИК] };

        equal([...athlete.excluded(p)].sort(), ['подтягивания', 'приседания']);
    });

    it('называет, чем именно исключено, — чтобы объяснить, а не просто скрыть', () => {
        equal(athlete.limitFor(ПРОФИЛЬ, 'выпады')?.name, 'Колено');
        equal(athlete.limitFor(ПРОФИЛЬ, 'подтягивания')?.name, 'Нет турника и брусьев');
        equal(athlete.limitFor(ПРОФИЛЬ, 'отжимания'), null);
    });

    it('предложенное взамен собирается отдельно', () => {
        equal([...athlete.preferred(ПРОФИЛЬ)], ['мостик']);
    });

});

describe('Профиль словами', () => {

    const names = new Map([
        ['выпады', 'Выпады'],
        ['приседания', 'Приседания'],
        ['подтягивания', 'Подтягивания'],
        ['мостик', 'Ягодичный мостик']
    ]);

    const words = {
        goal: 'Цель', days: 'дней в неделю', minutes: 'минут',
        equipment: 'Инвентарь', limit: 'Ограничение', exclude: 'Исключено', prefer: 'Взамен'
    };

    it('называет цель, рамки и инвентарь', () => {
        const строки = athlete.describe(ПРОФИЛЬ, names, words);

        assert(строки.some((s) => s.includes('выносливость')));
        assert(строки.some((s) => s.includes('дней в неделю: 5')));
        assert(строки.some((s) => s.includes('резинки, коврик')));
    });

    it('ограничение называет упражнениями, а не идентификаторами', () => {
        const строка = athlete.describe(ПРОФИЛЬ, names, words).find((s) => s.includes('Колено'));

        assert(строка.includes('Выпады, Приседания'), 'собеседник читает названия, а не ключи');
        assert(строка.includes('Ягодичный мостик'));
        assert(строка.includes('неполная амплитуда'), 'приписка к ограничению — часть его смысла');
    });

    it('прошедшее ограничение в сводку не идёт', () => {
        const p = { ...ПРОФИЛЬ, limits: [{ ...КОЛЕНО, healedAt: 100 }, ТУРНИК] };
        const текст = athlete.describe(p, names, words).join('\n');

        assert(!текст.includes('Колено'), 'зажившее колено собеседнику знать незачем');
        assert(текст.includes('Нет турника'));
    });

    it('удалённое упражнение не оставляет пустого места', () => {
        const p = { limits: [{ id: 'l3', name: 'Плечо', exclude: ['стёртое'] }] };
        const строка = athlete.describe(p, names, words)[0];

        equal(строка, 'Ограничение: Плечо', 'имени нет — и перечисления нет, а не запятая в пустоте');
    });

    it('пустой профиль не даёт ни строки', () => {
        equal(athlete.describe(null, names, words), []);
    });

});
