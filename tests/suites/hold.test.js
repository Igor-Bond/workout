/**
 * Отсчёт подхода на время (§57 ТЗ).
 *
 * Главное, что проверяется: записывается то, что правда прошло. Остановка на
 * тридцатой секунде из сорока пяти — обычное дело, и записать за неё цель
 * значило бы соврать ровно там, ради чего отсчёт и заводился.
 */

import { describe, it, equal, assert } from '../runner.js';
import { hold } from '../../js/core/hold.js';

const L = hold.LEAD;

describe('Состояние отсчёта', () => {

    it('начинается с подготовки', () => {
        const с = hold.at(45, 0);

        equal(с.phase, 'lead');
        equal(с.left, L, 'сразу после нажатия остаётся вся подготовка');
        equal(с.worked, 0);
    });

    it('подготовка досчитывает до единицы, а не до нуля', () => {
        equal(hold.at(45, L - 0.2).left, 1, 'ноль на экране означал бы, что уже пора, а ещё нет');
    });

    it('после подготовки идёт работа', () => {
        const с = hold.at(45, L + 1);

        equal(с.phase, 'work');
        equal(с.left, 44);
        equal(с.worked, 1);
    });

    it('к цели приходит в конец', () => {
        const с = hold.at(45, L + 45);

        equal(с.phase, 'done');
        equal(с.worked, 45);
    });

    it('за цель не перескакивает', () => {
        equal(hold.at(45, L + 60).worked, 45, 'записывается цель, а не то, сколько экран провисел');
    });

    it('остановленный раньше срока помнит, сколько прошло', () => {
        equal(hold.at(45, L + 30.7).worked, 30, 'тридцать, а не сорок пять и не тридцать одна');
    });

    it('без цели работает секундомером', () => {
        const с = hold.at(null, L + 12.4);

        equal(с.phase, 'work', 'у секундомера конца нет');
        equal(с.left, null);
        equal(с.worked, 12);
    });

});

describe('Сигналы отсчёта', () => {

    const типы = (target) => hold.cues(target).map((c) => c.type);
    const времена = (target, type) => hold.cues(target).filter((c) => c.type === type).map((c) => c.at);

    it('подготовка кончается отсчётом и ударом «начали»', () => {
        const c = hold.cues(45);

        equal(времена(45, 'count').slice(0, 3).join(','), `${L - 3},${L - 2},${L - 1}`);
        equal(c.find((x) => x.type === 'go').at, L, 'удар ровно в конце подготовки');
    });

    it('работа кончается отсчётом и ударом «стоп»', () => {
        const c = hold.cues(45);
        const конец = c[c.length - 1];

        equal(конец.type, 'done');
        equal(конец.at, L + 45);

        const счёт = времена(45, 'count');
        equal(счёт.slice(-3).join(','), `${L + 42},${L + 43},${L + 44}`);
    });

    it('пульс отмеряется от конца работы', () => {
        const пульс = времена(45, 'pulse');

        assert(пульс.length > 0, 'без пульса в тишине непонятно, идёт ли ещё подход');
        equal((L + 45 - пульс[пульс.length - 1]) % hold.PULSE, 0, 'последний пульс отстоит от отсчёта ровно на шаг');
        assert(пульс.every((at) => at < L + 45 - hold.COUNT), 'в последние три секунды звучит отсчёт, а не пульс');
    });

    it('очередь идёт по времени', () => {
        const c = hold.cues(45);
        assert(c.every((x, i) => i === 0 || c[i - 1].at <= x.at), 'иначе движок читал бы её задом наперёд');
    });

    it('короткий подход обходится без пульса, но не без отсчёта', () => {
        const c = hold.cues(4);

        equal(c.filter((x) => x.type === 'pulse').length, 0, 'в четыре секунды пульсу негде встать');
        assert(c.some((x) => x.type === 'done'));
    });

    it('у секундомера отсчитывать нечего', () => {
        const t = типы(null);

        equal(t[t.length - 1], 'go', 'звучит только подготовка и «начали»');
        assert(!t.includes('done'), 'конца у секундомера нет');
    });

});

describe('Цель отсчёта', () => {

    it('пустое поле означает секундомер, а не ноль секунд', () => {
        equal(hold.clamp(''), null);
        equal(hold.clamp(0), null);
        equal(hold.clamp('  '), null);
    });

    it('дробное округляется', () => {
        equal(hold.clamp('45.4'), 45);
    });

    it('опечатка режется по верхней границе', () => {
        equal(hold.clamp(99999), hold.LONGEST, 'полчаса удержания — это уже не подход, а лишний ноль');
    });

    it('отрицательное не принимается', () => {
        equal(hold.clamp(-10), null);
    });

});
