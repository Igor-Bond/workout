/**
 * Снимок к вопросу о еде (§68 ТЗ).
 *
 * Проверяется одно обещание, зато главное: снимок уменьшается **до**
 * отправки. Это единственное место приложения, где наружу уходит не текст, и
 * четыре мегабайта вместо полутораста килобайт человек оплатит дважды —
 * временем на мобильной связи и своей квотой у Google.
 */

import { describe, it, equal, assert } from '../runner.js';
import { photo } from '../../js/core/photo.js';

/** Снимок нужного размера — рисуем сами, чтобы ни от чего не зависеть. */
async function снимок(ширина, высота, тип = 'image/png') {
    const холст = document.createElement('canvas');

    холст.width = ширина;
    холст.height = высота;

    const кисть = холст.getContext('2d');

    /*
     * Рисуем похоже на фотографию, а не клеткой.
     *
     * Клетка в восемь точек — худший случай для JPEG: он хранит переходы, а
     * их там больше всего. Уменьшенная клетчатая картинка выходила тяжелее
     * исходной, и проверка веса ловила не приложение, а свою же выдумку.
     * Плавные переходы с крупными пятнами жмутся так же, как тарелка с едой.
     */
    const заливка = кисть.createLinearGradient(0, 0, ширина, высота);

    заливка.addColorStop(0, '#6b3f1d');
    заливка.addColorStop(0.5, '#c8a06a');
    заливка.addColorStop(1, '#2d4a2b');

    кисть.fillStyle = заливка;
    кисть.fillRect(0, 0, ширина, высота);

    for (let i = 0; i < 24; i++) {
        const r = (Math.min(ширина, высота) / 12) * (1 + (i % 5) / 4);

        кисть.fillStyle = `rgba(${40 + i * 8}, ${120 - i * 3}, ${60 + i * 5}, 0.55)`;
        кисть.beginPath();
        кисть.arc((i * 137) % ширина, (i * 219) % высота, r, 0, Math.PI * 2);
        кисть.fill();
    }

    const блоб = await new Promise((готово) => холст.toBlob(готово, тип));

    return new File([блоб], `проба.${тип === 'image/png' ? 'png' : 'jpg'}`, { type: тип });
}

describe('Снимок перед отправкой', () => {

    it('длинная сторона ужимается до тысячи точек', async () => {
        const снятое = await photo.shrink(await снимок(2400, 1200));

        equal(снятое.width, 1024, 'длинная сторона');
        equal(снятое.height, 512, 'и пропорции целы');
    });

    it('высокий снимок считается по высоте, а не по ширине', async () => {
        const снятое = await photo.shrink(await снимок(600, 1600));

        equal(снятое.height, 1024);
        equal(снятое.width, 384);
    });

    /*
     * Дорисованные точки не добавляют сведений — только вес файла и ложное
     * впечатление подробности.
     */
    it('маленькое не растягивается', async () => {
        const снятое = await photo.shrink(await снимок(320, 240));

        equal(снятое.width, 320);
        equal(снятое.height, 240);
    });

    it('что бы ни пришло, уходит JPEG без приставки', async () => {
        const снятое = await photo.shrink(await снимок(1200, 900));

        equal(снятое.mime, 'image/jpeg', 'прозрачности у фотографии еды не бывает');
        assert(!снятое.data.startsWith('data:'),
            'приставку отрезает чтение, а не отправка: иначе отправка знала бы про способ чтения');
        assert(снятое.data.length > 100, 'и это всё-таки картинка, а не пустая строка');
    });

    it('уменьшенное весит заметно меньше исходного', async () => {
        const исходный = await снимок(2400, 1800);
        const снятое = await photo.shrink(исходный);

        // Основание 64 раздувает на треть — сравниваем с поправкой
        const вес = снятое.data.length * 0.75;

        assert(вес < исходный.size / 2,
            `было ${Math.round(исходный.size / 1024)} КБ, стало ${Math.round(вес / 1024)} КБ`);
    });

    it('без снимка отказывается словами, а не молча', async () => {
        let сказано = '';

        try {
            await photo.shrink(null);
        } catch (e) {
            сказано = e.message;
        }

        assert(сказано.length > 0, 'тишина в ответ неотличима от поломки');
    });
});
