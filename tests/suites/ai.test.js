/**
 * Выбор модели Google (§60.2, Р-191).
 *
 * Состав моделей у Google меняется чаще, чем выходят версии приложения. Тот,
 * кто уже работает, впишет новую сам — а новому человеку зашитое умолчание,
 * которого у Google больше нет, закрывает вход целиком: ключ верный, а
 * приложение отвечает ошибкой и советует вписать другую, названия которой он
 * знать не может.
 *
 * Поэтому приложение спрашивает список у самого Google и выбирает из него.
 * Здесь проверяется выбор — то единственное, что можно проверить без ключа.
 */

import { describe, it, equal, assert } from '../runner.js';
import { ai, DEFAULT_MODEL } from '../../js/services/ai.js';

describe('Выбор модели', () => {

    it('из пустого списка выбирать нечего', () => {
        equal(ai.pick([]), null);
        equal(ai.pick(), null);
    });

    /*
     * Разговор у приложения короткий, а flash — самая дешёвая из отвечающих.
     */
    it('быстрая важнее мощной', () => {
        equal(ai.pick(['gemini-2.5-pro', 'gemini-2.5-flash']), 'gemini-2.5-flash');
    });

    it('из одинаковых берётся старшая по версии', () => {
        equal(ai.pick(['gemini-1.5-flash', 'gemini-2.5-flash', 'gemini-2.0-flash']), 'gemini-2.5-flash');
    });

    /*
     * «preview» и «exp» Google выключает без предупреждения, «lite» хуже
     * отвечает на длинный разбор — а разбор здесь именно длинный.
     */
    it('черновые и облегчённые пропускаются, пока есть обычные', () => {
        equal(ai.pick([
            'gemini-3.0-flash-preview',
            'gemini-3.0-flash-lite',
            'gemini-2.5-flash'
        ]), 'gemini-2.5-flash');
    });

    it('но если других нет — берётся что есть', () => {
        const выбор = ai.pick(['gemini-9.0-flash-preview']);

        equal(выбор, 'gemini-9.0-flash-preview', 'молчать хуже, чем выбрать не лучшее');
    });

    it('незнакомые имена не роняют выбор', () => {
        const выбор = ai.pick(['что-то-своё', 'gemini-2.5-flash']);

        equal(выбор, 'gemini-2.5-flash');
        assert(ai.pick(['что-то-своё']) === 'что-то-своё', 'единственное годится само по себе');
    });

    /*
     * Умолчание всё ещё нужно: до первой проверки ключа спрашивать список не
     * у кого. Но оно перестало быть единственной дорогой.
     */
    it('умолчание названо и похоже на имя модели', () => {
        assert(/^gemini-/.test(DEFAULT_MODEL), DEFAULT_MODEL);
    });
});

/** Ответ Google в том виде, в каком он приходит. */
const ответ = (текст, конец = 'STOP', сверх = {}) => ({
    candidates: [{ content: { parts: [{ text: текст }] }, finishReason: конец }],
    ...сверх
});

/** Поймать ошибку разбора — или null, если её не было. */
function отказ(данные) {
    try {
        ai.read(данные);
        return null;
    } catch (e) {
        return e;
    }
}

/**
 * Разбор ответа (§60, Р-205).
 *
 * Причину конца Google сообщает всегда, а читалась она только при пустом
 * тексте. Оборванный ответ проходил за целый: обрезанный план сохраняет дату
 * и несколько дней, разбор его принимает — и под половиной программы
 * появлялась кнопка «Перенести в план».
 */
describe('Разбор ответа', () => {

    it('законченный ответ отдаётся текстом', () => {
        equal(ai.read(ответ('Привет')), 'Привет');
    });

    it('ответ без причины конца — тоже законченный: так отвечают и старые модели', () => {
        equal(ai.read({ candidates: [{ content: { parts: [{ text: 'Да' }] } }] }), 'Да');
    });

    it('части склеиваются в один текст', () => {
        equal(ai.read({ candidates: [{ content: { parts: [{ text: 'С 04.10' }, { text: '.2026' }] }, finishReason: 'STOP' }] }), 'С 04.10.2026');
    });

    it('оборванный по длине — ошибка, и то, что успело прийти, едет на ней', () => {
        const e = отказ(ответ('С 04.10.2026, 8 недель\nПн Отжимания 3 × 20\nВт При', 'MAX_TOKENS'));

        assert(e, 'оборванное за целое выдавать нельзя');
        equal(e.finish, 'MAX_TOKENS');
        assert(e.partial.includes('Пн Отжимания 3 × 20'), 'пришедшее не выбрасывается');
        assert(/оборвал/i.test(e.message), e.message);
        assert(e.message.includes('MAX_TOKENS'), 'код Google — для того, кто будет пересказывать');
    });

    it('оборванный фильтром посередине — тоже оборванный', () => {
        const e = отказ(ответ('Начало совета', 'SAFETY'));

        equal(e.partial, 'Начало совета');
        assert(/фильтр/i.test(e.message), e.message);
    });

    it('пустой по длине говорит про размышление, а не «MAX_TOKENS»', () => {
        const e = отказ(ответ('', 'MAX_TOKENS'));

        assert(e && !e.partial, 'спасать нечего');
        assert(/размышлени/i.test(e.message), e.message);
        assert(!/^Ответ не получен: MAX_TOKENS$/.test(e.message), 'английское слово из чужого перечня — не объяснение');
    });

    it('непринятый вопрос назван фильтром, и код в скобках', () => {
        const e = отказ({ promptFeedback: { blockReason: 'PROHIBITED_CONTENT' } });

        assert(/не принял вопрос/i.test(e.message), e.message);
        assert(e.message.includes('PROHIBITED_CONTENT'));
        equal(e.finish, 'PROHIBITED_CONTENT');
    });

    it('совсем пустой ответ — пустой, а не «undefined»', () => {
        const e = отказ({});

        assert(e && /пуст/i.test(e.message), e?.message);
        assert(!/undefined/.test(e.message));
    });

    it('у ошибки ответа есть finish, у ошибки доступа — нет: по нему их и различают', () => {
        assert(отказ(ответ('', 'MAX_TOKENS')).finish, 'ответ был — доступ есть');
        equal(new Error('Ключ не принят.').finish, undefined);
    });
});

/**
 * Что спасти из оборванного (Р-205).
 *
 * Построчные ответы — карточки упражнений, вилка калорий — обрыв портит только
 * в последней строке. Остальные пришли честно, и выбрасывать их незачем.
 */
describe('Спасение оборванного', () => {

    it('берутся все строки, кроме последней', () => {
        equal(ai.salvage({ partial: 'А | 1\nБ | 2\nВ | 3 и ещё оборв' }), 'А | 1\nБ | 2');
    });

    it('из одной строки спасать нечего: она и оборвана', () => {
        equal(ai.salvage({ partial: 'Выпады | weight | Ноги | Шаг впе' }), '');
    });

    it('ошибка без пришедшего — пустая строка, а не исключение', () => {
        equal(ai.salvage(new Error('Нет связи')), '');
        equal(ai.salvage(null), '');
    });
});
