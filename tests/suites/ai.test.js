/**
 * Выбор модели Google (§60.2, Р-191).
 *
 * Состав моделей у Google меняется чаще, чем выходят версии приложения. Тот,
 * кто уже работает, впишет новую сам — а новому человеку зашитое умолчание,
 * которого у Google больше нет, закрывает вход целиком: ключ верный, а
 * приложение отвечает ошибкой и советует вписать другую, названия которой он
 * знать не может.
 *
 * Поэтому приложение спрашивает список у самого Google и выбирает из него.
 * Здесь проверяется выбор — то единственное, что можно проверить без ключа.
 */

import { describe, it, equal, assert } from '../runner.js';
import { ai, DEFAULT_MODEL } from '../../js/services/ai.js';

describe('Выбор модели', () => {

    it('из пустого списка выбирать нечего', () => {
        equal(ai.pick([]), null);
        equal(ai.pick(), null);
    });

    /*
     * Разговор у приложения короткий, а flash — самая дешёвая из отвечающих.
     */
    it('быстрая важнее мощной', () => {
        equal(ai.pick(['gemini-2.5-pro', 'gemini-2.5-flash']), 'gemini-2.5-flash');
    });

    it('из одинаковых берётся старшая по версии', () => {
        equal(ai.pick(['gemini-1.5-flash', 'gemini-2.5-flash', 'gemini-2.0-flash']), 'gemini-2.5-flash');
    });

    /*
     * «preview» и «exp» Google выключает без предупреждения, «lite» хуже
     * отвечает на длинный разбор — а разбор здесь именно длинный.
     */
    it('черновые и облегчённые пропускаются, пока есть обычные', () => {
        equal(ai.pick([
            'gemini-3.0-flash-preview',
            'gemini-3.0-flash-lite',
            'gemini-2.5-flash'
        ]), 'gemini-2.5-flash');
    });

    it('но если других нет — берётся что есть', () => {
        const выбор = ai.pick(['gemini-9.0-flash-preview']);

        equal(выбор, 'gemini-9.0-flash-preview', 'молчать хуже, чем выбрать не лучшее');
    });

    it('незнакомые имена не роняют выбор', () => {
        const выбор = ai.pick(['что-то-своё', 'gemini-2.5-flash']);

        equal(выбор, 'gemini-2.5-flash');
        assert(ai.pick(['что-то-своё']) === 'что-то-своё', 'единственное годится само по себе');
    });

    /*
     * Умолчание всё ещё нужно: до первой проверки ключа спрашивать список не
     * у кого. Но оно перестало быть единственной дорогой.
     */
    it('умолчание названо и похоже на имя модели', () => {
        assert(/^gemini-/.test(DEFAULT_MODEL), DEFAULT_MODEL);
    });
});
