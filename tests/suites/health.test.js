/**
 * Коэффициенты состояния тела и обмена (§66 ТЗ).
 *
 * Это единственное место приложения, где оно говорит человеку «хорошо» или
 * «стоит посмотреть». Неверная оценка выглядит убедительно ровно как верная,
 * а проверить её человеку нечем — он за тем и смотрит. Поэтому проверяется
 * не только арифметика, но и то, где приложение обязано промолчать.
 */

import { describe, it, equal, assert } from '../runner.js';
import { health } from '../../js/core/health.js';

describe('Индекс массы тела', () => {

    it('считается и округляется до десятой', () => {
        equal(health.bmi(92.9, 185).value, 27.1);
    });

    it('норма ВОЗ названа вслух', () => {
        const итог = health.bmi(80, 185);

        equal(итог.state, health.ХОРОШО);
        assert(итог.norm.includes('ВОЗ'), `чья мерка — важнее числа: ${итог.norm}`);
    });

    /*
     * Ниже нормы — тоже «стоит посмотреть», а не «хорошо». Приложение не
     * знает, отчего человек лёгкий, и хвалить его за это не вправе.
     */
    it('и ниже нормы, и выше — одинаково «стоит посмотреть»', () => {
        equal(health.bmi(55, 185).state, health.СМОТРЕТЬ);
        equal(health.bmi(110, 185).state, health.СМОТРЕТЬ);
    });

    it('без роста или веса молчит', () => {
        equal(health.bmi(80, null), null);
        equal(health.bmi(null, 185), null);
        equal(health.bmi(80, 5), null, 'рост в метрах — это чужая единица, а не пять сантиметров');
    });
});

describe('Талия к росту', () => {

    it('меньше половины роста — хорошо', () => {
        const итог = health.waistToHeight(88, 185);

        equal(итог.value, 0.48);
        equal(итог.state, health.ХОРОШО);
    });

    it('половина и больше — стоит посмотреть', () => {
        equal(health.waistToHeight(95, 185).state, health.СМОТРЕТЬ);
    });

    it('без ленты молчит', () => {
        equal(health.waistToHeight(null, 185), null);
    });
});

describe('Доля жира', () => {

    const мужчина = { sex: 'male', age: 44 };

    it('сорокалетний мужчина в 18 % — в норме своего возраста', () => {
        const итог = health.bodyFat(18, мужчина);

        equal(итог.state, health.ХОРОШО);
        assert(итог.norm.includes('возраста'), `мерка обязана назваться: ${итог.norm}`);
    });

    /*
     * Таблица возрастная намеренно: с годами доля жира растёт и у здорового
     * человека, и мерить сорокалетнего меркой двадцатилетнего значит
     * объявлять возраст болезнью.
     */
    it('одно и то же число у разных возрастов оценивается по-разному', () => {
        equal(health.bodyFat(24, { sex: 'male', age: 25 }).state, health.СМОТРЕТЬ);
        equal(health.bodyFat(24, { sex: 'male', age: 65 }).state, health.ХОРОШО);
    });

    it('у женщин своя таблица', () => {
        equal(health.bodyFat(30, { sex: 'female', age: 44 }).state, health.ХОРОШО);
        equal(health.bodyFat(30, { sex: 'male', age: 44 }).state, health.СМОТРЕТЬ);
    });

    /*
     * Биоимпеданс врёт на три–пять пунктов: зелёная зона обязана быть шире
     * промаха прибора, иначе отметка мигает день ото дня.
     */
    it('граница отодвинута на погрешность весов', () => {
        // 22 — верх таблицы для сорокалетнего, 23 внутри запаса
        equal(health.bodyFat(23, мужчина).state, health.ХОРОШО);
        equal(health.bodyFat(28, мужчина).state, health.СМОТРЕТЬ);
    });

    it('вчерашнее «хорошо» держится ещё полпункта', () => {
        const без = health.bodyFat(24.3, мужчина);
        const с = health.bodyFat(24.3, мужчина, health.ХОРОШО);

        equal(без.state, health.СМОТРЕТЬ);
        equal(с.state, health.ХОРОШО, 'иначе отметка прыгает от стакана воды');
    });

    it('без пола и возраста — число без оценки', () => {
        const итог = health.bodyFat(24, {});

        equal(итог.state, health.СПРАВКА);
        equal(итог.norm, null, 'выдуманной нормы быть не должно');
    });
});

describe('Основной обмен', () => {

    it('считается по Миффлину — Сан-Жеору', () => {
        // 10×92,9 + 6,25×185 − 5×44 + 5 = 1870
        equal(health.bmr({ weight: 92.9, height: 185, age: 44, sex: 'male' }), 1870);
    });

    it('у женщин своя поправка', () => {
        const м = health.bmr({ weight: 70, height: 170, age: 30, sex: 'male' });
        const ж = health.bmr({ weight: 70, height: 170, age: 30, sex: 'female' });

        equal(м - ж, 166, 'разница формулы — 5 и −161');
    });

    it('без пола молчит: формул две, и общей нет', () => {
        equal(health.bmr({ weight: 70, height: 170, age: 30 }), null);
    });
});

describe('Коэффициент активности', () => {

    /*
     * Берётся большее из двух: активность — не сумма ходьбы и зала, а то,
     * чего из них больше. Иначе тот, кто много ходит и много занимается,
     * получал бы расход, которого не бывает.
     */
    it('берётся большее из шагов и занятий', () => {
        equal(health.activityFactor({ steps: 12000, workoutsPerWeek: 0 }), 1.725);
        equal(health.activityFactor({ steps: 1000, workoutsPerWeek: 5 }), 1.725);
        equal(health.activityFactor({ steps: 12000, workoutsPerWeek: 5 }), 1.725,
            'вместе они не складываются');
    });

    it('без данных — покой', () => {
        equal(health.activityFactor({}), 1.2);
    });

    it('суточный расход — обмен, помноженный на активность', () => {
        equal(health.amr(1870, 1.55), 2899);
        equal(health.amr(null, 1.55), null);
    });
});

describe('Ход величины к себе же', () => {

    /*
     * У веса и талии нормы нет — есть направление. А куда «хорошо», решает
     * не приложение: цель названа человеком в профиле.
     */
    it('без названной цели — справка, а не оценка', () => {
        equal(health.trend(95, 92, {}).state, health.СПРАВКА);
    });

    it('с целью «вниз» снижение — хорошо, рост — стоит посмотреть', () => {
        equal(health.trend(95, 92, { goodDirection: 'down' }).state, health.ХОРОШО);
        equal(health.trend(92, 95, { goodDirection: 'down' }).state, health.СМОТРЕТЬ);
    });

    it('перемена меньше порога шума оценки не получает', () => {
        const итог = health.trend(92.5, 92.3, { goodDirection: 'down', noise: 0.5 });

        equal(итог.state, health.СПРАВКА, 'двести граммов — это вода, а не движение');
        equal(итог.delta, -0.2, 'но само число называется');
    });

    it('без чисел молчит', () => {
        equal(health.trend(null, 92, { goodDirection: 'down' }), null);
    });
});

/**
 * Ориентир недельного объёма (§66, Р-138).
 *
 * Единственная мерка на экране, взятая из тренировочных обзоров, а не из
 * медицины, — и единственная, где «слишком много» такая же новость, как
 * «слишком мало».
 */
describe('Недельный объём на группу мышц', () => {

    it('внутри ориентира — хорошо', () => {
        equal(health.weeklySets(12).state, health.ХОРОШО);
        equal(health.weeklySets(10).state, health.ХОРОШО, 'нижняя граница входит');
        equal(health.weeklySets(20).state, health.ХОРОШО, 'верхняя тоже');
    });

    it('и ниже, и выше ориентира — стоит посмотреть', () => {
        equal(health.weeklySets(4).state, health.СМОТРЕТЬ, 'четыре подхода — почти ничего');
        equal(health.weeklySets(28).state, health.СМОТРЕТЬ, 'двадцать восемь не окупаются усталостью');
    });

    it('мерка названа рядом с оценкой', () => {
        assert(health.weeklySets(12).norm.includes('10'), 'иначе это приговор без разбирательства');
    });

    it('без подходов оценивать нечего', () => {
        equal(health.weeklySets(0), null);
        equal(health.weeklySets(null), null);
    });
});

/**
 * Разгон: свежая нагрузка к накопленной (§66, Р-140).
 *
 * Отвечает не «в форме ли я», а «не слишком ли резко я прибавил» — и потому
 * красится в обе стороны.
 */
describe('Разгон нагрузки', () => {

    it('это отношение недельной нагрузки к шестинедельной', () => {
        equal(health.rampUp(45, 50).value, 0.9);
    });

    it('внутри ориентира — хорошо', () => {
        equal(health.rampUp(50, 50).state, health.ХОРОШО, 'ровно столько же, сколько обычно');
    });

    it('резкая прибавка отмечается', () => {
        equal(health.rampUp(80, 50).state, health.СМОТРЕТЬ, '1,6 — так и срываются');
    });

    /*
     * Ниже ориентира человек сбавил. Это не беда, но знать об этом стоит:
     * форма уходит быстрее, чем набирается.
     */
    it('и сбавленный темп тоже', () => {
        equal(health.rampUp(20, 50).state, health.СМОТРЕТЬ, '0,4 — это уже не отдых, а перерыв');
    });

    it('без нагрузок считать нечего', () => {
        equal(health.rampUp(0, 50), null);
        equal(health.rampUp(30, 0), null, 'деления на ноль не бывает');
        equal(health.rampUp(null, null), null);
    });

    it('мерка названа рядом с оценкой', () => {
        assert(health.rampUp(50, 50).norm.includes('0,8'), 'иначе это приговор без разбирательства');
    });
});

/**
 * Мерки в своих единицах (§66, Р-141).
 *
 * «ИМТ 27,1» человеку не говорит ничего, «для вашего роста здоровым считают
 * от 63 до 86 кг» говорит всё. Это та же норма ВОЗ, переведённая обратно.
 */
describe('Здоровый вес и пороги талии', () => {

    it('вилка веса — это норма ИМТ, переведённая в килограммы', () => {
        const вилка = health.weightRange(185);

        equal(вилка.from, 63.4);
        equal(вилка.to, 85.5);
    });

    /*
     * Обе величины обязаны считаться по одной норме: разъедься они, плитка
     * ИМТ говорила бы «выше нормы» при весе внутри названной вилки.
     */
    it('вилка и оценка индекса сходятся на границе', () => {
        const вилка = health.weightRange(185);

        equal(health.bmi(вилка.from, 185).state, health.ХОРОШО, 'нижний край вилки — уже норма');
        equal(health.bmi(вилка.to, 185).state, health.ХОРОШО, 'и верхний край вилки — ещё норма');
        equal(health.bmi(вилка.to + 1, 185).state, health.СМОТРЕТЬ, 'а за ним — уже нет');
    });

    it('без роста вилки нет', () => {
        equal(health.weightRange(null), null);
        equal(health.weightRange(20), null, 'рост в двадцать сантиметров — это опечатка');
    });

    it('пороги талии названы по полу', () => {
        equal(health.waistLimits('male').watch, 94);
        equal(health.waistLimits('male').risk, 102);
        equal(health.waistLimits('female').watch, 80);
        equal(health.waistLimits('female').risk, 88);
    });

    /*
     * Без пола приложение молчит, а не подставляет мужскую вилку: женщине с
     * талией 90 см она сказала бы «в порядке», а это не так.
     */
    it('без пола порогов нет', () => {
        equal(health.waistLimits(null), null);
        equal(health.waistLimits(''), null);
    });
});

/*
 * Ход величины по её собственным замерам (Р-179).
 *
 * Замер тела — одна запись на день, и величин в ней несколько: вес есть
 * каждый день, талию меряют лентой раз в неделю, состав привозят весы.
 * Отбор «что было месяц назад» по записи целиком давал талии «замер один»
 * при десятке точек на линии рядом — запись месячной давности была, а талии
 * в ней не было.
 *
 * Все сроки здесь заданы явно: проверка, зависящая от того, который сейчас
 * час, проваливается раз в сутки и не говорит почему.
 */
describe('Ход величины по своим замерам', () => {

    const ДЕНЬ = 86400000;
    const СЕЙЧАС = 1_700_000_000_000;

    /** Замеры по дням назад от «сейчас»: { назад: {...поля} }. */
    const история = (записи) => Object.entries(записи)
        .map(([назад, поля]) => ({ at: СЕЙЧАС - Number(назад) * ДЕНЬ, ...поля }))
        .sort((a, b) => a.at - b.at);

    const ход = (замеры, взять, ещё = {}) =>
        health.course(замеры, взять, { now: СЕЙЧАС, window: 30, ...ещё });

    it('пустая история — ничего', () => {
        equal(health.course([], (r) => r.waist, { now: СЕЙЧАС }), null);
        equal(health.course(null, (r) => r.waist, { now: СЕЙЧАС }), null);
    });

    /*
     * Тот самый случай, о котором сообщил владелец: линия талии из четырёх
     * точек, а подпись под ней — «не с чем сравнить: замер один».
     */
    it('талия сравнивается с талией, а не с записью, где её нет', () => {
        const замеры = история({
            45: { weight: 93, waist: 101 },
            40: { weight: 92.6 },
            20: { weight: 92, waist: 99.5 },
            1:  { weight: 91.3 },
            0:  { weight: 91.3, waist: 98.3 }
        });

        const талия = ход(замеры, (r) => r.waist);

        equal(талия.value, 98.3);
        equal(талия.at, СЕЙЧАС, 'показывается самый свежий замер талии');

        assert(талия.trend, 'записей с талией три — сравнить есть с чем');
        equal(талия.trend.delta, -2.7, 'сравнение идёт с замером старше месяца');
    });

    it('в день без ленты талия не пропадает, а называет свою дату', () => {
        const замеры = история({
            40: { weight: 93, waist: 101 },
            3:  { weight: 91.5, waist: 98.3 },
            0:  { weight: 91.3 }
        });

        const талия = ход(замеры, (r) => r.waist);

        equal(талия.value, 98.3);
        equal(талия.at, СЕЙЧАС - 3 * ДЕНЬ, 'дата своя, и экрану есть что сказать');
    });

    it('единственный замер — сравнивать не с чем, и это не ноль перемен', () => {
        const замеры = история({ 0: { weight: 91.3, waist: 98.3 } });

        equal(ход(замеры, (r) => r.waist).trend, null,
            'ноль перемен при одном замере — это «ничего не происходит» на пустом месте');
    });

    /*
     * Оба замера старше месяца: граница окна оставляла кандидатом и самый
     * свежий, и приложение сравнивало его с ним же (Р-134).
     */
    it('давняя пара замеров сравнивается между собой, а не сама с собой', () => {
        const замеры = история({
            90: { weight: 95, waist: 104 },
            60: { weight: 93, waist: 101 }
        });

        const талия = ход(замеры, (r) => r.waist);

        equal(талия.value, 101);
        equal(талия.trend.delta, -3);
    });

    it('нет замера старше окна — сравниваем с самым ранним, какой есть', () => {
        const замеры = история({
            14: { weight: 93, waist: 101 },
            7:  { weight: 92, waist: 100 },
            0:  { weight: 91.3, waist: 99 }
        });

        equal(ход(замеры, (r) => r.waist).trend.delta, -2);
    });

    it('направление и погрешность передаются оценке', () => {
        const замеры = история({
            40: { weight: 93, waist: 101 },
            0:  { weight: 91.3, waist: 98.3 }
        });

        equal(ход(замеры, (r) => r.waist, { goodDirection: 'down', noise: 1 }).trend.state,
            health.ХОРОШО);

        equal(ход(замеры, (r) => r.waist, { goodDirection: 'up', noise: 1 }).trend.state,
            health.СМОТРЕТЬ);

        equal(ход(замеры, (r) => r.waist).trend.state, health.СПРАВКА,
            'без названной цели куда хорошо — не приложению решать');
    });

    it('состав тела достаётся из вложенного поля так же', () => {
        const замеры = история({
            40: { weight: 93, body: { fat: 27.2, muscle: 36.4 } },
            0:  { weight: 91.3, body: { fat: 25.8 } }
        });

        equal(ход(замеры, (r) => r.body?.fat).value, 25.8);

        const мышцы = ход(замеры, (r) => r.body?.muscle);

        equal(мышцы.value, 36.4);
        equal(мышцы.at, СЕЙЧАС - 40 * ДЕНЬ, 'весы в этот раз мышц не прислали');
        equal(мышцы.trend, null, 'и сравнивать эту единственную долю не с чем');
    });
});
