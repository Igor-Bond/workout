/**
 * Графики (§27 ТЗ).
 *
 * Проверяется не то, как картинка выглядит, — это видно глазом, — а то, что
 * о ней сказано словами: имя для читалки экрана и подписи шкалы. Их глазом
 * как раз не проверишь, и врут они молча.
 */

import { describe, it, equal, assert } from '../runner.js';
import { chart } from '../../js/core/chart.js';

/** Разметка графика одной строкой — по ней и спрашиваем. */
const рисунок = (series, options) => String(chart.line(series, options));

const имя = (разметка) => разметка.match(/aria-label="([^"]*)"/)?.[1] || '';

const точки = (пары) => pairsToPoints(пары);

function pairsToPoints(пары) {
    return пары.map(([x, y], i) => ({ x, y, key: `k${i}`, label: `0${i + 1}.09` }));
}

const ряд = (пары, over = {}) => ({ color: 'var(--accent)', segments: [точки(пары)], ...over });

describe('Имя графика для читалки экрана (Р-143)', () => {

    /*
     * У SVG стоит role="img": без имени читалка говорит «изображение» и
     * замолкает, и всё содержимое картинки пропадает.
     */
    it('имя есть всегда, даже когда заголовка не дали', () => {
        const текст = имя(рисунок([ряд([[1, 5], [2, 7]])]));

        assert(текст.includes('Линия'), `имя обязано быть: «${текст}»`);
        assert(текст.includes('5') && текст.includes('7'), `и называть границы: «${текст}»`);
    });

    it('заголовок вызвавшего идёт первым', () => {
        const текст = имя(рисунок([ряд([[1, 5], [2, 7]])], { label: 'Вес, кг' }));

        assert(текст.startsWith('Вес, кг.'), `«${текст}»`);
    });

    /*
     * Пустой первый ряд при непустом втором давал «Линия: 0 значений с по , от
     * ∞ до −∞»: имя считалось по первому ряду, каким бы он ни был.
     */
    it('имя берётся из первого ряда, в котором есть точки', () => {
        const текст = имя(рисунок([
            { color: 'var(--accent)', segments: [] },
            ряд([[1, 10], [2, 20]], { color: 'var(--blue)' })
        ]));

        assert(!текст.includes('∞'), `бесконечности в имени быть не может: «${текст}»`);
        assert(текст.includes('10') && текст.includes('20'), `границы берутся у непустого: «${текст}»`);
    });

    /*
     * Слово при числе склоняется: «4 значения», а не «4 значений». Имя читают
     * вслух, и там это слышно.
     */
    it('число и слово согласованы', () => {
        assert(имя(рисунок([ряд([[1, 5], [2, 7]])])).includes('2 значения'), 'два значения');
        assert(имя(рисунок([ряд([[1, 5], [2, 7], [3, 9], [4, 9], [5, 9]])])).includes('5 значений'), 'пять значений');
    });
});

describe('Шкала линии (Р-114, Р-136, Р-138)', () => {

    const подписи = (разметка) => [...разметка.matchAll(/class="chart-label">([^<]*)</g)].map((m) => m[1]);

    /*
     * Безразмерным величинам — индексу массы тела, форме — границы поля нужны
     * так же, как весу: без них глаз читает не величину, а форму.
     */
    it('шкала подписывается и без единицы измерения', () => {
        const числа = подписи(рисунок([ряд([[1, 27.1], [2, 27.5]])], { scale: true }))
            .filter((s) => /^\d/.test(s) && !s.includes('.'));

        equal(числа.length, 2, `верх и низ: ${числа.join(' | ')}`);
    });

    it('без просьбы шкала не рисуется', () => {
        const числа = подписи(рисунок([ряд([[1, 27.1], [2, 27.5]])]))
            .filter((s) => /^\d+,/.test(s));

        equal(числа.length, 0, 'у графика без единицы и без просьбы подписей быть не должно');
    });

    /*
     * Подходов за неделю бывает ноль и не бывает минус два, а заданный размах
     * спокойно уводил шкалу ниже нуля (Р-138).
     */
    it('у величины с дном шкала ниже дна не опускается', () => {
        const числа = подписи(рисунок([ряд([[1, 0], [2, 2], [3, 0]])], { scale: true, minSpan: 6, floor: 0 }));

        assert(!числа.some((s) => s.includes('−')), `минуса в шкале быть не может: ${числа.join(' | ')}`);
        assert(числа.includes('0'), `и ноль пишется без десятых: ${числа.join(' | ')}`);
    });

    /*
     * Отношение талии к росту живёт между 0,4 и 0,6: десятой доли на такой
     * шкале не хватает, и оба края округлялись в одно число (Р-136).
     */
    it('у мелкой величины края шкалы не сливаются', () => {
        const числа = подписи(рисунок([ряд([[1, 0.55], [2, 0.54]])], { scale: true, minSpan: 0.06 }))
            .filter((s) => /^0,/.test(s));

        equal(числа.length, 2, `шкала обязана быть подписана: ${числа.join(' | ')}`);
        assert(числа[0] !== числа[1], `и называть два разных края: ${числа.join(' и ')}`);
    });
});

describe('Полоса «как обычно» (Р-139)', () => {

    it('рисуется прямоугольником, когда её дали', () => {
        const разметка = рисунок([ряд([[1, 50], [2, 55], [3, 52]])], { band: { from: 51, to: 54 } });

        assert(разметка.includes('<rect'), 'полоса — это прямоугольник за линией');
    });

    it('без полосы прямоугольника нет', () => {
        const разметка = рисунок([ряд([[1, 50], [2, 55]])]);

        assert(!разметка.includes('<rect'), 'ничего лишнего график не рисует');
    });
});

/**
 * Спарклайн в плитке (§27, Р-153).
 *
 * Он отвечает на один вопрос — «идёт или стоит», — и потому у него нет ни
 * шкалы, ни дат. Проверять тут надо то, чего не видно глазом: что линия
 * рвётся на пропуске, не уходит ниже дна и молчит для читалки.
 */
describe('Спарклайн', () => {

    const отрезок = (пары) => пары.map(([x, y]) => ({ x, y }));

    it('рисуется, когда точек хотя бы две', () => {
        const разметка = String(chart.spark([отрезок([[1, 5], [2, 7]])]));

        assert(разметка.includes('<path'), 'линия обязана быть');
    });

    /*
     * Одна точка — это не ход: рисовать по ней линию значило бы изображать
     * движение там, где его не видно.
     */
    it('на одной точке не рисуется вовсе', () => {
        equal(String(chart.spark([отрезок([[1, 5]])])), '');
        equal(String(chart.spark([])), '');
    });

    it('пропуск рвёт линию, а не соединяет прямой', () => {
        const разметка = String(chart.spark([отрезок([[1, 5], [2, 6]]), отрезок([[9, 7], [10, 8]])]));

        equal((разметка.match(/<path/g) || []).length, 2, 'две линии, а не одна через пропуск');
    });

    /*
     * Подходов за неделю бывает ноль и не бывает минус два: у величины с
     * дном линия не должна нырять ниже него даже ради запаса по краям.
     */
    it('у величины с дном линия не уходит под дно', () => {
        const разметка = String(chart.spark([отрезок([[1, 0], [2, 2], [3, 0]])], { floor: 0, height: 20 }));

        const игреки = [...разметка.matchAll(/[ML](-?[\d.]+),(-?[\d.]+)/g)].map((m) => Number(m[2]));

        assert(игреки.every((y) => y <= 20.01), `ниже поля точек быть не может: ${игреки.join(', ')}`);
        assert(игреки.some((y) => y >= 19), 'ноль обязан лечь на самое дно');
    });

    /*
     * Число рядом и разворот под ним говорят то же самое словами: лишний
     * «график» в речи читалки только мешает.
     */
    it('для читалки экрана спрятан', () => {
        const разметка = String(chart.spark([отрезок([[1, 5], [2, 7]])]));

        assert(разметка.includes('aria-hidden="true"'), разметка.slice(0, 120));
    });
});
