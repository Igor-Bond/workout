/**
 * Ссылки между ТЗ и журналом решений (§49).
 *
 * ТЗ отвечает на «как должно быть», журнал — на «чем было прежде и почему
 * поменяли». Разведены они намеренно, но разведённое расходится: ссылка
 * `(Р-12)` в ТЗ и запись «Р-12» в журнале — это одно решение, записанное в
 * двух местах, и ничто, кроме этой проверки, не заставит их совпадать.
 *
 * Проверяется в обе стороны. Ссылка без записи оставляет читателя ни с чем;
 * запись без ссылки — сирота, которую никто не найдёт: журнал читают не
 * подряд, а по ссылке из требования.
 */

import { describe, it, assert } from '../runner.js';

const читать = async (path) => (await fetch(`../${path}`, { cache: 'no-store' })).text();

describe('ТЗ и журнал решений', () => {

    it('у каждой ссылки в ТЗ есть запись в журнале', async () => {
        const spec = await читать('docs/SPEC.md');
        const journal = await читать('docs/DECISIONS.md');

        const записи = new Set([...journal.matchAll(/^## (Р-\d+)\./gm)].map((m) => m[1]));
        const ссылки = [...new Set([...spec.matchAll(/\((Р-\d+)\)/g)].map((m) => m[1]))];

        const битые = ссылки.filter((номер) => !записи.has(номер));

        assert(ссылки.length > 0, 'в ТЗ нет ни одной ссылки — проверка ничего не проверяет');
        assert(битые.length === 0, `ссылки в никуда: ${битые.join(', ')}`);
    });

    it('в журнале нет записей, на которые не ссылаются', async () => {
        const spec = await читать('docs/SPEC.md');
        const journal = await читать('docs/DECISIONS.md');

        const ссылки = new Set([...spec.matchAll(/\((Р-\d+)\)/g)].map((m) => m[1]));
        const сироты = [...journal.matchAll(/^## (Р-\d+)\./gm)]
            .map((m) => m[1])
            .filter((номер) => !ссылки.has(номер));

        assert(сироты.length === 0, `записи, которые никто не найдёт: ${сироты.join(', ')}`);
    });

    /*
     * Оглавление журнала ведётся руками, и якоря в нём тоже. Строка,
     * добавленная в таблицу и забытая в тексте, ведёт в пустоту, а запись
     * без строки в таблице не видна тому, кто листает оглавление.
     */
    it('оглавление журнала совпадает с его содержимым', async () => {
        const journal = await читать('docs/DECISIONS.md');

        const записи = [...journal.matchAll(/^## (Р-\d+)\./gm)].map((m) => m[1]);
        const строки = [...journal.matchAll(/^\| \[(Р-\d+)\]/gm)].map((m) => m[1]);

        assert(записи.join(' ') === строки.join(' '),
            `оглавление и записи разошлись:\n  в тексте: ${записи.join(', ')}\n  в таблице: ${строки.join(', ')}`);
    });
});
