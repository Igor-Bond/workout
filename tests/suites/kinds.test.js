/**
 * Виды упражнений — один список на всё приложение (§5).
 *
 * Их четыре, и следствий у них много: подписи, подсказки, поля ввода,
 * столбцы в итогах, величина рекорда. Пока следствия лежали порознь, ничто
 * не мешало забыть вид в одной из таблиц — и на экране появлялась пустота
 * там, где ждали слово.
 *
 * Поэтому здесь две проверки. Первая держит сам список: он один, и в нём всё
 * согласовано. Вторая ищет по исходникам таблицы, разложенные по видам, и
 * требует, чтобы в каждой были все четыре, — это и есть защита от «решения в
 * двух местах», а не только от этих конкретных пяти таблиц.
 */

import { describe, it, equal, assert } from '../runner.js';
import { KINDS, kindOf, kindLabel, kindFields } from '../../js/core/kinds.js';
import { sources, objects } from '../helpers/source.js';

const ВИДЫ = ['weight', 'reps', 'time', 'distance'];

describe('Виды упражнений', () => {

    it('видов ровно четыре и они те самые', () => {
        equal(KINDS.map((k) => k.value), ВИДЫ);
    });

    it('у каждого вида есть всё, что о нём спрашивают', () => {
        for (const kind of KINDS) {
            assert(!!kind.label, `${kind.value}: нет подписи`);
            assert(!!kind.hint, `${kind.value}: нет подсказки`);
            assert(kind.fields.length > 0, `${kind.value}: нет полей подхода`);
        }
    });

    /*
     * Главное поле — то, по которому видно, что подход этого вида. Оно
     * всегда первое из полей, и связь эта не случайна: спрашивают в первую
     * очередь то, ради чего упражнение и делают.
     */
    it('главное поле — первое из полей вида', () => {
        for (const kind of KINDS) {
            equal(kind.main, kind.fields[0], kind.value);
        }
    });

    it('незнакомый вид не выдаётся за знакомый', () => {
        equal(kindOf('прыжки в длину'), undefined, 'молча подставить силовое — соврать про записанное');
        equal(kindLabel('прыжки в длину'), 'прыжки в длину', 'показывается как есть');
        equal(kindFields('прыжки в длину'), kindFields('weight'), 'поля — как у силового, чаще всего он и есть');
    });
});

describe('Таблицы по видам упражнений', () => {

    /**
     * Где вид — не таблица, а условие.
     *
     * Эти места перечисляют виды по одному и по два намеренно: доля
     * собственного веса есть только у двух видов, а у снаряда её нет вовсе.
     * Каждое исключение названо с причиной — список без причин через полгода
     * превращается в место, куда прячут неудобные находки.
     */
    const МИМО = {
        'js/core/estimate.js': 'доля собственного веса есть только у двух видов из четырёх',
        'js/core/kinds.js': 'это и есть сам список видов'
    };

    /**
     * Таблица по видам — та, у которой все ключи виды.
     *
     * Различать приходится потому, что «вес», «повторения» и «дистанция» —
     * это ещё и поля подхода: таблица подписей полей выглядит почти так же.
     * Отличается она четвёртым ключом: у полей это «длительность», у видов —
     * «на время». Проще и надёжнее не гадать, а потребовать, чтобы в
     * таблице по видам не было ничего, кроме видов.
     */
    const поВидам = ({ keys }) => keys.length >= 2 && keys.every((key) => ВИДЫ.includes(key));

    it('в каждой таблице по видам есть все четыре', async () => {
        const неполные = [];
        const найдено = [];

        for (const { path, code } of await sources()) {
            if (МИМО[path]) continue;

            for (const table of objects(code).filter(поВидам)) {
                найдено.push(`${path}:${table.name}`);
                if (table.keys.length === ВИДЫ.length) continue;

                неполные.push(`${path}:${table.line} (${table.name}) — только ${table.keys.join(', ')}`);
            }
        }

        assert(найдено.length > 0, 'ни одной таблицы по видам не нашлось — проверка ничего не проверяет');

        assert(неполные.length === 0,
            `таблица по видам неполна, на экране будет пустота:\n${неполные.join('\n')}`);
    });
});
