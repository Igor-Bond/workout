/**
 * Весы по Bluetooth: разбор записей профиля (§65 ТЗ).
 *
 * Проверять тут надо ровно одно — разбор. Всё остальное в этой службе это
 * разговор с настоящим устройством, и подменять его заглушкой значило бы
 * проверять заглушку: беды случались не в порядке вызовов, а в шифровании,
 * в опознании человека и в том, что весы ждали выбора места на своём экране.
 * Ни одну из них никакой макет не воспроизводит.
 *
 * А вот разбор проверяется насухо и обязан быть проверен: поля в записи
 * необязательны и идут подряд, без имён и без длин. Пропустив одно, разбор
 * молча собьёт все следующие — вес станет ростом, а жир обменом. Ошибка при
 * этом не выглядит ошибкой: число просто окажется другим.
 *
 * Половина записей здесь — настоящие, снятые с SilverCrest SBF77 владельца.
 * Собранные вручную проверяют то, чего эти весы не присылают.
 */

import { describe, it, equal, assert } from '../runner.js';
import { scale } from '../../js/services/scale.js';

/** Запись из строки шестнадцатеричных байтов — так их и печатает разведка. */
function запись(строка) {
    const байты = строка.trim().split(/\s+/).map((b) => parseInt(b, 16));
    return new DataView(new Uint8Array(байты).buffer);
}

/** Округление до сотых: сравнивать доли граммов бессмысленно. */
const сотые = (v) => Math.round(v * 100) / 100;

describe('Вес с весов', () => {

    /*
     * Настоящая запись: 92,900 кг, 12 сентября 2026, 15:15:01, место 3,
     * ИМТ 27,1, рост 185 см.
     */
    const НАСТОЯЩАЯ = '0e 94 48 ea 07 09 0c 0f 0f 01 03 0f 01 3a 07';

    it('разбирает запись, снятую с настоящих весов', () => {
        const r = scale.parseWeight(запись(НАСТОЯЩАЯ));

        equal(сотые(r.weight), 92.9);
        equal(r.user, 3);
        equal(сотые(r.bmi), 27.1);
        equal(сотые(r.height), 185);

        const d = new Date(r.at);

        equal([d.getFullYear(), d.getMonth() + 1, d.getDate()], [2026, 9, 12]);
        equal([d.getHours(), d.getMinutes()], [15, 15]);
    });

    it('без необязательных полей остаётся один вес', () => {
        const r = scale.parseWeight(запись('00 94 48'));

        equal(сотые(r.weight), 92.9);
        equal(r.at, null);
        equal(r.user, null);
        equal(r.bmi, null, 'чего не прислали, того и нет — а не ноль');
    });

    /*
     * Фунты приложение не хранит: тоннаж и доля собственного веса считаются в
     * килограммах (§6), и две единицы в базе означали бы, что каждый расчёт
     * обязан помнить, откуда пришло число.
     */
    it('фунты переводятся в килограммы', () => {
        // 200,00 фунта = 90,72 кг
        const b = new Uint8Array(3);
        b[0] = 1;
        new DataView(b.buffer).setUint16(1, 20000, true);

        equal(сотые(scale.parseWeight(new DataView(b.buffer)).weight), 90.72);
    });

    /*
     * Часы весов сбиваются при смене батареек. Замер от этого пропадать не
     * должен — он просто становится сегодняшним.
     */
    it('негодная метка времени не роняет разбор', () => {
        const r = scale.parseWeight(запись('02 94 48 00 00 00 00 00 00 00'));

        equal(сотые(r.weight), 92.9);
        equal(r.at, null);
    });

});

describe('Состав тела', () => {

    /*
     * Настоящая запись: жир 24,5 %, обмен 7829 кДж, мышцы 38,5 %, сухая масса
     * 66,54 кг, вода 46,26 кг, сопротивление 483 Ом. Ни веса, ни роста, ни
     * метки времени эти весы в ней не присылают — и это обычное дело.
     */
    const НАСТОЯЩАЯ = '98 03 f5 00 95 1e 81 01 fc 33 24 24 de 12';

    it('разбирает запись, снятую с настоящих весов', () => {
        const r = scale.parseBody(запись(НАСТОЯЩАЯ));

        equal(сотые(r.fat), 24.5);
        equal(r.basal, 7829);
        equal(сотые(r.musclePercent), 38.5);
        equal(сотые(r.lean), 66.54);
        equal(сотые(r.water), 46.26);
        equal(сотые(r.impedance), 483);

        equal(r.weight, null, 'веса в этой записи нет — он приезжает своей');
        equal(r.at, null);
    });

    /*
     * Поля идут подряд и опознаются только битом признака. Пропущенное поле
     * сбивает все следующие, и заметить это по одному числу нельзя — здесь
     * пропущена середина, а проверяется хвост.
     */
    it('пропущенные поля не сбивают следующие', () => {
        const b = new Uint8Array(8);
        const dv = new DataView(b.buffer);

        dv.setUint16(0, 2048 | 1024, true);  // только вес и рост
        dv.setUint16(2, 300, true);          // жир 30 %
        dv.setUint16(4, 18580, true);        // вес 92,9 кг
        dv.setUint16(6, 1850, true);         // рост 185 см

        const r = scale.parseBody(dv);

        equal(сотые(r.fat), 30);
        equal(сотые(r.weight), 92.9);
        equal(сотые(r.height), 185);
        equal(r.water, null);
    });

});

/**
 * Замеры приезжают очередью (§65).
 *
 * Весы держат сделанное в памяти места и отдают накопленное сразу, как только
 * узнают человека. Значит, взвешиваться с телефоном в руке необязательно — и
 * значит, приехать может не один замер, а сколько накопилось.
 */
describe('Сведение весов с составами', () => {

    it('пары собираются по порядку', () => {
        const r = scale.pair([{ weight: 92.9 }, { weight: 93.1 }], [{ fat: 24.5 }, { fat: 24.7 }]);

        equal(r.length, 2);
        equal(r[0].body.fat, 24.5);
        equal(r[1].weight.weight, 93.1);
    });

    /*
     * Состав тела весы считают не всегда: человек встал в носках, и ток через
     * тело не прошёл. Вес при этом приезжает, и терять его незачем.
     */
    it('вес без состава остаётся весом', () => {
        const r = scale.pair([{ weight: 92.9 }], []);

        equal(r.length, 1);
        equal(r[0].body, null);
    });

    it('лишний состав не создаёт замера из ничего', () => {
        equal(scale.pair([], [{ fat: 24.5 }]).length, 0,
            'состав без веса — не взвешивание, а половина записи');
    });

});

describe('Что из состава остаётся в замере', () => {

    const НАСТОЯЩАЯ = '98 03 f5 00 95 1e 81 01 fc 33 24 24 de 12';

    it('хранится то, на что человек смотрит', () => {
        const r = scale.keep(scale.parseBody(запись(НАСТОЯЩАЯ)));

        equal(r, { fat: 24.5, water: 46.3, muscle: 38.5, basal: 7829 });
    });

    /*
     * Пустое поле внутри записи однажды уже роняло обмен с облаком (Р-97):
     * там его не принимают. Поэтому пустого тут не бывает — поля просто нет.
     */
    it('пустых полей не остаётся', () => {
        equal(scale.keep(null), {});
        equal(scale.keep({ fat: 0, water: null, musclePercent: undefined }), {});
    });

    it('сопротивление не хранится', () => {
        const r = scale.keep(scale.parseBody(запись(НАСТОЯЩАЯ)));

        assert(!('impedance' in r), 'служебное число прибора человеку ничего не говорит');
    });

});
