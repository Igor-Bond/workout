/**
 * Съеденное и дефицит (§68 ТЗ).
 *
 * Главное, что здесь проверяется, — разница между «не ел» и «не записал».
 * Ноль вместо пропуска превращает забытый вторник в день голодания, а
 * средний дефицит — в выдумку.
 */

import { describe, it, equal, assert } from '../runner.js';
import { intake } from '../../js/core/intake.js';

const DAY = 86400000;
const NOW = new Date(2026, 8, 15, 20, 0, 0).getTime();

/** Запись за n дней назад: время внутри тех суток. */
const запись = (днейНазад, kcal) => ({
    at: new Date(new Date(NOW - днейНазад * DAY).setHours(13, 0, 0, 0)).getTime(),
    kcal
});

describe('Съеденное за день', () => {

    it('складывается по всем записям суток', () => {
        equal(intake.day([запись(0, 450), запись(0, 720), запись(0, 310)], { now: NOW }), 1480);
    });

    it('чужие дни не берутся', () => {
        equal(intake.day([запись(1, 2500), запись(0, 600)], { now: NOW }), 600);
    });

    /*
     * Ноль значил бы «не ел», а на деле это «не записал». Разница здесь
     * важнее всего остального: день без записи не должен выглядеть
     * голоданием ни человеку, ни дефициту.
     */
    it('день без записей — это ничего, а не ноль', () => {
        equal(intake.day([запись(3, 2000)], { now: NOW }), null);
        equal(intake.day([], { now: NOW }), null);
    });
});

describe('Среднее за неделю', () => {

    it('считается по дням, в которые записывали', () => {
        const итог = intake.average([
            запись(0, 2000), запись(1, 2400), запись(2, 1600)
        ], { now: NOW });

        equal(итог.kcal, 2000);
        equal(итог.days, 3, 'три дня из семи');
        equal(итог.of, 7);
    });

    /*
     * Забытый день не тянет среднее вниз: человек в этот день не ел ноль.
     */
    it('пропущенные дни не занижают среднее', () => {
        const плотно = intake.average([запись(0, 2000), запись(1, 2000)], { now: NOW });
        const сдырой = intake.average([запись(0, 2000), запись(3, 2000)], { now: NOW });

        equal(плотно.kcal, сдырой.kcal, 'дыра между днями на число не влияет');
        equal(сдырой.days, 2, 'а на то, скольким дням верить, — влияет');
    });

    it('без записей среднего нет', () => {
        equal(intake.average([], { now: NOW }), null);
    });
});

describe('Дефицит', () => {

    it('это расход минус приход', () => {
        equal(intake.deficit({ spent: 2900, eaten: 2400 }), 500);
        equal(intake.deficit({ spent: 2900, eaten: 3200 }), -300, 'перебор называется минусом, а не прячется');
    });

    /*
     * Расход без прихода — половина разговора. Показать её как дефицит
     * значило бы объявить дефицитом весь суточный расход.
     */
    it('без одного из чисел не считается', () => {
        equal(intake.deficit({ spent: 2900 }), null);
        equal(intake.deficit({ eaten: 2400 }), null);
        equal(intake.deficit({ spent: 2900, eaten: null }), null);
    });
});

describe('Сколько дней подряд записывали', () => {

    it('считается с сегодняшнего дня назад', () => {
        equal(intake.streak([запись(0, 2000), запись(1, 2100), запись(2, 1900)], { now: NOW }), 3);
    });

    it('прерывается на первом пропуске', () => {
        equal(intake.streak([запись(0, 2000), запись(2, 2100)], { now: NOW }), 1);
    });

    it('без сегодняшней записи ряда нет вовсе', () => {
        equal(intake.streak([запись(1, 2000), запись(2, 2100)], { now: NOW }), 0);
    });
});
