/**
 * Темп по прошлому разу (§50.3, Р-178).
 *
 * Главное, что здесь проверяется, — что цель всегда последний круг прошлого
 * раза, куда бы ни шла линия. Соблазн велик и очевиден: раз числа росли,
 * предложить ещё больше; раз падали — меньше. Оба соблазна ошибочны, и
 * проверки стоят именно на них.
 *
 * Второе — молчание. Интервальный экран повторений не пишет вовсе, и
 * тренировка без проставленных чисел — обычное дело, а не сбой. Подсказки
 * в этом случае нет никакой.
 */

import { describe, it, equal, assert } from '../runner.js';
import { pace } from '../../js/core/pace.js';

/** Подходы одного упражнения, как их отдаёт база: новые первыми. */
const подходы = (тренировка, числа) => числа
    .map((reps, i) => ({ workoutId: тренировка, setNumber: i + 1, reps }))
    .reverse();

describe('Темп: чтение прошлого раза', () => {

    it('пустая история — подсказки нет', () => {
        equal(pace.read([]), null);
        equal(pace.read([], { exclude: 'w1' }), null);
    });

    it('своя же тренировка в счёт не идёт', () => {
        const свои = подходы('w1', [15, 16, 17]);

        equal(pace.read(свои, { exclude: 'w1' }), null,
            'сравнивать себя с самим собой посреди круга бессмысленно');
    });

    it('берётся ближайшая чужая тренировка, а не все подряд', () => {
        const история = [
            ...подходы('w2', [20, 21, 22]),
            ...подходы('w1', [10, 10, 10])
        ];

        const темп = pace.read(история, { exclude: 'w3' });

        equal(темп.rounds, 3);
        equal(темп.first, 20, 'среднее по двум заходам размазало бы форму линии');
        equal(темп.last, 22);
    });

    /*
     * Экран интервальной программы повторений не пишет: считать их, не
     * трогая телефон, нельзя. Проставляют их потом, на итогах, — и до тех
     * пор говорить нечего.
     */
    it('без проставленных повторений молчим', () => {
        const пустые = подходы('w1', [null, null, null]).map((s) => ({ ...s, duration: 20 }));

        equal(pace.read(пустые, { exclude: 'w2' }), null);
    });

    it('порядок кругов берётся из номера подхода, а не из порядка записей', () => {
        const вразброс = [
            { workoutId: 'w1', setNumber: 2, reps: 16 },
            { workoutId: 'w1', setNumber: 3, reps: 17 },
            { workoutId: 'w1', setNumber: 1, reps: 15 }
        ];

        const темп = pace.read(вразброс, { exclude: 'w2' });

        equal(темп.first, 15);
        equal(темп.last, 17);
    });
});

describe('Темп: куда шла линия', () => {

    const линия = (числа) => pace.read(подходы('w1', числа), { exclude: 'w2' });

    it('числа росли — до предела не дошли', () => {
        equal(линия([15, 16, 17]).trend, 'rise');
    });

    it('числа падали — начали быстрее, чем держится', () => {
        equal(линия([24, 20, 18]).trend, 'fall');
    });

    it('единица разницы — это ровно, а не спад', () => {
        equal(линия([17, 17, 16]).trend, 'flat',
            'повторения целые, и различать меньше единицы нечего');
    });

    it('у крупных чисел допуск тоже крупнее', () => {
        equal(линия([50, 52, 52]).trend, 'flat',
            'двойка на пятидесяти прыжках — это та же ровная линия');

        equal(линия([15, 16, 17]).trend, 'rise',
            'а двойка на пятнадцати приседаниях — уже рост');
    });

    it('один круг — направления нет', () => {
        equal(линия([17]).trend, 'single');
    });
});

describe('Темп: что сказано', () => {

    const фраза = (числа) => pace.line(pace.read(подходы('w1', числа), { exclude: 'w2' }));

    it('без темпа не говорит ничего', () => {
        equal(pace.line(null), '');
        equal(pace.aim(null), '');
    });

    /*
     * Ровно тот случай, который случился у владельца на первой табате:
     * 15 → 16 → 17 и 24 → 28 → 28. Предложить восемнадцать было бы гаданием;
     * семнадцать — числом, которое он уже показал уставшим.
     */
    it('на растущей линии цель — последний круг, а не следующий за ним', () => {
        const сказано = фраза([15, 16, 17]);

        assert(сказано.includes('17'), сказано);
        assert(!сказано.includes('18'), `прибавку приложение не выдумывает: ${сказано}`);
        assert(сказано.includes('запас'), сказано);
    });

    it('на падающей линии цель — тоже последний круг', () => {
        const сказано = фраза([24, 20, 18]);

        assert(сказано.includes('18'), сказано);
        assert(сказано.includes('быстро'), `названа причина, а не только число: ${сказано}`);
    });

    it('ровная линия — это уже успех, и сказано это', () => {
        const сказано = фраза([17, 17, 17]);

        assert(сказано.includes('17'), сказано);
        assert(сказано.includes('держите'), сказано);
    });

    it('оба конца линии названы: по одному числу вывод не проверить', () => {
        const сказано = фраза([24, 20, 18]);

        assert(сказано.includes('24') && сказано.includes('18'), сказано);
    });

    it('во время работы — одно число, читаемое на ходу', () => {
        const темп = pace.read(подходы('w1', [24, 20, 18]), { exclude: 'w2' });
        const коротко = pace.aim(темп);

        assert(коротко.includes('18'), коротко);
        assert(коротко.length <= 20, `двадцать секунд приседаний не оставляют времени читать: «${коротко}»`);
    });
});

/**
 * «Ровно» — утверждение про каждый круг (Р-209).
 *
 * Направление решают концы, и бугорок в середине его не отменяет. А вот
 * «прошлый раз ровно 20» про тренировку 20 → 10 → 20 было неправдой.
 */
describe('Темп: неровная линия', () => {

    const линия = (числа) => pace.read(подходы('w1', числа), { exclude: 'w2' });

    it('концы совпали, середина провалилась — это неровно, а не ровно', () => {
        equal(линия([20, 10, 20]).trend, 'uneven');
    });

    it('бугорок на падающей линии направления не отменяет', () => {
        equal(линия([24, 20, 22, 18]).trend, 'fall');
    });

    it('мелкая дрожь внутри допуска — по-прежнему ровно', () => {
        equal(линия([17, 16, 17, 17]).trend, 'flat');
    });

    it('сказано с размахом, а цель — всё тот же последний круг', () => {
        const сказано = pace.line(линия([20, 10, 20]));

        assert(сказано.includes('неровно'), сказано);
        assert(сказано.includes('10') && сказано.includes('20'), `размах назван: ${сказано}`);
        assert(!сказано.includes('ровно 20'), 'ровного там не было ничего');
    });
});

/**
 * С чем сравнивать (Р-209): только интервальные тренировки и только с той же
 * длиной работы. Сорок секунд приседаний дают вдвое больше, чем двадцать.
 */
describe('Темп: с чем сравнивать', () => {

    const тренировки = new Map([
        ['t20', { id: 't20', interval: { work: 20, rest: 10 } }],
        ['t40', { id: 't40', interval: { work: 40, rest: 20 } }],
        ['сил', { id: 'сил' }]
    ]);

    const все = [
        ...подходы('t40', [30, 28, 27]),
        ...подходы('сил', [40, 38, 35]),
        ...подходы('t20', [15, 16, 17])
    ];

    it('двадцать секунд — с двадцатью, хоть сорок и были позже', () => {
        const свои = pace.comparable(все, тренировки, { id: 'сегодня', interval: { work: 20, rest: 10 } });

        equal(pace.read(свои).numbers, [15, 16, 17]);
    });

    it('отдых не сверяется: длинный отдых сдвигает число на повтор, а не вдвое', () => {
        const свои = pace.comparable(все, тренировки, { id: 'сегодня', interval: { work: 20, rest: 15 } });

        equal(pace.read(свои).numbers, [15, 16, 17], 'иначе после перехода на длинный отдых подсказка пропала бы');
    });

    it('силовая не в счёт никогда', () => {
        const свои = pace.comparable(все, тренировки, { id: 'сегодня', interval: { work: 20, rest: 10 } });

        assert(!свои.some((s) => s.workoutId === 'сил'));
    });

    it('другой длины прошлого раза нет — молчим, а не подсказываем чужое', () => {
        const свои = pace.comparable(все, тренировки, { id: 'сегодня', interval: { work: 30, rest: 15 } });

        equal(pace.read(свои), null);
    });

    it('своя тренировка в счёт не идёт', () => {
        const свои = pace.comparable(подходы('t20', [15, 16, 17]), тренировки, { id: 't20', interval: { work: 20 } });

        equal(свои.length, 0);
    });
});
