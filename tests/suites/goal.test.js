/**
 * Цифровые цели (§67 ТЗ).
 *
 * Здесь считается то, что приложение потом скажет человеку про него самого:
 * сколько он прошёл, сколько осталось и когда придёт. Неверное число тут
 * выглядит так же убедительно, как верное, а проверить его человеку нечем —
 * он за тем и смотрит.
 */

import { describe, it, equal, assert } from '../runner.js';
import { goal } from '../../js/core/goal.js';

const DAY = 86400000;
const NOW = new Date(2026, 8, 15, 12, 0, 0).getTime();

describe('Пройденное к цели', () => {

    /*
     * «Осталось 4,6 кг» знает и школьник. Ради «прошли 1,6» цель и заводят —
     * поэтому доля считается от точки, где цель объявили.
     */
    it('доля считается от начала, а не от нуля', () => {
        const итог = goal.progress({ from: 94.2, target: 88, current: 92.6 });

        equal(Math.round(итог.share * 100), 26, '1,6 из 6,2 — это четверть пути');
        equal(Math.round(итог.left * 10) / 10, 4.6);
        equal(итог.direction, 'down');
        equal(итог.done, false);
    });

    it('перевыполненная цель даёт больше единицы, а не ровно сто процентов', () => {
        const итог = goal.progress({ from: 94, target: 90, current: 88 });

        assert(итог.share > 1, `обрезать перевыполнение — значит его спрятать: ${итог.share}`);
        equal(итог.done, true);
    });

    it('цель на рост считается так же', () => {
        const итог = goal.progress({ from: 70, target: 75, current: 72.5 });

        equal(итог.direction, 'up');
        equal(Math.round(итог.share * 100), 50);
        equal(итог.done, false);
    });

    it('цель, равная началу, — не цель', () => {
        equal(goal.progress({ from: 90, target: 90, current: 89 }), null);
    });

    it('без чисел ничего не считается', () => {
        equal(goal.progress({ from: null, target: 88, current: 92 }), null);
        equal(goal.progress({}), null);
    });
});

describe('Свой ход к цели', () => {

    const точка = (днейНазад, value) => ({ at: NOW - днейНазад * DAY, value });

    it('скорость берётся по краям окна и приводится к неделе', () => {
        const ход = goal.pace([точка(28, 94.2), точка(14, 93.4), точка(0, 92.6)], { now: NOW });

        equal(Math.round(ход * 100) / 100, -0.4, 'полтора килограмма за четыре недели — это 0,4 в неделю');
    });

    it('точки старше окна не берутся', () => {
        const ход = goal.pace([точка(200, 120), точка(14, 93), точка(0, 92.6)], { now: NOW });

        assert(Math.abs(ход) < 1, `прошлогодний вес в скорость не идёт: ${ход}`);
    });

    it('меньше двух замеров скорости не дают', () => {
        equal(goal.pace([точка(3, 92.6)], { now: NOW }), null);
        equal(goal.pace([], { now: NOW }), null);
    });

    /*
     * Два взвешивания в один день — это вода и соль, а не ход. «Полкило за
     * час» в пересчёте на неделю дало бы восемьдесят четыре килограмма.
     */
    it('два замера в один день скорости не дают', () => {
        const ход = goal.pace([
            { at: NOW - 3600000, value: 93.1 },
            { at: NOW, value: 92.6 }
        ], { now: NOW });

        equal(ход, null);
    });
});

describe('Срок прихода к цели', () => {

    it('считается по своему ходу', () => {
        const когда = goal.eta({ current: 92.6, target: 88, perWeek: -0.4, now: NOW });

        const недель = (когда - NOW) / (7 * DAY);

        equal(Math.round(недель), 12, '4,6 килограмма по 0,4 в неделю — это около двенадцати недель');
    });

    /*
     * Стоящая на месте величина не дойдёт никогда, идущая от цели — тем
     * более. Обещать срок в таких случаях значит придумывать.
     */
    it('на месте и в обратную сторону срока нет', () => {
        equal(goal.eta({ current: 92.6, target: 88, perWeek: 0, now: NOW }), null);
        equal(goal.eta({ current: 92.6, target: 88, perWeek: 0.3, now: NOW }), null);
    });

    it('дальше года срок не обещается', () => {
        equal(goal.eta({ current: 92.6, target: 88, perWeek: -0.02, now: NOW }), null,
            'при двадцати граммах в неделю дата вышла бы за десятилетие');
    });
});

describe('Приближаемся или удаляемся', () => {

    it('ход в сторону цели и от неё различаются', () => {
        equal(goal.heading({ target: 88, current: 92.6, perWeek: -0.4 }), 'toward');
        equal(goal.heading({ target: 88, current: 92.6, perWeek: 0.4 }), 'away');
        equal(goal.heading({ target: 88, current: 92.6, perWeek: 0 }), 'still');
    });

    /*
     * Доля может быть большой, а последние недели — обратный ход. Сказать об
     * этом надо: иначе цель хвалит за прошлое.
     */
    it('после перехода за цель обратный ход тоже виден', () => {
        equal(goal.heading({ target: 88, current: 87, perWeek: -0.3 }), 'away',
            'ушли ниже цели и продолжаем вниз — это движение от неё');
    });
});
