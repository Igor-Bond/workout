/**
 * Что уходит собеседнику (§60 ТЗ).
 *
 * Главное, что проверяется: наружу уходит ровно то, что собрано здесь, и
 * ничего сверх. Это единственное место, где приложение отправляет данные о
 * человеке за свои пределы, и ошибка тут стоит дороже прочих.
 */

import { describe, it, equal, assert } from '../runner.js';
import { prompt } from '../../js/core/prompt.js';
import { plan } from '../../js/core/plan.js';
import { report } from '../../js/core/report.js';
import { i18n } from '../../js/core/i18n.js';
import { config } from '../../js/config.js';

const INSTRUCTION = prompt.instruction();

const СВОДКА = 'Сводка тренировок — 06.09.2026\n\nО себе:\n— Ограничение: Колено';
const ПЛАН = 'С 07.09.2026, 8 недель\nПн Бицепс резинка 6 × 50\nВс отдых';

describe('Дело', () => {

    it('несёт сводку', () => {
        assert(prompt.dossier({ summary: СВОДКА }).includes('Ограничение: Колено'));
    });

    it('несёт действующую программу отдельным разделом', () => {
        const дело = prompt.dossier({ summary: СВОДКА, plan: ПЛАН });

        assert(дело.includes('Действующая программа'));
        assert(дело.includes('Пн Бицепс резинка 6 × 50'));
    });

    it('без программы раздела не заводит', () => {
        assert(!prompt.dossier({ summary: СВОДКА }).includes('Действующая программа'),
            'пустой раздел сказал бы, что программа есть и она пуста');
    });

    it('пустое дело — пустая строка, а не заголовки в пустоте', () => {
        equal(prompt.dossier({}), '');
        equal(prompt.dossier({ summary: '   ', plan: '\n' }), '');
    });

});

describe('Первое обращение', () => {

    it('дело идёт перед вопросом', () => {
        const текст = prompt.first({ summary: СВОДКА, question: 'Составь программу.' });

        assert(текст.indexOf('Сводка') < текст.indexOf('Составь'),
            'собеседник читает сверху вниз, и вопрос без дела он поймёт иначе');
    });

    it('без дела остаётся один вопрос', () => {
        equal(prompt.first({ question: 'Составь программу.' }), 'Составь программу.');
    });

    it('лишних пробелов не оставляет', () => {
        equal(prompt.first({ summary: '  ', question: '  Привет  ' }), 'Привет');
    });

});

describe('Наставление', () => {

    it('называет вид ответа, который приложение примет', () => {
        assert(INSTRUCTION.includes('Пн  <упражнение>'), 'иначе план придётся переписывать руками');
        assert(INSTRUCTION.includes('«+»'), 'день из нескольких упражнений');
    });

    it('требует соблюдать ограничения безусловно', () => {
        assert(/ограничени/i.test(INSTRUCTION));
    });

    /*
     * Образец с постоянной датой через месяц оказался в прошлом (Р-203), а
     * повторяет его модель охотнее любых слов вокруг.
     */
    it('называет сегодняшнее число: модели его взять неоткуда', () => {
        const текст = prompt.instruction({ now: new Date(2026, 9, 3, 15).getTime() });

        assert(текст.includes('Сегодня 03.10.2026'), текст.slice(0, 300));
    });

    it('образец плана начинается завтра — и сдвигается вместе с днём', () => {
        const сегодня = prompt.instruction({ now: new Date(2026, 9, 3, 15).getTime() });
        const через = prompt.instruction({ now: new Date(2026, 10, 20, 9).getTime() });

        assert(сегодня.includes('С 04.10.2026, 8 недель'), 'завтра, как и в задании сводки');
        assert(через.includes('С 21.11.2026, 8 недель'), 'постоянной даты в образце быть не может');
    });

    it('образец переходит через конец месяца и года', () => {
        assert(prompt.instruction({ now: new Date(2026, 11, 31, 23).getTime() }).includes('С 01.01.2027'));
    });

    it('образец, повторённый дословно, разбирается в план с той же датой', () => {
        const now = new Date(2026, 9, 3, 15).getTime();
        const шапка = prompt.instruction({ now }).split('\n').find((s) => s.startsWith('С '));

        const разобран = plan.parse([шапка, 'Пн Отжимания 6 × 50'].join('\n'));

        equal(разобран.from, new Date(2026, 9, 4).getTime());
    });

});

/**
 * Дата образца — числами на любом языке (Р-203).
 *
 * По-английски подпись даты словесная, «October 4, 2026», а разбор плана
 * читает дату только числами: ответ, повторивший образец дословно, не
 * разбирался.
 */
describe('Дата в образце плана', () => {

    /** Переключить язык на время проверки и вернуть как было. */
    function поАнглийски(body) {
        const было = config.get('lang');

        try {
            i18n.set('en');
            return body();
        } finally {
            i18n.set(было);
        }
    }

    it('в задании сводки по-английски — числами, и такой ответ разбирается', () => поАнглийски(() => {
        const now = new Date(2026, 9, 3, 15).getTime();
        const задание = report.request({ now }).join('\n');
        const шапка = задание.split('\n').find((s) => /\d{2}\.\d{2}\.\d{4}/.test(s));

        assert(шапка, `дата числами: ${задание.slice(-900)}`);
        assert(шапка.includes('04.10.2026'), шапка);
        equal(plan.parse([шапка, 'Mon Push-ups 6 × 50'].join('\n')).from, new Date(2026, 9, 4).getTime());
    }));

    it('наставление числами и по-английски', () => поАнглийски(() => {
        assert(prompt.instruction({ now: new Date(2026, 9, 3, 15).getTime() }).includes('04.10.2026'));
    }));

});

describe('План в ответе', () => {

    const инструменты = { parse: plan.parse, usable: plan.usable };

    it('узнаётся тем же разбором, что и вставка руками', () => {
        equal(prompt.hasPlan(ПЛАН, инструменты), true);
    });

    it('в обычном ответе плана нет', () => {
        equal(prompt.hasPlan('Я бы усилил субботу, но постепенно.', инструменты), false);
    });

    it('текст без даты начала планом не считается', () => {
        equal(prompt.hasPlan('Пн Бицепс резинка 6 × 50', инструменты), false,
            'кнопка «перенести» там, где переносить нечего, отправит человека за разочарованием');
    });

    it('пустое и мусор ничего не роняют', () => {
        equal(prompt.hasPlan('', инструменты), false);
        equal(prompt.hasPlan(ПЛАН, {}), false);
        equal(prompt.hasPlan(ПЛАН, { parse: () => { throw new Error('бум'); }, usable: () => true }), false);
    });

});

describe('Карточки упражнений', () => {

    const ИЗВЕСТНЫЕ = [
        { name: 'Жим лёжа', kind: 'weight', group: 'Грудь' },
        { name: 'Планка', kind: 'time', group: 'Пресс' }
    ];

    it('просьба несёт коды видов, образцы и сами названия', () => {
        const текст = prompt.cards({ names: ['Скручивания', 'Выпады'], known: ИЗВЕСТНЫЕ });

        assert(текст.includes('weight —'), 'без кодов вида ответ придётся угадывать');
        assert(текст.includes('Жим лёжа | weight | Грудь'), 'образец задаёт словарь групп');
        assert(текст.includes('Скручивания') && текст.includes('Выпады'));
    });

    it('без справочника просьба всё равно осмысленна', () => {
        const текст = prompt.cards({ names: ['Планка'] });

        assert(текст.includes('Планка'));
        assert(!текст.includes('уже заведённые'), 'обещать образцы, которых нет, незачем');
    });

    it('ответ разбирается в карточки', () => {
        const ответ = [
            'Скручивания | reps | Пресс | Лёжа на спине поднимайте лопатки.',
            'Выпады | weight | Ноги | Шаг вперёд с гантелями, колено не выходит за носок.'
        ].join('\n');

        const карточки = prompt.readCards(ответ, { names: ['Скручивания', 'Выпады'], same: plan.same });

        equal(карточки.length, 2);
        equal(карточки[0].kind, 'reps');
        equal(карточки[0].group, 'Пресс');
        assert(карточки[1].howTo.includes('колено'));
    });

    it('прощает обрамление, нумерацию и вид словом', () => {
        const ответ = [
            'Вот карточки:',
            '',
            '1. **Планка** | На время | Пресс | Держите корпус ровно.',
            '— Скручивания | длительность | Пресс |'
        ].join('\n');

        const карточки = prompt.readCards(ответ, { names: ['Планка', 'Скручивания'], same: plan.same });

        equal(карточки.length, 2);
        equal(карточки[0].name, 'Планка');
        equal(карточки[0].kind, 'time', 'подпись вида — тот же вид');
        equal(карточки[1].kind, 'time', 'подсказка вида — тоже');
        equal(карточки[1].howTo, '');
    });

    it('название возвращается своё, а не как его написал собеседник', () => {
        const карточки = prompt.readCards('жим лёжа | weight | Грудь | Ложитесь.',
            { names: ['Жим лёжа'], same: plan.same });

        equal(карточки[0].name, 'Жим лёжа', 'иначе в справочнике заведётся второе написание того же');
    });

    it('придуманное упражнение мимо', () => {
        const ответ = [
            'Планка | time | Пресс | Держите корпус.',
            'Берпи | reps | Всё тело | Присед, упор, прыжок.'
        ].join('\n');

        const карточки = prompt.readCards(ответ, { names: ['Планка'], same: plan.same });

        equal(карточки.length, 1, 'карточка того, чего в плане нет, засорит справочник');
        equal(карточки[0].name, 'Планка');
    });

    it('незнакомый вид становится обычным, а не пустым', () => {
        const карточки = prompt.readCards('Планка | статика | Пресс | Держите.',
            { names: ['Планка'], same: plan.same });

        equal(карточки[0].kind, 'weight', 'упражнение без вида приложение не покажет');
    });

    it('пустое и мусор ничего не роняют', () => {
        equal(prompt.readCards('', { names: ['Планка'] }).length, 0);
        equal(prompt.readCards('Не могу помочь.', { names: ['Планка'] }).length, 0);
        equal(prompt.readCards('| | |', { names: ['Планка'], same: plan.same }).length, 0);
    });

});

describe('Узнанные названия', () => {

    it('«= | уже заведённое» не карточка, а замена', () => {
        const карточки = prompt.readCards('Отжимания от пола | = | Отжимания',
            { names: ['Отжимания от пола'], same: plan.same });

        equal(карточки.length, 1);
        equal(карточки[0].same, 'Отжимания');
        equal(карточки[0].kind, undefined, 'заводить нечего — вид не нужен');
    });

    it('просьба объясняет, как сказать «это то же самое»', () => {
        assert(prompt.cards({ names: ['Планка'], known: [{ name: 'Планка с весом', kind: 'weight' }] })
            .includes('| = |'), 'иначе справочник раздуется двумя записями об одном движении');
    });

    it('равенство без второй половины — обычная карточка', () => {
        const карточки = prompt.readCards('Планка | = |', { names: ['Планка'], same: plan.same });

        equal(карточки[0].same, undefined);
        equal(карточки[0].kind, 'weight');
    });

});

/**
 * Вилка по описанию еды (§68).
 *
 * Проверяется не сама оценка — её даёт модель, — а два обещания приложения:
 * наружу уходит только описание еды, и вилкой человеку показывается вилка, а
 * не одно число, выданное за измеренное.
 */
describe('Сколько это примерно', () => {

    it('наружу уходит одно описание еды', () => {
        const текст = prompt.meal('тарелка борща и два куска хлеба');

        assert(текст.includes('тарелка борща и два куска хлеба'), текст);
        assert(!/\d{2,3}\s*кг|возраст|рост|тренировк/i.test(текст),
            `ни веса, ни возраста, ни истории — калорийность порции от них не зависит:\n${текст}`);
    });

    it('просят вилку, а не одно число', () => {
        const текст = prompt.meal('омлет');

        assert(текст.includes('тремя строками'), текст);
        assert(текст.includes('от скромной оценки к щедрой'), текст);
    });

    it('три оценки разбираются и выстраиваются по возрастанию', () => {
        const разбор = prompt.readMeal([
            '900 | обычная порция',
            '650 | скромно, без масла',
            '1200 | большая порция'
        ].join('\n'));

        equal(разбор.options.length, 3);
        equal(разбор.options[0].kcal, 650, 'скромная оценка стоит первой');
        equal(разбор.options[2].kcal, 1200);
        equal(разбор.options[1].why, 'обычная порция');
    });

    it('вопросы отделяются от оценок', () => {
        const разбор = prompt.readMeal([
            '400 | без масла',
            '700 | со сливочным маслом',
            '? | сколько масла было?',
            '? | порция с кулак или больше?'
        ].join('\n'));

        equal(разбор.options.length, 2);
        equal(разбор.questions.length, 2);
        equal(разбор.questions[0], 'сколько масла было?');
    });

    /*
     * Модель обрамляет строки звёздочками, начинает их тире и пишет единицы
     * рядом с числом. Всё это чинится здесь и человеку ничего не стоит.
     */
    it('звёздочки, тире и единицы рядом с числом не мешают', () => {
        const разбор = prompt.readMeal([
            '**— 1 200 ккал | щедро**',
            '- `800 ккал` | обычно'
        ].join('\n'));

        equal(разбор.options.length, 2);
        equal(разбор.options[0].kcal, 800);
        equal(разбор.options[1].kcal, 1200, 'разделитель разрядов — часть числа, а не второе число');
    });

    /*
     * Без чисел показывать нечего, и открыть пустое окно выбора было бы
     * хуже, чем сказать прямо: не вышло, впишите сами.
     */
    it('ответ без чисел — это не вилка', () => {
        equal(prompt.readMeal('Затрудняюсь сказать без веса порции.'), null);
        equal(prompt.readMeal(''), null);
    });

    /*
     * Короткое название (§68, Р-183).
     *
     * Описание пишут подробно — иначе вилка выйдет шире, — а живёт оно потом
     * меткой под карточкой питания. Подробное там занимает две строки и
     * читается хуже короткого.
     */
    it('короткое название просят и разбирают', () => {
        assert(prompt.meal('омлет').includes('короткое название'), prompt.meal('омлет'));

        const разбор = prompt.readMeal([
            '= | Пиво с закуской и мороженое',
            '650 | скромно',
            '900 | обычно'
        ].join('\n'));

        equal(разбор.name, 'Пиво с закуской и мороженое');
        equal(разбор.options.length, 2, 'строка названия оценкой не притворяется');
    });

    it('название необязательно — без него остаются свои слова', () => {
        equal(prompt.readMeal('700 | обычно').name, '');
    });

    /*
     * Просьба не обещание: описание в полсотни слов приходит и туда, где
     * просили коротко. Режем по последнему пробелу — обрывок посреди слова
     * читается как опечатка.
     */
    it('слишком длинное название укорачивается по словам', () => {
        const разбор = prompt.readMeal([
            '= | 0.5 светлого нефильтрованного, орешки криспы 100 гр, мороженое в вафельном стаканчике',
            '900 | обычно'
        ].join('\n'));

        assert(разбор.name.length <= prompt.КОРОТКО + 1, `вышло ${разбор.name.length}: ${разбор.name}`);
        assert(разбор.name.endsWith('…'), разбор.name);
        assert(!/\s…$/.test(разбор.name), `пробел перед многоточием: «${разбор.name}»`);

        const последнее = разбор.name.replace('…', '').split(' ').pop();
        assert('0.5 светлого нефильтрованного, орешки криспы 100 гр,'.includes(последнее),
            `слово обрублено посередине: «${разбор.name}»`);
    });

    it('одно длинное слово всё-таки режется — иначе не влезет', () => {
        const разбор = prompt.readMeal([
            `= | ${'я'.repeat(80)}`,
            '900 | обычно'
        ].join('\n'));

        assert(разбор.name.length <= prompt.КОРОТКО + 1, разбор.name.length);
    });

    it('из двух названий берётся первое', () => {
        const разбор = prompt.readMeal([
            '= | Борщ с хлебом',
            '= | Обед',
            '900 | обычно'
        ].join('\n'));

        equal(разбор.name, 'Борщ с хлебом');
    });

    it('из пяти оценок остаются края и середина', () => {
        const разбор = prompt.readMeal(
            [100, 200, 300, 400, 500].map((n) => `${n} | вариант`).join('\n')
        );

        equal(разбор.options.length, 3);
        equal(разбор.options[0].kcal, 100);
        equal(разбор.options[2].kcal, 500, 'края вилки важнее её середины');
    });
});
