/**
 * Правила оформления, которые нельзя увидеть глазом (§45).
 *
 * Обычные проверки экранов смотрят на разметку. Здесь смотрят на сам
 * стилевой файл — потому что проверяемое свойство ничего не рисует и
 * проявляется только пальцем на телефоне, которого у проверок нет.
 */

import { describe, it, assert } from '../runner.js';

const читать = async (path) => (await fetch(`../${path}`, { cache: 'no-store' })).text();

/**
 * Правила стилевого файла как есть: селектор и его объявления.
 *
 * Разбор нарочно наивный — берутся самые внутренние блоки. Этого хватает:
 * объявления живут только в них, а `@media` вокруг на состав объявлений не
 * влияет.
 */
function правила(css) {
    const out = [];

    for (const m of css.matchAll(/([^{}]*)\{([^{}]*)\}/g)) {
        const селектор = m[1].trim().split('\n').pop().trim();
        out.push({ селектор, тело: m[2] });
    }

    return out;
}

describe('Прокрутка вбок не уходит за пределы своего ящика', () => {

    /*
     * Р-181. Журнал подходов на телефоне шире экрана всего на десяток точек:
     * один свайп влево — прокрутка кончилась, а жест продолжился. Дальше его
     * подхватывает браузер и уводит по истории назад, то есть из приложения
     * вон; со стороны это выглядит так, будто окно уехало целиком.
     *
     * Свойство ничего не рисует, глазом его отсутствия не видно, и найти
     * такое можно только пальцем на настоящем телефоне. Поэтому — здесь.
     */
    it('у каждого, кто прокручивается вбок, сцепка остановлена', async () => {
        const css = await читать('css/style.css');

        const вбок = /(?:^|[;{\s])overflow(?:-x)?\s*:\s*(auto|scroll)/im;
        const сцепка = /overscroll-behavior(?:-x)?\s*:/i;

        const виновные = правила(css)
            .filter((п) => вбок.test(п.тело) && !сцепка.test(п.тело))
            .map((п) => п.селектор);

        assert(виновные.length === 0,
            `прокрутка вбок без overscroll-behavior-x: ${виновные.join(', ')}`);
    });

    /*
     * Проверка обязана падать на том, ради чего написана: разбор, ничего не
     * нашедший, отчитался бы об успехе с тем же видом.
     */
    it('разбор и вправду видит прокручиваемые вбок правила', async () => {
        const css = await читать('css/style.css');

        const найдено = правила(css)
            .filter((п) => /(?:^|[;{\s])overflow(?:-x)?\s*:\s*(auto|scroll)/im.test(п.тело));

        assert(найдено.length >= 3,
            `таких правил в файле не меньше трёх, а разбор нашёл ${найдено.length}`);
    });
});
