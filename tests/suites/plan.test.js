describe('Правка повторений в тексте плана (§59.1)', () => {

    const ТЕКСТ = [
        'С 07.09.2026, 8 недель',
        'Пн Бицепс резинка 6 × 50 + Пресс 6 × 25',
        'Сб Пресс 2 × 25 + Планка 2 × 45'
    ].join('\n');

    it('меняет повторения и не трогает подходы', () => {
        const итог = plan.retune(ТЕКСТ, 'Бицепс резинка', (r) => Math.round(r * 0.8));

        assert(итог.includes('Бицепс резинка 6 × 40'), итог);
        assert(итог.includes('Пресс 6 × 25'), 'соседнее упражнение не трогается');
    });

    it('правит все дни, где упражнение встречается', () => {
        const итог = plan.retune(ТЕКСТ, 'Пресс', (r) => r + 5);

        assert(итог.includes('Пресс 6 × 30'), итог);
        assert(итог.includes('Пресс 2 × 30'), 'суббота тоже');
    });

    it('короткое имя не переписывает длинное', () => {
        const текст = 'С 07.09.2026, 8 недель\nПн Пресс стоя 6 × 25 + Пресс 6 × 20';
        const итог = plan.retune(текст, 'Пресс', () => 99);

        assert(итог.includes('Пресс стоя 6 × 25'), `«Пресс» не должен трогать «Пресс стоя»: ${итог}`);
        assert(итог.includes('Пресс 6 × 99'));
    });

    it('строка без объёма остаётся как есть', () => {
        const текст = 'С 07.09.2026, 8 недель\nСр Баскетбол';

        equal(plan.retune(текст, 'Баскетбол', () => 10), текст);
    });

    it('план после правки разбирается по-прежнему', () => {
        const разобран = plan.parse(plan.retune(ТЕКСТ, 'Бицепс резинка', () => 40));

        equal(plan.usable(разобран), true);
        equal(разобран.days[1].items[0].reps, 40);
    });

    it('пустое имя и мусорный ответ ничего не портят', () => {
        equal(plan.retune(ТЕКСТ, '', () => 1), ТЕКСТ);
        equal(plan.retune(ТЕКСТ, 'Пресс', () => 0), ТЕКСТ, 'ноль повторений — не правка, а поломка');
    });

});
