/**
 * План тренировок: разбор текста и развёртка по дням (§56 ТЗ).
 *
 * Главное, что проверяется: план приходит текстом от человека или языковой
 * модели, и приложение обязано понять его в той форме, в какой его пишут, а
 * непонятое — назвать вслух, а не проглотить. И сдвиг при пропуске: он живёт
 * внутри недели, иначе один пропуск уводит весь план навсегда.
 */

import { describe, it, equal, assert } from '../runner.js';
import { plan } from '../../js/core/plan.js';

const DAY = 86400000;

/** Понедельник, 7 сентября 2026, полдень. */
const MONDAY = new Date(2026, 8, 7, 12, 0, 0).getTime();

/** Образец плана — ровно в том виде, какой приложение просит в сводке (§55). */
const ОБРАЗЕЦ = [
    'С 07.09.2026, 8 недель',
    'Этап 1 (недели 1–4): втягивание',
    'Пн Бицепс резинка 6 × 50',
    'Вт Спина резинка 12 × 35',
    'Ср Баскетбол',
    'Чт Трицепс резинка 6 × 50',
    'Пт Плечи резинка 12 × 35',
    'Сб Ноги и пресс 4 × 20',
    'Вс отдых'
].join('\n');

describe('Разбор плана', () => {

    it('берёт дату начала и срок из шапки', () => {
        const p = plan.parse(ОБРАЗЕЦ);

        equal(new Date(p.from).getDate(), 7);
        equal(new Date(p.from).getMonth(), 8);
        equal(p.weeks, 8);
    });

    it('без срока ставит восемь недель', () => {
        equal(plan.parse('С 07.09.2026\nПн Бицепс 6 × 50').weeks, 8);
    });

    it('раскладывает занятия по дням недели', () => {
        const days = plan.parse(ОБРАЗЕЦ).days;

        equal(days[1].name, 'Бицепс резинка');
        equal(days[1].sets, 6);
        equal(days[1].reps, 50);
        equal(days[3].name, 'Баскетбол');
        equal(days[0], null, 'воскресенье — отдых');
    });

    it('понимает день и сокращением, и словом', () => {
        const days = plan.parse('С 07.09.2026\nПонедельник Бицепс 6 × 50\nСР. Баскетбол\nfriday Плечи 12 × 35').days;

        equal(days[1].name, 'Бицепс', 'полное имя дня — обычный ответ языковой модели');
        equal(days[3].name, 'Баскетбол');
        equal(days[5].name, 'Плечи', 'план могут прислать и по-английски');
    });

    it('прозу за день недели не принимает', () => {
        const p = plan.parse('С 07.09.2026, 8 недель\nПн Бицепс 6 × 50\nПо самочувствию добавьте разминку');

        equal(p.problems.length, 1, 'иначе «По…» стало бы понедельником и заслонило бы бицепс');
        equal(p.days[1].name, 'Бицепс');
    });

    it('этап показывает, но не исполняет', () => {
        const p = plan.parse(ОБРАЗЕЦ);

        equal(p.stages.length, 1);
        equal(p.problems.length, 0, 'этап не должен уезжать в «не понято»');
    });

    it('непонятую строку называет вслух', () => {
        const p = plan.parse(`${ОБРАЗЕЦ}\nПить больше воды`);

        equal(p.problems.length, 1);
        equal(p.problems[0], 'Пить больше воды');
    });

    it('проза до шапки разбору не мешает', () => {
        const p = plan.parse('Вот ваш план:\n\nС 07.09.2026, 8 недель\nПн Бицепс 6 × 50');

        equal(p.problems.length, 0);
        equal(p.days[1].name, 'Бицепс');
    });

});

describe('Занятие дня', () => {

    it('читает «6 × 50»', () => {
        const з = plan.parseDay('Бицепс резинка 6 × 50');

        equal(з.name, 'Бицепс резинка');
        equal(з.sets, 6);
        equal(з.reps, 50);
    });

    it('не придирается к знаку умножения', () => {
        for (const знак of ['×', 'x', 'х', '*']) {
            equal(plan.parseDay(`Бицепс 6 ${знак} 50`).reps, 50, `разделитель «${знак}»`);
        }
    });

    it('принимает занятие без объёма', () => {
        const з = plan.parseDay('Баскетбол');

        equal(з.name, 'Баскетбол');
        equal(з.sets, null);
    });

    it('принимает одни подходы', () => {
        const з = plan.parseDay('Бицепс 6');

        equal(з.name, 'Бицепс');
        equal(з.sets, 6);
        equal(з.reps, null);
    });

    it('читает несколько упражнений через «+»', () => {
        const з = plan.parseDay('Бицепс резинка 6 × 50 + Пресс 6 × 25');

        equal(з.items.length, 2, 'блок и добор — один день, а не два');
        equal(з.items[0].name, 'Бицепс резинка');
        equal(з.items[1].name, 'Пресс');
        equal(з.items[1].reps, 25);
    });

    it('днём распоряжается первое упражнение', () => {
        const з = plan.parseDay('Бицепс резинка 6 × 50 + Пресс 6 × 25');

        equal(з.name, 'Бицепс резинка', 'по нему день узнаётся в истории');
        equal(з.sets, 6);
    });

    it('одиночное упражнение тоже с составом', () => {
        equal(plan.parseDay('Баскетбол').items.length, 1, 'чтобы читателю не гадать, есть items или нет');
    });

});

describe('Годность плана', () => {

    it('без даты начала план не годен', () => {
        assert(!plan.usable(plan.parse('Пн Бицепс 6 × 50')));
    });

    it('без единого занятия план не годен', () => {
        assert(!plan.usable(plan.parse('С 07.09.2026, 8 недель\nВс отдых')));
    });

    it('дата и хотя бы один день делают его годным', () => {
        assert(plan.usable(plan.parse(ОБРАЗЕЦ)));
    });

});

describe('Срок плана', () => {

    const p = plan.parse(ОБРАЗЕЦ);

    it('кончается через объявленное число недель', () => {
        equal(new Date(plan.until(p)).getDate(), 1, '7 сентября плюс 8 недель — 1 ноября');
    });

    it('в свой срок действует', () => {
        assert(plan.active(p, MONDAY + 3 * DAY));
    });

    it('до начала и после конца молчит', () => {
        assert(!plan.active(p, MONDAY - 2 * DAY));
        assert(!plan.active(p, plan.until(p) + DAY));
    });

});

describe('Развёртка по дням', () => {

    const p = plan.parse(ОБРАЗЕЦ);

    it('ставит каждому дню его занятие', () => {
        const ряд = plan.expand(p, { from: MONDAY, days: 7 });

        equal(ряд.length, 7);
        equal(ряд[0].session.name, 'Бицепс резинка');
        equal(ряд[2].session.name, 'Баскетбол');
        equal(ряд[6].session, null, 'воскресенье пустое');
    });

    it('повторяет ту же неделю дальше', () => {
        const ряд = plan.expand(p, { from: MONDAY, days: 14 });

        equal(ряд[7].session.name, 'Бицепс резинка', 'через неделю снова понедельник');
        equal(ряд[7].week, 2);
    });

    it('за срок не выходит', () => {
        const ряд = plan.expand(p, { from: plan.until(p) - 2 * DAY, days: 14 });

        assert(ряд.length <= 3, `хвост плана — не 14 дней, а ${ряд.length}`);
    });

});

describe('Сегодня по плану', () => {

    const p = plan.parse(ОБРАЗЕЦ);

    it('даёт ровно то, что стоит в сетке на сегодня', () => {
        equal(plan.today(p, { now: MONDAY })?.name, 'Бицепс резинка');
        equal(plan.today(p, { now: MONDAY + DAY })?.name, 'Спина резинка');
        equal(plan.today(p, { now: MONDAY + 2 * DAY })?.name, 'Баскетбол');
    });

    it('сделанное сегодня снимает с доски', () => {
        equal(plan.today(p, { now: MONDAY, done: ['Бицепс резинка'] }), null);
    });

    it('пропущенный день не переносится', () => {
        // Понедельник пропущен, и во вторник стоит вторничное:
        // сетка объявлена затем, чтобы день недели держался (Р-62)
        equal(plan.today(p, { now: MONDAY + DAY })?.name, 'Спина резинка');
    });

    it('пропуск не уводит среду с баскетболом', () => {
        equal(plan.today(p, { now: MONDAY + 2 * DAY })?.name, 'Баскетбол',
            'ради этого сетка и заводилась');
    });

    it('пропуск не съедает воскресный отдых', () => {
        equal(plan.today(p, { now: MONDAY + 6 * DAY }), null,
            'при сдвиге в воскресенье встал бы хвост недели');
    });

    it('вчерашнее сделанное сегодняшнего не отменяет', () => {
        equal(plan.today(p, { now: MONDAY + DAY, done: ['Бицепс резинка'] })?.name, 'Спина резинка');
    });

    it('регистр и «ё» сверке не мешают', () => {
        equal(plan.today(p, { now: MONDAY, done: ['бицепс резинка'] }), null);
    });

    it('через неделю пропущенное возвращается на своё место', () => {
        equal(plan.today(p, { now: MONDAY + 7 * DAY })?.name, 'Бицепс резинка');
    });

    it('в день отдыха молчит', () => {
        equal(plan.today(p, { now: MONDAY + 6 * DAY }), null);
    });

    it('вне срока молчит', () => {
        equal(plan.today(p, { now: MONDAY - DAY }), null);
    });

});

describe('Описание занятия', () => {

    it('называет объём — за ним и смотрят', () => {
        equal(plan.describe({ name: 'Бицепс', sets: 6, reps: 50 }), 'Бицепс 6 × 50');
    });

    it('без повторов даёт одни подходы', () => {
        equal(plan.describe({ name: 'Бицепс', sets: 6, reps: null }), 'Бицепс 6');
    });

    it('без объёма даёт одно название', () => {
        equal(plan.describe({ name: 'Баскетбол', sets: null }), 'Баскетбол');
    });

    it('добор не прячет', () => {
        equal(plan.describe(plan.parseDay('Бицепс резинка 6 × 50 + Пресс 6 × 25')),
            'Бицепс резинка 6 × 50 + Пресс 6 × 25',
            'иначе день на карточке выглядит вдвое легче, чем он есть');
    });

    it('дню без занятия подпись даёт не ядро', () => {
        equal(plan.describe(null), '', 'ядро не переводит — слово «отдых» ставит экран');
    });

});
